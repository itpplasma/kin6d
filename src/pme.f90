!> Particle-mesh Ewald (PME) action of the periodic Coulomb sum: the fast
!> counterpart of the direct Ewald sum of kin6d_nbody, which stays the oracle.
!>
!> Same convention as kin6d_ewald/kin6d_symbolic_physics: cube of edge L,
!> neutralizing uniform background, tin-foil boundary, Ewald parameter alpha.
!> - Real space: g erfc(alpha r)/r for minimum-image pairs with r < cutoff,
!>   cutoff < L/2, found by a linked cell list (no image beyond the minimum
!>   one; its erfc tail is part of the real-space truncation estimate).
!> - Reciprocal space: charges spread to a K^3 mesh with cardinal B-splines
!>   of even order p (weights generated by gen/gen_ocp.f90), FortNum FFT,
!>   energy-optimal influence function G = sum_M U^2 R / (sum_M U^2)^2 over
!>   alias vectors |M|_inf <= 2, energy E = (1/2) sum_k c G |Q(k)|^2.
!>   Forces are the exact gradient of this mesh energy (analytic B-spline
!>   differentiation), so the KDK integrates a Hamiltonian; momentum is not
!>   exactly conserved (mesh self force), which is part of the force error.
!> Parameters come from a requested rms force tolerance relative to the
!> declared scale F0 = |c| q^2/a^2 (a Wigner-Seitz radius): the real-space
!> estimate of Kolafa and Perram (Mol. Simul. 9, 351 (1992)) and the exact
!> mean-square reciprocal pair-force error functional of the used influence
!> function for uncorrelated positions (computed here as an alias sum).
!> Both are estimates; tests measure the error against direct Ewald.
!> Hot path: no allocation, no all-pairs matrix, no dynamic dispatch.
module kin6d_pme
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use, intrinsic :: ieee_arithmetic, only: ieee_is_finite
    use fortnum_fft, only: fortnum_fft_plan_t, fft_c2c_plan_init, fft_c2c
    use kin6d_coulomb_leaves, only: ewald_real_pair, ewald_real_pair_jvp, &
        ewald_self, ewald_background, ewald_reciprocal_weight
    use kin6d_near_encounter, only: near_split_t, near_pair, near_pair_jvp
    use kin6d_ocp_leaves, only: pme_bspline4, pme_bspline6, pme_bspline8, &
        pme_assignment_factor
    implicit none
    private
    public :: pme_parameters_t, pme_t, pme_select, pme_estimate, pme_setup
    public :: pme_force, pme_force_jvp, pme_constant

    real(dp), parameter :: pi = 3.14159265358979323846_dp, two_pi = 2*pi
    integer, parameter :: max_alias = 2

    type :: pme_parameters_t
        real(dp) :: length = 0.0_dp, alpha = 0.0_dp, cutoff = 0.0_dp
        integer :: mesh = 0, order = 0
        !> Requested rms force tolerance relative to force_scale = |c| q^2/a^2,
        !> and the estimated rms real/reciprocal force errors (absolute).
        real(dp) :: tolerance = 0.0_dp, force_scale = 0.0_dp
        real(dp) :: real_estimate = 0.0_dp, reciprocal_estimate = 0.0_dp
    end type

    type :: pme_t
        type(pme_parameters_t) :: p
        integer :: n = 0, cells = 0
        real(dp) :: h = 0.0_dp
        !> Mean mesh self-energy defect per unit c q^2:
        !> (1/2)[sum_{k/=0} R(k) - sum_mesh G(k) A(k)], added to the energy.
        real(dp) :: self_shift = 0.0_dp
        !> Near/far encounter split; `far` evaluations omit the near part.
        type(near_split_t) :: split
        !> Influence function per unit coupling on mesh bins 0..K-1.
        real(dp), allocatable :: influence(:, :, :)
        complex(dp), allocatable :: grid(:, :, :), dgrid(:, :, :), line(:)
        type(fortnum_fft_plan_t) :: plan
        integer, allocatable :: head(:), next(:), base(:, :)
        !> B-spline weights and first/second t-derivatives, (order, 3, n).
        real(dp), allocatable :: w(:, :, :), d(:, :, :), s(:, :, :)
    end type
contains
    !> Choose (cutoff, alpha, mesh, order) for `particles` charges of equal
    !> magnitude, |c| q^2 = coupling, so that the estimated rms force error is
    !> <= tolerance*force_scale/2 (each part <= 1/sqrt(2) of it; the factor 2
    !> covers the unestimated mesh self force, measured 1.1-1.5x). Candidates:
    !> order 4/6/8 (or the given one), cutoff 2.5..8 Wigner-Seitz radii
    !> below L/2; alpha from the real-space estimate, the smallest 2-3-5
    !> smooth even mesh meeting the reciprocal estimate. Keeps the cheapest
    !> by the cost model 2 V + N(30 n 2pi/3 rc^3 + 4 p^3) + 12 K^3 log2 K [ns],
    !> V the visited candidate pairs (27-cell stencil, or N^2/2 all pairs).
    subroutine pme_select(length, particles, coupling, tolerance, p, ok, order, &
                          max_cutoff)
        real(dp), intent(in) :: length, coupling, tolerance
        integer, intent(in) :: particles
        type(pme_parameters_t), intent(out) :: p
        logical, intent(out) :: ok
        integer, intent(in), optional :: order
        !> Optional upper limit of the real-space cutoff (default L/2).
        real(dp), intent(in), optional :: max_cutoff
        real(dp), parameter :: multiples(9) = [2.5_dp, 3.0_dp, 3.5_dp, 4.0_dp, &
                                               4.5_dp, 5.0_dp, 6.0_dp, 7.0_dp, 8.0_dp]
        type(pme_parameters_t) :: trial
        real(dp) :: density, a, target, cost, best, arg
        integer :: io, im, lo, hi, mid, orders(3), no, cells
        real(dp) :: visited
        integer, allocatable :: meshes(:)

        ok = .false.
        if (.not. ieee_is_finite(length) .or. length <= 0) return
        if (particles < 2 .or. .not. (coupling > 0)) return
        if (.not. (tolerance > 1.0e-12_dp .and. tolerance < 1)) return
        orders = [4, 6, 8]; no = 3
        if (present(order)) then
            if (order /= 4 .and. order /= 6 .and. order /= 8) return
            orders(1) = order; no = 1
        end if
        meshes = smooth_meshes(8, 192)
        density = particles/length**3
        a = (3/(4*pi*density))**(1.0_dp/3)
        target = tolerance*coupling/a**2/(2*sqrt(2.0_dp))
        best = huge(1.0_dp)
        do io = 1, no
            do im = 1, size(multiples)
                trial%length = length; trial%order = orders(io)
                trial%tolerance = tolerance; trial%force_scale = coupling/a**2
                trial%cutoff = multiples(im)*a
                if (trial%cutoff >= length/2) exit
                if (present(max_cutoff)) then
                    if (trial%cutoff > max_cutoff) exit
                end if
                ! Kolafa-Perram: 2 |c| q^2 sqrt(n/rc) exp(-alpha^2 rc^2) <= target.
                arg = 2*coupling*sqrt(density/trial%cutoff)/target
                if (arg <= 1) cycle
                trial%alpha = sqrt(log(arg))/trial%cutoff
                ! Doubling in K from the guess K ~ alpha L (alpha h ~ 1), then
                ! bisection over the sorted list (the estimate decreases in K).
                lo = first_at_least(meshes, max(trial%order, nint(trial%alpha*length)))
                hi = lo
                do
                    trial%mesh = meshes(hi)
                    call pme_estimate(trial, particles, coupling, 1)
                    if (trial%reciprocal_estimate <= target .or. hi == size(meshes)) exit
                    lo = hi + 1; hi = first_at_least(meshes, 2*meshes(hi))
                end do
                if (trial%reciprocal_estimate > target) cycle
                do while (hi > lo)
                    mid = (lo + hi)/2
                    trial%mesh = meshes(mid)
                    call pme_estimate(trial, particles, coupling, 1)
                    if (trial%reciprocal_estimate <= target) then
                        hi = mid
                    else
                        lo = mid + 1
                    end if
                end do
                trial%mesh = meshes(hi)
                call pme_estimate(trial, particles, coupling)
                if (trial%reciprocal_estimate > target) cycle
                cells = int(length/trial%cutoff)
                visited = real(particles, dp)**2/2
                if (cells >= 3) visited = particles*density*13.5_dp*(length/cells)**3
                cost = 2*visited + particles*(30*density*two_pi/3*trial%cutoff**3 + &
                                              4*real(trial%order, dp)**3) + &
                       12*real(trial%mesh, dp)**3*log(real(trial%mesh, dp))/log(2.0_dp)
                if (cost < best) then
                    best = cost; p = trial; ok = .true.
                end if
            end do
        end do
    end subroutine

    integer function first_at_least(list, value) result(i)
        integer, intent(in) :: list(:), value
        do i = 1, size(list) - 1
            if (list(i) >= value) return
        end do
        i = size(list)
    end function

    !> Even meshes in [lo, hi] whose only prime factors are 2, 3 and 5.
    function smooth_meshes(lo, hi) result(list)
        integer, intent(in) :: lo, hi
        integer, allocatable :: list(:)
        integer :: k, r
        allocate (list(0))
        do k = lo, hi, 2
            r = k
            do while (mod(r, 2) == 0)
                r = r/2
            end do
            do while (mod(r, 3) == 0)
                r = r/3
            end do
            do while (mod(r, 5) == 0)
                r = r/5
            end do
            if (r == 1) list = [list, k]
        end do
    end function

    !> Estimated rms force errors of p for `particles` uncorrelated charges
    !> with |c| q^2 = coupling: real space (Kolafa-Perram) and reciprocal
    !> space c q^2 sqrt((N-1) Q_F), with the mean-square pair-force error
    !> Q_F = sum_k sum_M |k_M|^2 [G^2 U_M^2 A - 2 G U_M^2 R_M + R_M^2],
    !> A = sum_M U_M^2 (Parseval over the uniformly averaged pair positions).
    !> The mesh self force is not included (measured in the tests).
    !> `alias` (default 2) limits the alias range of the sums; the
    !> selection search uses 1 and confirms the final mesh with 2.
    subroutine pme_estimate(p, particles, coupling, alias)
        type(pme_parameters_t), intent(inout) :: p
        integer, intent(in) :: particles
        real(dp), intent(in) :: coupling
        integer, intent(in), optional :: alias
        real(dp) :: qf, volume
        volume = p%length**3
        p%real_estimate = 2*coupling*sqrt(particles/(p%cutoff*volume))* &
                          exp(-(p%alpha*p%cutoff)**2)
        if (present(alias)) then
            call influence_sums(p, qf, alias=alias)
        else
            call influence_sums(p, qf)
        end if
        p%reciprocal_estimate = coupling*sqrt(max(0.0_dp, (particles - 1)*qf))
    end subroutine

    !> Alias sums over the octant |n_a| <= K/2 (G is even in each n_a):
    !> fills the influence function when `influence` is present and returns
    !> the reciprocal mean-square pair-force error functional qf.
    subroutine influence_sums(p, qf, influence, mesh_self, alias)
        type(pme_parameters_t), intent(in) :: p
        real(dp), intent(out) :: qf
        real(dp), intent(inout), optional :: influence(0:, 0:, 0:)
        real(dp), intent(out), optional :: mesh_self
        integer, intent(in), optional :: alias
        integer :: k, n(3), half, a, b, c, mult, m1, m2, m3, aliases
        real(dp) :: volume, k2, num, den, u2, r, s1, s2, s3, g, x
        real(dp), allocatable :: factor(:, :), kc(:, :)
        k = p%mesh; half = k/2; volume = p%length**3
        aliases = max_alias
        if (present(alias)) aliases = alias
        ! Axis tables: wave number and assignment factor sinc^(2p) of alias m.
        allocate (factor(0:half, -aliases:aliases), kc(0:half, -aliases:aliases))
        do m1 = -aliases, aliases
            do a = 0, half
                kc(a, m1) = two_pi*(a + m1*k)/p%length
                x = pi*real(a + m1*k, dp)/k
                factor(a, m1) = 1
                if (abs(x) > 0) call pme_assignment_factor(x, real(p%order, dp), &
                                                           factor(a, m1))
            end do
        end do
        qf = 0
        if (present(mesh_self)) mesh_self = 0
        do c = 0, half
            do b = 0, half
                do a = 0, half
                    n = [a, b, c]
                    num = 0; den = 0; s1 = 0; s2 = 0; s3 = 0
                    do m3 = -aliases, aliases
                        do m2 = -aliases, aliases
                            do m1 = -aliases, aliases
                                u2 = factor(a, m1)*factor(b, m2)*factor(c, m3)
                                k2 = kc(a, m1)**2 + kc(b, m2)**2 + kc(c, m3)**2
                                den = den + u2
                                if (k2 <= 0) cycle
                                call ewald_reciprocal_weight(k2, p%alpha, volume, &
                                                             1.0_dp, r)
                                num = num + u2*r
                                s1 = s1 + k2*u2; s2 = s2 + k2*u2*r; s3 = s3 + k2*r*r
                            end do
                        end do
                    end do
                    g = 0
                    if (any(n /= 0)) g = num/den**2
                    mult = product(merge(1, 2, n == 0 .or. n == half))
                    qf = qf + mult*(g*g*s1*den - 2*g*s2 + s3)
                    if (present(mesh_self)) mesh_self = mesh_self + mult*g*den
                    if (present(influence)) call fill_octant(influence, n, k, g)
                end do
            end do
        end do
    end subroutine

    subroutine fill_octant(influence, n, k, g)
        real(dp), intent(inout) :: influence(0:, 0:, 0:)
        integer, intent(in) :: n(3), k
        real(dp), intent(in) :: g
        integer :: sx, sy, sz
        do sz = -1, 1, 2
            do sy = -1, 1, 2
                do sx = -1, 1, 2
                    influence(modulo(sx*n(1), k), modulo(sy*n(2), k), &
                              modulo(sz*n(3), k)) = g
                end do
            end do
        end do
    end subroutine


    !> Allocate all scratch for n charges once and build the influence
    !> function; the force/tangent evaluations then never allocate.
    subroutine pme_setup(pme, p, n, ok)
        type(pme_t), intent(out) :: pme
        type(pme_parameters_t), intent(in) :: p
        integer, intent(in) :: n
        logical, intent(out) :: ok
        real(dp) :: qf, mesh_self
        integer :: k
        ok = .false.
        if (n < 1 .or. .not. (p%length > 0) .or. .not. (p%alpha > 0)) return
        if (.not. (p%cutoff > 0) .or. p%cutoff >= p%length/2) return
        if (p%order /= 4 .and. p%order /= 6 .and. p%order /= 8) return
        k = p%mesh
        if (k < p%order .or. mod(k, 2) /= 0) return
        pme%p = p; pme%n = n; pme%h = p%length/k
        pme%cells = int(p%length/p%cutoff)
        if (pme%cells < 3) pme%cells = 0
        allocate (pme%influence(0:k - 1, 0:k - 1, 0:k - 1))
        allocate (pme%grid(0:k - 1, 0:k - 1, 0:k - 1), pme%dgrid(0:k - 1, 0:k - 1, 0:k - 1))
        allocate (pme%line(0:k - 1), pme%head(max(1, pme%cells**3)), pme%next(n))
        allocate (pme%base(3, n), pme%w(p%order, 3, n), pme%d(p%order, 3, n))
        allocate (pme%s(p%order, 3, n))
        call fft_c2c_plan_init(pme%plan, k)
        call influence_sums(p, qf, pme%influence, mesh_self)
        pme%self_shift = (reciprocal_self(p) - mesh_self)/2
        ok = all(ieee_is_finite(pme%influence)) .and. ieee_is_finite(pme%self_shift)
    end subroutine

    !> sum_{k/=0} R(k) over the full reciprocal lattice (octant with
    !> multiplicity), truncated where exp(-k^2/(4 alpha^2)) < 1e-17.
    real(dp) function reciprocal_self(p) result(total)
        type(pme_parameters_t), intent(in) :: p
        integer :: a, b, c, top
        real(dp) :: r, volume
        volume = p%length**3
        top = ceiling(2.0_dp*p%alpha*p%length)
        total = 0
        do c = 0, top
            do b = 0, top
                do a = 0, top
                    if (a == 0 .and. b == 0 .and. c == 0) cycle
                    call ewald_reciprocal_weight((two_pi/p%length)**2* &
                        real(a*a + b*b + c*c, dp), p%alpha, volume, 1.0_dp, r)
                    total = total + product(merge(1, 2, [a, b, c] == 0))*r
                end do
            end do
        end do
    end function

    !> Configuration-independent energy: Gaussian self terms, the mean mesh
    !> self-energy defect and the neutralizing background (self images lie
    !> beyond cutoff < L/2).
    real(dp) function pme_constant(pme, coulomb, charge) result(u)
        type(pme_t), intent(in) :: pme
        real(dp), intent(in) :: coulomb, charge(:)
        real(dp) :: t
        integer :: i
        u = 0
        do i = 1, size(charge)
            call ewald_self(pme%p%alpha, coulomb*charge(i)**2, t)
            u = u + t + pme%self_shift*coulomb*charge(i)**2
        end do
        call ewald_background(pme%p%alpha, pme%p%length**3, coulomb*sum(charge)**2, t)
        u = u + t/2
    end function

    !> Add the real-space and mesh forces/energy of positions x(3n).
    subroutine pme_force(pme, coulomb, charge, x, force, potential, ok, far)
        type(pme_t), intent(inout) :: pme
        real(dp), intent(in) :: coulomb, charge(:), x(:)
        real(dp), intent(inout) :: force(:), potential
        logical, intent(out) :: ok
        !> Far part only (requires an active split).
        logical, intent(in), optional :: far
        call real_space(pme, coulomb, charge, x, force, potential, ok, far=far)
        if (.not. ok) return
        call mesh_potential(pme, coulomb, charge, x, potential)
        call gather(pme, charge, force)
    end subroutine

    !> Add the force tangent dF = (dF/dx) dx (real space and mesh).
    subroutine pme_force_jvp(pme, coulomb, charge, x, dx, dforce, ok, far)
        type(pme_t), intent(inout) :: pme
        real(dp), intent(in) :: coulomb, charge(:), x(:), dx(:)
        real(dp), intent(inout) :: dforce(:)
        logical, intent(out) :: ok
        logical, intent(in), optional :: far
        real(dp) :: unused
        unused = 0
        call real_space(pme, coulomb, charge, x, dforce, unused, ok, dx, far)
        if (.not. ok) return
        call mesh_potential(pme, coulomb, charge, x, unused)
        call mesh_tangent(pme, coulomb, charge, dx)
        call gather_tangent(pme, charge, dx, dforce)
    end subroutine

    !> Minimum-image pairs with r < cutoff from a linked cell list (cells of
    !> edge >= cutoff, 27-cell stencil, each unordered cell pair once); with
    !> fewer than 3 cells per edge, a tiled all-pairs loop. With dx present
    !> accumulate the force tangent into out instead of the force.
    subroutine real_space(pme, coulomb, charge, x, out, potential, ok, dx, far)
        type(pme_t), intent(inout) :: pme
        real(dp), intent(in) :: coulomb, charge(:), x(:)
        real(dp), intent(inout) :: out(:), potential
        logical, intent(out) :: ok
        real(dp), intent(in), optional :: dx(:)
        logical, intent(in), optional :: far
        integer, parameter :: tile = 64
        integer :: nc, i, j, c, c2, cx, cy, cz, ox, oy, oz, ib, jb
        real(dp) :: length, rc2
        logical :: tangent, split
        ok = .true.; tangent = present(dx)
        split = .false.
        if (present(far)) split = far .and. pme%split%active
        length = pme%p%length; rc2 = pme%p%cutoff**2; nc = pme%cells
        if (nc == 0) then
            do ib = 1, pme%n, tile
                do jb = ib, pme%n, tile
                    do i = ib, min(pme%n, ib + tile - 1)
                        do j = max(jb, i + 1), min(pme%n, jb + tile - 1)
                            call visit(i, j)
                            if (.not. ok) return
                        end do
                    end do
                end do
            end do
            return
        end if
        pme%head = 0
        do i = 1, pme%n
            c = cell_index(x(3*i - 2:3*i))
            pme%next(i) = pme%head(c); pme%head(c) = i
        end do
        do cz = 0, nc - 1
            do cy = 0, nc - 1
                do cx = 0, nc - 1
                    c = 1 + cx + nc*(cy + nc*cz)
                    do oz = -1, 1
                        do oy = -1, 1
                            do ox = -1, 1
                                c2 = 1 + modulo(cx + ox, nc) + nc*(modulo(cy + oy, nc) + &
                                     nc*modulo(cz + oz, nc))
                                if (c2 < c) cycle
                                i = pme%head(c)
                                do while (i > 0)
                                    j = pme%head(c2)
                                    if (c2 == c) j = pme%next(i)
                                    do while (j > 0)
                                        call visit(i, j)
                                        if (.not. ok) return
                                        j = pme%next(j)
                                    end do
                                    i = pme%next(i)
                                end do
                            end do
                        end do
                    end do
                end do
            end do
        end do
    contains
        integer function cell_index(p) result(c)
            real(dp), intent(in) :: p(3)
            integer :: q(3), a
            do a = 1, 3
                q(a) = min(nc - 1, int((p(a)/length - floor(p(a)/length))*nc))
            end do
            c = 1 + q(1) + nc*(q(2) + nc*q(3))
        end function

        subroutine visit(i, j)
            integer, intent(in) :: i, j
            real(dp) :: d(3), dd(3), f(3), u, g, du, fn(3), un
            integer :: a
            do a = 1, 3
                d(a) = x(3*i - 3 + a) - x(3*j - 3 + a)
                d(a) = d(a) - length*anint(d(a)/length)
            end do
            if (d(1)*d(1) + d(2)*d(2) + d(3)*d(3) >= rc2) return
            if (maxval(abs(d)) <= 0) then
                ok = .false.; return
            end if
            g = coulomb*charge(i)*charge(j)
            if (tangent) then
                dd = dx(3*i - 2:3*i) - dx(3*j - 2:3*j)
                call ewald_real_pair_jvp(d(1), d(2), d(3), pme%p%alpha, g, dd(1), &
                    dd(2), dd(3), 0.0_dp, 0.0_dp, f(1), f(2), f(3), du)
                if (split) then
                    call near_pair_jvp(pme%split, d, pme%p%alpha, g, dd, fn)
                    f = f - fn
                end if
            else
                call ewald_real_pair(d(1), d(2), d(3), pme%p%alpha, g, &
                                     f(1), f(2), f(3), u)
                if (split) then
                    call near_pair(pme%split, d, pme%p%alpha, g, fn, un)
                    f = f - fn; u = u - un
                end if
                potential = potential + u
            end if
            out(3*i - 2:3*i) = out(3*i - 2:3*i) + f
            out(3*j - 2:3*j) = out(3*j - 2:3*j) - f
        end subroutine
    end subroutine

    !> Spread charges with B-spline weights (cached per particle), transform,
    !> add the mesh energy (1/2) sum_k c G |Q(k)|^2 and leave the mesh
    !> potential Phi = IDFT(c G Q) (unnormalized inverse) in pme%grid.
    subroutine mesh_potential(pme, coulomb, charge, x, potential)
        type(pme_t), intent(inout) :: pme
        real(dp), intent(in) :: coulomb, charge(:), x(:)
        real(dp), intent(inout) :: potential
        integer :: i, a, b, k, j1, j2, j3, m1, m2, m3, p
        real(dp) :: u, t, q3, q2, e
        k = pme%p%mesh; p = pme%p%order
        do i = 1, pme%n
            do a = 1, 3
                u = x(3*i - 3 + a)/pme%h
                u = u - k*floor(u/k)
                b = min(k - 1, int(u)); t = u - b
                pme%base(a, i) = b
                call weights(p, t, pme%w(:, a, i), pme%d(:, a, i), pme%s(:, a, i))
            end do
        end do
        pme%grid = (0.0_dp, 0.0_dp)
        do i = 1, pme%n
            do j3 = 1, p
                m3 = modulo(pme%base(3, i) - j3 + 1, k)
                q3 = charge(i)*pme%w(j3, 3, i)
                do j2 = 1, p
                    m2 = modulo(pme%base(2, i) - j2 + 1, k)
                    q2 = q3*pme%w(j2, 2, i)
                    do j1 = 1, p
                        m1 = modulo(pme%base(1, i) - j1 + 1, k)
                        pme%grid(m1, m2, m3) = pme%grid(m1, m2, m3) + q2*pme%w(j1, 1, i)
                    end do
                end do
            end do
        end do
        call fft3(pme, pme%grid, -1)
        e = 0
        do m3 = 0, k - 1
            do m2 = 0, k - 1
                do m1 = 0, k - 1
                    e = e + pme%influence(m1, m2, m3)*(real(pme%grid(m1, m2, m3))**2 + &
                                                       aimag(pme%grid(m1, m2, m3))**2)
                    pme%grid(m1, m2, m3) = coulomb*pme%influence(m1, m2, m3)* &
                                           pme%grid(m1, m2, m3)
                end do
            end do
        end do
        potential = potential + coulomb*e/2
        call fft3(pme, pme%grid, 1)
    end subroutine

    !> F_i = -(q_i/h) sum_m grad_u W(m; x_i) Phi(m): exact gradient of the
    !> mesh energy.
    subroutine gather(pme, charge, force)
        type(pme_t), intent(in) :: pme
        real(dp), intent(in) :: charge(:)
        real(dp), intent(inout) :: force(:)
        integer :: i, j1, j2, j3, m1, m2, m3, k, p
        real(dp) :: f(3), phi, w1, w2, w3, d1, d2, d3
        k = pme%p%mesh; p = pme%p%order
        do i = 1, pme%n
            f = 0
            do j3 = 1, p
                m3 = modulo(pme%base(3, i) - j3 + 1, k)
                w3 = pme%w(j3, 3, i); d3 = pme%d(j3, 3, i)
                do j2 = 1, p
                    m2 = modulo(pme%base(2, i) - j2 + 1, k)
                    w2 = pme%w(j2, 2, i); d2 = pme%d(j2, 2, i)
                    do j1 = 1, p
                        m1 = modulo(pme%base(1, i) - j1 + 1, k)
                        w1 = pme%w(j1, 1, i); d1 = pme%d(j1, 1, i)
                        phi = real(pme%grid(m1, m2, m3))
                        f(1) = f(1) + d1*w2*w3*phi
                        f(2) = f(2) + w1*d2*w3*phi
                        f(3) = f(3) + w1*w2*d3*phi
                    end do
                end do
            end do
            force(3*i - 2:3*i) = force(3*i - 2:3*i) - charge(i)/pme%h*f
        end do
    end subroutine

    !> dPhi = IDFT(c G DFT(dQ)) in pme%dgrid, with the dipole spread
    !> dQ(m) = sum_j q_j grad_u W(m; x_j).dx_j/h (weights cached by
    !> mesh_potential at the same positions).
    subroutine mesh_tangent(pme, coulomb, charge, dx)
        type(pme_t), intent(inout) :: pme
        real(dp), intent(in) :: coulomb, charge(:), dx(:)
        integer :: i, j1, j2, j3, m1, m2, m3, k, p
        real(dp) :: e(3), w1, w2, w3, d1, d2, d3
        k = pme%p%mesh; p = pme%p%order
        pme%dgrid = (0.0_dp, 0.0_dp)
        do i = 1, pme%n
            e = charge(i)*dx(3*i - 2:3*i)/pme%h
            do j3 = 1, p
                m3 = modulo(pme%base(3, i) - j3 + 1, k)
                w3 = pme%w(j3, 3, i); d3 = pme%d(j3, 3, i)
                do j2 = 1, p
                    m2 = modulo(pme%base(2, i) - j2 + 1, k)
                    w2 = pme%w(j2, 2, i); d2 = pme%d(j2, 2, i)
                    do j1 = 1, p
                        m1 = modulo(pme%base(1, i) - j1 + 1, k)
                        w1 = pme%w(j1, 1, i); d1 = pme%d(j1, 1, i)
                        pme%dgrid(m1, m2, m3) = pme%dgrid(m1, m2, m3) + &
                            (d1*w2*w3*e(1) + w1*d2*w3*e(2) + w1*w2*d3*e(3))
                    end do
                end do
            end do
        end do
        call fft3(pme, pme%dgrid, -1)
        pme%dgrid = coulomb*pme%influence*pme%dgrid
        call fft3(pme, pme%dgrid, 1)
    end subroutine

    !> dF_i,a = -(q_i/h) sum_m [sum_b W_ab dx_ib/h Phi + W_a dPhi].
    subroutine gather_tangent(pme, charge, dx, dforce)
        type(pme_t), intent(in) :: pme
        real(dp), intent(in) :: charge(:), dx(:)
        real(dp), intent(inout) :: dforce(:)
        integer :: i, j1, j2, j3, m1, m2, m3, k, p
        real(dp) :: f(3), e(3), phi, dphi, w1, w2, w3, d1, d2, d3, s1, s2, s3
        k = pme%p%mesh; p = pme%p%order
        do i = 1, pme%n
            f = 0
            e = dx(3*i - 2:3*i)/pme%h
            do j3 = 1, p
                m3 = modulo(pme%base(3, i) - j3 + 1, k)
                w3 = pme%w(j3, 3, i); d3 = pme%d(j3, 3, i); s3 = pme%s(j3, 3, i)
                do j2 = 1, p
                    m2 = modulo(pme%base(2, i) - j2 + 1, k)
                    w2 = pme%w(j2, 2, i); d2 = pme%d(j2, 2, i); s2 = pme%s(j2, 2, i)
                    do j1 = 1, p
                        m1 = modulo(pme%base(1, i) - j1 + 1, k)
                        w1 = pme%w(j1, 1, i); d1 = pme%d(j1, 1, i); s1 = pme%s(j1, 1, i)
                        phi = real(pme%grid(m1, m2, m3))
                        dphi = real(pme%dgrid(m1, m2, m3))
                        f(1) = f(1) + (s1*w2*w3*e(1) + d1*d2*w3*e(2) + d1*w2*d3*e(3))*phi &
                               + d1*w2*w3*dphi
                        f(2) = f(2) + (d1*d2*w3*e(1) + w1*s2*w3*e(2) + w1*d2*d3*e(3))*phi &
                               + w1*d2*w3*dphi
                        f(3) = f(3) + (d1*w2*d3*e(1) + w1*d2*d3*e(2) + w1*w2*s3*e(3))*phi &
                               + w1*w2*d3*dphi
                    end do
                end do
            end do
            dforce(3*i - 2:3*i) = dforce(3*i - 2:3*i) - charge(i)/pme%h*f
        end do
    end subroutine

    !> In-place 3D DFT by 1D FortNum transforms along x (contiguous), y, z.
    subroutine fft3(pme, a, sign)
        type(pme_t), intent(inout) :: pme
        complex(dp), intent(inout) :: a(0:, 0:, 0:)
        integer, intent(in) :: sign
        integer :: i, j, k
        k = pme%p%mesh
        do j = 0, k - 1
            do i = 0, k - 1
                call fft_c2c(a(:, i, j), sign, pme%plan)
            end do
        end do
        do j = 0, k - 1
            do i = 0, k - 1
                pme%line = a(i, :, j)
                call fft_c2c(pme%line, sign, pme%plan)
                a(i, :, j) = pme%line
            end do
        end do
        do j = 0, k - 1
            do i = 0, k - 1
                pme%line = a(i, j, :)
                call fft_c2c(pme%line, sign, pme%plan)
                a(i, j, :) = pme%line
            end do
        end do
    end subroutine

    subroutine weights(p, t, w, d, s)
        integer, intent(in) :: p
        real(dp), intent(in) :: t
        real(dp), intent(out) :: w(:), d(:), s(:)
        select case (p)
        case (4)
            call pme_bspline4(t, w(1), w(2), w(3), w(4), d(1), d(2), d(3), d(4), &
                              s(1), s(2), s(3), s(4))
        case (6)
            call pme_bspline6(t, w(1), w(2), w(3), w(4), w(5), w(6), d(1), d(2), &
                d(3), d(4), d(5), d(6), s(1), s(2), s(3), s(4), s(5), s(6))
        case default
            call pme_bspline8(t, w(1), w(2), w(3), w(4), w(5), w(6), w(7), w(8), &
                d(1), d(2), d(3), d(4), d(5), d(6), d(7), d(8), s(1), s(2), s(3), &
                s(4), s(5), s(6), s(7), s(8))
        end select
    end subroutine
end module kin6d_pme
