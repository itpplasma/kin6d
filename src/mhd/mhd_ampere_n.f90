module kin6d_mhd_ampere_n
    !! L4 (first stage): per-n Ampere operator of a plasma-response field with
    !! the exact exterior.
    !!
    !! Field.  A response field B e^{i n phi} (n /= 0) is generated by a
    !! current J e^{i n phi} supported in the meridional domain Omega (the
    !! plasma, bounded by the curve Gamma).  Inside, B = curl_n A with A in
    !! the V1 space of fortfem_meridian_feec_n; outside, B = grad_n u with
    !! L_n u = 0 and u decaying.  Coils outside Gamma do not enter: the
    !! coil field is added to the response field by the caller.
    !!
    !! Gauge.  For n /= 0 every A is gauge equivalent to one with
    !! a = R A_phi = 0 (A -> A - grad_n(a/(i n)), a in V0), so the unknown is
    !! the Nedelec part A_pol alone, as in Albert, Lainer and Biro,
    !! Comput. Phys. Commun. 277 (2022) 108401, Eq. (37), and in MEPHIT.  The
    !! curl-curl form is then positive definite.  Restricting the test space
    !! to a' = 0 drops the R A'_phi equation, which is implied when the
    !! current is discretely divergence free (it is the A_pol equation tested
    !! with grad a'/(i n)).
    !!
    !! Weak form (derivation in fortfem_meridian_magnetic_coupling):
    !!
    !!     (curl_n A', curl_n A)_M2 + <C A', S^{-1} C A> = mu0 (A', J),
    !!
    !! with C = C2 curl_n the normal flux R B.n paired with the P2 traces of
    !! the boundary curve, S the symmetric Galerkin Steklov-Poincare map of
    !! L_n (fortfem_toroidal_mode_boundary_operators_2d).  The exterior
    !! potential trace is u = -S^{-1} C A.  The Schur block is dense on the
    !! boundary Nedelec dofs; the operator is Hermitian positive definite and
    !! factored once per (mesh, n).  With MUMPS (fortsparse, KIN6D_ENABLE_MUMPS)
    !! the Hermitian H = A + i B is factored as its real symmetric positive
    !! definite equivalent [[A, -B], [B, A]] by nested-dissection Cholesky
    !! (the fortsparse MUMPS backend is real); otherwise by complex SuperLU.
    !!
    !! Units.  SI; A in T m, B in T, J in A/m^2.  Inner products carry the
    !! measure R dR dZ (the 2 pi of the phi integral is dropped throughout).
    !! Complex amplitudes follow kin6d_coils_3d: a field X(R, Z) e^{i n phi}
    !! stands for the physical field X e^{i n phi} + c.c.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use, intrinsic :: ieee_arithmetic, only: ieee_is_finite
    use fortfem_meridian_feec_n, only: meridian_feec_t, meridian_op_complex, &
        meridian_stiffness, meridian_point_basis_t, meridian_point_basis_init, &
        meridian_point_basis, meridian_zcsc_matmul, meridian_field_i
    use fortfem_equilibrated_hcurl_meridian_n, only: &
        meridian_hcurl_estimate_t, meridian_hcurl_equilibrated_bound, HCURL_OK
    use fortfem_meridian_magnetic_coupling, only: meridian_boundary_t, &
        meridian_boundary_build, meridian_flux_pairing
    use fortfem_axisymmetric_gs_boundary_operators_2d, only: gs_bem_operators_t
    use fortfem_toroidal_mode_boundary_operators_2d, only: tm_bem_assemble, &
        tm_bem_steklov_symmetric, tm_bem_neumann_to_dirichlet
    use fortsparse, only: csc_t, csc_z_t, csc_from_triplet, csc_matvec, &
        csc_conjugate_transpose, fortsparse_status_t, status_ok, &
        sparse_solver_t, sparse_factor, sparse_solve, sparse_destroy
    use kin6d_gs_direct, only: gs_direct_t, gs_direct_available, &
        gs_direct_factor, gs_direct_solve, gs_direct_free
    implicit none
    private

    real(dp), parameter, public :: mu0 = 4.0e-7_dp*3.14159265358979323846_dp

    type, public :: ampere_n_error_t
        !! Ordinary-arithmetic diagnostics, never a continuous certificate.
        !! The coupled discrete norm includes the exterior Steklov energy;
        !! the equilibrated reconstruction covers a different problem with
        !! the candidate's tangential trace fixed. Its missing exterior
        !! remainder is explicit and is never silently set to zero.
        real(dp) :: discrete_energy_error = huge(1.0_dp)
        real(dp) :: residual_norm = huge(1.0_dp)
        type(meridian_hcurl_estimate_t) :: interior
        integer :: discrete_status = -1
        integer :: interior_status = -1
        character(len=32) :: discrete_claim = 'unavailable'
        character(len=32) :: interior_claim = 'unavailable'
        character(len=32) :: continuous_claim = 'unavailable-exterior-remainder'
        character(len=32) :: derivative_claim = 'unavailable'
        logical :: exterior_remainder_available = .false.
    end type ampere_n_error_t

    type, public :: ampere_n_t
        integer :: n = 0
        integer :: nn = 0          !! Nedelec dofs (unknowns)
        integer :: n2 = 0          !! V2 dofs
        integer :: ntr = 0         !! P2 boundary trace dofs
        type(meridian_boundary_t) :: bd
        type(csc_z_t) :: matrix    !! full coupled operator for residual checks
        type(ampere_n_error_t) :: error
        type(csc_z_t) :: curl      !! V2 <- Nedelec, curl_n in the gauge a = 0
        integer, allocatable :: bdof(:)          !! boundary Nedelec dofs
        complex(dp), allocatable :: cb(:, :)     !! C on bdof, (ntr, nbe)
        real(dp), allocatable :: sinv(:, :)      !! S^{-1}, (ntr, ntr)
        type(sparse_solver_t) :: solver
        type(gs_direct_t) :: direct      !! MUMPS Cholesky of the real form
        logical :: use_direct = .false.
        logical :: factored = .false.
    end type ampere_n_t

    public :: ampere_n_build
    public :: ampere_n_error, ampere_n_equilibrated_error
    public :: ampere_n_solve
    public :: ampere_n_curl
    public :: ampere_n_trace
    public :: ampere_n_free
    public :: ampere_n_field_point

contains

    subroutine ampere_n_build(fs, n, amp, status)
        type(meridian_feec_t), intent(in) :: fs
        integer, intent(in) :: n
        type(ampere_n_t), intent(inout) :: amp
        integer, intent(out) :: status

        type(csc_z_t) :: zfull, kfull, c2, cfull
        type(gs_bem_operators_t) :: ops
        type(fortsparse_status_t) :: fst
        integer, allocatable :: rows(:), cols(:), loc(:)
        real(dp), allocatable :: vals(:), s(:, :)
        complex(dp), allocatable :: zv(:), d(:, :)
        integer :: nn, j, p, cnt, nbe, i, st, total

        status = 1
        if (n == 0) return
        call ampere_n_free(amp)
        amp%n = n
        nn = fs%nn
        amp%nn = nn
        amp%n2 = fs%sp(2)%ndof

        ! curl_n restricted to the Nedelec columns
        call meridian_op_complex(fs%curl, n, zfull, st)
        if (st /= 0) return
        call leading_columns(zfull, nn, amp%curl, st)
        if (st /= 0) return

        ! boundary chain, normal-flux pairing, C = C2 curl
        call meridian_boundary_build(fs, amp%bd, st)
        if (st /= 0) return
        call meridian_flux_pairing(fs, amp%bd, rows, cols, vals, st)
        if (st /= 0) return
        amp%ntr = 2*amp%bd%n_panels
        allocate (zv(size(vals)))
        zv = cmplx(vals, 0.0_dp, dp)
        call csc_from_triplet(amp%ntr, amp%n2, rows, cols, zv, c2, fst)
        if (.not. status_ok(fst)) return
        call meridian_zcsc_matmul(c2, amp%curl, cfull, st)
        if (st /= 0) return
        allocate (loc(nn))
        loc = 0
        nbe = 0
        do j = 1, nn
            if (cfull%col_ptr(j + 1) > cfull%col_ptr(j)) then
                nbe = nbe + 1
                loc(j) = nbe
            end if
        end do
        allocate (amp%bdof(nbe), amp%cb(amp%ntr, nbe))
        amp%cb = (0.0_dp, 0.0_dp)
        do j = 1, nn
            if (loc(j) == 0) cycle
            amp%bdof(loc(j)) = j
            do p = cfull%col_ptr(j), cfull%col_ptr(j + 1) - 1
                amp%cb(cfull%row_idx(p), loc(j)) = cfull%val(p)
            end do
        end do

        ! exterior Steklov-Poincare map and its inverse
        call tm_bem_assemble(amp%bd%curve, n, 1, ops, st)
        if (st /= 0) return
        call tm_bem_steklov_symmetric(ops, s, st)
        if (st /= 0) return
        call tm_bem_neumann_to_dirichlet(s, amp%sinv, st)
        if (st /= 0) return

        ! K + C^H S^{-1} C
        d = matmul(conjg(transpose(amp%cb)), &
            matmul(cmplx(amp%sinv, 0.0_dp, dp), amp%cb))
        call meridian_stiffness(fs, 1, n, kfull, st)
        if (st /= 0) return
        total = kfull%nnz + nbe*nbe
        deallocate (rows, cols)
        allocate (rows(total), cols(total))
        deallocate (zv)
        allocate (zv(total))
        cnt = 0
        do j = 1, nn
            do p = kfull%col_ptr(j), kfull%col_ptr(j + 1) - 1
                if (kfull%row_idx(p) > nn) cycle
                cnt = cnt + 1
                rows(cnt) = kfull%row_idx(p)
                cols(cnt) = j
                zv(cnt) = kfull%val(p)
            end do
        end do
        do j = 1, nbe
            do i = 1, nbe
                cnt = cnt + 1
                rows(cnt) = amp%bdof(i)
                cols(cnt) = amp%bdof(j)
                zv(cnt) = d(i, j)
            end do
        end do
        call csc_from_triplet(nn, nn, rows(1:cnt), cols(1:cnt), zv(1:cnt), &
            kfull, fst)
        if (.not. status_ok(fst)) return
        amp%matrix = kfull
        if (gs_direct_available()) then
            call factor_real_form(kfull, amp, st)
            if (st /= 0) return
            amp%use_direct = .true.
        else
            call sparse_factor(amp%solver, kfull, fst)
            if (.not. status_ok(fst)) return
        end if
        amp%factored = .true.
        status = 0
    end subroutine ampere_n_build

    subroutine factor_real_form(h, amp, status)
        !! MUMPS Cholesky of [[A, -B], [B, A]] for H = A + i B (Hermitian
        !! positive definite, so the real form is symmetric positive
        !! definite; its CSC is its CSR).
        type(csc_z_t), intent(in) :: h
        type(ampere_n_t), intent(inout) :: amp
        integer, intent(out) :: status
        type(csc_t) :: m
        type(fortsparse_status_t) :: fst
        integer, allocatable :: rows(:), cols(:)
        real(dp), allocatable :: vals(:)
        integer :: n, j, p, c, i
        logical :: ok

        status = 1
        n = h%ncol
        allocate (rows(4*h%nnz), cols(4*h%nnz), vals(4*h%nnz))
        c = 0
        do j = 1, n
            do p = h%col_ptr(j), h%col_ptr(j + 1) - 1
                i = h%row_idx(p)
                rows(c + 1:c + 4) = [i, i, n + i, n + i]
                cols(c + 1:c + 4) = [j, n + j, j, n + j]
                vals(c + 1:c + 4) = [real(h%val(p), dp), -aimag(h%val(p)), &
                    aimag(h%val(p)), real(h%val(p), dp)]
                c = c + 4
            end do
        end do
        call csc_from_triplet(2*n, 2*n, rows, cols, vals, m, fst)
        if (.not. status_ok(fst)) return
        call gs_direct_factor(amp%direct, 2*n, m%col_ptr, m%row_idx, m%val, ok)
        if (ok) status = 0
    end subroutine factor_real_form

    subroutine leading_columns(a, nc, b, status)
        !! b = a(:, 1:nc).
        type(csc_z_t), intent(in) :: a
        integer, intent(in) :: nc
        type(csc_z_t), intent(out) :: b
        integer, intent(out) :: status
        integer :: nz

        status = 1
        if (nc > a%ncol) return
        nz = a%col_ptr(nc + 1) - 1
        b%nrow = a%nrow
        b%ncol = nc
        b%nnz = nz
        b%col_ptr = a%col_ptr(1:nc + 1)
        b%row_idx = a%row_idx(1:nz)
        b%val = a%val(1:nz)
        status = 0
    end subroutine leading_columns

    subroutine ampere_n_solve(amp, f, a, status, fs, fsd, current)
        !! Solve the coupled equation. Every result carries a discrete
        !! residual/energy diagnostic and explicit continuous-error status.
        !! Optional fs, fsd and current enable the fixed-trace interior
        !! reconstruction; current is already mu0-scaled, in T/m. The callback
        !! must be thread safe; fs must be the space used to build amp.
        !! This does not certify the exterior problem.
        type(ampere_n_t), intent(inout) :: amp
        complex(dp), intent(in) :: f(:)
        complex(dp), intent(out) :: a(:)
        integer, intent(out) :: status
        type(meridian_feec_t), intent(in), optional :: fs, fsd
        procedure(meridian_field_i), optional :: current
        integer :: st
        type(ampere_n_error_t) :: estimate

        amp%error = ampere_n_error_t()
        call solve_factored(amp, f, a, status)
        if (status /= 0) return
        call ampere_n_error(amp, f, a, estimate, st)
        estimate%discrete_status = st
        amp%error = estimate
        ! Failure of a diagnostic does not invalidate the candidate solve.
        if (.not. present(fs)) return
        if (.not. present(fsd)) return
        if (.not. present(current)) return
        call ampere_n_equilibrated_error(fs, fsd, amp, a, current, estimate, st)
        amp%error = estimate
    end subroutine ampere_n_solve

    subroutine solve_factored(amp, f, a, status)
        type(ampere_n_t), intent(inout) :: amp
        complex(dp), intent(in) :: f(:)
        complex(dp), intent(out) :: a(:)
        integer, intent(out) :: status
        type(fortsparse_status_t) :: fst
        real(dp), allocatable :: fr(:), xr(:)
        integer :: n
        logical :: ok

        status = 1
        if (.not. amp%factored) return
        if (size(f) /= amp%nn .or. size(a) /= amp%nn) return
        if (amp%use_direct) then
            n = size(f)
            allocate (fr(2*n), xr(2*n))
            fr(1:n) = real(f, dp)
            fr(n + 1:) = aimag(f)
            call gs_direct_solve(amp%direct, fr, xr, ok)
            if (.not. ok) return
            a = cmplx(xr(1:n), xr(n + 1:), dp)
            status = 0
            return
        end if
        call sparse_solve(amp%solver, f, a, fst)
        if (status_ok(fst)) status = 0
    end subroutine solve_factored

    subroutine ampere_n_error(amp, f, a, estimate, status)
        !! Residual dual norm sqrt(real(r^H K^-1 r)) for the full coupled
        !! discrete equation K a = f. An equation-level correction solve is
        !! independent of the candidate algorithm and includes C^H S^-1 C.
        !! Rounding/factorization errors are not enclosed: this is an
        !! indicator, not a rigorous finite-dimensional certificate.
        type(ampere_n_t), intent(inout) :: amp
        complex(dp), intent(in) :: f(:), a(:)
        type(ampere_n_error_t), intent(out) :: estimate
        integer, intent(out) :: status
        complex(dp), allocatable :: residual(:), correction(:)
        real(dp) :: energy

        estimate = ampere_n_error_t()
        estimate%discrete_status = 1
        status = 1
        if (.not. amp%factored) return
        if (size(f) /= amp%nn .or. size(a) /= amp%nn) return
        residual = f - csc_matvec(amp%matrix, a)
        if (.not. all(ieee_is_finite(real(residual, dp)))) return
        if (.not. all(ieee_is_finite(aimag(residual)))) return
        estimate%residual_norm = norm2(abs(residual))
        allocate (correction(amp%nn))
        call solve_factored(amp, residual, correction, status)
        if (status /= 0) return
        energy = real(dot_product(residual, correction), dp)
        if (.not. ieee_is_finite(energy) .or. energy < 0.0_dp) then
            status = 2
            estimate%discrete_status = status
            return
        end if
        estimate%discrete_energy_error = sqrt(energy)
        estimate%discrete_claim = 'indicator'
        estimate%discrete_status = 0
    end subroutine ampere_n_error

    subroutine ampere_n_equilibrated_error(fs, fsd, amp, a, current, estimate, &
            status)
        !! Fixed-trace interior Prager--Synge diagnostic with R dR dZ pairing.
        !! This estimates the interior solution whose tangential A equals the
        !! candidate's trace; it is not a bound for the coupled solution.
        !! Non-polynomial quadrature and exterior/derivative remainders remain
        !! unavailable. Existing algebraic diagnostics are preserved.
        type(meridian_feec_t), intent(in) :: fs, fsd
        type(ampere_n_t), intent(in) :: amp
        complex(dp), intent(in) :: a(:)
        procedure(meridian_field_i) :: current
        type(ampere_n_error_t), intent(inout) :: estimate
        integer, intent(out) :: status
        complex(dp), allocatable :: full_a(:)

        estimate%interior = meridian_hcurl_estimate_t()
        estimate%interior_claim = 'unavailable'
        estimate%interior_status = -1
        status = 1
        if (.not. amp%factored) return
        if (size(a) /= amp%nn .or. fs%nn /= amp%nn) return
        allocate (full_a(fs%sp(1)%ndof))
        full_a = (0.0_dp, 0.0_dp)
        full_a(:amp%nn) = a
        call meridian_hcurl_equilibrated_bound(fs, fsd, amp%n, full_a, current, &
            estimate%interior, status)
        estimate%interior_status = status
        if (status /= HCURL_OK) return
        estimate%interior_claim = 'indicator-fixed-tangential-trace'
    end subroutine ampere_n_equilibrated_error

    subroutine ampere_n_curl(amp, a, b2)
        !! V2 coefficients of B = curl_n A.
        type(ampere_n_t), intent(in) :: amp
        complex(dp), intent(in) :: a(:)
        complex(dp), allocatable, intent(out) :: b2(:)

        b2 = csc_matvec(amp%curl, a)
    end subroutine ampere_n_curl

    subroutine ampere_n_trace(amp, a, u)
        !! Exterior potential trace u = -S^{-1} C A at the P2 trace nodes of
        !! the boundary curve (B = grad_n u outside, in T m).
        type(ampere_n_t), intent(in) :: amp
        complex(dp), intent(in) :: a(:)
        complex(dp), allocatable, intent(out) :: u(:)
        complex(dp), allocatable :: ca(:)

        ca = matmul(amp%cb, a(amp%bdof))
        u = -matmul(cmplx(amp%sinv, 0.0_dp, dp), ca)
    end subroutine ampere_n_trace

    subroutine ampere_n_field_point(fs, pb, b2, t, xi, eta, x, b, status)
        !! Physical point x and field B (R, phi, Z components) at the
        !! reference point (xi, eta) of triangle t from V2 coefficients b2.
        type(meridian_feec_t), intent(in) :: fs
        type(meridian_point_basis_t), intent(in) :: pb
        complex(dp), intent(in) :: b2(:)
        integer, intent(in) :: t
        real(dp), intent(in) :: xi, eta
        real(dp), intent(out) :: x(2)
        complex(dp), intent(out) :: b(3)
        integer, intent(out) :: status
        real(dp), allocatable :: phi(:, :)
        complex(dp) :: c
        integer :: i

        allocate (phi(3, fs%sp(2)%nloc))
        call meridian_point_basis(fs, pb, 2, t, xi, eta, x, phi, status)
        b = (0.0_dp, 0.0_dp)
        if (status /= 0) return
        do i = 1, fs%sp(2)%nloc
            c = real(fs%sp(2)%sgn(i, t), dp)*b2(fs%sp(2)%dof(i, t))
            b = b + c*phi(:, i)
        end do
    end subroutine ampere_n_field_point

    subroutine ampere_n_free(amp)
        type(ampere_n_t), intent(inout) :: amp

        if (amp%factored .and. .not. amp%use_direct) call sparse_destroy(amp%solver)
        if (amp%use_direct) call gs_direct_free(amp%direct)
        amp%use_direct = .false.
        amp%factored = .false.
        amp%error = ampere_n_error_t()
        amp%matrix = csc_z_t()
        if (allocated(amp%bdof)) deallocate (amp%bdof)
        if (allocated(amp%cb)) deallocate (amp%cb)
        if (allocated(amp%sinv)) deallocate (amp%sinv)
    end subroutine ampere_n_free

end module kin6d_mhd_ampere_n
