program gen_equilibrium_bulk
    ! D7 volume moments and the perimeter-current convention for beta_p, li.
    use fortsym_expr, only: expr_t, sym, pi_expr, operator(+), operator(*), &
        operator(/), operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: r, gr, gz, p, volume, pint, bint, current, length, mu0, bp
    r = sym('r'); gr = sym('flux_r'); gz = sym('flux_z')
    p = sym('p'); volume = sym('volume')
    pint = sym('pint'); bint = sym('bint')
    current = sym('current'); length = sym('length')
    mu0 = sym('mu0')
    bp = mu0*current/length
    call w%open('gen_equilibrium_bulk', &
        'src/generated/milca_equilibrium_bulk_leaves.f90')
    call w%line('! Generated by gen/gen_equilibrium_bulk.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_equilibrium_bulk_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('equilibrium_bulk_density', &
        [character(6) :: 'r', 'flux_r', 'flux_z', 'p'], &
        [character(4) :: 'pvol', 'bvol'], &
        [2*pi_expr()*r*p, 2*pi_expr()*(gr**2 + gz**2)/r], ad=.true.)
    call w%emit('equilibrium_bulk_normalize', &
        [character(7) :: 'volume', 'pint', 'bint', 'current', 'length', 'mu0'], &
        [character(6) :: 'beta_p', 'li'], &
        [2*mu0*pint/(volume*bp**2), bint/(volume*bp**2)], ad=.true.)
    call w%line('end module milca_equilibrium_bulk_leaves')
    call w%close()
end program
