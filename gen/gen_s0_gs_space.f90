program gen_s0_gs_space
    ! Polar m-harmonic displacements, expressed in the toroidal (R,phi,Z) frame.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sin, cos, operator(+), operator(-), &
        operator(*), operator(/)
    use fortsym_diff, only: diff
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: writer
    type(expr_t) :: r, theta, m, u(3), du(3), c, s, cr, ci
    type(expr_t) :: x(3,2), xr(3,2), xt(3,2), dx(3,2), dz(3,2)
    type(expr_t) :: r0, z0
    integer :: a, b, j
    call arena%init()
    r = sym(arena, 'r'); theta = sym(arena, 'theta'); m = sym(arena, 'm')
    u = [sym(arena, 'u'), sym(arena, 'v'), sym(arena, 'w')]
    du = [sym(arena, 'su'), sym(arena, 'sv'), sym(arena, 'sw')]
    r0 = sym(arena, 'r0'); z0 = sym(arena, 'z0')
    c = cos(theta); s = sin(theta); cr = cos(m*theta); ci = sin(m*theta)
    ! (u, i*v, i*w) exp(i*m*theta) in the minor-cylinder (r,theta,axis) frame.
    x(1,1) = cr*c*u(1)+ci*s*u(2)
    x(1,2) = ci*c*u(1)-cr*s*u(2)
    x(2,1) = -ci*u(3); x(2,2) = cr*u(3)
    x(3,1) = cr*s*u(1)-ci*c*u(2)
    x(3,2) = ci*s*u(1)+cr*c*u(2)
    do b = 1, 2
        do a = 1, 3
            xr(a,b) = diff(x(a,b),u(1))*du(1)
            do j = 2, 3
                xr(a,b) = xr(a,b)+diff(x(a,b),u(j))*du(j)
            end do
            xt(a,b) = diff(x(a,b),theta)
            dx(a,b) = c*xr(a,b)-s/r*xt(a,b)
            dz(a,b) = s*xr(a,b)+c/r*xt(a,b)
        end do
    end do
    call writer%open(arena, 'gen_s0_gs_space', &
        'src/generated/kin6d_s0_gs_space_leaves.f90')
    call writer%line('! Generated by gen/gen_s0_gs_space.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('! r>0; amplitudes (u,i*v,i*w) exp(i*m*theta).')
    call writer%line('module kin6d_s0_gs_space_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('s0_polar_jet', &
        [character(5) :: 'r','theta','m','u','v','w','su','sv','sw'], &
        [character(4) :: 'x1r','x2r','x3r','x1i','x2i','x3i', &
        'd1r','d2r','d3r','d1i','d2i','d3i', &
        'z1r','z2r','z3r','z1i','z2i','z3i'], &
        [reshape(x,[6]),reshape(dx,[6]),reshape(dz,[6])], ad=.true.)
    call writer%emit('s0_polar_geometry', &
        [character(5) :: 'r','theta','r0','z0'], &
        [character(3) :: 'pr','pz','jac'], &
        [r0+r*c,z0+r*s,r*(r0+r*c)], ad=.true.)
    call writer%line('end module kin6d_s0_gs_space_leaves')
    call writer%close()
end program gen_s0_gs_space
