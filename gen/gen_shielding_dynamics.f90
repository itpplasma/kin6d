program gen_shielding_dynamics
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, exp, abs, sin, cos, &
                        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = '44da68f44c1ef3bc7617a307409c812a6ea4d515'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: a, b, k, rho, h, slope, radius, residual, x, acc, mu
    type(expr_t) :: j, points, tmax, frames, dx, c, r
    integer :: unit
    call arena%init()
    engine = make_native_engine(arena)
    a = sym(arena, 'a'); b = sym(arena, 'b'); k = sym(arena, 'k')
    rho = sym(arena, 'rho'); h = sym(arena, 'h'); slope = sym(arena, 'slope')
    radius = sym(arena, 'radius'); residual = sym(arena, 'residual')
    x = sym(arena, 'x'); acc = sym(arena, 'acc')
    j = sym(arena, 'j'); points = sym(arena, 'points')
    tmax = sym(arena, 'tmax'); frames = sym(arena, 'frames')
    dx = sym(arena, 'dx'); c = sym(arena, 'c'); r = sym(arena, 'r')
    mu = k**2 + 1
    open (newunit=unit, file='src/generated/kin6d_shielding_dynamics_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_shielding_dynamics.f90; do not edit.'
  write (unit, '(a)') '! Periodic planar drift-diffusion-Poisson, finite cosine source.'
    write (unit, '(a)') '! eta_t=eta_xx-eta+rho; -phi_xx=rho-eta; zero mean/gauge.'
    write (unit, '(a)') '! Smooth modal leaves: primal/JVP/VJP Euclidean pairings.'
    write (unit, '(a)') 'module kin6d_shielding_dynamics_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('shielding_step', ['a  ', 'k  ', 'rho', 'h  '], ['b'], &
              [a + h*(rho - mu*a)], ad=.true.)
  call emit('shielding_slope', ['a', 'b', 'h'], ['slope'], [(b - a)/h], interval=.true.)
    call emit('shielding_residual_interval', ['a    ', 'k    ', 'rho  ', 'slope'], &
              ['residual'], [slope + mu*a - rho], rigorous=.true.)
 call emit('shielding_radius_interval', ['radius  ','residual','k       ','h       '], &
              ['next'], [exp(-mu*h)*radius + h*residual], rigorous=.true.)
    call emit('shielding_mode', ['a  ', 'k  ', 'rho', 'x  '], &
              ['density  ', 'potential', 'field    '], &
              [a*cos(k*x), (rho - a)*cos(k*x)/k**2, (rho - a)*sin(k*x)/k], &
              ad=.true., interval=.true.)
    call emit('shielding_amplitudes_interval', ['a  ', 'rho', 'k  '], &
     ['density  ','potential','field    '], [a,(rho-a)/k**2,(rho-a)/k], rigorous=.true.)
  call emit('shielding_add_interval', ['acc','c  '], ['next'], [acc+c], rigorous=.true.)
    call emit('shielding_error_interval', ['acc', 'r  ', 'k  '], &
     ['density  ','potential','field    '], [acc+r,acc+r/k**2,acc+r/k], rigorous=.true.)
    call emit('shielding_curvature_interval', ['acc', 'c  ', 'k  '], ['next'], &
              [acc + k**2*abs(c)], rigorous=.true.)
    call emit('shielding_time_curvature_interval', ['acc', 'rho', 'k  '], &
              ['next'], [acc + mu*abs(rho)/k**2], rigorous=.true.)
    call emit('shielding_band_interval', ['c', 'r'], ['lower', 'upper'], &
              [c - r, c + r], rigorous=.true.)
    call emit('shielding_radius_width_interval', ['a', 'b'], ['r'], &
              [(b - a)/2], rigorous=.true.)
    call emit('shielding_equilibrium', ['rho', 'k  '], ['a'], [rho/mu], ad=.true.)
    call emit('shielding_coordinate', ['j     ', 'points'], ['x'], &
              [-pi_expr(arena) + 2*pi_expr(arena)*j/(points - 1)])
    call emit('shielding_time', ['j     ', 'frames', 'tmax  '], ['t'], &
              [j*tmax/(frames - 1)])
    call emit('shielding_interval_length', ['a', 'b'], ['h'], [b - a], interval=.true.)
    write (unit, '(a)') 'end module kin6d_shielding_dynamics_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_shielding_dynamics; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%exp = str('exp')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_shielding_dynamics')
        spec%generator_revision = str(revision)
       spec%regenerate_command = str('gen_shielding_dynamics from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_shielding_dynamics
