program gen_shielding_dynamics
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, exp, abs, sin, cos, &
                        operator(+), operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: a, b, k, rho, h, slope, radius, residual, x, acc, mu
    type(expr_t) :: j, points, tmax, frames, dx, c, r
    call arena%init()
    a = sym(arena, 'a'); b = sym(arena, 'b'); k = sym(arena, 'k')
    rho = sym(arena, 'rho'); h = sym(arena, 'h'); slope = sym(arena, 'slope')
    radius = sym(arena, 'radius'); residual = sym(arena, 'residual')
    x = sym(arena, 'x'); acc = sym(arena, 'acc')
    j = sym(arena, 'j'); points = sym(arena, 'points')
    tmax = sym(arena, 'tmax'); frames = sym(arena, 'frames')
    dx = sym(arena, 'dx'); c = sym(arena, 'c'); r = sym(arena, 'r')
    mu = k**2 + 1
    call w%open(arena, 'gen_shielding_dynamics', 'src/generated/kin6d_shielding_dynamics_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_shielding_dynamics.f90; do not edit.'
  write (w%unit, '(a)') '! Periodic planar drift-diffusion-Poisson, finite cosine source.'
    write (w%unit, '(a)') '! eta_t=eta_xx-eta+rho; -phi_xx=rho-eta; zero mean/gauge.'
    write (w%unit, '(a)') '! Smooth modal leaves: primal/JVP/VJP Euclidean pairings.'
    write (w%unit, '(a)') 'module kin6d_shielding_dynamics_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('shielding_step', ['a  ', 'k  ', 'rho', 'h  '], ['b'], &
              [a + h*(rho - mu*a)], ad=.true.)
  call w%emit('shielding_slope', ['a', 'b', 'h'], ['slope'], [(b - a)/h], interval=.true.)
    call w%emit('shielding_residual_interval', ['a    ', 'k    ', 'rho  ', 'slope'], &
              ['residual'], [slope + mu*a - rho], rigorous=.true.)
 call w%emit('shielding_radius_interval', ['radius  ','residual','k       ','h       '], &
              ['next'], [exp(-mu*h)*radius + h*residual], rigorous=.true.)
    call w%emit('shielding_mode', ['a  ', 'k  ', 'rho', 'x  '], &
              ['density  ', 'potential', 'field    '], &
              [a*cos(k*x), (rho - a)*cos(k*x)/k**2, (rho - a)*sin(k*x)/k], &
              ad=.true., interval=.true.)
    call w%emit('shielding_amplitudes_interval', ['a  ', 'rho', 'k  '], &
     ['density  ','potential','field    '], [a,(rho-a)/k**2,(rho-a)/k], rigorous=.true.)
  call w%emit('shielding_add_interval', ['acc','c  '], ['next'], [acc+c], rigorous=.true.)
    call w%emit('shielding_error_interval', ['acc', 'r  ', 'k  '], &
     ['density  ','potential','field    '], [acc+r,acc+r/k**2,acc+r/k], rigorous=.true.)
    call w%emit('shielding_curvature_interval', ['acc', 'c  ', 'k  '], ['next'], &
              [acc + k**2*abs(c)], rigorous=.true.)
    call w%emit('shielding_time_curvature_interval', ['acc', 'rho', 'k  '], &
              ['next'], [acc + mu*abs(rho)/k**2], rigorous=.true.)
    call w%emit('shielding_band_interval', ['c', 'r'], ['lower', 'upper'], &
              [c - r, c + r], rigorous=.true.)
    call w%emit('shielding_radius_width_interval', ['a', 'b'], ['r'], &
              [(b - a)/2], rigorous=.true.)
    call w%emit('shielding_equilibrium', ['rho', 'k  '], ['a'], [rho/mu], ad=.true.)
    call w%emit('shielding_coordinate', ['j     ', 'points'], ['x'], &
              [-pi_expr(arena) + 2*pi_expr(arena)*j/(points - 1)])
    call w%emit('shielding_time', ['j     ', 'frames', 'tmax  '], ['t'], &
              [j*tmax/(frames - 1)])
    call w%emit('shielding_interval_length', ['a', 'b'], ['h'], [b - a], interval=.true.)
    write (w%unit, '(a)') 'end module kin6d_shielding_dynamics_leaves'
    call w%close()
end program gen_shielding_dynamics
