!> H1b leaves: semiclassical pair corrections used to compare the classical
!> finite-N parent with exact quantum cell states (docs/quantum-classical-
!> correlations.md). One symbolic source for the pair thermal length, the
!> Kelbg diffraction potential, the leading-order exchange factor/potential
!> and the leading Wigner--Kirkwood weight.
program gen_quantum_classical
    use fortsym_expr, only: expr_t, sym, pi_expr, sqrt, exp, log, erfc, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: hbar, mu, kt, r, lam, g, x, p, beta, mass, lap, grad2, xs
    type(expr_t) :: series

    hbar = sym('hbar'); mu = sym('mu'); kt = sym('kt')
    r = sym('r'); lam = sym('lam'); g = sym('g')
    p = sym('ps'); beta = sym('beta'); mass = sym('mass')
    lap = sym('laplacian'); grad2 = sym('gradient2')
    xs = sym('xs')
    x = r/lam
    call w%open('gen_quantum_classical', &
                'src/generated/milca_quantum_classical_leaves.f90')
    call w%line('! Generated by gen/gen_quantum_classical.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Pair thermal length lam = hbar/sqrt(2 mu kT) (mu reduced mass);')
    call w%line('! Kelbg potential u = g [1 - exp(-x^2) + sqrt(pi) x erfc(x)]/r, x=r/lam;')
    call w%line('! exchange factor X = exp(-r^2/lam^2) (ideal same-spin pair at')
    call w%line('! leading order), Pauli potential -kT ln(1 - p X_sum); Wigner--Kirkwood')
    call w%line('! weight 1 - (hbar beta)^2 lap U/(12 m) + hbar^2 beta^3 |grad U|^2/(24 m).')
    call w%line('module milca_quantum_classical_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('qcm_pair_length', ['hbar', 'mu  ', 'kt  '], ['lam'], &
                [hbar/sqrt(2*mu*kt)], ad=.true.)
    call w%emit('qcm_kelbg', ['r  ', 'lam', 'g  '], ['u'], &
        [g*(1 - exp(-x**2))/r + g*sqrt(pi_expr())*erfc(x)/lam], ad=.true.)
    ! (1 - exp(-x^2))/r = (r/lam^2) sum_k (-x^2)^k/(k+1)!, truncated at x^10:
    ! relative remainder below x^10/7! < 2e-14 for x < 0.1.
    series = (r/lam**2)*(1 - x**2/2 + x**4/6 - x**6/24 + x**8/120 - x**10/720)
    call w%emit('qcm_kelbg_series', ['r  ', 'lam', 'g  '], ['u'], &
        [g*series + g*sqrt(pi_expr())*erfc(x)/lam], ad=.true.)
    call w%emit('qcm_kelbg_excess', ['r  ', 'lam', 'g  '], ['u'], &
        [g*(sqrt(pi_expr())*erfc(x)/lam - exp(-x**2)/r)], ad=.true.)
    call w%emit('qcm_exchange', ['r  ', 'lam'], ['factor'], [exp(-x**2)], ad=.true.)
    ! Pauli potential of a summed (periodic-image) exchange factor xs.
    call w%emit('qcm_pauli', ['xs', 'kt', 'ps'], ['u'], &
                [-kt*log(1 - p*xs)], ad=.true.)
    call w%emit('qcm_wigner_kirkwood', ['beta     ', 'hbar     ', 'mass     ', &
                'laplacian', 'gradient2'], ['weight'], &
                [1 - hbar**2*beta**2*lap/(12*mass) + &
                 hbar**2*beta**3*grad2/(24*mass)], ad=.true.)
    call w%line('end module milca_quantum_classical_leaves')
    call w%close()
end program
