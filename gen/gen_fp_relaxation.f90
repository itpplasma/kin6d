program gen_fp_relaxation
    ! Benchmark B04: test-ion Fokker-Planck relaxation in a fixed Maxwellian bath.
    ! With x=v/v_t, v_t=sqrt(2 T_b/m_b):
    !   H = n erf(x)/v,  G = n v_t[(x+1/(2x)) erf(x)+exp(-x^2)/sqrt(pi)],
    !   A_r = Gamma(1+m_a/m_b) H',  D_par = (Gamma/2) G'',  D_perp = (Gamma/2) G'/v.
    ! Radial derivatives are taken symbolically by fortsym diff.
    ! The Legendre reduction of d_t f = div(-A f + div(D f)) for f = sum_l f_l P_l is
    !   d_t f_l = v^-2 d_v[v^2 (-A_r f_l + d_v(D_par f_l) + 2(D_par-D_perp) f_l/v)]
    !             - l(l+1) D_perp f_l / v^2,
    ! which check_reduction proves for l=0,1,2 and arbitrary radial functions.
    use fortsym_expr, only: expr_t, sym, rat, exp, sqrt, erf, log, abs, pi_expr, &
        operator(+), operator(-), operator(*), operator(/), &
        operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_check, only: suite_t, suite_begin, suite_end, check_identity
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(symengine_engine_t) :: symengine
    type(suite_t) :: suite
    type(expr_t) :: v, vt, nb, gam, mr, r, a, e, dp, h, lo, hi, f0, f1, f2
    type(expr_t) :: w2, w3, w4, w6, mu, mass, tpar, tperp, drift, dens, ll, dperp
    type(expr_t) :: muf, lval
    type(expr_t) :: va, x, dt, s2, bh1, bh2, bim, v0, width, tb, ma, pi_e, sq_pi
    type(expr_t) :: qa, qb, lnl, eps, temp, cf, tail, kf, ci
    type(expr_t) :: Hpot, Gpot, dHv, dGv, d2Gv, term, mterm, bterm, cterm, rate
    type(expr_t) :: cfun, sx, ex
    type(expr_t) :: CC(3), Rr, gR, arR, dpR, dqR, uu, ww, den, chart(3), res
    type(expr_t) :: nn(3), Dm(3, 3), Vv(3), Jc(3), fC, lhs, rhs, rad, Jr, muc, Pl
    type(expr_t) :: zero, one, jet(0:3, 4)
    integer :: l, i, j
    character(len=4), parameter :: none4 = '    '

    engine = make_native_engine()
    symengine = make_symengine_engine()
    zero = rat(0_8, 1_8)
    one = rat(1_8, 1_8)
    pi_e = pi_expr()
    sq_pi = sqrt(pi_e)
    v = sym('v'); vt = sym('vt'); nb = sym('nb')
    gam = sym('gam'); mr = sym('mr')
    r = sym('r'); a = sym('a'); e = sym('e')
    dp = sym('dp'); h = sym('h'); lo = sym('lo')
    hi = sym('hi'); f0 = sym('f0'); f1 = sym('f1')
    f2 = sym('f2'); w2 = sym('w2'); w3 = sym('w3')
    w4 = sym('w4'); w6 = sym('w6'); mu = sym('mu')
    mass = sym('mass'); tpar = sym('tpar'); tperp = sym('tperp')
    drift = sym('drift'); dens = sym('dens'); ll = sym('ll')
    dperp = sym('dperp'); va = sym('va'); x = sym('x')
    dt = sym('dt'); v0 = sym('v0'); width = sym('width')
    tb = sym('tb'); ma = sym('ma')
    qa = sym('qa'); qb = sym('qb'); lnl = sym('lnl')
    eps = sym('eps'); temp = sym('temp'); cf = sym('cf')
    tail = sym('tail'); kf = sym('kf'); ci = sym('ci')

    ! Bath potentials of the speed v, with derivatives from fortsym diff.
    Hpot = nb*erf(v/vt)/v
    Gpot = nb*vt*((v/vt + vt/(2*v))*erf(v/vt) + exp(-(v/vt)**2)/sq_pi)
    dHv = diff(Hpot, v)
    dGv = diff(Gpot, v)
    d2Gv = diff(dGv, v)
    term = gam*(1 + mr)*dHv ! A_r(v)
    mterm = gam*rat(1_8, 2_8)*d2Gv ! D_par(v)
    bterm = gam*rat(1_8, 2_8)*dGv/v ! D_perp(v)
    cterm = gam*(d2Gv - dGv/v)/v ! 2(D_par-D_perp)/v
    rate = -gam*(1 + mr)*dHv/v ! slow-down rate -A_r/v

    call suite_begin(suite, 'fp_relaxation_legendre_reduction')
    call check_reduction()
    call suite_end(suite)

    call w%open('gen_fp_relaxation', 'src/generated/kin6d_fp_relaxation_leaves.f90')
    w%simplify_roots = .true.
    call w%line('! Generated by gen/gen_fp_relaxation.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Benchmark B04 Maxwellian-bath leaves (fortsym diff of H and G),')
    call w%line('! Legendre face fluxes, moment weights, projection and time-step weights.')
    call w%line('module kin6d_fp_relaxation_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('fp_rel_friction', ['v   ', 'vt  ', 'nb  ', 'gam ', 'mr  '], &
        ['value'], [term])
    call w%emit('fp_rel_diff_par', ['v   ', 'vt  ', 'nb  ', 'gam '], ['value'], [mterm])
    call w%emit('fp_rel_diff_perp', ['v   ', 'vt  ', 'nb  ', 'gam '], ['value'], [bterm])
    call w%emit('fp_rel_cross', ['v   ', 'vt  ', 'nb  ', 'gam '], ['value'], [cterm])
    call w%emit('fp_rel_rate_at', ['v   ', 'vt  ', 'nb  ', 'gam ', 'mr  '], &
        ['value'], [rate])
    call w%emit('fp_rel_face_lo', ['r   ', 'a   ', 'e   ', 'dp  ', 'h   '], &
        ['value'], [r**2*((e - a)*rat(1_8, 2_8) - dp/h)])
    call w%emit('fp_rel_face_hi', ['r   ', 'a   ', 'e   ', 'dp  ', 'h   '], &
        ['value'], [r**2*((e - a)*rat(1_8, 2_8) + dp/h)])
    call w%emit('fp_rel_sink', ['h     ', 'dperp ', 'll    '], ['value'], &
        [ll*h*dperp])
    call w%emit('fp_rel_w2', ['lo', 'hi'], ['value'], &
        [(hi**3 - lo**3)*rat(1_8, 3_8)])
    call w%emit('fp_rel_w3', ['lo', 'hi'], ['value'], &
        [(hi**4 - lo**4)*rat(1_8, 4_8)])
    call w%emit('fp_rel_w4', ['lo', 'hi'], ['value'], &
        [(hi**5 - lo**5)*rat(1_8, 5_8)])
    call w%emit('fp_rel_w6', ['lo', 'hi'], ['value'], &
        [(hi**7 - lo**7)*rat(1_8, 7_8)])
    call w%emit('fp_rel_mom_n', ['w2', 'f0'], ['value'], [4*pi_e*w2*f0])
    call w%emit('fp_rel_mom_u', ['w3', 'f1'], ['value'], &
        [4*pi_e*rat(1_8, 3_8)*w3*f1])
    call w%emit('fp_rel_mom_pz', ['w4', 'f0', 'f2'], ['value'], &
        [2*pi_e*w4*(rat(2_8, 3_8)*f0 + rat(4_8, 15_8)*f2)])
    call w%emit('fp_rel_mom_pperp', ['w4', 'f0', 'f2'], ['value'], &
        [2*pi_e*w4*(rat(4_8, 3_8)*f0 - rat(4_8, 15_8)*f2)])
    call w%emit('fp_rel_mom_v4', ['w6', 'f0'], ['value'], [4*pi_e*w6*f0])
    bim = dens*(mass/(2*pi_e*tperp))*sqrt(mass/(2*pi_e*tpar))* &
        exp(-mass*v**2*(1 - mu**2)/(2*tperp) - mass*(v*mu - drift)**2/(2*tpar))
    call w%emit('fp_rel_vproj0', ['v    ', 'mu   ', 'mass ', 'tpar ', 'tperp', &
        'drift', 'dens '], ['value'], [rat(1_8, 2_8)*bim*v**2])
    call w%emit('fp_rel_vproj1', ['v    ', 'mu   ', 'mass ', 'tpar ', 'tperp', &
        'drift', 'dens '], ['value'], [rat(3_8, 2_8)*bim*mu*v**2])
    call w%emit('fp_rel_vproj2', ['v    ', 'mu   ', 'mass ', 'tpar ', 'tperp', &
        'drift', 'dens '], ['value'], &
        [rat(5_8, 4_8)*bim*(3*mu**2 - 1)*v**2])
    call w%emit('fp_rel_gauss', ['v    ', 'v0   ', 'width'], ['value'], &
        [exp(-(v - v0)**2/(2*width**2))])
    call w%emit('fp_rel_maxwell', ['v ', 'ma', 'tb'], ['value'], &
        [exp(-ma*v**2/(2*tb))])
    ! TR-BDF2 with gamma = 2 - sqrt(2); the BDF2 stage uses bh1 = gamma dt, bh2 = (1-gamma) dt.
    s2 = 2 - sqrt(2*one)
    bh1 = s2*dt
    bh2 = (1 - s2)*dt
    call w%emit('fp_rel_bdf2_a0', ['dt'], ['value'], [(2*bh2 + bh1)/(bh2*(bh1 + bh2))])
    call w%emit('fp_rel_bdf2_a1', ['dt'], ['value'], [-(bh1 + bh2)/(bh1*bh2)])
    call w%emit('fp_rel_bdf2_a2', ['dt'], ['value'], [bh2/(bh1*(bh1 + bh2))])
    call w%emit('fp_rel_trap_c', ['dt'], ['value'], [s2*dt*rat(1_8, 2_8)])
    ! Heavy slow-limit rate nu_s and the time unit tau_s at speed va (conventions.md).
    call w%emit('fp_rel_nu_s', ['gam', 'mr ', 'nb ', 'vt '], ['value'], &
        [gam*(1 + mr)*4*nb/(3*sq_pi*vt**3)])
    cfun = erf(sqrt(x)) - 2*sqrt(x/pi_e)*exp(-x)
    muf = sym('muf')
    call w%emit('fp_rel_mu', ['x'], ['value'], [cfun])
    call w%emit('fp_rel_tau_s', ['va ', 'muf', 'gam', 'nb ', 'mr '], ['value'], &
        [va**3/((1 + mr)*muf*gam*nb)])
    ! Scalars of the case: Coulomb factor, speeds, grid, tail bound and x_s.
    call w%emit('fp_rel_gamma', ['qa  ', 'qb  ', 'lnl ', 'eps ', 'ma  '], ['value'], &
        [qa**2*qb**2*lnl/(4*pi_e*eps**2*ma**2)])
    call w%emit('fp_rel_speed', ['temp  ', 'mass  ', 'cf    '], ['value'], &
        [sqrt(cf*temp/mass)])
    call w%emit('fp_rel_vmax', ['drift ', 'tpar  ', 'mass  ', 'tail  '], ['value'], &
        [abs(drift) + sqrt(2*tpar*(-log(tail))/mass)])
    call w%emit('fp_rel_face', ['kf  ', 'h   '], ['value'], [kf*h])
    call w%emit('fp_rel_centre', ['ci  ', 'h   '], ['value'], [(ci - rat(1_8, 2_8))*h])
    call w%emit('fp_rel_xs', ['va  ', 'vt  '], ['value'], [(va/vt)**2])
    call w%line('end module kin6d_fp_relaxation_leaves')
    call w%close()

contains

    ! Legendre reduction: Cartesian divergence of the flux equals the radial
    ! per-l operator for arbitrary radial functions g, A_r, D_par, D_perp. R = |x|
    ! and each function's jet F_0 .. F_3 at R are independent symbols, differentiated
    ! by the chain rule d_i R = x_i/R, d_i F_k = F_(k+1) x_i/R, so the identity holds
    ! for every choice of the functions. The rational residual is then restricted
    ! to R = |x| by the stereographic chart x = R (2u, 2w, 1 - u^2 - w^2)/(1 + u^2 + w^2),
    ! which covers the sphere up to one point, so no radical enters the zero test.
    subroutine check_reduction()
        integer :: mode, i1, j1, m, k
        type(engine_result_t) :: zt
        character(len=6), parameter :: fname(4) = ['g     ', 'A_r   ', 'D_par ', 'D_perp']
        CC(1) = sym('x'); CC(2) = sym('y'); CC(3) = sym('z')
        Rr = sym('R')
        do m = 1, 4
            do k = 0, 3
                jet(k, m) = sym(trim(fname(m))//'_'//achar(48 + k))
            end do
        end do
        gR = jet(0, 1); arR = jet(0, 2); dpR = jet(0, 3); dqR = jet(0, 4)
        uu = sym('u'); ww = sym('w')
        den = 1 + uu**2 + ww**2
        chart(1) = Rr*2*uu/den; chart(2) = Rr*2*ww/den; chart(3) = Rr*(1 - uu**2 - ww**2)/den
        do i1 = 1, 3
            nn(i1) = CC(i1)/Rr
        end do
        muc = CC(3)/Rr
        do mode = 0, 2
            select case (mode)
            case (0)
                Pl = one
            case (1)
                Pl = muc
            case default
                Pl = rat(3_8, 2_8)*muc**2 - rat(1_8, 2_8)
            end select
            lval = rat(int(mode*(mode + 1), 8), 1_8)
            fC = gR*Pl
            do i1 = 1, 3
                do j1 = 1, 3
                    if (i1 == j1) then
                        Dm(i1, j1) = dpR*nn(i1)*nn(j1) + dqR*(one - nn(i1)*nn(j1))
                    else
                        Dm(i1, j1) = dpR*nn(i1)*nn(j1) - dqR*nn(i1)*nn(j1)
                    end if
                end do
            end do
            do i1 = 1, 3
                Vv(i1) = zero
                do j1 = 1, 3
                    Vv(i1) = Vv(i1) + chain(Dm(i1, j1)*fC, j1)
                end do
                Jc(i1) = -arR*nn(i1)*fC + Vv(i1)
            end do
            lhs = zero
            do i1 = 1, 3
                lhs = lhs + chain(Jc(i1), i1)
            end do
            Jr = -arR*gR + chain(dpR*gR, 0) + 2*(dpR - dqR)*gR/Rr
            rad = chain(Rr**2*Jr, 0)/Rr**2 - lval*dqR*gR/Rr**2
            rhs = rad*Pl
            ! Both sides are bilinear in the jets of g and of (A_r, D_par, D_perp),
            ! so the identity is the vanishing of every mixed second derivative.
            do k = 0, 3
                do m = 2, 4
                    do j1 = 0, 3
                        res = diff(diff(lhs - rhs, jet(k, 1)), jet(j1, m))
                        do i1 = 1, 3
                            res = subs(res, CC(i1), chart(i1))
                        end do
                        zt = engine%zero_test(res)
                        if (zt%verdict == VERDICT_TRUE) then
                            call check_identity(suite, engine, 'legendre mode', res)
                        else
                            call check_identity(suite, symengine, 'legendre mode', res)
                        end if
                    end do
                end do
            end do
        end do
    end subroutine check_reduction

    ! Total derivative d/dx_k (k = 1..3) or d/dR (k = 0) through the jets.
    function chain(e, k) result(d)
        type(expr_t), intent(in) :: e
        integer, intent(in) :: k
        type(expr_t) :: d, radial
        integer :: m, o
        radial = zero
        do m = 1, 4
            do o = 0, 2
                radial = radial + diff(e, jet(o, m))*jet(o + 1, m)
            end do
        end do
        if (k == 0) then
            d = diff(e, Rr) + radial
        else
            d = diff(e, CC(k)) + (diff(e, Rr) + radial)*nn(k)
        end if
    end function chain

end program gen_fp_relaxation
