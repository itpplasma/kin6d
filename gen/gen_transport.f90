program gen_transport
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, func, abs, sin, cos, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: v, nu, k, sc, ss, determinant, a, b, x, acc, index, count
    type(expr_t) :: vl, vr, v0, v1, al, ar, intercept, slope, residual, source_error
    type(expr_t) :: dnu, primal_radius, source_tangent_error, center, qnorm, radius
    type(expr_t) :: fc0, fc1, fs0, fs1, gc0, gc1, gs0, gs1, bc(3), bs(3)
    type(expr_t) :: dsource, f, physical_scale, relative_tolerance, absolute_floor
    type(expr_t) :: lo, hi, fc, fs, gc, gs
    type(expr_t) :: sine, cosine
    call arena%init()
    v = sym(arena, 'v'); nu = sym(arena, 'nu'); k = sym(arena, 'k')
    sc = sym(arena, 'sc'); ss = sym(arena, 'ss')
    a = sym(arena, 'a'); b = sym(arena, 'b'); x = sym(arena, 'x')
    acc = sym(arena, 'acc'); index = sym(arena, 'j'); count = sym(arena, 'cells')
    vl = sym(arena, 'vl'); vr = sym(arena, 'vr')
    v0 = sym(arena, 'v0'); v1 = sym(arena, 'v1')
    al = sym(arena, 'al'); ar = sym(arena, 'ar')
    intercept = sym(arena, 'intercept'); slope = sym(arena, 'slope')
    residual = sym(arena, 'residual'); source_error = sym(arena, 'source_error')
    dnu = sym(arena, 'dnu_magnitude'); primal_radius = sym(arena, 'primal_radius')
    source_tangent_error = sym(arena, 'source_tangent_error')
    center = sym(arena, 'center'); qnorm = sym(arena, 'qnorm')
    radius = sym(arena, 'radius'); dsource = sym(arena, 'dsource')
    f = sym(arena, 'f'); physical_scale = sym(arena, 'physical_scale')
    relative_tolerance = sym(arena, 'relative_tolerance')
    absolute_floor = sym(arena, 'absolute_floor')
    lo = sym(arena, 'lo'); hi = sym(arena, 'hi')
    fc0 = sym(arena, 'fc0'); fc1 = sym(arena, 'fc1')
    fs0 = sym(arena, 'fs0'); fs1 = sym(arena, 'fs1')
    gc0 = sym(arena, 'gc0'); gc1 = sym(arena, 'gc1')
    gs0 = sym(arena, 'gs0'); gs1 = sym(arena, 'gs1')
    fc = sym(arena, 'fc'); fs = sym(arena, 'fs')
    gc = sym(arena, 'gc'); gs = sym(arena, 'gs')
    sine = sym(arena, 'sine'); cosine = sym(arena, 'cosine')

    ! v*f_x + nu*f = supplied source, x periodic with period2*pi, nu>0.
    ! Fourier convention: a*cos(k*x)+b*sin(k*x), integer k>=0.
    ! [nu, k*v; -k*v, nu] is invertible: det=nu**2+(k*v)**2>0.
    ! At k=0, source_sin=candidate_sin=0 and the mean equation is nu*a=sc.
    determinant = nu**2 + (k*v)**2
    ! Quadratic Bernstein coefficients of the continuous P1-v residual.
    ! Shared cell endpoints and strictly ordered vl<vr are declared by the caller.
    bc(1) = gc0 - nu*fc0 - k*v0*fs0
    bc(2) = (gc0 + gc1 - nu*(fc0 + fc1) - k*(v0*fs1 + v1*fs0))/2
    bc(3) = gc1 - nu*fc1 - k*v1*fs1
    bs(1) = gs0 - nu*fs0 + k*v0*fc0
    bs(2) = (gs0 + gs1 - nu*(fs0 + fs1) + k*(v0*fc1 + v1*fc0))/2
    bs(3) = gs1 - nu*fs1 + k*v1*fc1

    call w%open(arena, 'gen_transport', 'src/generated/kin6d_transport_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_transport.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, '(a)') '! Domain: nu>0, ordered velocity cells, integer Fourier modes.'
    write (w%unit, '(a)') '! Source: independently supplied exact finite Fourier/P1 data.'
    write (w%unit, '(a)') '! Derivatives differentiate the implicit nodal equation.'
    write (w%unit, '(a)') '! Certificates use residual/inverse bounds.'
    write (w%unit, '(a)') '! Oracles: independent 2x2/FD and Bernstein fixtures.'
    write (w%unit, '(a)') 'module kin6d_transport_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'

    call w%emit('transport_node', ['v ', 'nu', 'k ', 'sc', 'ss'], ['a', 'b'], &
        [(nu*sc - k*v*ss)/determinant, (k*v*sc + nu*ss)/determinant], ad=.true.)
    call w%emit('transport_grid_coordinate', ['j    ', 'cells'], ['value'], &
        [-1 + 2*index/count])
    count = sym(arena, 'points')
    call w%emit('transport_plot_x', ['j     ', 'points'], ['x'], &
        [2*pi_expr(arena)*index/(count - 1)])
    call w%emit('transport_source_affine', ['v        ', 'intercept', 'slope    '], &
        ['value'], [intercept + slope*v], ad=.true.)
    call w%emit('transport_interpolate', ['v ', 'vl', 'vr', 'al', 'ar'], ['value'], &
        [al + (ar - al)*(v - vl)/(vr - vl)], ad=.true., interval=.true.)
    call w%emit('transport_mode_accumulate', ['x  ', 'k  ', 'a  ', 'b  ', 'acc'], &
        ['next'], [acc + a*cos(k*x) + b*sin(k*x)], ad=.true., interval=.true.)
    call w%emit('transport_basis', ['x', 'k'], ['sine  ', 'cosine'], &
        [sin(k*x), cos(k*x)], ad=.true., interval=.true.)
    call w%emit('transport_weighted_mode_accumulate', &
        ['sine  ', 'cosine', 'a     ', 'b     ', 'acc   '], ['updated'], &
        [acc + a*cosine + b*sine], ad=.true., interval=.true.)
    call w%emit('transport_scalar_add', ['acc  ', 'value'], ['next'], &
        [acc + sym(arena, 'value')], ad=.true., interval=.true.)
    ! Fourier candidate curvature: |d_xx f| <= sum k**2*(|a_k|+|b_k|).
    ! This bounds the supplied reconstruction, not the unknown true solution.
    call w%emit('transport_curvature_accumulate_interval', &
        ['k  ', 'a  ', 'b  ', 'acc'], ['updated'], &
        [acc + k**2*(abs(a) + abs(b))], rigorous=.true.)
    call w%emit('transport_abs_value', ['value'], ['magnitude'], &
        [abs(sym(arena, 'value'))])
    call w%emit('transport_bound_pair', ['lo', 'hi'], ['bound'], &
        [func('max', [-lo, hi])])
    call w%emit('transport_mass_cell', ['vl', 'vr', 'f0', 'f1'], ['value'], &
        [pi_expr(arena)*(vr - vl)*(sym(arena, 'f0') + sym(arena, 'f1'))], &
        ad=.true., interval=.true.)
    call w%emit('transport_observable_radius', ['radius'], ['bound'], &
        [4*pi_expr(arena)*radius], interval=.true.)
    call w%emit('transport_cosine_moment_cell', ['vl', 'vr', 'al', 'ar'], ['value'], &
        [(vr - vl)*(al + ar)/4], ad=.true., interval=.true.)
    call w%emit('transport_accuracy', &
        ['bound             ', 'physical_scale    ', &
        'relative_tolerance', 'absolute_floor    '], &
        ['error ', 'target'], [sym(arena, 'bound')/physical_scale, &
        absolute_floor + relative_tolerance*physical_scale], interval=.true.)
    call w%emit('transport_residual_cell_interval', &
        ['v0 ', 'v1 ', 'nu ', 'k  ', 'fc0', 'fc1', 'fs0', 'fs1', &
        'gc0', 'gc1', 'gs0', 'gs1'], &
        ['bc0', 'bc1', 'bc2', 'bs0', 'bs1', 'bs2'], &
        [bc(1), bc(2), bc(3), bs(1), bs(2), bs(3)], rigorous=.true.)
    call w%emit('transport_residual_box_interval', &
        ['v ', 'nu', 'k ', 'fc', 'fs', 'gc', 'gs'], ['rc', 'rs'], &
        [gc - nu*fc - k*v*fs, gs - nu*fs + k*v*fc], rigorous=.true.)
    call w%emit('transport_certificate_radius_interval', &
        ['nu          ', 'residual    ', 'source_error'], ['radius'], &
        [(residual + source_error)/nu], rigorous=.true.)
    call w%emit('transport_tangent_radius_interval', &
        ['nu                  ', 'residual            ', 'dnu_magnitude       ', &
        'primal_radius       ', 'source_tangent_error'], ['radius'], &
        [(residual + dnu*primal_radius + source_tangent_error)/nu], rigorous=.true.)
    call w%emit('transport_tangent_source_interval', ['dsource', 'f      ', 'dnu    '], &
        ['value'], [dsource - sym(arena, 'dnu')*f], rigorous=.true.)
    call w%emit('transport_goal_band_interval', ['center', 'qnorm ', 'radius'], &
        ['lower', 'upper'], [center - qnorm*radius, center + qnorm*radius], &
        rigorous=.true.)
    write (w%unit, '(a)') 'end module kin6d_transport_leaves'
    call w%close()

end program gen_transport
