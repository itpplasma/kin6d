program gen_species
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: reduced_mass, bohr_radius, rydberg_energy, &
        sommerfeld_parameter, wigner_seitz_radius, coupling_parameter, &
        fermi_energy, degeneracy_parameter, density_parameter, debye_length, &
        plasma_frequency
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: hbar, m1, m2, g, v, m, gs, n, t, a, ef, mu
    type(expr_t) :: hr, kr, hsi, ksi, qsi, msi, lsi

    call arena%init()
    hbar = sym(arena, 'hbar'); m1 = sym(arena, 'm1'); m2 = sym(arena, 'm2')
    g = sym(arena, 'g'); v = sym(arena, 'v'); m = sym(arena, 'm')
    gs = sym(arena, 'g_self'); n = sym(arena, 'density')
    t = sym(arena, 'temperature')
    call w%open(arena, 'gen_species', 'src/generated/kin6d_species_leaves.f90')
    call w%line('! Generated by gen/gen_species.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Physical scales from gen/kin6d_symbolic_physics.f90.')
    call w%line('! Reduced units: g=q_i q_j/(4 pi eps0), T in energy units (k_B=1).')
    call w%line('! Fermi energy: spin-1/2. Debye length/plasma frequency: one')
    call w%line('! responsive species with g_self=q^2/(4 pi eps0) and mass m.')
    call w%line('module kin6d_species_leaves')
    call w%line('implicit none')
    call w%line('contains')
    mu = reduced_mass(m1, m2)
    call w%emit('species_pair_scales', ['hbar', 'm1  ', 'm2  ', 'g   '], &
                ['mu     ', 'bohr   ', 'rydberg'], &
                [mu, bohr_radius(hbar, mu, g), rydberg_energy(hbar, mu, g)], ad=.true.)
    call w%emit('species_sommerfeld', ['g   ', 'hbar', 'v   '], ['eta'], &
                [sommerfeld_parameter(g, hbar, v)], ad=.true.)
    a = wigner_seitz_radius(n)
    ef = fermi_energy(hbar, m, n)
    call w%emit('species_plasma_scales', ['hbar       ', 'm          ', &
                'g_self     ', 'density    ', 'temperature'], &
                ['wigner_seitz', 'gamma       ', 'fermi       ', 'theta       ', &
                 'rs          ', 'debye       ', 'omega_p     '], &
                [a, coupling_parameter(gs, a, t), ef, degeneracy_parameter(t, ef), &
                 density_parameter(a, bohr_radius(hbar, m, gs)), &
                 debye_length(t, n, gs), plasma_frequency(n, gs, m)], ad=.true.)
    ! SI map of declared reduced units. With reduced hbar_r, Coulomb constant
    ! k_r and SI mass/charge units M, Q:  hbar_r = hbar_SI T/(M L^2) and
    ! k_r = k_SI Q^2 T^2/(M L^3) give L and T below.
    hr = sym(arena, 'hbar_r'); kr = sym(arena, 'k_r')
    hsi = sym(arena, 'hbar_si'); ksi = sym(arena, 'k_si')
    qsi = sym(arena, 'charge_si'); msi = sym(arena, 'mass_si')
    lsi = kr*hsi**2/(ksi*qsi**2*hr**2*msi)
    call w%emit('species_unit_map', ['hbar_r   ', 'k_r      ', 'hbar_si  ', &
                'k_si     ', 'charge_si', 'mass_si  '], ['length_si', 'time_si  '], &
                [lsi, hr*msi*lsi**2/hsi])
    call w%line('end module kin6d_species_leaves')
    call w%close()
end program gen_species
