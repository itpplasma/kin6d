program gen_nonnested
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, log, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(expr_t) :: r1, r2, len, r, br, bz, bp, b0, psi, pp, n
    type(expr_t) :: velocity(2), gauge(2)
    type(expr_t) :: bphi, cpar, cperp, q, d, conductivity(6)
    call arena%init()
    r1 = sym(arena, 'r1'); r2 = sym(arena, 'r2'); len = sym(arena, 'len')
    r = sym(arena, 'r'); br = sym(arena, 'br')
    bz = sym(arena, 'bz'); bp = sym(arena, 'bp'); b0 = sym(arena, 'b0')
    psi = sym(arena, 'psi'); pp = sym(arena, 'pp')
    n = sym(arena, 'n')
    bphi = sym(arena, 'bphi'); cpar = sym(arena, 'cpar')
    cperp = sym(arena, 'cperp')
    call w%open(arena, 'gen_nonnested', &
        'src/generated/kin6d_nonnested_leaves.f90')
    call w%line('! Generated by gen/gen_nonnested.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_nonnested_leaves')
    call w%line('implicit none')
    call w%line('contains')
    ! Integral of 1/distance along a finite straight segment; coefficient
    ! multiplies mu0 I/(4 pi) times the oriented unit segment vector.
    call w%emit('segment_potential', ['r1 ', 'r2 ', 'len'], ['value'], &
        [log((r1 + r2 + len)/(r1 + r2 - len))], ad=.true.)
    call w%emit('axisymmetric_pressure', ['psi', 'pp '], ['p'], [pp*psi], &
        ad=.true.)
    velocity = [r*br/(b0 + bp), r*bz/(b0 + bp)]
    call w%emit('fieldline_velocity', ['r ', 'br', 'bz', 'bp', 'b0'], &
        ['vr', 'vz'], velocity, ad=.true.)
    gauge = [r*bz/n, 0 - r*br/n]
    call w%emit('vacuum_gauge', ['r ', 'br', 'bz', 'n '], ['ar', 'az'], &
        gauge, ad=.true.)
    ! NN2 anisotropic conduction K = cperp I + (cpar - cperp) B B / |B|^2,
    ! physical (R, phi, Z) components krr, krp, krz, kpp, kpz, kzz. The JVP
    ! with respect to B is the transport-field Jacobian block.
    q = br*br + bphi*bphi + bz*bz
    d = (cpar - cperp)/q
    conductivity = [cperp + d*br*br, d*br*bphi, d*br*bz, &
        cperp + d*bphi*bphi, d*bphi*bz, cperp + d*bz*bz]
    call w%emit('anisotropic_conductivity', &
        ['br   ', 'bphi ', 'bz   ', 'cpar ', 'cperp'], &
        ['krr', 'krp', 'krz', 'kpp', 'kpz', 'kzz'], conductivity, ad=.true.)
    call w%line('end module kin6d_nonnested_leaves')
    call w%close()
end program gen_nonnested
