program gen_nonnested
    use fortsym_expr, only: expr_t, sym, num, sqrt, pi_expr, operator(+), &
        operator(-), operator(*), operator(/), operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: r, br, bz, bp, b0, psi, pp, n
    type(expr_t) :: velocity(2), gauge(2)
    type(expr_t) :: bphi, cpar, cperp, q, d, conductivity(6)
    type(expr_t) :: gpr, gpp, gpz, gfr, gfp, gfz, ephi, gpar, gperp
    type(expr_t) :: bg, bf, coef, flux(3), current(3)
    type(expr_t) :: krr, krz, kzz, f0, fr, fz, data(6), lower, width, height
    type(expr_t) :: rmin, chil, par2, force2, volume, length_scale, pressure_scale
    type(expr_t) :: drive, lambda_target, jr, jp, jz
    type(expr_t) :: dm(3, 3), cof(3, 3), jac, metric(13), gm(2, 2), up(2), x1, y1
    type(expr_t) :: df(3, 3)
    character(3) :: dnames(9), dfnames(9)
    integer :: i, j
    gpr = sym('gpr'); gpp = sym('gpp'); gpz = sym('gpz')
    gfr = sym('gfr'); gfp = sym('gfp'); gfz = sym('gfz')
    ephi = sym('ephi'); gpar = sym('gpar')
    gperp = sym('gperp')
    r = sym('r'); br = sym('br')
    bz = sym('bz'); bp = sym('bp'); b0 = sym('b0')
    psi = sym('psi'); pp = sym('pp')
    n = sym('n')
    bphi = sym('bphi'); cpar = sym('cpar')
    cperp = sym('cperp')
    call w%open('gen_nonnested', &
        'src/generated/milca_nonnested_leaves.f90')
    call w%line('! Generated by gen/gen_nonnested.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_nonnested_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('axisymmetric_pressure', ['psi', 'pp '], ['p'], [pp*psi], &
        ad=.true.)
    velocity = [r*br/(b0 + bp), r*bz/(b0 + bp)]
    call w%emit('fieldline_velocity', ['r ', 'br', 'bz', 'bp', 'b0'], &
        ['vr', 'vz'], velocity, ad=.true.)
    gauge = [r*bz/n, 0 - r*br/n]
    call w%emit('vacuum_gauge', ['r ', 'br', 'bz', 'n '], ['ar', 'az'], &
        gauge, ad=.true.)
    ! NN2 anisotropic conduction K = cperp I + (cpar - cperp) B B / |B|^2,
    ! physical (R, phi, Z) components krr, krp, krz, kpp, kpz, kzz. The JVP
    ! with respect to B is the transport-field Jacobian block.
    q = br*br + bphi*bphi + bz*bz
    d = (cpar - cperp)/q
    conductivity = [cperp + d*br*br, d*br*bphi, d*br*bz, &
        cperp + d*bphi*bphi, d*bphi*bz, cperp + d*bz*bz]
    call w%emit('anisotropic_conductivity', &
        ['br   ', 'bphi ', 'bz   ', 'cpar ', 'cperp'], &
        ['krr', 'krp', 'krz', 'kpp', 'kpz', 'kzz'], conductivity, ad=.true.)
    ! NN2 coupled lane. Transport flux K grad p and the current
    !     J = B x grad p / |B|^2 + g_par b b.E - G grad Phi,
    !     G = g_par b b + g_perp (I - b b),  E = ephi e_phi,
    ! all in physical (R, phi, Z) components. Their JVPs in (B, grad p,
    ! grad Phi, ephi) are the Newton blocks of milca_nonnested_coupled.
    bg = br*gpr + bphi*gpp + bz*gpz
    flux = [cperp*gpr + d*bg*br, cperp*gpp + d*bg*bphi, cperp*gpz + d*bg*bz]
    call w%emit('anisotropic_flux', &
        ['br   ', 'bphi ', 'bz   ', 'gpr  ', 'gpp  ', 'gpz  ', 'cpar ', 'cperp'], &
        ['qr', 'qp', 'qz'], flux, ad=.true.)
    bf = br*gfr + bphi*gfp + bz*gfz
    coef = (gpar*bphi*ephi - (gpar - gperp)*bf)/q
    current = [(bphi*gpz - bz*gpp)/q + coef*br - gperp*gfr, &
        (bz*gpr - br*gpz)/q + coef*bphi - gperp*gfp, &
        (br*gpp - bphi*gpr)/q + coef*bz - gperp*gfz]
    call w%emit('coupled_current', &
        ['br   ', 'bphi ', 'bz   ', 'gpr  ', 'gpp  ', 'gpz  ', 'gfr  ', &
        'gfp  ', 'gfz  ', 'ephi ', 'gpar ', 'gperp'], &
        ['jr', 'jp', 'jz'], current, ad=.true.)
    ! I1 physical defects, separate from weak equation residuals and D3.
    ! b.grad p and the force carried by -g_perp (I-bb) grad Phi.
    call w%emit('island_defect_density', &
        ['br   ', 'bphi ', 'bz   ', 'gpr  ', 'gpp  ', 'gpz  ', &
        'gfr  ', 'gfp  ', 'gfz  ', 'gperp'], ['parallel2', 'force2   '], &
        [bg**2/q, gperp**2*((bphi*gfz - bz*gfp)**2 &
        + (bz*gfr - br*gfz)**2 + (br*gfp - bphi*gfr)**2)], &
        ad=.true.)
    par2 = sym('par2'); force2 = sym('force2')
    volume = sym('volume'); length_scale = sym('length_scale')
    pressure_scale = sym('pressure_scale')
    call w%emit('island_defect_norm', &
        ['par2          ', 'force2        ', 'volume        ', &
        'length_scale  ', 'pressure_scale'], ['epsilon_parallel', 'ohmic_force_rms '], &
        [length_scale*sqrt(par2/volume)/pressure_scale, sqrt(force2/volume)], &
        ad=.true.)
    ! Closure B fits a signed parallel current drive on a fixed seed.
    ! lambda = J.B/|B|^2 = gpar (B_phi E_phi - B.grad Phi)/|B|^2 + drive.
    drive = sym('drive')
    lambda_target = sym('lambda_target')
    call w%emit('fitted_parallel_drive', &
        ['br           ', 'bphi         ', 'bz           ', 'gfr          ', &
        'gfp          ', 'gfz          ', 'ephi         ', 'gpar         ', &
        'lambda_target'], ['drive'], [lambda_target - gpar*(bphi*ephi - bf)/q], &
        ad=.true.)
    call w%emit('parallel_drive_current', ['br   ', 'bphi ', 'bz   ', 'drive'], &
        ['jr', 'jp', 'jz'], [drive*br, drive*bphi, drive*bz], ad=.true.)
    jr = sym('jr'); jp = sym('jp'); jz = sym('jz')
    call w%emit('profile_current_diagnostic', &
        ['br           ', 'bphi         ', 'bz           ', 'jr           ', &
        'jp           ', 'jz           ', 'gpr          ', 'gpp          ', &
        'gpz          ', 'drive        ', 'lambda_target'], &
        ['lambda_defect', 'parallel_p   '], &
        [(jr*br + jp*bphi + jz*bz)/q + drive - lambda_target, bg/sqrt(q)], &
        ad=.true.)
    ! NN2 equilibrated-flux data of the axisymmetric N = 0 block with
    ! measure R dR dZ, as a planar problem in dR dZ: tensor A = R K_pol,
    ! strong source R f0 and flux R (K_pol grad p_h - f_pol) of the weak load
    ! <v f0 + grad v . f>; K_pol = (krr, krz; krz, kzz).
    krr = sym('krr'); krz = sym('krz'); kzz = sym('kzz')
    f0 = sym('f0'); fr = sym('fr'); fz = sym('fz')
    data = [r*krr, r*krz, r*kzz, r*f0, r*(krr*gpr + krz*gpz - fr), &
        r*(krz*gpr + kzz*gpz - fz)]
    call w%emit('transport_error_data', &
        ['r  ', 'krr', 'krz', 'kzz', 'f0 ', 'fr ', 'fz ', 'gpr', 'gpz'], &
        ['a11   ', 'a12   ', 'a22   ', 'source', 'qr    ', 'qz    '], data, &
        ad=.true.)
    ! Cell lower eigenvalue bound of A from R >= rmin and K >= chil I.
    rmin = sym('rmin'); chil = sym('chil')
    call w%emit('transport_error_lower', ['rmin', 'chil'], ['lower'], &
        [rmin*chil], ad=.true.)
    ! Friedrichs constant of the energy norm from the enclosing W x H
    ! rectangle and A >= lower on the whole domain.
    lower = sym('lower')
    width = sym('width'); height = sym('height')
    call w%emit('transport_error_friedrichs', ['lower ', 'width ', 'height'], &
        ['cf'], [1/(pi_expr()*sqrt(lower*(1/width**2 + 1/height**2)))], &
        ad=.true.)
    ! NN1 mapped Hodge tensors from the Piola maps of D, whose columns are
    ! the images of the orthonormal reference (R, phi, Z) frame vectors:
    ! P1 = D^-T = C/jac with cofactor columns c1 = d2 x d3, c2 = d3 x d1,
    ! c3 = d1 x d2, P2 = D/jac, jac = det D = d1.c1, so
    ! K1 = jac P1^T P1 = C^T C/jac and K2 = jac P2^T P2 = D^T D/jac
    ! (upper triangles 11, 12, 13, 22, 23, 33).
    do j = 1, 3
        do i = 1, 3
            dnames(3*(i - 1) + j) = 'd'//achar(48 + i)//achar(48 + j)
            dm(i, j) = sym(dnames(3*(i - 1) + j))
        end do
    end do
    cof(:, 1) = cross(dm(:, 2), dm(:, 3))
    cof(:, 2) = cross(dm(:, 3), dm(:, 1))
    cof(:, 3) = cross(dm(:, 1), dm(:, 2))
    jac = dot(dm(:, 1), cof(:, 1))
    metric(1) = jac
    metric(2:7) = upper(cof)
    metric(8:13) = upper(dm)
    do i = 2, 13
        metric(i) = metric(i)/jac
    end do
    call w%emit('piola_metric', dnames, ['jac', 'a11', 'a12', 'a13', 'a22', &
        'a23', 'a33', 'b11', 'b12', 'b13', 'b22', 'b23', 'b33'], metric, &
        ad=.true.)
    ! NN1 phi-preserving displacement map y = x + u(x, phi) of the meridian
    ! plane, in orthonormal cylindrical frames: rows physical (R, phi, Z),
    ! columns reference (R, phi, Z). With the coordinate Jacobian G (gij =
    ! d y_i/d x_j, identity included) and up = du/dphi,
    ! df = diag(1, y_R, 1) dy/dq diag(1, 1/x_R, 1).
    gm(1, 1) = sym('g11'); gm(1, 2) = sym('g12')
    gm(2, 1) = sym('g21'); gm(2, 2) = sym('g22')
    up(1) = sym('up1'); up(2) = sym('up2')
    x1 = sym('x1'); y1 = sym('y1')
    df(1, :) = [gm(1, 1), up(1)/x1, gm(1, 2)]
    df(2, :) = [num(0), y1/x1, num(0)]
    df(3, :) = [gm(2, 1), up(2)/x1, gm(2, 2)]
    do j = 1, 3
        do i = 1, 3
            dfnames(3*(i - 1) + j) = 'f'//achar(48 + i)//achar(48 + j)
        end do
    end do
    call w%emit('meridian_map_jacobian', ['g11', 'g12', 'g21', 'g22', 'up1', &
        'up2', 'x1 ', 'y1 '], [dfnames, 'jac'], &
        [df(1, :), df(2, :), df(3, :), det(df)], ad=.true.)
    call w%line('end module milca_nonnested_leaves')
    call w%close()
contains
    function cross(a, b) result(c)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: c(3)
        c(1) = a(2)*b(3) - a(3)*b(2)
        c(2) = a(3)*b(1) - a(1)*b(3)
        c(3) = a(1)*b(2) - a(2)*b(1)
    end function

    function dot(a, b) result(c)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: c
        c = a(1)*b(1) + a(2)*b(2) + a(3)*b(3)
    end function

    function upper(a) result(g)
        ! Upper triangle of the Gram matrix A^T A of the columns of a.
        type(expr_t), intent(in) :: a(3, 3)
        type(expr_t) :: g(6)
        g = [dot(a(:, 1), a(:, 1)), dot(a(:, 1), a(:, 2)), dot(a(:, 1), a(:, 3)), &
            dot(a(:, 2), a(:, 2)), dot(a(:, 2), a(:, 3)), dot(a(:, 3), a(:, 3))]
    end function

    function det(a) result(d)
        type(expr_t), intent(in) :: a(3, 3)
        type(expr_t) :: d
        d = dot(a(:, 1), cross(a(:, 2), a(:, 3)))
    end function
end program gen_nonnested
