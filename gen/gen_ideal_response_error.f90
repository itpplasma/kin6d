program gen_ideal_response_error
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(-), operator(/)
    use kin6d_gen_support, only: leaf_writer_t
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: writer
    type(expr_t) :: defect, after, ratio

    call arena%init()
    defect = sym(arena, 'defect')
    after = sym(arena, 'after')
    ratio = sym(arena, 'ratio')
    call writer%open(arena, 'gen_ideal_response_error', &
        'src/generated/kin6d_ideal_response_error_leaves.f90')
    call writer%line('! Generated by gen/gen_ideal_response_error.f90; do not edit.')
    call writer%line('module kin6d_ideal_response_error_leaves')
    call writer%line('    implicit none')
    call writer%line('contains')
    call writer%emit('ideal_ratio', &
        ['defect', 'after '], ['ratio'], [after/defect], ad=.true.)
    call writer%emit('ideal_tail', ['defect', 'ratio '], ['tail'], &
        [defect/(1 - ratio)], ad=.true.)
    call writer%line('end module kin6d_ideal_response_error_leaves')
    call writer%close()
end program gen_ideal_response_error
