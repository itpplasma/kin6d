program gen_interaction
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, func, abs, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: r(3), u(3), coupling, h, r2, norm, force(4), rn(3), un(3)
    type(expr_t) :: a0(3), a1(3), next_norm, jerk(3), radius, rate, value, dot
    type(expr_t) :: normal(3), direction(4), variables(4), energy, contact
    type(expr_t) :: speed2, discriminant, impact(3), reflected(3), time
    integer :: unit, j
    logical :: force_only
    character(32) :: argument

    force_only = .false.
    if (command_argument_count() > 1) error stop 'usage: gen_interaction ['// &
        '--force-only]'
    if (command_argument_count() == 1) then
        call get_command_argument(1, argument)
        if (trim(argument) /= '--force-only') error stop 'expected --force-only'
        force_only = .true.
    end if

    call arena%init()
    engine = make_native_engine(arena)
    r = [sym(arena, 'dx'), sym(arena, 'dy'), sym(arena, 'dz')]
    u = [sym(arena, 'ux'), sym(arena, 'uy'), sym(arena, 'uz')]
    coupling = sym(arena, 'coupling'); h = sym(arena, 'h')
    radius = sym(arena, 'radius'); rate = sym(arena, 'rate')
    value = sym(arena, 'value')
    normal = [sym(arena, 'nx'), sym(arena, 'ny'), sym(arena, 'nz')]
    r2 = r(1)**2 + r(2)**2 + r(3)**2
    norm = func('sqrt', [r2])
    do j = 1, 3
        force(j) = coupling*r(j)/(r2*norm)
        a0(j) = force(j)
        rn(j) = r(j) + h*u(j) + h**2*a0(j)/2
    end do
    force(4) = coupling/norm
    next_norm = func('sqrt', [rn(1)**2 + rn(2)**2 + rn(3)**2])
    do j = 1, 3
        a1(j) = coupling*rn(j)/next_norm**3
        un(j) = u(j) + h*(a0(j) + a1(j))/2
    end do
    variables = [r(1), r(2), r(3), coupling]
    direction = [u(1), u(2), u(3), 0*coupling]
    jerk = jvp(force(:3), variables, direction)
    energy = (u(1)**2 + u(2)**2 + u(3)**2)/2 + force(4)
    dot = r(1)*u(1) + r(2)*u(2) + r(3)*u(3)
    speed2 = u(1)**2 + u(2)**2 + u(3)**2
    discriminant = dot**2 - speed2*(r2 - radius**2)
    contact = (-dot - func('sqrt', [discriminant]))/speed2

    open (newunit=unit, file='src/generated/kin6d_interaction_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_interaction.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, '(a)') '! Unscreened Coulomb F=C*r/|r|^3, U=C/|r|, |r|>0.'
    write (unit, '(a)') '! Two-body relative dynamics: coupling=C/reduced_mass>0.'
    write (unit, &
           '(a)') '! Cartesian 3D; no softening, screening or confining force.'
    write (unit, '(a)') '! JVP/VJP use Euclidean Cartesian leaf pairings.'
    write (unit, &
           '(a)') '! Neutral event time has an approaching non-grazing root domain.'
    write (unit, '(a)') 'module kin6d_interaction_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('interaction_pair_force', ['dx      ', 'dy      ', 'dz      ', &
                                  'coupling'], ['fx       ', 'fy       ', 'fz       ', &
                                                       'potential'], &
              force, ad=.true., interval=.true.)
    if (force_only) then
        write (unit, '(a)') 'end module kin6d_interaction_leaves'
        close (unit)
        stop
    end if
    call emit('interaction_verlet', ['dx      ', 'dy      ', 'dz      ', &
                                     'ux      ', 'uy      ', 'uz      ', 'coupling', &
                                     'h       '], &
              ['rx', 'ry', 'rz', 'vx', 'vy', 'vz'], [rn, un], ad=.true.)
    call emit('interaction_energy', ['dx      ', 'dy      ', 'dz      ', &
                                     'ux      ', 'uy      ', 'uz      ', 'coupling'], &
              ['energy'], &
              [energy], ad=.true., interval=.true.)
    call emit('interaction_force_rate_interval', ['dx      ', 'dy      ', &
                                                  'dz      ', &
                               'coupling', 'ux      ', 'uy      ', 'uz      '], ['jx', &
                                                                          'jy', 'jz'], &
              jerk, rigorous=.true.)
    call emit('interaction_taylor_position_interval', &
              ['value', 'rate ', 'accel', 'h    '], ['next'], &
              [value + h*rate + h**2*sym(arena, 'accel')/2], rigorous=.true.)
    call emit('interaction_taylor_velocity_interval', &
              ['value', 'accel', 'jerk ', 'h    '], ['next'], &
              [value + h*sym(arena, 'accel') + h**2*sym(arena, 'jerk')/2], &
              rigorous=.true.)
    call emit('interaction_affine', ['value', 'rate ', 'h    '], &
              ['next'], [value + h*rate], ad=.true., interval=.true.)
    call emit('interaction_inflate_interval', ['value ', 'radius'], &
              ['lower', 'upper'], [value - radius, value + radius], rigorous=.true.)
    call emit('interaction_particle_error_interval', ['value ', 'center'], &
              ['radius'], [abs(value - sym(arena, 'center'))/2], rigorous=.true.)
    call emit('interaction_particle_coordinate', ['value', 'sign '], ['position'], &
              [value*sym(arena, 'sign')/2], ad=.true., interval=.true.)
    call emit('interaction_contact_outline', ['xc   ', 'yc   ', 'angle'], &
              ['x', 'y'], &
              [sym(arena, 'xc') + func('cos', [sym(arena, 'angle')])/2, &
               sym(arena, 'yc') + func('sin', [sym(arena, 'angle')])/2], ad=.true.)
    call emit('interaction_outline_angle', ['index'], ['angle'], &
              [2*pi_expr(arena)*sym(arena, 'index')/64], ad=.true.)
    call emit('interaction_plot_scale', ['value', 'scale'], ['scaled'], &
              [value*sym(arena, 'scale')], ad=.true.)
   call emit('interaction_plot_energy_drift', ['value    ', 'reference', 'scale    '], &
              ['scaled'], [(value - sym(arena, 'reference'))*sym(arena, 'scale')/ &
                           sym(arena, 'reference')], ad=.true.)
    call emit('interaction_frame_time', ['index ', 'stride', 'h     '], ['time'], &
              [sym(arena, 'index')*sym(arena, 'stride')*h], ad=.true., &
              interval=.true.)
    call emit('interaction_contact_time', ['dx    ', 'dy    ', 'dz    ', &
                                    'ux    ', 'uy    ', 'uz    ', 'radius'], ['time'], &
              [contact], ad=.true.)
    call emit('interaction_contact_geometry', ['dx    ', 'dy    ', 'dz    ', &
                                               'ux    ', 'uy    ', 'uz    ', &
                                               'radius'], &
              ['gap2        ', 'speed2      ', 'radial      ', 'discriminant'], &
              [r2 - radius**2, speed2, dot, discriminant], ad=.true.)
    time = sym(arena, 'time')
    do j = 1, 3
        impact(j) = r(j) + contact*u(j)
        normal(j) = impact(j)/radius
    end do
    dot = u(1)*normal(1) + u(2)*normal(2) + u(3)*normal(3)
    do j = 1, 3
        reflected(j) = u(j) - 2*dot*normal(j)
        rn(j) = impact(j) + (time - contact)*reflected(j)
    end do
    call emit('interaction_contact_after', ['dx    ', 'dy    ', 'dz    ', &
                                            'ux    ', 'uy    ', 'uz    ', 'radius', &
                                            'time  '], &
              ['rx', 'ry', 'rz', 'vx', 'vy', 'vz'], &
              [rn, reflected], ad=.true.)
    normal = [sym(arena, 'nx'), sym(arena, 'ny'), sym(arena, 'nz')]
    dot = u(1)*normal(1) + u(2)*normal(2) + u(3)*normal(3)
    call emit('interaction_contact_reflect', ['ux', 'uy', 'uz', 'nx', 'ny', 'nz'], &
              ['vx', 'vy', 'vz'], [u(1) - 2*dot*normal(1), &
                                   u(2) - 2*dot*normal(2), &
                                   u(3) - 2*dot*normal(3)], ad=.true.)
    write (unit, '(a)') 'end module kin6d_interaction_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_interaction; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_interaction')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_interaction from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_interaction
