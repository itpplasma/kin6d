program gen_interaction
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, func, abs, sqrt, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use fortsym_products, only: jvp
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: coulomb_force, coulomb_potential
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: r(3), u(3), coupling, h, r2, rn(3), jerk(3), radius, rate
    type(expr_t) :: value, dot, normal(3), direction(4), variables(4), energy
    type(expr_t) :: contact, speed2, discriminant, impact(3), reflected(3), time
    integer :: j

    call arena%init()
    r = [sym(arena, 'dx'), sym(arena, 'dy'), sym(arena, 'dz')]
    u = [sym(arena, 'ux'), sym(arena, 'uy'), sym(arena, 'uz')]
    coupling = sym(arena, 'coupling'); h = sym(arena, 'h')
    radius = sym(arena, 'radius'); rate = sym(arena, 'rate')
    value = sym(arena, 'value')
    normal = [sym(arena, 'nx'), sym(arena, 'ny'), sym(arena, 'nz')]
    r2 = r(1)**2 + r(2)**2 + r(3)**2
    ! Relative acceleration and specific energy from the single Coulomb source
    ! with coupling = g/mu; the force rate is its tangent along r' = u.
    variables = [r(1), r(2), r(3), coupling]
    direction = [u(1), u(2), u(3), 0*coupling]
    jerk = jvp(coulomb_force(coupling, r), variables, direction)
    energy = (u(1)**2 + u(2)**2 + u(3)**2)/2 + coulomb_potential(coupling, sqrt(r2))
    dot = r(1)*u(1) + r(2)*u(2) + r(3)*u(3)
    speed2 = u(1)**2 + u(2)**2 + u(3)**2
    discriminant = dot**2 - speed2*(r2 - radius**2)
    contact = (-dot - func('sqrt', [discriminant]))/speed2

    call w%open(arena, 'gen_interaction', 'src/generated/kin6d_interaction_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_interaction.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, '(a)') '! Relative-coordinate Coulomb encounter: coupling=g/mu>0;'
    write (w%unit, '(a)') '! Coulomb terms from gen/kin6d_symbolic_physics.f90, |r|>0.'
    write (w%unit, &
           '(a)') '! Cartesian 3D; no softening, screening or confining force.'
    write (w%unit, '(a)') '! JVP/VJP use Euclidean Cartesian leaf pairings.'
    write (w%unit, &
           '(a)') '! Neutral event time has an approaching non-grazing root domain.'
    write (w%unit, '(a)') 'module kin6d_interaction_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('interaction_energy', ['dx      ', 'dy      ', 'dz      ', &
                                     'ux      ', 'uy      ', 'uz      ', 'coupling'], &
              ['energy'], &
              [energy], ad=.true., interval=.true.)
    call w%emit('interaction_force_rate_interval', ['dx      ', 'dy      ', &
                                                  'dz      ', &
                               'coupling', 'ux      ', 'uy      ', 'uz      '], ['jx', &
                                                                          'jy', 'jz'], &
              jerk, rigorous=.true.)
    call w%emit('interaction_taylor_position_interval', &
              ['value', 'rate ', 'accel', 'h    '], ['next'], &
              [value + h*rate + h**2*sym(arena, 'accel')/2], rigorous=.true.)
    call w%emit('interaction_taylor_velocity_interval', &
              ['value', 'accel', 'jerk ', 'h    '], ['next'], &
              [value + h*sym(arena, 'accel') + h**2*sym(arena, 'jerk')/2], &
              rigorous=.true.)
    call w%emit('interaction_affine', ['value', 'rate ', 'h    '], &
              ['next'], [value + h*rate], ad=.true., interval=.true.)
    call w%emit('interaction_particle_error_interval', ['value ', 'center'], &
              ['radius'], [abs(value - sym(arena, 'center'))/2], rigorous=.true.)
    call w%emit('interaction_particle_coordinate', ['value', 'sign '], ['position'], &
              [value*sym(arena, 'sign')/2], ad=.true., interval=.true.)
    call w%emit('interaction_frame_time', ['index ', 'stride', 'h     '], ['time'], &
              [sym(arena, 'index')*sym(arena, 'stride')*h], ad=.true., &
              interval=.true.)
    call w%emit('interaction_contact_time', ['dx    ', 'dy    ', 'dz    ', &
                                    'ux    ', 'uy    ', 'uz    ', 'radius'], ['time'], &
              [contact], ad=.true.)
    call w%emit('interaction_contact_geometry', ['dx    ', 'dy    ', 'dz    ', &
                                               'ux    ', 'uy    ', 'uz    ', &
                                               'radius'], &
              ['gap2        ', 'speed2      ', 'radial      ', 'discriminant'], &
              [r2 - radius**2, speed2, dot, discriminant], ad=.true.)
    time = sym(arena, 'time')
    do j = 1, 3
        impact(j) = r(j) + contact*u(j)
        normal(j) = impact(j)/radius
    end do
    dot = u(1)*normal(1) + u(2)*normal(2) + u(3)*normal(3)
    do j = 1, 3
        reflected(j) = u(j) - 2*dot*normal(j)
        rn(j) = impact(j) + (time - contact)*reflected(j)
    end do
    call w%emit('interaction_contact_after', ['dx    ', 'dy    ', 'dz    ', &
                                            'ux    ', 'uy    ', 'uz    ', 'radius', &
                                            'time  '], &
              ['rx', 'ry', 'rz', 'vx', 'vy', 'vz'], &
              [rn, reflected], ad=.true.)
    normal = [sym(arena, 'nx'), sym(arena, 'ny'), sym(arena, 'nz')]
    dot = u(1)*normal(1) + u(2)*normal(2) + u(3)*normal(3)
    call w%emit('interaction_contact_reflect', ['ux', 'uy', 'uz', 'nx', 'ny', 'nz'], &
              ['vx', 'vy', 'vz'], [u(1) - 2*dot*normal(1), &
                                   u(2) - 2*dot*normal(2), &
                                   u(3) - 2*dot*normal(3)], ad=.true.)
    write (w%unit, '(a)') 'end module kin6d_interaction_leaves'
    call w%close()
end program gen_interaction
