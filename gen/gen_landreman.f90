program gen_landreman
    ! Landreman v2 eqs. (7)-(8), mu0=1, cylindrical (R,phi,Z).
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, sin, cos, &
                        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(native_engine_t) :: eng
    type(engine_result_t) :: check
    type(leaf_writer_t) :: w
    type(expr_t) :: r, z, delta, psi, p, b(3), j(3), gp(2), f
    type(expr_t) :: theta, rho, u, t, len, angle, up, zp, rp, weight, ratio
    type(expr_t) :: residual(6)
    integer :: k
    call arena%init()
    eng = make_native_engine(arena)
    r = sym(arena, 'r'); z = sym(arena, 'z'); delta = sym(arena, 'delta')
    psi = (r*r - 1)**2/4 + z*z
    p = 2*(delta - psi)
    f = sqrt(1 - 4*psi)
    b = [2*z/r, f/r, 1 - r*r]
    gp = [diff(psi, r), diff(psi, z)]
    j = [0 - diff(b(2), z), diff(b(1), z) - diff(b(3), r), &
         diff(r*b(2), r)/r]
    residual(1) = diff(r*b(1), r)/r + diff(b(3), z)
    residual(2) = b(1)*gp(1) + b(3)*gp(2)
    residual(3) = j(2)*b(3) - j(3)*b(2) - diff(p, r)
    residual(4) = j(3)*b(1) - j(1)*b(3)
    residual(5) = j(1)*b(2) - j(2)*b(1) - diff(p, z)
    residual(6) = j(1)*gp(1) + j(3)*gp(2)
    do k = 1, 6
        check = eng%zero_test(residual(k))
        if (check%verdict /= VERDICT_TRUE) then
            print *, 'unproved Landreman identity', k
            error stop 1
        end if
    end do
    call w%open(arena, 'gen_landreman', &
                'src/generated/kin6d_landreman_leaves.f90')
    call w%line('! Generated by gen/gen_landreman.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! mu0=1; R>0, 0<delta<1/4, psi<=delta. Order (R,phi,Z).')
    call w%line('module kin6d_landreman_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('landreman_axisymmetric', ['r    ', 'z    ', 'delta'], &
                [character(4) :: 'psi', 'p', 'br', 'bt', 'bz', 'jr', 'jt', 'jz', &
                 'gr', 'gz'], [psi, p, b, j, gp], ad=.true.)
    call w%emit('landreman_toroidal_external', ['r    ', 'delta'], &
                ['bt'], [sqrt(1 - 4*delta)/r], ad=.true.)
    ! Construct a point on S0 along a radial line in (u=(R^2-1)/2,Z).
    ! Its Euclidean distance is an upper estimate of distance to S0.
    ratio = sqrt(delta/psi)
    call w%emit('landreman_project_surface', ['r    ', 'z    ', 'delta'], &
                ['rs', 'zs'], [sqrt(1 + (r*r - 1)*ratio), z*ratio], ad=.true.)
    theta = sym(arena, 'theta'); rho = sym(arena, 'rho')
    u = sqrt(delta)*cos(theta); t = sqrt(delta)*sin(theta)
    call w%emit('landreman_surface', ['theta', 'delta'], &
                [character(4) :: 'r', 'z', 'dr', 'dz'], &
                [sqrt(1 + 2*u), t, -t/sqrt(1 + 2*u), u], ad=.true.)
    ! Boundary-centred Duffy rays in the circular (u,z) cross-section.
    ! angle is measured from the tangent into the inward half-plane.
    angle = sym(arena, 'angle')
    len = 2*sqrt(delta)*sin(angle)
    up = u + rho*len*cos(theta + angle + acos(-1.0d0)/2)
    zp = t + rho*len*sin(theta + angle + acos(-1.0d0)/2)
    rp = sqrt(1 + 2*up)
    weight = (2/rp + 2*rp)*rho*len*len/rp
    call w%emit('landreman_current_ray', &
                ['theta', 'delta', 'rho  ', 'angle'], &
                [character(6) :: 'rp', 'zp', 'weight'], [rp, zp, weight], ad=.true.)
    call w%line('end module kin6d_landreman_leaves')
    call w%close()
    print *, 'Landreman: six exact native zero tests PASS (no probes)'
end program gen_landreman
