program gen_dk_ntv
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: cos_t, sin_t, eps, k, offset, b

    ! Frozen-field NTV benchmark surface: |B|/B0 = b = 1 - eps cos(theta),
    ! b.grad theta = k, lambda = (1 - xi^2)/b. The grad-B precession is local,
    ! Omega_d = pre lambda (cos(theta) - offset) with bounce average
    ! -(mu B0/(e chi')) eps' (2E/K - 1 - offset); per unit pre the factor of
    ! (1 - xi^2) is (cos(theta) - offset)/b. The drive lambda S has the
    ! Legendre components 2/(3b) (P0) and -2/(3b) (P2) of S, and the flux
    ! measure int dlambda/|xi| lambda = int dxi (2/b) lambda gives 2/b^2 per
    ! unit (1 - xi^2). With the streaming b.grad theta = k b of Boozer angles
    ! (Jacobian ~ 1/B^2) the streaming and mirror factors are k b and
    ! k eps sin(theta)/2, and the surface measure dtheta/(b.grad theta B)
    ! adds 1/b to the flux measure.
    cos_t = sym('cos_t'); sin_t = sym('sin_t'); eps = sym('eps'); k = sym('k')
    offset = sym('offset')
    b = 1 - eps*cos_t

    call writer%open('gen_dk_ntv', 'src/generated/milca_dk_ntv_leaves.f90')
    call writer%line('! Generated by gen/gen_dk_ntv.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module milca_dk_ntv_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('dk_ntv_point', ['cos_t ', 'sin_t ', 'eps   ', 'k     ', 'offset'], &
        ['b        ', 'mirror   ', 'drift    ', 'source   ', 'measure  ', 'stream_b ', &
        'mirror_b ', 'measure_b'], &
        [b, k*eps*sin_t/(2*b), (cos_t - offset)/b, 2/(3*b), 2/(b*b), k*b, k*eps*sin_t/2, &
        2/(b*b*b)], ad=.true.)
    call writer%line('end module milca_dk_ntv_leaves')
    call writer%close()
end program gen_dk_ntv
