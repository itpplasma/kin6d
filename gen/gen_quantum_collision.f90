program gen_quantum_collision
    ! Generates the project-owned numerical leaves of the QG6 binary-collision
    ! kernel (src/pairs/quantum_collision_kernel.f90) and hybrid classical/quantum
    ! encounter (src/quantum/hybrid_encounter.f90). Physics from
    ! gen/kin6d_symbolic_physics.f90 (screened partial-wave potential,
    ! Sommerfeld parameter); kinematics of the repulsive Kepler hyperbola.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, exp, log, atan, tan, erf, pi_expr, rat, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: screened_partial_wave_potential, &
                                      yukawa_potential, sommerfeld_parameter
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: r, l, g, mu, hbar, lambda, v, eta, kappa, b, b90, theta, n
    type(expr_t) :: ls, x, dens, m, mf, lnl, psi, gr, vb, temp, a, v2, h, h2, amag
    type(expr_t) :: u, energy

    call arena%init()
    r = sym(arena, 'r'); l = sym(arena, 'l'); g = sym(arena, 'g')
    mu = sym(arena, 'mu'); hbar = sym(arena, 'hbar'); lambda = sym(arena, 'lambda')
    v = sym(arena, 'v'); eta = sym(arena, 'eta'); kappa = sym(arena, 'kappa')
    b = sym(arena, 'b'); b90 = sym(arena, 'b90'); theta = sym(arena, 'theta')
    n = sym(arena, 'n'); ls = sym(arena, 'ls'); x = sym(arena, 'x')
    dens = sym(arena, 'density'); m = sym(arena, 'm'); mf = sym(arena, 'mf')
    lnl = sym(arena, 'lnl'); psi = sym(arena, 'psi'); gr = sym(arena, 'gr')
    vb = sym(arena, 'vb'); temp = sym(arena, 'temperature'); a = sym(arena, 'a')
    v2 = sym(arena, 'v2'); h = sym(arena, 'h'); h2 = sym(arena, 'h2')
    amag = sym(arena, 'amag'); u = sym(arena, 'u'); energy = sym(arena, 'energy')

    call w%open(arena, 'gen_quantum_collision', &
                'src/generated/kin6d_quantum_collision_leaves.f90')
    call w%line('! Generated by gen/gen_quantum_collision.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! QG6 binary Coulomb collision kernel: relative motion, reduced mass mu,')
    call w%line('! coupling g > 0 (repulsive), bare g/r or screened g exp(-r/lambda)/r.')
    call w%line('! eta = g/(hbar v), k = mu v/hbar, kappa = k lambda_D, b90 = g/(mu v^2).')
    call w%line('! Coulomb logarithms are normalized as sigma_tr/(4 pi b90^2).')
    call w%line('! JVP/VJP use Euclidean pairings of the listed real arguments.')
    call w%line('module kin6d_quantum_collision_leaves')
    call w%line('implicit none')
    call w%line('contains')

    ! Screened radial operator (shared symbolic definition, replaces g/r).
    call w%emit('qc_screened_radial_potential', ['r     ', 'l     ', 'g     ', 'mu    ', &
              'hbar  ', 'lambda'], ['v'], &
              [screened_partial_wave_potential(g, hbar, mu, l, r, lambda)], ad=.true.)
    ! Classical screened radial function in u = 1/r at energy E (deflection).
    call w%emit('qc_yukawa_radial', ['u     ', 'b     ', 'g     ', 'energy', 'lambda'], &
              ['f'], [1 - b**2*u**2 - yukawa_potential(g, lambda, 1/u)/energy])

    ! Pair scales at relative speed v.
    call w%emit('qc_pair_scales', ['g   ', 'mu  ', 'hbar', 'v   '], &
              ['eta      ', 'k        ', 'lambdabar', 'b90      '], &
              [sommerfeld_parameter(g, hbar, v), mu*v/hbar, hbar/(mu*v), g/(mu*v**2)], &
              ad=.true.)

    ! Rutherford deflection of impact parameter b and its inverse.
    call w%emit('qc_rutherford_deflection', ['b  ', 'b90'], ['theta'], &
              [2*atan(b90/b)], ad=.true.)
    call w%emit('qc_rutherford_impact', ['theta', 'b90  '], ['b'], [b90/tan(theta/2)])

    ! Pure-Coulomb partial-wave ring n = l+1: sigma_{l+1}-sigma_l = atan(eta/n),
    ! deflection 2 atan(eta/n), momentum-transfer term n/(n^2+eta^2).
    call w%emit('qc_ring_deflection', ['eta', 'n  '], ['chi'], [2*atan(eta/n)], ad=.true.)
    call w%emit('qc_ring_transfer', ['eta', 'n  '], ['t'], [n/(n**2 + eta**2)], ad=.true.)
    ! Fraction of ring l = n-1 inside k b <= kappa (Langer rings k b_l = sqrt(l(l+1))).
    call w%emit('qc_partial_ring', ['kappa', 'n    '], ['w'], &
              [(kappa**2 - n*(n - 1))/(2*n)])

    ! Classical Rutherford transfer with sharp impact cut, total and far zone
    ! (k b_s)^2 = ls < (k b) < kappa.
    call w%emit('qc_cut_log_classical', ['eta  ', 'kappa'], ['lnl'], &
              [log(1 + kappa**2/eta**2)/2], ad=.true.)
    call w%emit('qc_far_classical_log', ['eta  ', 'kappa', 'ls   '], ['lnl'], &
              [log((kappa**2 + eta**2)/(ls + eta**2))/2], ad=.true.)
    ! First Born approximation for the Yukawa potential (closed form).
    call w%emit('qc_born_yukawa_log', ['kappa'], ['lnl'], &
              [(log(1 + 4*kappa**2) - 4*kappa**2/(1 + 4*kappa**2))/2], ad=.true.)

    ! Chandrasekhar function and test-particle slowing-down rate (Landau
    ! collision integral, constant Coulomb logarithm lnl).
    call w%emit('qc_chandrasekhar', ['x'], ['psi'], &
              [erf(x) - 2*x*exp(-x**2)/sqrt(pi_expr(arena))], ad=.true.)
    call w%emit('qc_slowing_rate', ['density', 'g      ', 'm      ', 'mf     ', &
              'lnl    ', 'v      ', 'psi    '], ['nu'], &
              [(1 + m/mf)*4*pi_expr(arena)*dens*g**2*lnl*psi/(m**2*v**3)], ad=.true.)
    ! Maxwellian relative-speed weight (field Maxwellian shifted by the beam
    ! velocity vb) and the angular moment int c exp(a c) dc * exp(-a).
    call w%emit('qc_maxwell_weight', ['gr         ', 'vb         ', 'temperature', &
              'mf         '], ['w'], &
              [2*pi_expr(arena)*gr**4*(mf/(2*pi_expr(arena)*temp))**rat(arena, 3_8, 2_8)* &
               exp(-mf*(gr - vb)**2/(2*temp))])
    call w%emit('qc_angle_moment', ['a'], ['j'], [((a - 1) + (a + 1)*exp(-2*a))/a**2])
    call w%emit('qc_angle_moment_series', ['a'], ['j'], &
              [2*exp(-a)*(a/3 + a**3/30 + a**5/840 + a**7/45360 + a**9/3991680)])

    ! Repulsive Kepler hyperbola (specific quantities, kappa_g = g/mu).
    call w%emit('qc_asymptotic_speed', ['v2', 'r ', 'g ', 'mu'], ['vinf'], &
              [sqrt(v2 + 2*g/(mu*r))])
    call w%emit('qc_orbit_cosine', ['h2  ', 'r   ', 'g   ', 'mu  ', 'amag'], ['c'], &
              [(h2/r + g/mu)/amag])
    call w%emit('qc_radial_speed', ['v ', 'r ', 'g ', 'mu', 'h '], ['vr'], &
              [sqrt(v**2 - 2*g/(mu*r) - h**2/r**2)])

    call w%line('end module kin6d_quantum_collision_leaves')
    call w%close()
end program gen_quantum_collision
