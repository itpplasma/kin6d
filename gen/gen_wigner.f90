program gen_wigner
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, num, pi_expr, exp, sin, cos, sqrt, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use fortsym_string, only: str
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: modal_poisson, phase_rotation
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: hbar, k, eta, nr, ni, dt, s, vr, vi, n, fr, fi, phase
    type(expr_t) :: tr, ti, dphase, v, u, sigma, weight, er, ei, length, acc
    type(expr_t) :: vth, v0, a, omega, c, b, disc, mode(4)

    call arena%init()
    hbar = sym(arena, 'hbar'); k = sym(arena, 'k'); eta = sym(arena, 'eta')
    nr = sym(arena, 'nr'); ni = sym(arena, 'ni'); dt = sym(arena, 'dt')
    s = sym(arena, 's'); vr = sym(arena, 'vr'); vi = sym(arena, 'vi')
    n = sym(arena, 'n'); fr = sym(arena, 'fr'); fi = sym(arena, 'fi')
    phase = sym(arena, 'phase'); tr = sym(arena, 'tr'); ti = sym(arena, 'ti')
    dphase = sym(arena, 'dphase'); v = sym(arena, 'v'); u = sym(arena, 'u')
    sigma = sym(arena, 'sigma'); weight = sym(arena, 'weight')
    er = sym(arena, 'er'); ei = sym(arena, 'ei'); length = sym(arena, 'length')
    acc = sym(arena, 'acc'); vth = sym(arena, 'vth'); v0 = sym(arena, 'v0')

    call w%open(arena, 'gen_wigner', 'src/generated/kin6d_wigner_leaves.f90')
    w%runtime%sqrt = str('sqrt')
    call w%line('! Generated by gen/gen_wigner.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! 1X1V electron Wigner-Poisson with neutralizing background.')
    call w%line('! Units: t omega_p, x omega_p/v_ref, v/v_ref, m = 1, electron q = -1,')
    call w%line('! hbar = hbar omega_p/(m v_ref^2). phi_xx = n - 1, V = -phi.')
    call w%line('! Kick in (x,eta): d/dt fhat = i sum_k s_k(eta) Vhat_k e^{ikx} fhat,')
    call w%line('! s_k = 2 sin(hbar k eta/2)/hbar (Wigner), k eta (Vlasov, hbar = 0).')
    call w%line('! Free streaming reuses kin6d_streaming_leaves:streaming_rotation.')
    call w%line('module kin6d_wigner_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('wigner_shift_symbol', ['hbar', 'k   ', 'eta '], ['s'], &
        [2*sin(hbar*k*eta/2)/hbar], ad=.true.)
    call w%emit('vlasov_shift_symbol', ['k  ', 'eta'], ['s'], [k*eta], ad=.true.)
    ! Electron charge rho_k = -n_k (k /= 0): shared modal Poisson law with
    ! rc = Re rho_k, rs = -Im rho_k; phi_k = phi_c - i phi_s, E_k = E_c - i E_s.
    mode = modal_poisson(num(arena, 1), k, -nr, ni)
    ! Electron potential energy V = -phi, i.e. V_k = n_k/k^2.
    call w%emit('wigner_potential_mode', ['k ', 'nr', 'ni'], ['vr', 'vi'], &
        [-mode(1), mode(2)], ad=.true.)
    ! E = -phi_x: E_k = i n_k/k.
    call w%emit('wigner_field_mode', ['k ', 'nr', 'ni'], ['er', 'ei'], &
        [mode(3), -mode(4)], ad=.true.)
    ! Mode coefficient of the kick phase dt*(1/n) i s Vhat (inverse DFT later).
    call w%emit('wigner_phase_coefficient', ['dt', 's ', 'vr', 'vi', 'n '], &
        ['pr', 'pi'], [-dt*s*vi/n, dt*s*vr/n], ad=.true.)
    ! Exact kick e^{i phase} fhat and its tangent e^{i phase}(t + i dphase f).
    call w%emit('wigner_kick', ['fr   ', 'fi   ', 'phase'], ['gr', 'gi'], &
        phase_rotation(fr, fi, cos(phase), sin(phase)))
    call w%emit('wigner_kick_tangent', ['fr    ', 'fi    ', 'tr    ', 'ti    ', &
        'phase ', 'dphase'], ['gr', 'gi'], &
        phase_rotation(tr - dphase*fi, ti + dphase*fr, cos(phase), sin(phase)))
    call w%emit('wigner_field_energy_mode', ['er    ', 'ei    ', 'length', &
        'n     ', 'acc   '], ['next'], [acc + length*(er**2 + ei**2)/(2*n**2)])
    call w%emit('wigner_maxwellian', ['v     ', 'u     ', 'sigma ', 'weight'], &
        ['f'], [weight*exp(-(v - u)**2/(2*sigma**2))/ &
        (sqrt(2*pi_expr(arena))*sigma)], ad=.true.)
    ! Small-k quantum Bohm-Gross law (asymptotic oracle, not the exact root).
    call w%emit('wigner_bohm_gross', ['k   ', 'vth ', 'hbar'], ['omega'], &
        [sqrt(1 + 3*k**2*vth**2 + hbar**2*k**4/4)], ad=.true.)
    ! Cold symmetric quantum two-stream (two beams, density 1/2 each):
    ! 1 = (1/2)/((w-a)^2-W^2) + (1/2)/((w+a)^2-W^2), a = k v0, W = hbar k^2/2,
    ! u = w^2 solves u^2 + b u + c^2 - c = 0, c = a^2 - W^2, b = 2c - 4a^2 - 1.
    a = k*v0
    omega = hbar*k**2/2
    c = a**2 - omega**2
    b = 2*c - 4*a**2 - 1
    disc = (4*a**2 + 1)**2 - 16*a**2*c
    call w%emit('wigner_cold_two_stream', ['k   ', 'v0  ', 'hbar'], ['umin'], &
        [(-b - sqrt(disc))/2], ad=.true.)
    call w%line('end module kin6d_wigner_leaves')
    call w%close()
end program gen_wigner
