program gen_solovev_geometry
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: solovev_level
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: writer
    type(expr_t) :: r, z, r0, level, tau, h, p, c, beta, ni, nj
    type(expr_t) :: gi, gj, v, bir, biz, bjr, bjz, krr, krz, kzz
    type(expr_t) :: hi, hj, hij, pi, pj, pij, ci, cj, di
    type(expr_t) :: boundary, q, a, b, pc, ai, aj, bi, bj, ei, eij
    type(expr_t) :: aij, bij, pci, pcj, discriminant
    call arena%init()
    r = sym(arena, 'r'); z = sym(arena, 'z'); r0 = sym(arena, 'r0')
    tau = sym(arena, 'tau'); h = sym(arena, 'h'); p = sym(arena, 'p')
    c = sym(arena, 'c'); beta = sym(arena, 'beta')
    ni = sym(arena, 'ni'); nj = sym(arena, 'nj')
    gi = sym(arena, 'gi'); gj = sym(arena, 'gj'); v = sym(arena, 'v')
    bir = sym(arena, 'bir'); biz = sym(arena, 'biz')
    bjr = sym(arena, 'bjr'); bjz = sym(arena, 'bjz')
    krr = sym(arena, 'krr'); krz = sym(arena, 'krz'); kzz = sym(arena, 'kzz')
    hi = sym(arena, 'hi'); hj = sym(arena, 'hj'); hij = sym(arena, 'hij')
    pi = sym(arena, 'pi'); pj = sym(arena, 'pj'); pij = sym(arena, 'pij')
    ci = sym(arena, 'ci'); cj = sym(arena, 'cj')
    di = sym(arena, 'di'); level = sym(arena, 'level')
    boundary = solovev_level(r, z, r0)
    q = 1-tau
    a = h-p; b = -h**2+q*h*p; pc = 2*a*c+b
    ai = hi-pi; aj = hj-pj
    bi = -2*h*hi+q*(p*hi+h*pi)
    bj = -2*h*hj+q*(p*hj+h*pj)
    ei = 2*tau*h*hi
    aij = hij-pij
    bij = -2*hi*hj-2*h*hij+q*(p*hij+hi*pj+hj*pi+h*pij)
    eij = 2*tau*(hi*hj+h*hij)
    pci = 2*ai*c+bi; pcj = 2*aj*c+bj
    discriminant = (h-q*p)**2-4*tau*(h-p)
    call writer%open(arena, 'gen_solovev_geometry', &
        'src/generated/kin6d_solovev_geometry_leaves.f90')
    call writer%line('! Generated by gen/gen_solovev_geometry.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('! Smooth-piece spatial jets; no arithmetic/geometry certificate.')
    call writer%line('module kin6d_solovev_geometry_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('solovev_geometry_rectangle', ['r0   ', 'level'], &
        ['rmin', 'rmax', 'zmax'], [sqrt(r0**2-sqrt(level)), &
        sqrt(r0**2+sqrt(level)), sqrt(level)/(2*sqrt(r0**2-sqrt(level)))], &
        ad=.true.)
    call writer%emit('solovev_geometry_level', ['r ', 'z ', 'r0'], &
        ['value'], [boundary], ad=.true.)
    call writer%emit('solovev_boundary_jet', ['r ', 'z ', 'r0'], &
        ['gr ', 'gz ', 'hrr', 'hrz', 'hzz'], &
        [diff(boundary, r), diff(boundary, z), diff(diff(boundary, r), r), &
        diff(diff(boundary, r), z), diff(diff(boundary, z), z)], ad=.true.)
    call writer%emit('solovev_inverse_discriminant', ['tau', 'h  ', 'p  '], &
        ['discriminant'], [discriminant], ad=.true.)
    call writer%emit('solovev_inverse_scale', ['tau', 'h  ', 'p  '], &
        ['c'], [2*tau*h/(h-q*p+sqrt(discriminant))], ad=.true.)
    call writer%emit('solovev_h_first', ['h ', 'gi', 'v '], &
        ['hi'], [-h*gi/v], ad=.true.)
    call writer%emit('solovev_h_second', &
        ['gi ', 'gj ', 'v  ', 'bir', 'biz', 'bjr', 'bjz', &
        'krr', 'krz', 'kzz', 'hi ', 'hj '], ['hij'], &
        [-(bir*krr*bjr+(bir*bjz+biz*bjr)*krz+biz*kzz*bjz+gi*hj+gj*hi)/v], &
        ad=.true.)
    call writer%emit('solovev_facet_first', ['p   ', 'beta', 'ni  '], &
        ['pi'], [-p**2*ni/beta], ad=.true.)
    call writer%emit('solovev_facet_second', ['p   ', 'beta', 'ni  ', 'nj  '], &
        ['pij'], [2*p**3*ni*nj/beta**2], ad=.true.)
    call writer%emit('solovev_c_first', &
        ['tau', 'h  ', 'p  ', 'c  ', 'hi ', 'pi '], &
        ['ci'], [-(ai*c**2+bi*c+ei)/pc], ad=.true.)
    call writer%emit('solovev_c_second', &
        ['tau', 'h  ', 'p  ', 'c  ', 'hi ', 'hj ', 'hij', 'pi ', 'pj ', &
        'pij', 'ci ', 'cj '], ['cij'], &
        [-(aij*c**2+bij*c+eij+pci*cj+pcj*ci+2*a*ci*cj)/pc], ad=.true.)
    ! Indexed Cartesian assembly uses these scalar leaves for each component.
    call writer%emit('solovev_map_first', ['c ', 'di', 'ci', 'ni'], &
        ['ji'], [c*ni+di*ci], ad=.true.)
    call writer%emit('solovev_map_second', ['di ', 'ci ', 'cj ', 'hij', 'ni ', 'nj '], &
        ['hessian'], [ni*cj+nj*ci+di*hij], ad=.true.)
    call writer%line('end module kin6d_solovev_geometry_leaves')
    call writer%close()
end program
