! Manufactured invariant state and first orbit harmonic, with full nonlinear
! and linearised strong sources differentiated in Cartesian coordinates.
program gen_vrmhd_mms_fourier
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, sin, cos, operator(+), &
        operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs_many
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(symengine_engine_t) :: engine
    type(leaf_writer_t) :: w, nonlinear
    type(expr_t) :: xyz(3), x, y, r0, k, c0, s0, e, q1, q2, ct, st, radius, zero, one
    type(expr_t) :: u(36), force(12), roots(84), full(48), a(3), b(3), jv(3), v(3)
    type(expr_t) :: rho, te, ti, pressure, eta, nu, chi(2), stress(3, 3), gv(3, 3)
    type(expr_t) :: strain(3, 3), unitb(3), flux(3), mom(3, 3), divv, heat(2), &
        temperature, aa, section_a(3), local_v(3), normalization, cp, sp
    type(engine_result_t) :: simplified
    character(16) :: names(84), suffix, index_text
    character(16), allocatable :: arguments(:)
    character(:), allocatable :: signature, declaration
    integer :: kind, i, l, s
    call arena%init(); engine = make_symengine_engine(arena)
    zero = rat(arena, 0_int64, 1_int64); one = rat(arena, 1_int64, 1_int64)
    x = sym(arena, 'x'); y = sym(arena, 'y'); r0 = sym(arena, 'r0')
    k = sym(arena, 'k')
    c0 = sym(arena, 'c0'); s0 = sym(arena, 's0'); e = sym(arena, 'e')
    xyz = [sym(arena, 'xx'), sym(arena, 'yy'), sym(arena, 'zz')]
    do i = 1, 84
        write (names(i), '(a,i0)') 'out', i
    end do
    call w%open(arena, 'gen_vrmhd_mms_fourier', &
        'test/support/vrmhd_mms_fourier_leaves.f90')
    call w%line('! Generated by gen/gen_vrmhd_mms_fourier.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module vrmhd_mms_fourier_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call nonlinear%open(arena, 'gen_vrmhd_mms_fourier', &
        'test/support/vrmhd_mms_nonlinear_leaves.f90')
    call nonlinear%line('! Generated by gen/gen_vrmhd_mms_fourier.f90; do not edit.')
    call nonlinear%line('! FortSym revision: '//fortsym_revision)
    call nonlinear%line('module vrmhd_mms_nonlinear_leaves')
    call nonlinear%line('implicit none')
    call nonlinear%line('contains')
    do kind = 1, 3
        if (kind == 1) then
            suffix = 'rotation'
            radius = (xyz(1)**2 + xyz(2)**2)**rat(arena, 1_int64, 2_int64)
            q1 = radius; q2 = xyz(3); ct = xyz(1)/radius; st = xyz(2)/radius
        else if (kind == 2) then
            suffix = 'translation'
            q1 = xyz(1); q2 = xyz(2); ct = cos(xyz(3)/r0); st = sin(xyz(3)/r0)
        else
            suffix = 'screw'
            q1 = cos(k*xyz(3))*xyz(1) + sin(k*xyz(3))*xyz(2)
            q2 = -sin(k*xyz(3))*xyz(1) + cos(k*xyz(3))*xyz(2)
            ct = cos(xyz(3)/r0); st = sin(xyz(3)/r0)
        end if
        arguments = [character(16) :: 'x', 'y', 'r0', 'c0', 's0']
        signature = '(x,y,r0,c0,s0'
        declaration = 'real(8), intent(in) :: x,y,r0,c0,s0'
        if (kind == 3) then
            arguments = [character(16) :: 'x', 'y', 'r0', 'k', 'c0', 's0']
            signature = '(x,y,r0,k,c0,s0'
            declaration = 'real(8), intent(in) :: x,y,r0,k,c0,s0'
        end if
        ! cos and sin of t + t0 for the orbit parameter t and phase (c0, s0).
        cp = ct*c0 - st*s0; sp = st*c0 + ct*s0
        if (kind == 2) then
            ct = one; st = zero
        else if (kind == 3) then
            ct = cos(k*xyz(3)); st = sin(k*xyz(3))
        end if
        rho = 2 + sin(q1)*cos(q2)/10 + e*(sin(q1)*sin(q2)*cp + cos(q1 + q2)*sp)/10
        te = one + sin(q1)*sin(q2)/10 + e*cos(q1)*cos(q2)*sp/10
        ti = one + cos(q1)*sin(q2)/10 + e*sin(q1 + q2)*cp/10
        local_v = [sin(q1)*cos(q2)/10 + e*cos(q1)*sin(q2)*cp/10, &
            cos(q1)*sin(q2)/10 + e*sin(q1 + q2)*sp/10, &
            one/5 + cos(q1 + q2)/20 + e*(cp + sin(q1)*sp)/10]
        v = rotate(local_v)
        aa = one + cos(q1)*cos(q2)/10
        if (kind == 1) then
            section_a = [cos(q1)*sin(q2)/(10*q1), aa/q1, &
                -sin(q1)*cos(q2)/(10*q1)]
            a = rotate(section_a)
        else
            section_a = [sin(q2)/10, zero, cos(q1)*cos(q2)/10]
            if (kind == 3) then
                a = curl(rotate(section_a))
            else
                a = curl(section_a)
            end if
        end if
        section_a = [sin(q2)*cp, cos(q1)*sp, sin(q1)*cos(q2)*cp]
        section_a = rotate(section_a)
        do i = 1, 3
            a(i) = a(i) + e*section_a(i)/10
        end do
        b = curl(a); jv = curl(b)
        pressure = rho*(te + ti)
        eta = te**rat(arena, -3_int64, 2_int64)/5
        nu = ti**rat(arena, -3_int64, 2_int64)/5
        chi = [te**rat(arena, 5_int64, 2_int64)/5, ti**rat(arena, 5_int64, 2_int64)/5]
        do l = 1, 3
            do i = 1, 3
                gv(i, l) = diff(v(i), xyz(l))
                mom(i, l) = rho*v(i)*v(l)
            end do
        end do
        divv = gv(1, 1) + gv(2, 2) + gv(3, 3)
        do l = 1, 3
            do i = 1, 3
                strain(i, l) = (gv(i, l) + gv(l, i))/2
                if (i == l) strain(i, l) = strain(i, l) - divv/3
                stress(i, l) = 2*nu*strain(i, l)
            end do
        end do
        normalization = (b(1)**2 + b(2)**2 + b(3)**2 + one/100)**rat(arena, &
            1_int64, 2_int64)
        do i = 1, 3
            unitb(i) = b(i)/normalization
            flux(i) = rho*v(i) - diff(rho, xyz(i))/10
        end do
        force(1) = divergence(flux)
        force(2:4) = cross(jv, b)
        force(5:7) = cross(v, b)
        do i = 2, 7
            force(i) = -force(i)
        end do
        do i = 1, 3
            force(1 + i) = force(1 + i) + diff(pressure, xyz(i))
            ! The stationary skew balance subtracts half the mass defect.
            force(1 + i) = force(1 + i) - v(i)*force(1)/2
            force(4 + i) = force(4 + i) + eta*jv(i)
            do l = 1, 3
                force(1 + i) = force(1 + i) + diff(mom(i, l) - stress(i, l), xyz(l))
            end do
        end do
        force(8:10) = zero
        heat(1) = eta*(jv(1)**2 + jv(2)**2 + jv(3)**2)
        heat(2) = zero
        do l = 1, 3
            do i = 1, 3
                heat(2) = heat(2) + stress(i, l)*gv(i, l)
            end do
        end do
        do s = 1, 2
            temperature = te
            if (s == 2) temperature = ti
            flux = gradient(temperature)
            aa = unitb(1)*flux(1) + unitb(2)*flux(2) + unitb(3)*flux(3)
            do i = 1, 3
                flux(i) = 3*rho*temperature*v(i)/2 &
                    - rho*(flux(i)/20 + (chi(s) - one/20)*unitb(i)*aa)
            end do
            force(10 + s) = divergence(flux) + rho*temperature*divv - heat(s)
        end do
        u(1) = rho; u(2:4) = v; u(5:7) = a; u(8:10) = jv
        u(11) = te; u(12) = ti; u(13:15) = gradient(rho)
        u(16:24) = reshape(gv, [9]); u(25:27) = b
        u(28:30) = gradient(te); u(31:33) = gradient(ti); u(34:36) = curl(jv)
        full(:36) = u; full(37:) = force
        do i = 1, 48
            if (kind == 1) then
                full(i) = subs_many(full(i), xyz, [x, zero, y])
            else
                full(i) = subs_many(full(i), xyz, [x, y, zero])
            end if
            if (i <= 36) then
                simplified = engine%simplify(full(i)); full(i) = simplified%value
            end if
        end do
        call nonlinear%emit('vrmhd_mms_nonlinear_'//trim(suffix), &
            [character(16) :: arguments, 'e'], names(:48), full)
        call nonlinear%line('subroutine mms_nonlinear_'//trim(suffix)// &
            signature//',e,u)')
        call nonlinear%line(declaration//',e')
        call nonlinear%line('real(8), intent(out) :: u(48)')
        call nonlinear%line('call vrmhd_mms_nonlinear_'//trim(suffix)// &
            signature//',e, &')
        do i = 1, 48
            write (index_text, '(i0)') i
            if (i < 48) then
                call nonlinear%line('u('//trim(index_text)//'), &')
            else
                call nonlinear%line('u('//trim(index_text)//'))')
            end if
        end do
        call nonlinear%line('end subroutine')
        do i = 1, 36
            roots(i) = subs_many(u(i), [e], [zero])
            roots(36 + i) = subs_many(diff(u(i), e), [e], [zero])
        end do
        do i = 1, 12
            roots(72 + i) = subs_many(diff(force(i), e), [e], [zero])
        end do
        do i = 1, 84
            if (kind == 1) then
                roots(i) = subs_many(roots(i), xyz, [x, zero, y])
            else
                roots(i) = subs_many(roots(i), xyz, [x, y, zero])
            end if
            ! Linearised sources remain factored to avoid symbolic expansion.
            if (i <= 72) then
                simplified = engine%simplify(roots(i)); roots(i) = simplified%value
            end if
        end do
        print '(a,a)', 'manufactured Fourier expressions ', trim(suffix)
        call w%emit('vrmhd_mms_fourier_'//trim(suffix), &
            arguments, names, roots)
        call w%line('subroutine mms_fourier_'//trim(suffix)//signature//',u)')
        call w%line(declaration)
        call w%line('real(8), intent(out) :: u(84)')
        call w%line('call vrmhd_mms_fourier_'//trim(suffix)//signature//', &')
        do i = 1, 84
            write (index_text, '(i0)') i
            if (i < 84) then
                call w%line('u('//trim(index_text)//'), &')
            else
                call w%line('u('//trim(index_text)//'))')
            end if
        end do
        call w%line('end subroutine')
    end do
    call w%line('end module vrmhd_mms_fourier_leaves'); call w%close()
    call nonlinear%line('end module vrmhd_mms_nonlinear_leaves')
    call nonlinear%close()
contains
    function rotate(local) result(global)
        type(expr_t), intent(in) :: local(3)
        type(expr_t) :: global(3)
        global = [ct*local(1) - st*local(2), st*local(1) + ct*local(2), local(3)]
    end function
    function gradient(f) result(g)
        type(expr_t), intent(in) :: f
        type(expr_t) :: g(3)
        integer :: j
        do j = 1, 3
            g(j) = diff(f, xyz(j))
        end do
    end function
    function divergence(v) result(d)
        type(expr_t), intent(in) :: v(3)
        type(expr_t) :: d
        d = diff(v(1), xyz(1)) + diff(v(2), xyz(2)) + diff(v(3), xyz(3))
    end function
    function curl(v) result(c)
        type(expr_t), intent(in) :: v(3)
        type(expr_t) :: c(3)
        c = [diff(v(3), xyz(2)) - diff(v(2), xyz(3)), &
            diff(v(1), xyz(3)) - diff(v(3), xyz(1)), &
            diff(v(2), xyz(1)) - diff(v(1), xyz(2))]
    end function
    function cross(a, b) result(c)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: c(3)
        c = [a(2)*b(3) - a(3)*b(2), a(3)*b(1) - a(1)*b(3), a(1)*b(2) - a(2)*b(1)]
    end function
end program gen_vrmhd_mms_fourier
