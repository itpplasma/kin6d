program gen_boozer_orbit
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
        operator(*), operator(/)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: xi, mass, charge, energy, phi, b, g, dpsi_p, v, mu, rho

    ! The point of the orbit with surface s* on a ray theta = const, labelled
    ! by xi = v_par/v there (milca_boozer_orbit): P_zeta = rho G - psi_p is
    ! that of the turning points on s*, so the orbit position s is the root of
    !   R = m xi v G/(Z e B) - (psi_p(s) - psi_p(s*)),
    ! v = sqrt(2 (H - Z e Phi)/m), with B, G, Phi and psi_p at s. The magnetic
    ! moment of the orbit is mu = m v^2 (1 - xi^2)/(2 B). Their tangents give
    ! Newton's step in s and, by the implicit function theorem, ds/dxi and
    ! ds/ds* from the spline derivatives of B, G, Phi and psi_p. At fixed mu
    ! the orbit point on a leg is the root in s of the energy residual
    !   (Z e rho B)^2/(2 m) + mu B + Z e Phi - H,  rho = (psi_p(s) - psi_p(s*))/G.
    xi = sym('xi'); mass = sym('mass'); charge = sym('charge'); energy = sym('energy')
    phi = sym('phi'); b = sym('b'); g = sym('g'); dpsi_p = sym('dpsi_p')
    v = sqrt(2*(energy - charge*phi)/mass)
    mu = sym('mu')
    rho = dpsi_p/g

    call writer%open('gen_boozer_orbit', 'src/generated/milca_boozer_orbit_leaves.f90')
    call writer%line('! Generated by gen/gen_boozer_orbit.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module milca_boozer_orbit_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('orbit_pitch_residual', ['xi    ', 'mass  ', 'charge', 'energy', &
        'phi   ', 'b     ', 'g     ', 'dpsi_p'], ['residual'], &
        [mass*xi*v*g/(charge*b) - dpsi_p], ad=.true.)
    call writer%emit('orbit_moment', ['xi    ', 'mass  ', 'charge', 'energy', 'phi   ', &
        'b     '], ['mu'], [mass*v*v*(1 - xi*xi)/(2*b)], ad=.true.)
    call writer%emit('orbit_energy_residual', ['dpsi_p', 'g     ', 'b     ', 'mass  ', &
        'charge', 'mu    ', 'phi   ', 'energy'], ['residual'], &
        [(charge*rho*b)*(charge*rho*b)/(2*mass) + mu*b + charge*phi - energy], ad=.true.)
    call writer%line('end module milca_boozer_orbit_leaves')
    call writer%close()
end program gen_boozer_orbit
