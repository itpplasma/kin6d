program gen_vrmhd_section
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_expr, only: expr_t, sym, rat, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs_many
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(symengine_engine_t) :: engine
    type(expr_t) :: x, y, k, z, one, xi(3), omega(3, 3), s
    type(expr_t) :: v(3), vx(3), vy(3), gv(3, 3), f(2), g(3)
    type(expr_t) :: u(2), ux(2), uy(2), a, ax, ay, c, av(3), da(3, 3), b(3)
    type(expr_t) :: roots(6), keys(4), replacements(4), gc(3), gcurl(3)
    type(expr_t) :: test(3), field(3), contraction
    type(expr_t) :: cart(3), orbit(3), angle, ov(3, 3), oc(3), frequency
    type(engine_result_t) :: simplified
    character(16) :: suffix
    character(16) :: vn(9), out(9), cn(9)
    integer :: kind, i, j
    engine = make_symengine_engine()
    z = rat(0_int64, 1_int64); one = rat(1_int64, 1_int64)
    x = sym('x'); y = sym('y'); k = sym('k')
    f = [sym('fx'), sym('fy')]
    u = [sym('u1'), sym('u2')]
    ux = [sym('u1x'), sym('u2x')]
    uy = [sym('u1y'), sym('u2y')]
    a = sym('a'); ax = sym('ax'); ay = sym('ay')
    c = sym('c')
    do i = 1, 3
        v(i) = sym('v'//achar(48 + i))
        vx(i) = sym('vx'//achar(48 + i))
        vy(i) = sym('vy'//achar(48 + i))
        vn(i) = 'v'//achar(48 + i)
        vn(3 + i) = 'vx'//achar(48 + i); vn(6 + i) = 'vy'//achar(48 + i)
    end do
    do i = 1, 9
        write (out(i), '(a,i0)') 'g', i
    end do
    cn = [character(16) :: 'x', 'y', 'k', 'u1', 'u2', 'c', 'a', 'ax', 'ay']
    call w%open('gen_vrmhd_section', &
        'src/generated/kin6d_vrmhd_section_leaves.f90')
    call w%line('! Generated by gen/gen_vrmhd_section.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_vrmhd_section_leaves')
    call w%line('implicit none')
    call w%line('contains')
    do kind = 1, 2
        omega = z
        if (kind == 1) then
            suffix = 'rotation'
            xi = [z, x, z]
            omega(1, 2) = -one; omega(2, 1) = one
            g = [f(1), z, f(2)]
            gv(:, 1) = vx; gv(:, 3) = vy
            gv(:, 2) = [-v(2)/x, v(1)/x, z]
            av = [u(1), a/x, u(2)]
        else
            suffix = 'screw'
            xi = [-k*y, k*x, one]
            omega(1, 2) = -k; omega(2, 1) = k
            g = [f(1), f(2), k*(y*f(1) - x*f(2))]
            gv(:, 1) = vx; gv(:, 2) = vy
            do i = 1, 3
                gv(i, 3) = k*(y*vx(i) - x*vy(i))
                do j = 1, 3
                    gv(i, 3) = gv(i, 3) + omega(i, j)*v(j)
                end do
            end do
            s = one + k*k*(x*x + y*y)
            av = [u(1), u(2), k*(y*u(1) - x*u(2))]
            do i = 1, 3
                av(i) = av(i) + a*xi(i)/s
            end do
        end if
        do i = 1, 3
            da(i, 1) = diff(av(i), x) + diff(av(i), a)*ax
            da(i, 2) = diff(av(i), y) + diff(av(i), a)*ay
            do j = 1, 2
                da(i, 1) = da(i, 1) + diff(av(i), u(j))*ux(j)
                da(i, 2) = da(i, 2) + diff(av(i), u(j))*uy(j)
            end do
        end do
        if (kind == 1) then
            da(:, 3) = da(:, 2)
            da(:, 2) = [-av(2)/x, av(1)/x, z]
        else
            do i = 1, 3
                da(i, 3) = k*(y*da(i, 1) - x*da(i, 2))
                do j = 1, 3
                    da(i, 3) = da(i, 3) + omega(i, j)*av(j)
                end do
            end do
        end if
        b = [da(3, 2) - da(2, 3), da(1, 3) - da(3, 1), da(2, 1) - da(1, 2)]
        keys = [ux(1), uy(1), ux(2), uy(2)]
        replacements = [z, z, c, z]
        roots(:3) = av
        do i = 1, 3
            roots(3 + i) = subs_many(b(i), keys, replacements)
            call prove(b(i) - subs_many(roots(3 + i), [c], [ux(2) - uy(1)]))
            simplified = engine%simplify(roots(3 + i))
            roots(3 + i) = simplified%value
        end do
        call w%emit('vrmhd_grad_'//trim(suffix), &
            [character(16) :: 'x', 'y', 'k', 'fx', 'fy'], out(:3), g, &
            ad=.true.)
        call w%emit('vrmhd_velocity_'//trim(suffix), &
            [character(16) :: 'x', 'y', 'k', vn], out, reshape(gv, [9]), &
            ad=.true.)
        call w%emit('vrmhd_curl_'//trim(suffix), cn, &
            [character(16) :: 'a1', 'a2', 'a3', 'b1', 'b2', 'b3'], roots, &
            ad=.true.)
        ! The prescribed closed form uses the full coordinate pullback.
        if (kind == 1) then
            av = [z, a/x, z]
        else
            av = [z, z, a]
        end if
        call w%emit('vrmhd_harmonic_'//trim(suffix), &
            [character(16) :: 'x', 'a'], &
            [character(16) :: 'h1', 'h2', 'h3'], av, ad=.true.)
        ! A Fourier factor g(t) of the orbit parameter t (rotation angle or
        ! screw axial coordinate) adds g'(t) times these products.
        cart = [sym('cx'), sym('cy'), sym('cz')]
        if (kind == 1) then
            ! tan(t) = Y/X has the derivative of t on the section Y = 0.
            angle = cart(2)/cart(1)
        else
            angle = cart(3)
        end if
        do i = 1, 3
            if (kind == 1) then
                orbit(i) = subs_many(diff(angle, cart(i)), cart, [x, z, y])
            else
                orbit(i) = subs_many(diff(angle, cart(i)), cart, [x, y, z])
            end if
            simplified = engine%simplify(orbit(i)); orbit(i) = simplified%value
        end do
        call prove(xi(1)*orbit(1) + xi(2)*orbit(2) + xi(3)*orbit(3) - one)
        if (kind == 1) then
            call prove(orbit(1)); call prove(orbit(3))
        else
            call prove(orbit(1)); call prove(orbit(2))
        end if
        do i = 1, 3
            do j = 1, 3
                ov(i, j) = v(i)*orbit(j)
            end do
        end do
        oc = [orbit(2)*v(3) - orbit(3)*v(2), orbit(3)*v(1) - orbit(1)*v(3), &
            orbit(1)*v(2) - orbit(2)*v(1)]
        do i = 1, 3
            simplified = engine%simplify(oc(i)); oc(i) = simplified%value
            gc(i) = v(1)*orbit(i)
            simplified = engine%simplify(gc(i)); gc(i) = simplified%value
            do j = 1, 3
                simplified = engine%simplify(ov(i, j)); ov(i, j) = simplified%value
            end do
        end do
        call w%emit('vrmhd_orbit_grad_'//trim(suffix), &
            [character(16) :: 'x', 'y', 'k', 'v1'], out(:3), gc)
        call w%emit('vrmhd_orbit_velocity_'//trim(suffix), &
            [character(16) :: 'x', 'y', 'k', vn(:3)], out, reshape(ov, [9]))
        call w%emit('vrmhd_orbit_curl_'//trim(suffix), &
            [character(16) :: 'x', 'y', 'k', vn(:3)], out(:3), oc)
        ! The section component of a gradient is a discrete Nedelec gradient.
        do i = 1, 3
            gc(i) = subs_many(roots(3 + i), [u(1), u(2), c, a, ax, ay], &
                [f(1), f(2), z, z, z, z])
            call prove(gc(i))
            gcurl(i) = subs_many(roots(3 + i), [u(1), u(2), c, a, ax, ay], &
                [z, z, z, one, z, z])
            if (kind == 1) then
                call prove(gcurl(i))
            else
                call prove(gcurl(i) - 2*k*xi(i)/s**2)
            end if
        end do
    end do
    ! Coordinate one-forms dq1,dq2,dz are closed under a Fourier gradient.
    ! The horizontal orbit one-form used above is not closed for screw twist.
    av = [u(1), u(2), k*(y*u(1)-x*u(2))+a]
    do i = 1, 3
        da(i, 1) = diff(av(i), x) + diff(av(i), a)*ax
        da(i, 2) = diff(av(i), y) + diff(av(i), a)*ay
        do j = 1, 2
            da(i, 1) = da(i, 1) + diff(av(i), u(j))*ux(j)
            da(i, 2) = da(i, 2) + diff(av(i), u(j))*uy(j)
        end do
    end do
    do i = 1, 3
        da(i, 3) = k*(y*da(i, 1)-x*da(i, 2))
        do j = 1, 3
            da(i, 3) = da(i, 3) + omega(i, j)*av(j)
        end do
    end do
    b = [da(3, 2)-da(2, 3), da(1, 3)-da(3, 1), da(2, 1)-da(1, 2)]
    roots(:3) = av
    frequency = sym('frequency')
    do i = 1, 3
        roots(3+i) = subs_many(b(i), keys, replacements)
        call prove(b(i)-subs_many(roots(3+i), [c], [ux(2)-uy(1)]))
        simplified = engine%simplify(roots(3+i)); roots(3+i) = simplified%value
        gc(i) = subs_many(roots(3+i), [u(1), u(2), c, a, ax, ay], &
            [f(1), f(2), z, z, z, z])
        call prove(gc(i))
        gc(i) = subs_many(roots(3+i), [u(1), u(2), c, a, ax, ay], &
            [f(1), f(2), z, z, frequency*v(1), frequency*v(2)])
    end do
    oc = [-v(2), v(1), z]
    do i = 1, 3
        call prove(gc(i)+frequency*oc(i))
    end do
    call w%emit('vrmhd_curl_screw_coordinates', cn, out(:6), roots, ad=.true.)
    ! Contravariant two-form push by J=[e_x,e_y,xi], det J=1.
    gcurl = [v(1)+xi(1)*v(3), v(2)+xi(2)*v(3), v(3)]
    do i = 1, 3
        call prove(subs_many(gcurl(i), v, [ay, -ax, c])-roots(3+i))
    end do
    call w%emit('vrmhd_face_screw_coordinates', &
        [character(16) :: 'x', 'y', 'k', vn(:3)], out(:3), gcurl)
    do i = 1, 3
        field(i) = sym('b'//achar(48 + i))
        test(i) = sym('w'//achar(48 + i))
    end do
    contraction = z
    do i = 1, 3
        contraction = contraction + field(i)*test(i)
    end do
    call w%emit('vrmhd_pairing', &
        [character(16) :: 'b1', 'b2', 'b3', 'w1', 'w2', 'w3'], &
        [character(16) :: 'value'], [contraction], ad=.true.)
    call w%line('end module kin6d_vrmhd_section_leaves')
    call w%close()
    print '(a)', 'Invariant Cartesian gradients and curls: 36 identities passed'
contains
    subroutine prove(e)
        type(expr_t), intent(in) :: e
        type(engine_result_t) :: result
        result = engine%zero_test(e)
        if (result%verdict /= VERDICT_TRUE) error stop 'invariant curl identity'
    end subroutine
end program gen_vrmhd_section
