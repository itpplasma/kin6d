program gen_metriplectic
    ! Pointwise leaves and exact identities of the metriplectic relaxation
    ! (docs/metriplectic-relaxation.md). Every identity below is a polynomial
    ! or rational zero test; an unproved identity aborts generation.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*), &
        operator(/)
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(expr_t) :: j(3), b(3), v(3), a(3), d(3), c(3), h(3, 3)
    type(expr_t) :: e(3), ev(3), f(3), fv(3), jb, bb, diss, lambda
    type(expr_t) :: jj, kb, kbb, ha(3), hd(3), hm(3), ka, kad
    integer :: i, checks
    call arena%init()
    j = [sym(arena, 'jr'), sym(arena, 'jp'), sym(arena, 'jz')]
    b = [sym(arena, 'br'), sym(arena, 'bp'), sym(arena, 'bz')]
    v = [sym(arena, 'vr'), sym(arena, 'vp'), sym(arena, 'vz')]
    call w%open(arena, 'gen_metriplectic', &
        'src/generated/kin6d_metriplectic_leaves.f90')
    checks = 0
    ! Ideal (magneto-frictional) metric: dA/dt = (J x B1) x B1 = -D(B1) J,
    ! D(B1) = |B1|^2 I - B1 B1^T, in physical (R, phi, Z) components.
    f = cross(j, b); e = cross(f, b)
    fv = cross(v, b); ev = cross(fv, b)
    diss = dot(f, f)
    ! Negative control: a nonzero polynomial must not pass the zero test.
    block
        type(engine_result_t) :: control
        control = w%engine%zero_test(dot(j, e))
        if (control%verdict == VERDICT_TRUE) error stop 'vacuous zero test'
    end block
    ! Helicity is a Casimir of the metric: D(B1) B1 = 0 pointwise.
    call prove(dot(b, e), 'helicity Casimir b.((j x b) x b)')
    ! Energy is dissipated at the rate |J x B1|^2.
    call prove(dot(j, e) + diss, 'dissipation j.((j x b) x b) = -|j x b|^2')
    ! The metric is symmetric: v.(D j) = j.(D v).
    call prove(dot(v, e) - dot(j, ev), 'metric symmetry')
    ! Collision-bracket form |g|^2 I - g g^T of Bressan et al. with g = B1.
    bb = dot(b, b); jb = dot(j, b)
    do i = 1, 3
        call prove(e(i) + bb*j(i) - jb*b(i), 'projector form')
    end do
    ! Global (Taylor) metric J - lambda B1 with lambda = (J,B1)/(B1,B1);
    ! jj, kb and kbb stand for the M-weighted Gram entries.
    jj = sym(arena, 'jj'); kb = sym(arena, 'jb'); kbb = sym(arena, 'bb')
    lambda = kb/kbb
    call prove(kb - lambda*kbb, 'Taylor metric annihilates the helicity gradient')
    call prove((jj - lambda*kb) - (jj - 2*lambda*kb + lambda*lambda*kbb), &
        'Taylor dissipation equals |J - lambda B1|^2')
    ! Implicit midpoint conserves the quadratic helicity exactly:
    ! K(a) = a.H a + 2 a.c with symmetric H, increment d, midpoint a + d/2.
    a = [sym(arena, 'a1'), sym(arena, 'a2'), sym(arena, 'a3')]
    d = [sym(arena, 'd1'), sym(arena, 'd2'), sym(arena, 'd3')]
    c = [sym(arena, 'c1'), sym(arena, 'c2'), sym(arena, 'c3')]
    h(1, 1) = sym(arena, 'h11'); h(2, 2) = sym(arena, 'h22')
    h(3, 3) = sym(arena, 'h33'); h(1, 2) = sym(arena, 'h12')
    h(1, 3) = sym(arena, 'h13'); h(2, 3) = sym(arena, 'h23')
    h(2, 1) = h(1, 2); h(3, 1) = h(1, 3); h(3, 2) = h(2, 3)
    do i = 1, 3
        ha(i) = dot(h(i, :), a); hd(i) = dot(h(i, :), d)
        hm(i) = ha(i) + hd(i)/2
    end do
    ka = dot(a, ha) + 2*dot(a, c)
    kad = dot(add(a, d), add(ha, hd)) + 2*dot(add(a, d), c)
    call prove(kad - ka - 2*dot(d, add(hm, c)), 'midpoint quadratic invariant')
    call w%line('! Generated by gen/gen_metriplectic.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_metriplectic_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('friction_drift', ['jr', 'jp', 'jz', 'br', 'bp', 'bz'], &
        ['er  ', 'ep  ', 'ez  ', 'diss'], [e, diss], ad=.true.)
    call w%line('end module kin6d_metriplectic_leaves')
    call w%close()
    print '(a,i0,a)', 'gen_metriplectic: ', checks, ' identities proved'
contains
    function cross(x, y) result(z)
        type(expr_t), intent(in) :: x(3), y(3)
        type(expr_t) :: z(3)
        z(1) = x(2)*y(3) - x(3)*y(2)
        z(2) = x(3)*y(1) - x(1)*y(3)
        z(3) = x(1)*y(2) - x(2)*y(1)
    end function

    function add(x, y) result(z)
        type(expr_t), intent(in) :: x(3), y(3)
        type(expr_t) :: z(3)
        z(1) = x(1) + y(1); z(2) = x(2) + y(2); z(3) = x(3) + y(3)
    end function

    function dot(x, y) result(s)
        type(expr_t), intent(in) :: x(3), y(3)
        type(expr_t) :: s
        s = x(1)*y(1) + x(2)*y(2) + x(3)*y(3)
    end function

    subroutine prove(expression, label)
        type(expr_t), intent(in) :: expression
        character(*), intent(in) :: label
        type(engine_result_t) :: proof
        proof = w%engine%zero_test(expression)
        if (proof%verdict /= VERDICT_TRUE) then
            print '(2a)', 'Unproved metriplectic identity: ', label
            error stop 1
        end if
        checks = checks + 1
    end subroutine
end program gen_metriplectic
