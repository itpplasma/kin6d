program gen_islands
    use fortsym_expr, only: expr_t, sym, sqrt, atan2, log, operator(+), &
                            operator(-), operator(*), operator(/), operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: a, b, c, d, x, y, z, lx, ly, lz, r3
    type(expr_t) :: m, n, phi
    type(expr_t) :: r, q0, qc, q, y1, y2, jp
    type(expr_t) :: r1, r2, len, cx, cy, cz, c2, n1, n2, f, t1, t2
    a = sym('a'); b = sym('b')
    c = sym('c'); d = sym('d')
    x = sym('x'); y = sym('y'); z = sym('z')
    lx = sym('lx'); ly = sym('ly'); lz = sym('lz')
    m = sym('m'); n = sym('n'); phi = sym('phi')
    call w%open('gen_islands', 'src/generated/milca_island_leaves.f90')
    call w%line('! Generated by gen/gen_islands.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_island_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('poincare_invariants', ['a', 'b', 'c', 'd'], &
                ['residue    ', 'determinant'], [(2 - a - d)/4, a*d - b*c], ad=.true.)
    call w%emit('helical_phase', ['x  ', 'y  ', 'm  ', 'n  ', 'phi'], &
                ['phase'], [m*atan2(y, x) - n*phi], ad=.true.)
    r3 = (sqrt(x*x + y*y + z*z))**3
    call w%emit('biot_savart_integrand', ['x ', 'y ', 'z ', 'lx', 'ly', 'lz'], &
                ['bx', 'by', 'bz'], &
                [(ly*z - lz*y)/r3, (lz*x - lx*z)/r3, (lx*y - ly*x)/r3], ad=.true.)
    ! Keep the domain check ahead of divisions by the line distance or the
    ! endpoint distances; the geometric leaf itself is regular there.
    cx = ly*z - lz*y; cy = lz*x - lx*z; cz = lx*y - ly*x
    c2 = cx*cx + cy*cy + cz*cz
    n1 = sqrt(x*x + y*y + z*z)
    n2 = sqrt((x - lx)**2 + (y - ly)**2 + (z - lz)**2)
    t1 = lx*x + ly*y + lz*z
    t2 = lx*(x - lx) + ly*(y - ly) + lz*(z - lz)
    call w%emit('segment_geometry', ['x ', 'y ', 'z ', 'lx', 'ly', 'lz'], &
        ['cx    ', 'cy    ', 'cz    ', 'cross2', 'len2  ', 'n1    ', 'n2    ', &
         'dot1  ', 'dot2  '], &
        [cx, cy, cz, c2, lx*lx + ly*ly + lz*lz, n1, n2, t1, t2], ad=.true.)
    cx = sym('cx'); cy = sym('cy'); cz = sym('cz'); c2 = sym('cross2')
    n1 = sym('n1'); n2 = sym('n2'); t1 = sym('dot1'); t2 = sym('dot2')
    f = (t1/n1 - t2/n2)/c2
    call w%emit('segment_field', &
        ['cx    ', 'cy    ', 'cz    ', 'cross2', 'n1    ', 'n2    ', 'dot1  ', 'dot2  '], &
        ['bx', 'by', 'bz'], [f*cx, f*cy, f*cz], ad=.true.)
    ! Integral of 1/distance along a finite straight segment; coefficient
    ! multiplies mu0 I/(4 pi) times the oriented unit segment vector.
    r1 = sym('r1'); r2 = sym('r2'); len = sym('len')
    call w%emit('segment_potential', ['r1 ', 'r2 ', 'len'], ['value'], &
        [log((r1 + r2 + len)/(r1 + r2 - len))], ad=.true.)
    r = sym('r'); q0 = sym('q0'); qc = sym('qc')
    y1 = sym('y1'); y2 = sym('y2')
    q = q0 + qc*r*r
    jp = -8*q0*qc*r/q**3
    call w%emit('cylindrical_outer_rhs', &
                ['r ', 'y1', 'y2', 'q0', 'qc', 'm ', 'n '], ['dy1', 'dy2'], &
                [y2, 0 - y2/r + (m*m/(r*r) + jp/(r*(1/q - n/m)))*y1], ad=.true.)
    call w%emit('driven_cylinder_data', ['r ', 'q0', 'qc'], &
                ['safety', 'shape ', 'psi   '], &
                [q, (q0/q)**2, log(q/(q0 + qc))/(2*qc)], ad=.true.)
    call w%line('end module')
    call w%close()
end program
