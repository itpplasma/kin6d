program gen_islands
    use fortsym_expr, only: expr_t, sym, sqrt, atan2, log, operator(+), &
                            operator(-), operator(*), operator(/), operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: a, b, c, d, x, y, z, lx, ly, lz, r3
    type(expr_t) :: m, n, phi
    type(expr_t) :: r, q0, qc, q, y1, y2, jp
    a = sym('a'); b = sym('b')
    c = sym('c'); d = sym('d')
    x = sym('x'); y = sym('y'); z = sym('z')
    lx = sym('lx'); ly = sym('ly'); lz = sym('lz')
    m = sym('m'); n = sym('n'); phi = sym('phi')
    call w%open('gen_islands', 'src/generated/kin6d_island_leaves.f90')
    call w%line('! Generated by gen/gen_islands.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_island_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('poincare_invariants', ['a', 'b', 'c', 'd'], &
                ['residue    ', 'determinant'], [(2 - a - d)/4, a*d - b*c], ad=.true.)
    call w%emit('helical_phase', ['x  ', 'y  ', 'm  ', 'n  ', 'phi'], &
                ['phase'], [m*atan2(y, x) - n*phi], ad=.true.)
    r3 = (sqrt(x*x + y*y + z*z))**3
    call w%emit('biot_savart_integrand', ['x ', 'y ', 'z ', 'lx', 'ly', 'lz'], &
                ['bx', 'by', 'bz'], &
                [(ly*z - lz*y)/r3, (lz*x - lx*z)/r3, (lx*y - ly*x)/r3], ad=.true.)
    r = sym('r'); q0 = sym('q0'); qc = sym('qc')
    y1 = sym('y1'); y2 = sym('y2')
    q = q0 + qc*r*r
    jp = -8*q0*qc*r/q**3
    call w%emit('cylindrical_outer_rhs', &
                ['r ', 'y1', 'y2', 'q0', 'qc', 'm ', 'n '], ['dy1', 'dy2'], &
                [y2, 0 - y2/r + (m*m/(r*r) + jp/(r*(1/q - n/m)))*y1], ad=.true.)
    call w%emit('driven_cylinder_data', ['r ', 'q0', 'qc'], &
                ['safety', 'shape ', 'psi   '], &
                [q, (q0/q)**2, log(q/(q0 + qc))/(2*qc)], ad=.true.)
    call w%line('end module')
    call w%close()
end program
