program gen_dk_mono
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: b, b_theta, kappa, k

    ! Axisymmetric surface in Boozer angles, B = B0 b(theta), v = 1. The
    ! parallel derivative is b.grad theta d_theta with b.grad theta = kappa b,
    ! kappa = iota B0/(G + iota I); the flux-surface measure is 1/b^2.
    ! With u = I/Omega_0 = 1 the radial drift is
    !   v_d.grad psi = xi b.grad(xi/b) = -k (b_theta/b^2) (1 + xi^2)/2
    ! at fixed lambda, whose Legendre components are 2/3 and 1/3 of the
    ! factor; the parallel electric field drives xi b.
    b = sym('b'); b_theta = sym('b_theta'); kappa = sym('kappa')
    k = kappa*b

    call writer%open('gen_dk_mono', 'src/generated/kin6d_dk_mono_leaves.f90')
    call writer%line('! Generated by gen/gen_dk_mono.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module kin6d_dk_mono_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    ! Streaming factor k, mirror factor k d(ln b)/2, the P0 and P2
    ! components of the radial drift, the P1 component of the electric
    ! drive and the flux-surface weight.
    call writer%emit('dk_mono_point', ['b      ', 'b_theta', 'kappa  '], &
        ['stream ', 'mirror ', 'drift0 ', 'drift2 ', 'drive_e', 'weight '], &
        [k, k*b_theta/(2*b), -(2*k*b_theta)/(3*b*b), -(k*b_theta)/(3*b*b), b, 1/(b*b)], ad=.true.)
    call writer%line('end module kin6d_dk_mono_leaves')
    call writer%close()
end program gen_dk_mono
