program gen_coulomb
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, pi_expr, sqrt, exp, erfc, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: coulomb_potential, coulomb_force, &
        sphere_potential_inside, sphere_force_inside, ewald_real_potential, &
        ewald_real_force, ewald_reciprocal_weight, ewald_self_potential, &
        ewald_background_potential, partial_wave_potential
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: x(3), g, radius, alpha, volume, k2, r2, r, m, length
    type(expr_t) :: hbar, mu, l, count, d, k, shell_weight

    call arena%init()
    x = [sym(arena, 'dx'), sym(arena, 'dy'), sym(arena, 'dz')]
    g = sym(arena, 'g'); radius = sym(arena, 'radius'); alpha = sym(arena, 'alpha')
    volume = sym(arena, 'volume'); k2 = sym(arena, 'k2'); m = sym(arena, 'm')
    length = sym(arena, 'length'); hbar = sym(arena, 'hbar')
    mu = sym(arena, 'mu'); l = sym(arena, 'l')
    r2 = x(1)**2 + x(2)**2 + x(3)**2
    r = sqrt(r2)
    call w%open(arena, 'gen_coulomb', 'src/generated/kin6d_coulomb_leaves.f90')
    call w%line('! Generated by gen/gen_coulomb.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Single Coulomb definition (gen/kin6d_symbolic_physics.f90).')
    call w%line('! g=q_i q_j/(4 pi eps0) in declared reduced units; g>0 repulsive.')
    call w%line('! Force on the particle at d=(dx,dy,dz) from the source at 0.')
    call w%line('! Cartesian 3D; no softening; r>0 is the domain (fails closed).')
    call w%line('! Periodic: cube volume V, neutralizing background, k=2 pi n/L.')
    call w%line('! JVP/VJP use Euclidean Cartesian leaf pairings.')
    call w%line('module kin6d_coulomb_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('coulomb_pair', ['dx', 'dy', 'dz', 'g '], &
                ['fx       ', 'fy       ', 'fz       ', 'potential'], &
                [coulomb_force(g, x), coulomb_potential(g, r)], &
                ad=.true., interval=.true.)
    call w%emit('coulomb_sphere_inside', ['dx    ', 'dy    ', 'dz    ', 'g     ', &
                                          'radius'], &
                ['fx       ', 'fy       ', 'fz       ', 'potential'], &
                [sphere_force_inside(g, radius, x), &
                 sphere_potential_inside(g, radius, r2)], ad=.true., interval=.true.)
    call w%emit('ewald_real_pair', ['dx   ', 'dy   ', 'dz   ', 'alpha', 'g    '], &
                ['fx       ', 'fy       ', 'fz       ', 'potential'], &
                [ewald_real_force(g, alpha, x), ewald_real_potential(g, alpha, r)], &
                ad=.true.)
    call w%emit('ewald_reciprocal_weight', ['k2    ', 'alpha ', 'volume', 'g     '], &
                ['weight'], [ewald_reciprocal_weight(g, alpha, volume, k2)], ad=.true.)
    call w%emit('ewald_self', ['alpha', 'g    '], ['potential'], &
                [ewald_self_potential(g, alpha)], ad=.true.)
    call w%emit('ewald_background', ['alpha ', 'volume', 'g     '], ['potential'], &
                [ewald_background_potential(g, alpha, volume)], ad=.true.)
    call w%emit('coulomb_partial_wave', ['r   ', 'g   ', 'hbar', 'mu  ', 'l   '], &
                ['potential'], [partial_wave_potential(g, hbar, mu, l, sym(arena, 'r'))], &
                ad=.true.)
    ! Truncation shells per unit |g|. With the separation wrapped into
    ! [-L/2,L/2]^3, every image of max-norm index m has distance >= (m-1/2)L;
    ! the shell holds (2m+1)^3-(2m-1)^3 = 24 m^2 + 2 lattice vectors. Real
    ! terms erfc(a d)/d and their gradients decrease in d, so the shell term
    ! bounds every omitted image of that shell. Reciprocal vectors of shell m
    ! have |k| >= 2 pi m/L and exp(-k^2/(4a^2))/k^2 (times k for the force)
    ! decreases in |k|.
    count = 24*m**2 + 2
    d = (m - rat(arena, 1_int64, 2_int64))*length
    shell_weight = count/d
    call w%emit('ewald_real_shell_bound', ['m     ', 'alpha ', 'length'], &
                ['potential', 'force    '], &
                [shell_weight*erfc(alpha*d), &
                 shell_weight*(erfc(alpha*d)/d + &
                               2*alpha*exp(-alpha**2*d**2)/sqrt(pi_expr(arena)))])
    k = 2*pi_expr(arena)*m/length
    shell_weight = (24*m**2 + 2)*ewald_reciprocal_weight(1 + 0*m, alpha, length**3, k**2)
    call w%emit('ewald_reciprocal_shell_bound', ['m     ', 'alpha ', 'length'], &
                ['potential', 'force    '], [shell_weight, shell_weight*k])
    call w%line('end module kin6d_coulomb_leaves')
    call w%close()
end program gen_coulomb
