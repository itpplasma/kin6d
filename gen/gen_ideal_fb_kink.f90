program gen_ideal_fb_kink
    ! Unit-radius uniform-current screw pinch, mu0=1, k*Bz=q, ka -> 0.
    ! Retain the derivation and emit the independent asymptotic test oracle.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sin, cos, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(engine_result_t) :: check
    type(leaf_writer_t) :: writer
    type(expr_t) :: x, y, t, q, pressure, b(2), xi(2), db(2), current
    type(expr_t) :: volume, vacuum, total, wp, wv, standing, checks(7), factor
    integer :: i
    call arena%init()
    engine = make_native_engine(arena)
    x = sym(arena, 'x'); y = sym(arena, 'y')
    t = sym(arena, 't'); q = sym(arena, 'q')
    pressure = 1 - x*x - y*y
    b = [0 - y, x]
    current = diff(b(2), x) - diff(b(1), y)
    xi = [cos(t), sin(t)]
    ! Q=(B.grad)xi-(xi.grad)B; q=k*Bz, theta=k*z.
    db = [q*diff(xi(1), t) + xi(2), q*diff(xi(2), t) - xi(1)]
    volume = db(1)**2 + db(2)**2 &
        + current*(xi(1)*db(2) - xi(2)*db(1))
    vacuum = (q - 1)**2
    total = volume + vacuum
    ! The raw map Hessian keeps the b^2 surface term in the vacuum
    ! co-energy. DCON's energy-principle split transfers it to the plasma.
    wp = q*q; wv = vacuum - 1
    standing = (2*q*(q - 1) + 2*q*(q + 1))/4
    checks(1) = diff(b(1), x) + diff(b(2), y)
    checks(2) = 0 - current*b(2) - diff(pressure, x)
    checks(3) = current*b(1) - diff(pressure, y)
    checks(4) = volume - (q*q - 1)
    checks(5) = total - 2*q*(q - 1)
    checks(6) = wp + wv - total
    checks(7) = standing - q*q
    do i = 1, size(checks)
        check = engine%zero_test(checks(i))
        if (check%verdict /= VERDICT_TRUE) then
            print *, 'unproved kink identity', i
            error stop 1
        end if
    end do
    factor = sym(arena, 'factor')
    wv = factor*(q - 1)**2 - 1
    total = wp + wv
    standing = (q*q - 1 + factor*(q*q + 1))/2
    call writer%open(arena, 'gen_ideal_fb_kink', &
        'test/generated/ideal_fb_kink_leaves.f90')
    call writer%line('! Generated by gen/gen_ideal_fb_kink.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module ideal_fb_kink_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('cylinder_kink_energy', [character(6) :: 'q', 'factor'], &
        [character(8) :: 'plasma', 'vacuum', 'total', 'standing'], &
        [wp, wv, total, standing], ad=.true.)
    call writer%line('end module ideal_fb_kink_leaves')
    call writer%close()
    print *, 'Kink: seven exact native zero tests PASS (no probes)'
end program
