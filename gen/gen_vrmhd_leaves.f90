program gen_vrmhd_leaves
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, &
        operator(+), operator(-), operator(*), operator(/), &
        operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: writer
    type(expr_t) :: rho, rd, t, td, mi, q, coef, t0, par, perp, eps
    type(expr_t) :: mu0, eta, nu, nup, te, ti, rate, source, p, divergence
    type(expr_t) :: v(3), vd(3), b(3), current(3), js(3), w(3), ck(3)
    type(expr_t) :: g(3), h(3), gv(3, 3), gw(3, 3), strain(3, 3)
    type(expr_t) :: stress(3, 3), norm2, trace, bbstrain, value, heating, transport
    character(16) :: vector_args(3)
    integer :: i, j

    call arena%init()
    rho = sym(arena, 'rho'); rd = sym(arena, 'rho_dot')
    t = sym(arena, 'temperature'); td = sym(arena, 'temperature_dot')
    mi = sym(arena, 'mi'); q = sym(arena, 'q')
    coef = sym(arena, 'reference'); t0 = sym(arena, 't0')
    par = sym(arena, 'parallel'); perp = sym(arena, 'perpendicular')
    eps = sym(arena, 'epsilon_b'); mu0 = sym(arena, 'mu0')
    eta = sym(arena, 'eta'); nu = sym(arena, 'nu'); nup = sym(arena, 'nu_parallel')
    te = sym(arena, 'te'); ti = sym(arena, 'ti'); rate = sym(arena, 'rate')
    source = sym(arena, 'source'); p = sym(arena, 'pressure')
    divergence = sym(arena, 'divergence')
    call vector('v', v); call vector('v_dot', vd); call vector('b', b)
    call vector('j', current); call vector('js', js); call vector('w', w)
    call vector('curl_w', ck); call vector('grad_f', g); call vector('grad_q', h)
    call matrix('grad_v', gv); call matrix('grad_w', gw)

    call writer%open(arena, 'gen_vrmhd_leaves', &
        'src/generated/kin6d_vrmhd_leaves.f90')
    call writer%line('! Generated by gen/gen_vrmhd_leaves.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('! SI; temperatures in joules; Cartesian grad_v_ij = d_j v_i.')
    call writer%line( &
        '! Mixed current; weak forms and domains: docs/vrmhd-weak-form.md.')
    call writer%line('module kin6d_vrmhd_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call leaf('eta', 'reference temperature t0', &
        coef*(t/t0)**rat(arena, -3_int64, 2_int64))
    call leaf('nu', 'reference temperature t0', &
        coef*(t/t0)**rat(arena, -3_int64, 2_int64))
    call leaf('chi_parallel', 'reference temperature t0', &
        coef*(t/t0)**rat(arena, 5_int64, 2_int64))
    call leaf('chi_perpendicular', 'reference', coef)
    call leaf('pressure', 'rho te ti mi', rho*(te + ti)/mi)
    call leaf('mass_density', 'rho_dot q', rd*q)
    call leaf('mass_momentum', &
        'rho rho_dot v_1 v_2 v_3 v_dot_1 v_dot_2 v_dot_3 w_1 w_2 w_3', &
        rho*dot(vd, w) + rd*dot(v, w))
    call leaf('mass_temperature', 'rho rho_dot temperature temperature_dot mi q', &
        3*(rho*td + rd*t)*q/(2*mi))
    call leaf('mass_induction', 'v_dot_1 v_dot_2 v_dot_3 w_1 w_2 w_3', dot(vd, w))
    call leaf('ampere', &
        'mu0 j_1 j_2 j_3 w_1 w_2 w_3 b_1 b_2 b_3 curl_w_1 curl_w_2 curl_w_3', &
        mu0*dot(current, w) - dot(b, ck))
    call leaf('density_advection', 'rho v_1 v_2 v_3 grad_q_1 grad_q_2 grad_q_3', &
        -rho*dot(v, h))
    norm2 = dot(b, b) + eps**2
    transport = perp*dot(g, h) + (par - perp)*dot(b, g)*dot(b, h)/norm2
    call leaf('transport', &
        'parallel perpendicular epsilon_b b_1 b_2 b_3 '// &
        'grad_f_1 grad_f_2 grad_f_3 grad_q_1 grad_q_2 grad_q_3', &
        transport)
    call leaf('conduction', &
        'rho mi parallel perpendicular epsilon_b b_1 b_2 b_3 '// &
        'grad_f_1 grad_f_2 grad_f_3 grad_q_1 grad_q_2 grad_q_3', rho*transport/mi)
    value = rat(arena, 0_int64, 1_int64)
    do j = 1, 3
        do i = 1, 3
            value = value - rho*v(i)*v(j)*gw(i, j)
        end do
    end do
    call leaf('momentum_advection', 'rho v_1 v_2 v_3 '//matrix_names('grad_w'), value)
    call leaf('pressure_work', 'pressure divergence', -p*divergence)
    call leaf('lorentz', 'j_1 j_2 j_3 b_1 b_2 b_3 w_1 w_2 w_3', &
        dot(cross(current, b), w))
    call leaf('induction_ideal', 'v_1 v_2 v_3 b_1 b_2 b_3 w_1 w_2 w_3', &
        dot(cross(v, b), w))
    call leaf('induction_resistive', &
        'eta j_1 j_2 j_3 js_1 js_2 js_3 w_1 w_2 w_3', &
        -eta*(dot(current, w) - dot(js, w)))
    call leaf('ohmic', 'eta j_1 j_2 j_3 js_1 js_2 js_3 q', &
        eta*(dot(current, current) - dot(current, js))*q)
    trace = gv(1, 1) + gv(2, 2) + gv(3, 3)
    do j = 1, 3
        do i = 1, 3
            strain(i, j) = (gv(i, j) + gv(j, i))/2
            if (i == j) strain(i, j) = strain(i, j) - trace/3
        end do
    end do
    bbstrain = rat(arena, 0_int64, 1_int64)
    do j = 1, 3
        do i = 1, 3
            bbstrain = bbstrain + b(i)*b(j)*strain(i, j)/norm2
        end do
    end do
    value = rat(arena, 0_int64, 1_int64); heating = rat(arena, 0_int64, 1_int64)
    do j = 1, 3
        do i = 1, 3
            stress(i, j) = 2*nu*strain(i, j) + 3*nup*bbstrain*b(i)*b(j)/norm2
            if (i == j) stress(i, j) = stress(i, j) - nup*bbstrain*dot(b, b)/norm2
            value = value + stress(i, j)*gw(i, j)
            heating = heating + stress(i, j)*gv(i, j)
        end do
    end do
    call leaf('viscosity', 'nu nu_parallel epsilon_b b_1 b_2 b_3 '// &
        matrix_names('grad_v')//' '//matrix_names('grad_w'), -value)
    call leaf('viscous_heat', 'nu nu_parallel epsilon_b b_1 b_2 b_3 '// &
        matrix_names('grad_v')//' q', heating*q)
    call leaf('temperature_advection', &
        'rho mi temperature v_1 v_2 v_3 grad_q_1 grad_q_2 grad_q_3', &
        -3*rho*t*dot(v, h)/(2*mi))
    call leaf('compression', 'rho mi temperature divergence q', rho*t*divergence*q/mi)
    call leaf('equipartition', 'rho mi rate te ti q', rho*rate*(ti - te)*q/mi)
    call leaf('source', 'source q', source*q)
    call writer%line('end module kin6d_vrmhd_leaves')
    call writer%close()
contains
    subroutine leaf(name, names, root)
        character(*), intent(in) :: name, names
        type(expr_t), intent(in) :: root
        character(32) :: args(40)
        integer :: first, last, n
        first = 1; n = 0
        do
            last = index(names(first:), ' ')
            n = n + 1
            if (last == 0) then
                args(n) = names(first:)
                exit
            end if
            args(n) = names(first:first + last - 2)
            first = first + last
        end do
        call writer%emit('vrmhd_'//name, args(:n), ['value'], [root], ad=.true.)
    end subroutine

    subroutine vector(prefix, a)
        character(*), intent(in) :: prefix
        type(expr_t), intent(out) :: a(3)
        integer :: k
        do k = 1, 3
            vector_args(k) = prefix//'_'//achar(48 + k)
            a(k) = sym(arena, trim(vector_args(k)))
        end do
    end subroutine

    subroutine matrix(prefix, a)
        character(*), intent(in) :: prefix
        type(expr_t), intent(out) :: a(3, 3)
        integer :: row, col
        do col = 1, 3
            do row = 1, 3
                a(row, col) = sym(arena, prefix//'_'//achar(48 + row)//achar(48 + col))
            end do
        end do
    end subroutine

    function matrix_names(prefix) result(names)
        character(*), intent(in) :: prefix
        character(:), allocatable :: names
        integer :: row, col
        names = ''
        do col = 1, 3
            do row = 1, 3
                if (len(names) > 0) names = names//' '
                names = names//prefix//'_'//achar(48 + row)//achar(48 + col)
            end do
        end do
    end function

    function dot(a, b) result(c)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: c
        c = a(1)*b(1) + a(2)*b(2) + a(3)*b(3)
    end function

    function cross(a, b) result(c)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: c(3)
        c = [a(2)*b(3) - a(3)*b(2), a(3)*b(1) - a(1)*b(3), a(1)*b(2) - a(2)*b(1)]
    end function
end program gen_vrmhd_leaves
