program gen_homma
    ! Pointwise mathematics of the Rosenbluth-potential oracle.
    ! Radial integrands for l=0 and l=1 Legendre components of 1/|v-v'| and
    ! |v-v'|, split at s=v, with v-derivatives from FortSym diff. Closed
    ! Maxwellian forms (erf) serve as independent references.
    use fortsym_expr, only: expr_t, sym, pi_expr, erf, exp, sqrt, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_expr, only: rat
    use milca_gen_support, only: leaf_writer_t
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: v, s, vt, n, c, x, pi, pi32, fm, pt, zero
    type(expr_t) :: vv(3), jet(0:3, 4), vm ! radial jets of the Cartesian assembly
    type(expr_t) :: h0lo, h0hi, k0lo, k0hi, h1lo, h1hi, g1lo, g1hi
    type(expr_t) :: ih0lo, ih0hi, ig0lo, ig0hi, ih1lo, ih1hi, ig1lo, ig1hi
    character(len=2), parameter :: vargs(5) = ['v ', 's ', 'vt', 'n ', 'c ']
    character(len=2), parameter :: cargs(3) = ['v ', 'vt', 'n ']

    zero = rat(0_8, 1_8)
    v = sym('v'); s = sym('s'); vt = sym('vt')
    n = sym('n'); c = sym('c')
    pi = pi_expr()
    pi32 = pi*sqrt(pi)
    x = s/vt
    fm = n*exp(-x**2)/(pi32*vt**3)
    pt = fm*c*(2*x**2 - 5)/2*s

    ! Kernels for s<v (lo: r<=s, r>=v) and s>v (hi: r<=v, r>=s).
    h0lo = 1/v
    h0hi = 1/s
    k0lo = (s**2 + 3*v**2)/(3*v)
    k0hi = (v**2 + 3*s**2)/(3*s)
    h1lo = s/v**2
    h1hi = v/s**2
    g1lo = s*(s**2 - 5*v**2)/(5*v**2)
    g1hi = v*(v**2 - 5*s**2)/(5*s**2)

    ih0lo = 4*pi*s**2*fm*h0lo
    ih0hi = 4*pi*s**2*fm*h0hi
    ig0lo = 4*pi*s**2*fm*k0lo
    ig0hi = 4*pi*s**2*fm*k0hi
    ih1lo = 4*pi/3*s**2*pt*h1lo
    ih1hi = 4*pi/3*s**2*pt*h1hi
    ig1lo = 4*pi/3*s**2*pt*g1lo
    ig1hi = 4*pi/3*s**2*pt*g1hi

    call w%open('gen_homma', 'src/generated/milca_homma_leaves.f90')
    call w%line('! Generated by gen/gen_homma.f90; do not edit.')
    call w%line('! Radial integrands of the Rosenbluth potentials for the l=0 (Maxwellian)')
    call w%line('! and l=1 (distortion, linear in q) parts. lo: s<v, hi: s>v.')
    call w%line('! Potential H=int f/|v-v''|, G=int f|v-v''|; d=k-th v-derivative.')
    call w%line('module milca_homma_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('homma_ih0_lo', vargs, ['out'], [ih0lo])
    call w%emit('homma_ih0_hi', vargs, ['out'], [ih0hi])
    call w%emit('homma_ih0_lo_d1', vargs, ['out'], [diff(ih0lo, v)])
    call w%emit('homma_ih0_hi_d1', vargs, ['out'], [diff(ih0hi, v)])
    call w%emit('homma_ig0_lo', vargs, ['out'], [ig0lo])
    call w%emit('homma_ig0_hi', vargs, ['out'], [ig0hi])
    call w%emit('homma_ig0_lo_d1', vargs, ['out'], [diff(ig0lo, v)])
    call w%emit('homma_ig0_hi_d1', vargs, ['out'], [diff(ig0hi, v)])
    call w%emit('homma_ig0_lo_d2', vargs, ['out'], [diff(diff(ig0lo, v), v)])
    call w%emit('homma_ig0_hi_d2', vargs, ['out'], [diff(diff(ig0hi, v), v)])
    call w%emit('homma_ih1_lo', vargs, ['out'], [ih1lo])
    call w%emit('homma_ih1_hi', vargs, ['out'], [ih1hi])
    call w%emit('homma_ih1_lo_d1', vargs, ['out'], [diff(ih1lo, v)])
    call w%emit('homma_ih1_hi_d1', vargs, ['out'], [diff(ih1hi, v)])
    call w%emit('homma_ig1_lo', vargs, ['out'], [ig1lo])
    call w%emit('homma_ig1_hi', vargs, ['out'], [ig1hi])
    call w%emit('homma_ig1_lo_d1', vargs, ['out'], [diff(ig1lo, v)])
    call w%emit('homma_ig1_hi_d1', vargs, ['out'], [diff(ig1hi, v)])
    call w%emit('homma_ig1_lo_d2', vargs, ['out'], [diff(diff(ig1lo, v), v)])
    call w%emit('homma_ig1_hi_d2', vargs, ['out'], [diff(diff(ig1hi, v), v)])
    ! Radial integrands at v = 0, where the s<v part is empty and the s>v kernels
    ! are regular: H_M(0), G_M''(0) and h1'(0) = lim h1/v. G_M'(0), H_M'(0),
    ! h1(0) and g1(0) vanish because the l=0 jets are even and the l=1 jets odd in v.
    call w%emit('homma_ih0_zero', vargs, ['out'], [subs(ih0hi, v, zero)])
    call w%emit('homma_ig0_zero', vargs, ['out'], [subs(ig0hi, v, zero)])
    call w%emit('homma_ig0_zero_d2', vargs, ['out'], [subs(diff(diff(ig0hi, v), v), v, zero)])
    call w%emit('homma_ih1_zero_d1', vargs, ['out'], [subs(diff(ih1hi, v), v, zero)])
    call w%emit('homma_profile_m', vargs, ['out'], [fm])
    call w%emit('homma_profile_t', vargs, ['out'], [pt])

    ! Closed Maxwellian references, x=v/vt, background density n.
    x = v/vt
    call w%emit('homma_closed_h0', cargs, ['out'], [n*erf(x)/v])
    call w%emit('homma_closed_h0p', cargs, ['out'], &
        [n*(-erf(x)/v**2 + 2*exp(-x**2)/(sqrt(pi)*v*vt))])
    call w%emit('homma_closed_g0p_over_v', cargs, ['out'], &
        [n*((1 - 1/(2*x**2))*erf(x) + exp(-x**2)/(sqrt(pi)*x))/(x*vt)])
    call w%emit('homma_closed_g0pp_minus_g0p_over_v', cargs, ['out'], &
        [n/vt*(erf(x)*(3/(2*x**3) - 1/x) - 3*exp(-x**2)/(sqrt(pi)*x**2))])
    ! Brute-force 3D integrands on spheres around v: w=v+r*omega, Jacobian r^2,
    ! 1/|v-w|=1/r and |v-w|=r. Independent of the radial split.
    block
        type(expr_t) :: r, wx, wy, wz, qx, qy, qz, wsq, sw, xw, fw, qw, ft
        character(len=2), parameter :: bargs(10) = ['r ', 'wx', 'wy', 'wz', 'vt', &
            'n ', 'c ', 'qx', 'qy', 'qz']
        r = sym('r'); wx = sym('wx'); wy = sym('wy')
        wz = sym('wz'); qx = sym('qx'); qy = sym('qy')
        qz = sym('qz')
        wsq = wx**2 + wy**2 + wz**2
        sw = sqrt(wsq)
        xw = sw/vt
        fw = n*exp(-xw**2)/(pi32*vt**3)
        qw = qx*wx + qy*wy + qz*wz
        ft = fw*c*(2*xw**2 - 5)/2*qw
        call w%emit('homma_bf_hm', bargs, ['out'], [r*fw])
        call w%emit('homma_bf_gm', bargs, ['out'], [r**3*fw])
        call w%emit('homma_bf_ht', bargs, ['out'], [r*ft])
        call w%emit('homma_bf_gt', bargs, ['out'], [r**3*ft])
    end block
    ! Maxwellian test species of thermal speed va: 4 pi s^2 f_a(s), unit weight.
    block
        type(expr_t) :: sa, va, ta
        sa = sym('sa'); va = sym('va')
        ta = 4*pi*sa**2*exp(-(sa/va)**2)/(pi32*va**3)
        call w%emit('homma_test_maxwell', ['sa', 'va'], ['out'], [ta])
    end block
    ! Homma closure: q = -k_par (b.g) b + k_wedge (b x g) - k_perp g_perp, g=grad T.
    ! tau, k_par, k_perp and k_wedge use the background species (n, T, m, qc, lnL).
    block
        type(expr_t) :: gx, gy, gz, bx, by, bz, nd, te, ms, qc, bm, lm, e0
        type(expr_t) :: tau, kpar, om, kperp, kwedge, bg, qx, qy, qz
        character(len=2), parameter :: cl_args(13) = ['gx', 'gy', 'gz', 'bx', 'by', 'bz', &
            'nd', 'te', 'ms', 'qc', 'bm', 'lm', 'e0']
        gx = sym('gx'); gy = sym('gy'); gz = sym('gz')
        bx = sym('bx'); by = sym('by'); bz = sym('bz')
        nd = sym('nd'); te = sym('te'); ms = sym('ms')
        qc = sym('qc'); bm = sym('bm'); lm = sym('lm')
        e0 = sym('e0')
        tau = 12*pi32*e0**2*sqrt(ms)*te*sqrt(te)/(nd*qc**4*lm)
        om = qc*bm/ms
        kpar = 39*nd*te*tau/(10*ms)
        kperp = nd*te/(ms*om**2*tau)
        kwedge = 5*nd*te/(2*ms*om)
        bg = bx*gx + by*gy + bz*gz
        qx = -kpar*bg*bx + kwedge*(by*gz - bz*gy) - kperp*(gx - bg*bx)
        qy = -kpar*bg*by + kwedge*(bz*gx - bx*gz) - kperp*(gy - bg*by)
        qz = -kpar*bg*bz + kwedge*(bx*gy - by*gx) - kperp*(gz - bg*bz)
        call w%emit('homma_closure_qx', cl_args, ['out'], [qx])
        call w%emit('homma_closure_qy', cl_args, ['out'], [qy])
        call w%emit('homma_closure_qz', cl_args, ['out'], [qz])
    end block
    call emit_assembly()
    ! Pair constants: v_t = sqrt(2 T/m_b), distortion c = 2 m_b/(5 n T^2) of
    ! conventions.md, Gamma = q_a^2 q_b^2 lnL/(4 pi eps0^2 m_a^2) and Gamma (1 + m_a/m_b).
    block
        type(expr_t) :: tb, mb, nb, qa, qb, lnl, e0, ma, gam
        tb = sym('tb'); mb = sym('mb'); nb = sym('nb')
        qa = sym('qa'); qb = sym('qb'); lnl = sym('lnl')
        e0 = sym('e0'); ma = sym('ma')
        gam = qa**2*qb**2*lnl/(4*pi*e0**2*ma**2)
        call w%emit('homma_pair_vt', ['tb', 'mb'], ['out'], [sqrt(2*tb/mb)])
        call w%emit('homma_pair_c', ['tb', 'mb', 'nb'], ['out'], [2*mb/(5*nb*tb**2)])
        call w%emit('homma_pair_gamma', ['qa ', 'qb ', 'lnl', 'e0 ', 'ma '], ['out'], [gam])
        call w%emit('homma_pair_gamma_prime', ['qa ', 'qb ', 'lnl', 'e0 ', 'ma ', 'mb '], &
            ['out'], [gam*(1 + ma/mb)])
    end block
    call w%line('end module milca_homma_leaves')
    call w%close()

contains

    !> Cartesian gradients and Hessians from the radial integrals at |v| = vm:
    !> H_M = h0(vm), G_M = g0(vm), H_T = (q.v) h1(vm)/vm, G_T = (q.v) g1(vm)/vm.
    !> Each radial jet F_k is a symbol with d_i F_k = F_(k+1) v_i/vm, so FortSym
    !> diff applies the chain rule. Also the direction average of grad H_T,
    !> q (u + vm u'/3) with u = h1/vm, from <v_i v_j>/vm^2 = delta_ij/3, and the
    !> v -> 0 limits: grad H_M -> 0, Hess G_M -> g0''(0) I (g0'/vm -> g0''(0)),
    !> grad H_T -> h1'(0) q (h1/vm -> h1'(0)) and Hess G_T -> 0 (g1/vm even in vm).
    subroutine emit_assembly()
        type(expr_t) :: qq(3), qv, roots(18), u, avg
        type(expr_t) :: zero_roots(18), hm, gm, ht, gt
        character(len=4), parameter :: jname(0:3, 4) = reshape([ &
            'h0  ', 'dh0 ', 'd2h0', 'd3h0', 'g0  ', 'dg0 ', 'd2g0', 'd3g0', &
            'h1  ', 'dh1 ', 'd2h1', 'd3h1', 'g1  ', 'dg1 ', 'd2g1', 'd3g1'], [4, 4])
        character(len=4), parameter :: aargs(13) = ['v1  ', 'v2  ', 'v3  ', 'q1  ', &
            'q2  ', 'q3  ', 'dh0 ', 'dg0 ', 'd2g0', 'h1  ', 'dh1 ', 'g1  ', 'dg1 ']
        character(len=4), parameter :: aargs2(14) = [aargs, 'd2g1']
        character(len=6), parameter :: outs(18) = ['ghm1  ', 'ghm2  ', 'ghm3  ', &
            'dgm11 ', 'dgm22 ', 'dgm33 ', 'dgm12 ', 'dgm13 ', 'dgm23 ', &
            'ght1  ', 'ght2  ', 'ght3  ', 'dgt11 ', 'dgt22 ', 'dgt33 ', 'dgt12 ', &
            'dgt13 ', 'dgt23 ']
        integer, parameter :: pi1(6) = [1, 2, 3, 1, 1, 2], pj1(6) = [1, 2, 3, 2, 3, 3]
        integer :: i, k, m
        type(expr_t) :: zero_e

        zero_e = zero
        do k = 1, 3
            vv(k) = sym('v'//achar(48 + k))
            qq(k) = sym('q'//achar(48 + k))
        end do
        do m = 1, 4
            do k = 0, 3
                jet(k, m) = sym(trim(jname(k, m)))
            end do
        end do
        vm = sqrt(vv(1)**2 + vv(2)**2 + vv(3)**2)
        qv = qq(1)*vv(1) + qq(2)*vv(2) + qq(3)*vv(3)
        hm = jet(0, 1); gm = jet(0, 2); ht = qv*jet(0, 3)/vm; gt = qv*jet(0, 4)/vm
        do i = 1, 3
            roots(i) = chain(hm, i)
            roots(9 + i) = chain(ht, i)
        end do
        do k = 1, 6
            roots(3 + k) = chain(chain(gm, pj1(k)), pi1(k))
            roots(12 + k) = chain(chain(gt, pj1(k)), pi1(k))
        end do
        w%simplify_roots = .true.
        call w%emit('homma_assemble', aargs2, outs, roots)
        ! Direction average of grad H_T per unit q, as a function of the speed.
        u = jet(0, 3)/vv(1)
        avg = u + vv(1)*(diff(u, vv(1)) + jet(1, 3)/vv(1))/3
        call w%emit('homma_isotropic_ht', ['v1 ', 'h1 ', 'dh1'], ['out'], [avg])
        do k = 1, 18
            zero_roots(k) = zero_e
        end do
        do k = 1, 3
            zero_roots(3 + k) = jet(2, 2)
            zero_roots(9 + k) = qq(k)*jet(1, 3)
        end do
        call w%emit('homma_assemble_zero', ['q1  ', 'q2  ', 'q3  ', 'd2g0', 'dh1 '], &
            outs, zero_roots)
        w%simplify_roots = .false.
    end subroutine emit_assembly

    !> d/dv_i through the radial jets of emit_assembly.
    function chain(e, i) result(d)
        type(expr_t), intent(in) :: e
        integer, intent(in) :: i
        type(expr_t) :: d
        integer :: mm, kk
        d = diff(e, vv(i))
        do mm = 1, 4
            do kk = 0, 2
                d = d + diff(e, jet(kk, mm))*jet(kk + 1, mm)*vv(i)/vm
            end do
        end do
    end function chain
end program gen_homma
