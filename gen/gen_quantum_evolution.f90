program gen_quantum_evolution
    use fortsym_expr, only: expr_t, sym, func, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: hr, hi, xr, xi, hb, acc, value, scale, h, s
    type(expr_t) :: y0, y1, f0, f1, c(0:3)
    type(expr_t) :: radius, residual, norm, delta, primal
    type(expr_t) :: row_r, row_i, gamma, xmax, width, operations, tiny_value, dimension
    integer :: j

    hr = sym('hr'); hi = sym('hi')
    xr = sym('xr'); xi = sym('xi')
    hb = sym('hb'); acc = sym('acc')
    value = sym('value'); scale = sym('scale')
    h = sym('h'); s = sym('s')
    y0 = sym('y0'); y1 = sym('y1')
    f0 = sym('f0'); f1 = sym('f1')
    radius = sym('radius'); residual = sym('residual')
    norm = sym('norm'); delta = sym('delta')
    primal = sym('primal')
    row_r = sym('row_r'); row_i = sym('row_i')
    gamma = sym('gamma'); xmax = sym('xmax')
    width = sym('width'); operations = sym('operations')
    tiny_value = sym('tiny_value')
    dimension = sym('dimension')
    do j = 0, 3
        block
            character(1) :: digit
            write (digit, '(i1)') j
            c(j) = sym('c'//digit)
        end block
    end do
    call w%open('gen_quantum_evolution', 'src/generated/milca_quantum_evolution_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_quantum_evolution.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, '(a)') '! Constant supplied Hermitian H; i*hbar*psi_t=H*psi.'
    write (w%unit, '(a)') '! hbar,h>0. Packed real/imag Hilbert pairing; no positivity.'
    write (w%unit, '(a)') '! sqrt norm primal admits zero; its JVP/VJP require value>0.'
    write (w%unit, '(a)') '! Residual/radius certificate: FortNum ode_residual_certificate.'
    write (w%unit, '(a)') 'module milca_quantum_evolution_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('qe_rhs_term', ['hr', 'hi', 'xr', 'xi', 'hb'], ['yr', 'yi'], &
              [(hr*xi + hi*xr)/hb, (-hr*xr + hi*xi)/hb], ad=.true., interval=.true.)
    ! Coarse aggregate allowance for the point action used by Tier A. With
    ! 8*n+4 as a conservative FP path length, include coefficient box widths
    ! and normal-tiny absolute underflow allowances before Hilbert amplification.
    call w%emit('qe_action_allowance', &
        ['row_r     ', 'row_i     ', 'gamma     ', 'xmax      ', 'width     ', &
         'operations', 'tiny_value', 'dimension ', 'hb        '], ['allowance'], &
        [((row_r + row_i)*(gamma*xmax + width) + &
          operations*tiny_value*(1 + hb)*(1 + gamma))*func('sqrt',[dimension])/hb], &
        ad=.true., interval=.true.)
    call w%emit('qe_add', ['acc  ', 'value'], ['next'], [acc + value], &
              ad=.true., interval=.true.)
    call w%emit('qe_scale', ['value', 'scale'], ['next'], [value*scale], &
              ad=.true., interval=.true.)
    call w%emit('qe_hermite', ['y0', 'y1', 'f0', 'f1', 'h '], &
              ['c0', 'c1', 'c2', 'c3'], &
              [y0, h*f0, 3*(y1 - y0) - h*(2*f0 + f1), &
               2*(y0 - y1) + h*(f0 + f1)], ad=.true.)
    call w%emit('qe_evaluate', ['c0', 'c1', 'c2', 'c3', 's '], ['value'], &
              [c(0) + s*(c(1) + s*(c(2) + s*c(3)))], ad=.true., interval=.true.)
    call w%emit('qe_evaluate_rate', ['c1', 'c2', 'c3', 's ', 'h '], ['value'], &
        [(c(1) + s*(2*c(2) + 3*s*c(3)))/h], ad=.true., interval=.true.)
    call w%emit('qe_square_add', ['acc  ', 'value'], ['next'], [acc + value**2], &
              ad=.true., interval=.true.)
    call w%emit('qe_norm', ['value'], ['norm'], [func('sqrt', [value])], &
              ad=.true., interval=.true.)
    call w%emit('qe_radius', ['radius  ', 'h       ', 'residual', &
                            'delta   ', 'primal  '], ['next'], &
              [radius + h*(residual + delta*primal)])
    call w%emit('qe_band', ['value ', 'radius'], ['lower', 'upper'], &
              [value - radius, value + radius], ad=.true., interval=.true.)
    call w%emit('qe_goal_error', ['norm  ', 'radius', 'scale '], ['error'], &
              [scale*radius*(2*norm + radius)], ad=.true., interval=.true.)
    call w%emit('qe_fraction', ['value', 'h    '], ['s'], [value/h], &
              ad=.true., interval=.true.)
    call w%emit('qe_complement', ['s'], ['value'], [1 - s], &
              ad=.true., interval=.true.)
    call w%emit('qe_time', ['cell    ', 'fraction', 'h       '], ['time'], &
              [(sym('cell') - 1 + sym('fraction'))*h], &
              ad=.true., interval=.true.)
    write (w%unit, '(a)') 'end module milca_quantum_evolution_leaves'
    call w%close()
end program gen_quantum_evolution
