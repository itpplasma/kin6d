program gen_quantum_evolution
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, func, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: hr, hi, xr, xi, hb, acc, value, scale, h, s
    type(expr_t) :: y0, y1, f0, f1, c(0:3), a(0:3), r(0:3)
    type(expr_t) :: radius, residual, norm, delta, primal
    integer :: unit, j

    call arena%init()
    engine = make_native_engine(arena)
    hr = sym(arena, 'hr'); hi = sym(arena, 'hi')
    xr = sym(arena, 'xr'); xi = sym(arena, 'xi')
    hb = sym(arena, 'hb'); acc = sym(arena, 'acc')
    value = sym(arena, 'value'); scale = sym(arena, 'scale')
    h = sym(arena, 'h'); s = sym(arena, 's')
    y0 = sym(arena, 'y0'); y1 = sym(arena, 'y1')
    f0 = sym(arena, 'f0'); f1 = sym(arena, 'f1')
    radius = sym(arena, 'radius'); residual = sym(arena, 'residual')
    norm = sym(arena, 'norm'); delta = sym(arena, 'delta')
    primal = sym(arena, 'primal')
    do j = 0, 3
        block
            character(1) :: digit
            write (digit, '(i1)') j
            c(j) = sym(arena, 'c'//digit)
            a(j) = sym(arena, 'a'//digit)
            r(j) = sym(arena, 'r'//digit)
        end block
    end do
    open (newunit=unit, file='src/generated/kin6d_quantum_evolution_leaves.f90', &
          status='replace')
    write (unit, '(a)') '! Generated by gen/gen_quantum_evolution.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, '(a)') '! Constant supplied Hermitian H; i*hbar*psi_t=H*psi.'
    write (unit, '(a)') '! hbar,h>0. Packed real/imag Hilbert pairing; no positivity.'
    write (unit, '(a)') '! sqrt norm primal admits zero; its JVP/VJP require value>0.'
    write (unit, '(a)') 'module kin6d_quantum_evolution_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('qe_rhs_term', ['hr', 'hi', 'xr', 'xi', 'hb'], ['yr', 'yi'], &
              [(hr*xi + hi*xr)/hb, (-hr*xr + hi*xi)/hb], ad=.true., interval=.true.)
    call emit('qe_add', ['acc  ', 'value'], ['next'], [acc + value], &
              ad=.true., interval=.true.)
    call emit('qe_scale', ['value', 'scale'], ['next'], [value*scale], &
              ad=.true., interval=.true.)
    call emit('qe_hermite', ['y0', 'y1', 'f0', 'f1', 'h '], &
              ['c0', 'c1', 'c2', 'c3'], &
              [y0, h*f0, 3*(y1 - y0) - h*(2*f0 + f1), &
               2*(y0 - y1) + h*(f0 + f1)], ad=.true., interval=.true.)
    call emit('qe_evaluate', ['c0', 'c1', 'c2', 'c3', 's '], ['value'], &
              [c(0) + s*(c(1) + s*(c(2) + s*c(3)))], ad=.true., interval=.true.)
    call emit('qe_residual', ['c1', 'c2', 'c3', 'h ', 'a0', 'a1', 'a2', 'a3'], &
              ['r0', 'r1', 'r2', 'r3'], &
              [c(1)/h - a(0), 2*c(2)/h - a(1), 3*c(3)/h - a(2), -a(3)], &
              ad=.true., interval=.true.)
    call emit('qe_bernstein', ['r0', 'r1', 'r2', 'r3'], &
              ['b0', 'b1', 'b2', 'b3'], &
              [r(0), r(0) + r(1)/3, r(0) + 2*r(1)/3 + r(2)/3, &
               r(0) + r(1) + r(2) + r(3)], ad=.true., interval=.true.)
    call emit('qe_square_add', ['acc  ', 'value'], ['next'], [acc + value**2], &
              ad=.true., interval=.true.)
    call emit('qe_norm', ['value'], ['norm'], [func('sqrt', [value])], &
              ad=.true., interval=.true.)
    call emit('qe_radius', ['radius  ', 'h       ', 'residual', &
                            'delta   ', 'primal  '], ['next'], &
              [radius + h*(residual + delta*primal)], ad=.true., interval=.true.)
    call emit('qe_band', ['value ', 'radius'], ['lower', 'upper'], &
              [value - radius, value + radius], ad=.true., interval=.true.)
    call emit('qe_goal_error', ['norm  ', 'radius', 'scale '], ['error'], &
              [scale*radius*(2*norm + radius)], ad=.true., interval=.true.)
    call emit('qe_fraction', ['value', 'h    '], ['s'], [value/h], &
              ad=.true., interval=.true.)
    call emit('qe_complement', ['s'], ['value'], [1 - s], &
              ad=.true., interval=.true.)
    call emit('qe_time', ['cell    ', 'fraction', 'h       '], ['time'], &
              [(sym(arena, 'cell') - 1 + sym(arena, 'fraction'))*h], &
              ad=.true., interval=.true.)
    write (unit, '(a)') 'end module kin6d_quantum_evolution_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_quantum_evolution; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_quantum_evolution')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_quantum_evolution from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_quantum_evolution
