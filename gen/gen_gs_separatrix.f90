program gen_gs_separatrix
    ! Signed flux gap and directional derivative used by the LCFS search.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(expr_t) :: psi, level, sigma, gr, gz, ur, uz

    call arena%init()
    psi = sym(arena, 'psi'); level = sym(arena, 'level')
    sigma = sym(arena, 'sigma')
    gr = sym(arena, 'gr'); gz = sym(arena, 'gz')
    ur = sym(arena, 'ur'); uz = sym(arena, 'uz')
    call w%open(arena, 'gen_gs_separatrix', &
                'src/generated/kin6d_gs_separatrix_leaves.f90')
    call w%line('! Generated by gen/gen_gs_separatrix.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_gs_separatrix_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('gs_lcfs_ray_jet', &
                [character(5) :: 'psi', 'level', 'sigma', 'gr', 'gz', 'ur', 'uz'], &
                [character(5) :: 'gap', 'slope'], &
                [sigma*(psi - level), sigma*(gr*ur + gz*uz)], ad=.true.)
    call w%line('end module kin6d_gs_separatrix_leaves')
    call w%close()
end program gen_gs_separatrix
