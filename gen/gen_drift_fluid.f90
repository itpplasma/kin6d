program gen_drift_fluid
    use fortsym_expr, only: expr_t, sym, sqrt, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: alpha, kappa, kx, ky, k2, d, order, b, wstar, nu
    type(expr_t) :: s, r, p, gam, om, beta, mu, c, kpar

    alpha = sym('alpha'); kappa = sym('kappa'); kx = sym('kx'); ky = sym('ky')
    d = sym('d'); order = sym('order'); b = sym('b'); wstar = sym('wstar')
    nu = sym('nu'); gam = sym('gam'); om = sym('om')
    beta = sym('beta'); mu = sym('mu'); c = sym('c'); kpar = sym('kpar')
    k2 = kx**2 + ky**2

    call w%open('gen_drift_fluid', 'src/generated/milca_drift_fluid_leaves.f90')
    w%runtime%sqrt = str_sqrt()
    call w%line('! Generated by gen/gen_drift_fluid.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Local linear roots of fluid drift-wave models, exp[i(kx x + ky y - omega t)].')
    call w%line('! Hasegawa-Wakatani (docs/drift-turbulence.md): lengths rho_s, time')
    call w%line('! 1/Omega_i, kappa = rho_s/L_n. With mu = -i omega + nu:')
    call w%line('! mu^2 + b mu + i b wstar = 0, b = alpha (1 + k^2)/k^2,')
    call w%line('! wstar = ky kappa/(1 + k^2), nu = d k^(2 order).')
    call w%line('! Drift-Alfven, homogeneous slab, cold ions, no sound wave: lengths rho_s,')
    call w%line('! time L_n/c_s, parallel length L_par; beta = (beta_e/2)(L_par/L_n)^2,')
    call w%line('! mu = (m_e/m_i)(L_par/L_n)^2, c = 0.51 (nu_e L_n/c_s) mu:')
    call w%line('! omega^2 [beta (omega - ky) + mu k^2 omega + i c k^2]')
    call w%line('!   = kpar^2 [(1 + k^2) omega - ky].')
    call w%line('module milca_drift_fluid_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('hw_coupling', ['alpha', 'kappa', 'kx   ', 'ky   '], &
        ['b    ', 'wstar'], [alpha*(1 + k2)/k2, ky*kappa/(1 + k2)], ad=.true.)
    call w%emit('drift_hyperviscosity', ['d    ', 'order', 'kx   ', 'ky   '], &
        ['nu'], [d*k2**order], ad=.true.)
    ! mu = b [-1 +- sqrt(1 - i s)]/2, s = 4 wstar/b, sqrt(1 - i s) = p - i s/(2p),
    ! p = sqrt((r + 1)/2), r = sqrt(1 + s^2). The growing branch is written
    ! without the cancellation in p - 1. Requires b > 0.
    s = 4*wstar/b
    r = sqrt(1 + s**2)
    p = sqrt((r + 1)/2)
    call w%emit('hw_roots', ['b    ', 'wstar', 'nu   '], &
        ['gam_p', 'om_p ', 'gam_m', 'om_m '], &
        [wstar*s/((r + 1)*(p + 1)) - nu, wstar/p, -b*(1 + p)/2 - nu, -wstar/p], &
        ad=.true.)
    ! Eigenvector n/phi = 1 + k^2 mu/alpha of the root omega = om + i gam.
    call w%emit('hw_density_response', &
        ['alpha', 'kx   ', 'ky   ', 'nu   ', 'gam  ', 'om   '], ['nr', 'ni'], &
        [1 + k2*(gam + nu)/alpha, -k2*om/alpha], ad=.true.)
    ! a3 omega^3 + (a2r + i a2i) omega^2 + a1 omega + a0 = 0.
    call w%emit('drift_alfven_cubic', &
        ['beta', 'mu  ', 'c   ', 'kpar', 'kx  ', 'ky  '], &
        ['a3 ', 'a2r', 'a2i', 'a1 ', 'a0 '], &
        [beta + mu*k2, -beta*ky, c*k2, -kpar**2*(1 + k2), kpar**2*ky], ad=.true.)
    ! Limits: electron drift wave (kpar -> infinity) and the kinetic or
    ! inertial Alfven wave (ky -> 0 in the drive, c = 0).
    call w%emit('drift_alfven_limits', ['beta', 'mu  ', 'kpar', 'kx  ', 'ky  '], &
        ['om_drift  ', 'om_alfven2'], &
        [ky/(1 + k2), kpar**2*(1 + k2)/(beta + mu*k2)], ad=.true.)
    call w%line('end module milca_drift_fluid_leaves')
    call w%close()
contains
    function str_sqrt() result(name)
        use fortsym_string, only: str_t, str
        type(str_t) :: name
        name = str('sqrt')
    end function
end program gen_drift_fluid
