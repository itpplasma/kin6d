program gen_drift_fluid
    use fortsym_expr, only: expr_t, sym, num, sqrt, exp, sin, cos, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: alpha, kappa, kx, ky, k2, d, order, b, wstar, nu
    type(expr_t) :: s, r, p, gam, om, beta, mu, c, kpar
    type(expr_t) :: px, py, ph, fx, fy, f
    type(expr_t) :: t, q, grow, decay, ch(2), sh(2), g(2), m(2, 2, 2), e(2, 2, 2)
    type(expr_t) :: zr, zi, nr, ni, pr, pi, half, sr, si, ind, jr, ji
    integer :: a, c2

    alpha = sym('alpha'); kappa = sym('kappa'); kx = sym('kx'); ky = sym('ky')
    d = sym('d'); order = sym('order'); b = sym('b'); wstar = sym('wstar')
    nu = sym('nu'); gam = sym('gam'); om = sym('om')
    beta = sym('beta'); mu = sym('mu'); c = sym('c'); kpar = sym('kpar')
    t = sym('t'); zr = sym('zr'); zi = sym('zi'); nr = sym('nr'); ni = sym('ni')
    sr = sym('sr'); si = sym('si')
    px = sym('px'); py = sym('py'); ph = sym('p')
    fx = sym('fx'); fy = sym('fy'); f = sym('f')
    k2 = kx**2 + ky**2

    call w%open('gen_drift_fluid', 'src/generated/milca_drift_fluid_leaves.f90')
    w%runtime%sqrt = str_sqrt()
    call w%line('! Generated by gen/gen_drift_fluid.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Local linear roots of fluid drift-wave models, exp[i(kx x + ky y - omega t)].')
    call w%line('! Hasegawa-Wakatani (docs/drift-turbulence.md): lengths rho_s, time')
    call w%line('! 1/Omega_i, kappa = rho_s/L_n. With mu = -i omega + nu:')
    call w%line('! mu^2 + b mu + i b wstar = 0, b = alpha (1 + k^2)/k^2,')
    call w%line('! wstar = ky kappa/(1 + k^2), nu = d k^(2 order).')
    call w%line('! Drift-Alfven, homogeneous slab, cold ions, no sound wave: lengths rho_s,')
    call w%line('! time L_n/c_s, parallel length L_par; beta = (beta_e/2)(L_par/L_n)^2,')
    call w%line('! mu = (m_e/m_i)(L_par/L_n)^2, c = 0.51 (nu_e L_n/c_s) mu:')
    call w%line('! omega^2 [beta (omega - ky) + mu k^2 omega + i c k^2]')
    call w%line('!   = kpar^2 [(1 + k^2) omega - ky].')
    call w%line('module milca_drift_fluid_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('hw_coupling', ['alpha', 'kappa', 'kx   ', 'ky   '], &
        ['b    ', 'wstar'], [alpha*(1 + k2)/k2, ky*kappa/(1 + k2)], ad=.true.)
    call w%emit('drift_hyperviscosity', ['d    ', 'order', 'kx   ', 'ky   '], &
        ['nu'], [d*k2**order], ad=.true.)
    ! mu = b [-1 +- sqrt(1 - i s)]/2, s = 4 wstar/b, sqrt(1 - i s) = p - i s/(2p),
    ! p = sqrt((r + 1)/2), r = sqrt(1 + s^2). The growing branch is written
    ! without the cancellation in p - 1. Requires b > 0.
    s = 4*wstar/b
    r = sqrt(1 + s**2)
    p = sqrt((r + 1)/2)
    call w%emit('hw_roots', ['b    ', 'wstar', 'nu   '], &
        ['gam_p', 'om_p ', 'gam_m', 'om_m '], &
        [wstar*s/((r + 1)*(p + 1)) - nu, wstar/p, -b*(1 + p)/2 - nu, -wstar/p], &
        ad=.true.)
    ! Eigenvector n/phi = 1 + k^2 mu/alpha of the root omega = om + i gam.
    call w%emit('hw_density_response', &
        ['alpha', 'kx   ', 'ky   ', 'nu   ', 'gam  ', 'om   '], ['nr', 'ni'], &
        [1 + k2*(gam + nu)/alpha, -k2*om/alpha], ad=.true.)
    ! a3 omega^3 + (a2r + i a2i) omega^2 + a1 omega + a0 = 0.
    call w%emit('drift_alfven_cubic', &
        ['beta', 'mu  ', 'c   ', 'kpar', 'kx  ', 'ky  '], &
        ['a3 ', 'a2r', 'a2i', 'a1 ', 'a0 '], &
        [beta + mu*k2, -beta*ky, c*k2, -kpar**2*(1 + k2), kpar**2*ky], ad=.true.)
    ! Limits: electron drift wave (kpar -> infinity) and the kinetic or
    ! inertial Alfven wave (ky -> 0 in the drive, c = 0).
    call w%emit('drift_alfven_limits', ['beta', 'mu  ', 'kpar', 'kx  ', 'ky  '], &
        ['om_drift  ', 'om_alfven2'], &
        [ky/(1 + k2), kpar**2*(1 + k2)/(beta + mu*k2)], ad=.true.)
    ! Pointwise products of the split bracket {phi, f} = (p1 + d/dx p2 + d/dy p3)/3,
    ! p1 = phi_x f_y - phi_y f_x, p2 = phi f_y - phi_y f, p3 = phi_x f - phi f_x.
    ! The three equal forms of the bracket are averaged so that the collocated
    ! sums of f {phi, f} and phi {phi, f} vanish term by term.
    call w%emit('bracket_split_products', &
        ['px', 'py', 'p ', 'fx', 'fy', 'f '], ['p1', 'p2', 'p3'], &
        [px*fy - py*fx, ph*fy - py*f, px*f - ph*fx], ad=.true.)
    ! Linear part of Hasegawa-Wakatani for one mode in (zeta, n), phi = -zeta/k^2:
    ! d/dt (zeta, n) = (M - nu) (zeta, n), M = [[-alpha/k^2, -alpha],
    ! [(-alpha + i kappa ky)/k^2, -alpha]], trace -b, determinant i b wstar.
    m(1, 1, :) = [-alpha/k2, num(0)]
    m(1, 2, :) = [-alpha, num(0)]
    m(2, 1, :) = [-alpha/k2, kappa*ky/k2]
    m(2, 2, :) = [-alpha, num(0)]
    call w%emit('hw_linear_matrix', ['alpha', 'kappa', 'kx   ', 'ky   '], &
        ['m11 ', 'm12 ', 'm21r', 'm21i', 'm22 '], &
        [m(1, 1, 1), m(1, 2, 1), m(2, 1, 1), m(2, 1, 2), m(2, 2, 1)], ad=.true.)
    ! exp[(M - nu) t] = e^{-nu t} e^{-b t/2} [cosh(z) + (2/Delta) sinh(z) (M + b/2)],
    ! Delta = b (p - i q), q = s/(2 p), z = Delta t/2 = u - i v. The factor
    ! e^{-b t/2} is combined with e^{+-u} so that no term overflows. Requires b > 0.
    b = alpha*(1 + k2)/k2
    s = 4*(ky*kappa/(1 + k2))/b
    r = sqrt(1 + s**2)
    p = sqrt((r + 1)/2)
    q = s/(2*p)
    half = b*t/2
    grow = exp(half*(s**2/(2*(r + 1)*(p + 1))) - nu*t)
    decay = exp(-half*(p + 1) - nu*t)
    ch = [(grow + decay)/2*cos(half*q), -(grow - decay)/2*sin(half*q)]
    sh = [(grow - decay)/2*cos(half*q), -(grow + decay)/2*sin(half*q)]
    g = cmul(sh, [2*p/(b*(p**2 + q**2)), 2*q/(b*(p**2 + q**2))])
    do a = 1, 2
        do c2 = 1, 2
            e(a, c2, :) = cmul(g, m(a, c2, :))
        end do
        e(a, a, :) = [e(a, a, 1) + ch(1) + g(1)*b/2, e(a, a, 2) + ch(2) + g(2)*b/2]
    end do
    call w%emit('hw_propagator', ['alpha', 'kappa', 'kx   ', 'ky   ', 'nu   ', 't    '], &
        ['e11r', 'e11i', 'e12r', 'e12i', 'e21r', 'e21i', 'e22r', 'e22i'], &
        [e(1, 1, 1), e(1, 1, 2), e(1, 2, 1), e(1, 2, 2), &
         e(2, 1, 1), e(2, 1, 2), e(2, 2, 1), e(2, 2, 2)])
    ! Without coupling (alpha = 0) M is nilpotent: exp = e^{-nu t} (1 + M t).
    call w%emit('hw_propagator_decoupled', ['kappa', 'kx   ', 'ky   ', 'nu   ', 't    '], &
        ['e11 ', 'e21i'], [exp(-nu*t), exp(-nu*t)*kappa*ky*t/k2])
    ! Contributions of one coefficient pair to the box averages of the ledger
    ! (docs/drift-turbulence.md): energy, potential enstrophy, flux,
    ! resistive sink and the two hyperviscous sinks.
    pr = -zr/k2; pi = -zi/k2
    call w%emit('hw_mode_ledger', &
        ['alpha', 'kappa', 'kx   ', 'ky   ', 'nu   ', 'zr   ', 'zi   ', 'nr   ', 'ni   '], &
        ['energy   ', 'enstrophy', 'flux     ', 'd_alpha  ', 'd_e      ', 'd_w      '], &
        [(nr**2 + ni**2 + k2*(pr**2 + pi**2))/2, ((nr - zr)**2 + (ni - zi)**2)/2, &
         kappa*ky*(nr*pi - ni*pr), alpha*((nr - pr)**2 + (ni - pi)**2), &
         nu*(nr**2 + ni**2 + k2*(pr**2 + pi**2)), nu*((nr - zr)**2 + (ni - zi)**2)], &
        ad=.true.)
    ! Two-dimensional drift-Alfven model of stage DA with one parallel wave
    ! number (docs/drift-turbulence.md), lengths rho_s, time L_n/c_s. Per mode
    ! the state is (zeta, n, psi), phi = -zeta/k^2, psi = beta a + mu j =
    ! ind j with the inductance ind = beta/k^2 + mu.
    ind = beta/k2 + mu
    call w%emit('da_inductance', ['beta', 'mu  ', 'kx  ', 'ky  '], ['ind'], [ind], &
                ad=.true.)
    ! d/dt (zeta, n, psi) = (L - nu) (zeta, n, psi) with the nonzero entries
    ! L13 = L23 = kpar/ind, L21 = i kappa ky/k^2, L31 = -kpar/k^2, L32 = -kpar,
    ! L33 = -(c + i beta kappa ky/k^2)/ind.
    call w%emit('da_linear_matrix', &
        ['beta ', 'mu   ', 'c    ', 'kpar ', 'kappa', 'kx   ', 'ky   '], &
        ['l13 ', 'l21i', 'l31 ', 'l32 ', 'l33r', 'l33i'], &
        [kpar/ind, kappa*ky/k2, -kpar/k2, -kpar, -c/ind, -beta*kappa*ky/(k2*ind)], &
        ad=.true.)
    ! Contributions of one coefficient triple to the box averages: energy
    ! (n^2 + |grad phi|^2 + beta |grad a|^2 + mu j^2)/2, potential enstrophy,
    ! flux, resistive sink c j^2 and the two hyperviscous sinks.
    pr = -zr/k2; pi = -zi/k2
    jr = sr/ind; ji = si/ind
    call w%emit('da_mode_ledger', &
        ['beta ', 'mu   ', 'c    ', 'kappa', 'kx   ', 'ky   ', 'nu   ', 'zr   ', &
         'zi   ', 'nr   ', 'ni   ', 'sr   ', 'si   '], &
        ['energy   ', 'enstrophy', 'flux     ', 'd_c      ', 'd_e      ', 'd_w      '], &
        [(nr**2 + ni**2 + k2*(pr**2 + pi**2) + (sr**2 + si**2)/ind)/2, &
         ((nr - zr)**2 + (ni - zi)**2)/2, kappa*ky*(nr*pi - ni*pr), &
         c*(jr**2 + ji**2), &
         nu*(nr**2 + ni**2 + k2*(pr**2 + pi**2) + (sr**2 + si**2)/ind), &
         nu*((nr - zr)**2 + (ni - zi)**2)], ad=.true.)
    call w%line('end module milca_drift_fluid_leaves')
    call w%close()
contains
    !> Product of two complex numbers given as (real, imaginary).
    function cmul(x, y) result(z)
        type(expr_t), intent(in) :: x(2), y(2)
        type(expr_t) :: z(2)
        z = [x(1)*y(1) - x(2)*y(2), x(1)*y(2) + x(2)*y(1)]
    end function

    function str_sqrt() result(name)
        use fortsym_string, only: str_t, str
        type(str_t) :: name
        name = str('sqrt')
    end function
end program gen_drift_fluid
