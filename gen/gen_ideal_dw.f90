program gen_ideal_dw
    ! Pointwise ideal-MHD energy leaves for global stability (docs/stability.md,
    ! P1e). Two derivations of the plasma potential energy: the Eulerian form of
    ! Bernstein et al. (1958) and the Hessian of the adiabatic frozen-in energy
    ! at the identity map. Values are twice the delta-W bilinear density, the
    ! convention of the xi form, so that the stiffness matrix is their integral.
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*), &
        operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use milca_symbolic_ideal, only: frozen_energy, adiabatic_internal_energy
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: b(3), g(3, 3), p, q(3), gam, mu, x(3), a(3, 3), y(3), c(3, 3)
    type(expr_t) :: bern, lag, zero, one
    character(8) :: bnames(42), lnames(24)
    integer :: i, j, checks

    zero = 0*sym('p'); one = 1 + zero
    checks = 0
    call writer%open('gen_ideal_dw', 'src/generated/milca_ideal_dw_leaves.f90')
    call symbols()
    bern = bernstein(x, a, y, c, g, q)
    lag = lagrangian(a, c)
    call prove_symmetry()
    call prove_lagrangian_hessian()
    call prove_homogeneous_link()
    call prove_dispersion()
    call prove_adiabatic_state()

    call writer%line('! Generated by gen/gen_ideal_dw.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module milca_ideal_dw_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('dw_bernstein', bnames, ['value'], [bern], ad=.true.)
    call writer%emit('dw_lagrange', lnames, ['value'], [lag], ad=.true.)
    call emit_boundary()
    call emit_point_mass()
    call emit_point_adiabatic()
    call emit_point_inertia()
    call emit_screw_pinch()
    call writer%line('end module milca_ideal_dw_leaves')
    call writer%close()
    print '(a,i0,a)', 'PASS: ', checks, ' exact delta-W identities (no probes)'
contains
    subroutine symbols()
        integer :: k
        do i = 1, 3
            write(bnames(i), '(a,i1)') 'b', i
            b(i) = sym(trim(bnames(i)))
            write(bnames(13 + i), '(a,i1)') 'q', i
            q(i) = sym(trim(bnames(13 + i)))
            write(bnames(18 + i), '(a,i1)') 'x', i
            x(i) = sym(trim(bnames(18 + i)))
            write(bnames(30 + i), '(a,i1)') 'y', i
            y(i) = sym(trim(bnames(30 + i)))
        end do
        bnames(13) = 'p'; p = sym('p')
        bnames(17) = 'gam'; gam = sym('gam')
        bnames(18) = 'mu'; mu = sym('mu')
        do j = 1, 3
            do i = 1, 3
                k = i + 3*(j - 1)
                ! g(i,j) = d_j B_i, a(i,j) = d_j xi_i, c(i,j) = d_j eta_i
                write(bnames(3 + k), '(a,i1,i1)') 'g', i, j
                write(bnames(21 + k), '(a,i1,i1)') 'a', i, j
                write(bnames(33 + k), '(a,i1,i1)') 'c', i, j
                g(i, j) = sym(trim(bnames(3 + k)))
                a(i, j) = sym(trim(bnames(21 + k)))
                c(i, j) = sym(trim(bnames(33 + k)))
            end do
        end do
        lnames = [character(8) :: bnames(1:3), 'p', 'gam', 'mu', bnames(22:30), &
            bnames(34:42)]
    end subroutine symbols

    function qfield(xv, av, gv) result(qv)
        ! Q = curl(xi x B) = xi div B - B div xi + (B.grad) xi - (xi.grad) B
        type(expr_t), intent(in) :: xv(3), av(3, 3), gv(3, 3)
        type(expr_t) :: qv(3), divx, divb
        integer :: k, l
        divx = av(1, 1) + av(2, 2) + av(3, 3)
        divb = gv(1, 1) + gv(2, 2) + gv(3, 3)
        do k = 1, 3
            qv(k) = xv(k)*divb - b(k)*divx
            do l = 1, 3
                qv(k) = qv(k) + b(l)*av(k, l) - xv(l)*gv(k, l)
            end do
        end do
    end function qfield

    function bernstein(xv, av, yv, cv, gv, qv) result(form)
        ! Hermitian part of |Q|^2/mu - xi.(J x Q) + gamma p |div xi|^2
        ! + (xi.grad p) div xi, J = curl B / mu.
        type(expr_t), intent(in) :: xv(3), av(3, 3), yv(3), cv(3, 3), gv(3, 3), qv(3)
        type(expr_t) :: form, qx(3), qy(3), cur(3), divx, divy, jqx(3), jqy(3)
        integer :: k
        qx = qfield(xv, av, gv); qy = qfield(yv, cv, gv)
        cur(1) = (gv(3, 2) - gv(2, 3))/mu
        cur(2) = (gv(1, 3) - gv(3, 1))/mu
        cur(3) = (gv(2, 1) - gv(1, 2))/mu
        jqx = cross(cur, qx); jqy = cross(cur, qy)
        divx = av(1, 1) + av(2, 2) + av(3, 3)
        divy = cv(1, 1) + cv(2, 2) + cv(3, 3)
        form = gam*p*divx*divy
        do k = 1, 3
            form = form + qx(k)*qy(k)/mu &
                + (xv(k)*qv(k)*divy + yv(k)*qv(k)*divx)/2 &
                - (yv(k)*jqx(k) + xv(k)*jqy(k))/2
        end do
    end function bernstein

    function lagrangian(av, cv) result(form)
        ! Hessian of the adiabatic frozen-in energy at F = I (proved below).
        type(expr_t), intent(in) :: av(3, 3), cv(3, 3)
        type(expr_t) :: form, ta, tc, ac, b2, ba, bc, ab(3), cb(3)
        integer :: k, l
        ta = av(1, 1) + av(2, 2) + av(3, 3)
        tc = cv(1, 1) + cv(2, 2) + cv(3, 3)
        ac = zero; b2 = zero; ba = zero; bc = zero
        do k = 1, 3
            ab(k) = zero; cb(k) = zero
            b2 = b2 + b(k)**2
            do l = 1, 3
                ac = ac + av(k, l)*cv(l, k)
                ab(k) = ab(k) + av(k, l)*b(l)
                cb(k) = cb(k) + cv(k, l)*b(l)
            end do
            ba = ba + b(k)*ab(k); bc = bc + b(k)*cb(k)
        end do
        form = -(ba*tc + bc*ta)/mu + (b2/(2*mu) - p)*ta*tc &
            + (b2/(2*mu) + p)*ac + gam*p*ta*tc
        do k = 1, 3
            form = form + ab(k)*cb(k)/mu
        end do
    end function lagrangian

    function cross(u, v) result(w)
        type(expr_t), intent(in) :: u(3), v(3)
        type(expr_t) :: w(3)
        w(1) = u(2)*v(3) - u(3)*v(2)
        w(2) = u(3)*v(1) - u(1)*v(3)
        w(3) = u(1)*v(2) - u(2)*v(1)
    end function cross

    subroutine prove_symmetry()
        call prove(bern - bernstein(y, c, x, a, g, q))
        call prove(lag - lagrangian(c, a))
    end subroutine prove_symmetry

    subroutine prove_lagrangian_hessian()
        ! Adiabatic internal energy p J^(1-gamma)/(gamma-1) equals the frozen
        ! pressure term -p J plus gamma p (J-1)^2/2 up to second order at J = 1,
        ! so both have the same Hessian at the identity map.
        type(expr_t) :: d(3, 3), jac, density, h
        integer :: k, l, m, n, r, s
        do n = 1, 3
            do m = 1, 3
                block
                    character(8) :: name
                    write(name, '(a,i1,i1)') 'f', m, n
                    d(m, n) = sym(trim(name))
                end block
            end do
        end do
        density = frozen_energy(d, b, p, mu, one, jac)
        density = density + gam*p*(jac - 1)**2/2
        do n = 1, 3
            do m = 1, 3
                do l = 1, 3
                    do k = 1, 3
                        h = diff(diff(density, d(k, l)), d(m, n))
                        do s = 1, 3
                            do r = 1, 3
                                if (r == s) then
                                    h = subs(h, d(r, s), one)
                                else
                                    h = subs(h, d(r, s), zero)
                                end if
                            end do
                        end do
                        call prove(h - diff(diff(lag, a(k, l)), c(m, n)))
                    end do
                end do
            end do
        end do
    end subroutine prove_lagrangian_hessian

    subroutine prove_homogeneous_link()
        ! Uniform B and p: the two forms differ by (B^2/2mu + p) times the null
        ! Lagrangian tr(AC) - tr A tr C = div(xi.grad eta - xi div eta), whose
        ! integral is a boundary term.
        type(expr_t) :: hom, b2, ac, ta, tc, zg(3, 3), zq(3)
        integer :: k, l
        zg = zero; zq = zero
        hom = bernstein(x, a, y, c, zg, zq)
        b2 = b(1)**2 + b(2)**2 + b(3)**2
        ac = zero
        do k = 1, 3
            do l = 1, 3
                ac = ac + a(k, l)*c(l, k)
            end do
        end do
        ta = a(1, 1) + a(2, 2) + a(3, 3); tc = c(1, 1) + c(2, 2) + c(3, 3)
        call prove(lag - hom - (b2/(2*mu) + p)*(ac - ta*tc))
    end subroutine prove_homogeneous_link

    subroutine prove_dispersion()
        ! Uniform medium, unit density, plane wave grad xi = xi k^T: the wave
        ! matrix K has the shear-Alfven and magnetosonic roots of omega^2.
        type(expr_t) :: k(3), ap(3, 3), cp(3, 3), zg(3, 3), zq(3), form
        type(expr_t) :: kk(3, 3), m(3, 3), lam, det, kb, k2, b2, cs
        integer :: r, s
        k = [sym('k1'), sym('k2'), sym('k3')]
        lam = sym('lam')
        zg = zero; zq = zero
        do s = 1, 3
            do r = 1, 3
                ap(r, s) = x(r)*k(s); cp(r, s) = y(r)*k(s)
            end do
        end do
        form = bernstein(x, ap, y, cp, zg, zq)
        do s = 1, 3
            do r = 1, 3
                kk(r, s) = diff(diff(form, y(r)), x(s))
                m(r, s) = -kk(r, s)
            end do
            m(s, s) = lam + m(s, s)
        end do
        det = m(1, 1)*(m(2, 2)*m(3, 3) - m(2, 3)*m(3, 2)) &
            - m(1, 2)*(m(2, 1)*m(3, 3) - m(2, 3)*m(3, 1)) &
            + m(1, 3)*(m(2, 1)*m(3, 2) - m(2, 2)*m(3, 1))
        kb = k(1)*b(1) + k(2)*b(2) + k(3)*b(3)
        k2 = k(1)**2 + k(2)**2 + k(3)**2
        b2 = b(1)**2 + b(2)**2 + b(3)**2
        cs = gam*p
        call prove(mu**2*(det - (lam - kb**2/mu) &
            *(lam**2 - lam*k2*(b2/mu + cs) + k2*kb**2*cs/mu)))
    end subroutine prove_dispersion

    subroutine emit_boundary()
        ! Free boundary: vacuum density |grad phi|^2/mu for delta B = grad phi,
        ! and the surface term (nu.xi)(nu.eta) nu.[[grad(p + B^2/2mu)]].
        type(expr_t) :: u(3), v(3), nu(3), jump, vac, srf
        character(8) :: vn(7), sn(10)
        integer :: k
        do k = 1, 3
            write(vn(k), '(a,i1)') 'u', k; write(vn(3 + k), '(a,i1)') 'v', k
            write(sn(k), '(a,i1)') 'n', k
            u(k) = sym(trim(vn(k))); v(k) = sym(trim(vn(3 + k)))
            nu(k) = sym(trim(sn(k)))
        end do
        vn(7) = 'mu'
        sn(4:6) = bnames(19:21); sn(7:9) = bnames(31:33); sn(10) = 'jump'
        jump = sym('jump')
        vac = (u(1)*v(1) + u(2)*v(2) + u(3)*v(3))/mu
        srf = (nu(1)*x(1) + nu(2)*x(2) + nu(3)*x(3)) &
            *(nu(1)*y(1) + nu(2)*y(2) + nu(3)*y(3))*jump
        call writer%emit('dw_vacuum', vn, ['value'], [vac], ad=.true.)
        call writer%emit('dw_surface', sn, ['value'], [srf], ad=.true.)
    end subroutine emit_boundary

    subroutine emit_screw_pinch()
        ! Screw pinch B = Btheta(r) e_theta + Bz(r) e_z at theta = 0 in the
        ! (e_r, e_theta, e_z) frame: d_theta e_theta = -e_r gives g(1,2).
        type(expr_t) :: r, bt, btp, bz, bzp, out(12)
        character(8) :: outn(12)
        integer :: k
        r = sym('r'); bt = sym('bt'); btp = sym('btp')
        bz = sym('bz'); bzp = sym('bzp')
        out = 0*r
        out(2) = bt; out(3) = bz
        out(5) = btp; out(6) = bzp
        out(7) = -bt/r
        outn(1:3) = bnames(1:3)
        do k = 1, 9
            outn(3 + k) = bnames(3 + k)
        end do
        call writer%emit('dw_screw_pinch_field', [character(8) :: 'r', 'bt', &
            'btp', 'bz', 'bzp'], outn, out)
        call emit_density_jets(r)
    end subroutine emit_screw_pinch

    subroutine emit_density_jets(r)
        ! Physical components and radial derivatives from the contravariant
        ! densities of the cylinder, sqrt(g) xi^i = (r xi_r, xi_theta, r xi_z):
        ! r div xi = X' + i (m T + kz Z), so the pair (S_p, S_(p-1)) is exact.
        type(expr_t), intent(in) :: r
        type(expr_t) :: u(6), out(6)
        character(8) :: un(6), on(6)
        integer :: k
        un = [character(8) :: 'xd', 'xdp', 'td', 'tdp', 'zd', 'zdp']
        on = [character(8) :: 'xr', 'xrp', 'xt', 'xtp', 'xz', 'xzp']
        do k = 1, 6
            u(k) = sym(trim(un(k)))
        end do
        out(1) = u(1)/r; out(2) = u(2)/r - u(1)/r**2
        out(3) = u(3); out(4) = u(4)
        out(5) = u(5)/r; out(6) = u(6)/r - u(5)/r**2
        call writer%emit('dw_cylinder_density_jets', [character(8) :: 'r', un], &
            on, out)
    end subroutine emit_density_jets

    subroutine emit_point_mass()
        ! Physical perpendicular inertia of a map-lane displacement delta X =
        ! e_1 dq_1 + e_2 dq_2 (chart tangents e_a, toroidal component fixed):
        ! m_ac = rho J (P e_a).(P e_c), J = sigma det DX, B = DX b / J and
        ! P = I - B B^T/|B|^2. At gamma = 0 the parallel component carries no
        ! energy, and the minimal kinetic energy is this perpendicular norm.
        type(expr_t) :: rho, sigma, bb(3), dx(3, 3), e(3, 2), jac, fb(3), bsq, &
            pe(3, 2), out(3)
        character(8) :: names(23)
        integer :: i, k, c
        rho = sym('rho'); sigma = sym('sigma')
        names(1:2) = [character(8) :: 'rho', 'sigma']
        do i = 1, 3
            write(names(2 + i), '(a,i1)') 'r', i
            bb(i) = sym(trim(names(2 + i)))
        end do
        do k = 1, 3
            do i = 1, 3
                write(names(5 + i + 3*(k - 1)), '(a,i1,i1)') 'f', i, k
                dx(i, k) = sym(trim(names(5 + i + 3*(k - 1))))
            end do
        end do
        do k = 1, 2
            do i = 1, 3
                write(names(14 + i + 3*(k - 1)), '(a,i1,i1)') 'e', i, k
                e(i, k) = sym(trim(names(14 + i + 3*(k - 1))))
            end do
        end do
        jac = sigma*(dx(1, 1)*(dx(2, 2)*dx(3, 3) - dx(2, 3)*dx(3, 2)) &
            - dx(1, 2)*(dx(2, 1)*dx(3, 3) - dx(2, 3)*dx(3, 1)) &
            + dx(1, 3)*(dx(2, 1)*dx(3, 2) - dx(2, 2)*dx(3, 1)))
        do i = 1, 3
            fb(i) = dx(i, 1)*bb(1) + dx(i, 2)*bb(2) + dx(i, 3)*bb(3)
        end do
        bsq = fb(1)**2 + fb(2)**2 + fb(3)**2
        do k = 1, 2
            do i = 1, 3
                pe(i, k) = e(i, k) - fb(i)*(fb(1)*e(1, k) + fb(2)*e(2, k) &
                    + fb(3)*e(3, k))/bsq
            end do
        end do
        c = 0
        do k = 1, 2
            do i = 1, k
                c = c + 1
                out(c) = rho*jac*(pe(1, i)*pe(1, k) + pe(2, i)*pe(2, k) &
                    + pe(3, i)*pe(3, k))
            end do
        end do
        call writer%emit('dw_point_mass', names(1:20), &
            [character(8) :: 'm11', 'm12', 'm22'], out)
    end subroutine emit_point_mass

    subroutine state_symbols(names, dx, jac, cof)
        ! DX of the solved state (column-major names f11, f21, ...), its
        ! Jacobian for sigma = 1 and the cofactors dJ/dDX.
        character(8), intent(out) :: names(9)
        type(expr_t), intent(out) :: dx(3, 3), jac, cof(9)
        integer :: i, k
        do k = 1, 3
            do i = 1, 3
                write(names(i + 3*(k - 1)), '(a,i1,i1)') 'f', i, k
                dx(i, k) = sym(trim(names(i + 3*(k - 1))))
            end do
        end do
        jac = dx(1, 1)*(dx(2, 2)*dx(3, 3) - dx(2, 3)*dx(3, 2)) &
            - dx(1, 2)*(dx(2, 1)*dx(3, 3) - dx(2, 3)*dx(3, 1)) &
            + dx(1, 3)*(dx(2, 1)*dx(3, 2) - dx(2, 2)*dx(3, 1))
        do k = 1, 3
            do i = 1, 3
                cof(i + 3*(k - 1)) = diff(jac, dx(i, k))
            end do
        end do
    end subroutine state_symbols

    subroutine prove_adiabatic_state()
        ! At a state with Jacobian J0 /= 1 the adiabatic internal energy
        ! e(J) = p J0 (J/J0)^(1-gam)/(gam-1) and the frozen pressure term -p J
        ! of the equilibrium functional have the same gradient in DX, so the
        ! gamma = 0 equilibrium is the adiabatic one. Their Hessians in DX
        ! differ by (gam p/J0) dJ dJ^T, which is gam p J0 (div xi)(div eta)
        ! per reference volume because dJ = J0 div xi. Proved entry by entry
        ! for a general DX; the last identities tie the increment to the
        ! Hessian at the identity map proved above.
        type(expr_t) :: u0, full, dx(3, 3), jac, cof(9), g, h
        character(8) :: names(9)
        integer :: i, k, r, s
        u0 = sym('jac0')
        call state_symbols(names, dx, jac, cof)
        full = adiabatic_internal_energy(p, gam, u0, jac) + p*jac
        do k = 1, 9
            g = diff(full, dx(1 + mod(k - 1, 3), 1 + (k - 1)/3))
            call prove(subs(g, u0, jac))
            do i = 1, k
                h = diff(g, dx(1 + mod(i - 1, 3), 1 + (i - 1)/3))
                call prove(subs(h, u0, jac) - gam*p*cof(i)*cof(k)/jac)
            end do
        end do
        ! At the identity map the increment is the gam p tr A tr C of
        ! dw_lagrange.
        do r = 1, 9
            do s = 1, 9
                h = cof(r)*cof(s)
                do k = 1, 3
                    do i = 1, 3
                        if (i == k) then
                            h = subs(h, dx(i, k), one)
                        else
                            h = subs(h, dx(i, k), zero)
                        end if
                    end do
                end do
                call prove(gam*p*h - diff(diff(gam*p*(a(1, 1) + a(2, 2) + a(3, 3)) &
                    *(c(1, 1) + c(2, 2) + c(3, 3)), a(1 + mod(r - 1, 3), &
                    1 + (r - 1)/3)), c(1 + mod(s - 1, 3), 1 + (s - 1)/3)))
            end do
        end do
    end subroutine prove_adiabatic_state

    subroutine emit_point_adiabatic()
        ! Adiabatic energy (gam p/J) dJ^2 of a displacement about a solved
        ! state, J = sigma det DX. The displacement is a variation of DX plus
        ! a parallel part beta B, B = DX b/J, whose energy the frozen-in
        ! Hessian does not see. Its compression is dJ = J div(beta B) =
        ! J B.grad beta = b.d(beta)/ds, by div B = 0 and the identity
        ! (DX b).(cof g) = det DX (b.g) proved here. Output: the packed
        ! symmetric matrix c r r^T over r = (dJ/dDX (9), b (3)), column-major
        ! DX first, then the reference gradient of beta.
        type(expr_t) :: sigma, dx(3, 3), jac, cof(9), row(12), out(78), grad(3), &
            fb(3), lhs, c
        character(8) :: names(9), outn(78)
        integer :: i, k, n
        sigma = sym('sigma')
        call state_symbols(names, dx, jac, cof)
        grad = [sym('g1'), sym('g2'), sym('g3')]
        lhs = zero
        do i = 1, 3
            fb(i) = dx(i, 1)*b(1) + dx(i, 2)*b(2) + dx(i, 3)*b(3)
            do k = 1, 3
                lhs = lhs + fb(i)*cof(i + 3*(k - 1))*grad(k)
            end do
        end do
        call prove(lhs - jac*(b(1)*grad(1) + b(2)*grad(2) + b(3)*grad(3)))
        do i = 1, 9
            row(i) = sigma*cof(i)
        end do
        row(10:12) = b
        ! sigma^2 = 1: 1/J = sigma/det DX.
        c = gam*p*sigma/jac
        n = 0
        do k = 1, 12
            do i = 1, k
                n = n + 1
                write(outn(n), '(a,i2.2,i2.2)') 'h', i, k
                out(n) = c*row(i)*row(k)
            end do
        end do
        call writer%emit('dw_point_adiabatic', [character(8) :: 'gam', 'p', &
            'sigma', names, bnames(1:3)], outn, out)
    end subroutine emit_point_adiabatic

    subroutine emit_point_inertia()
        ! Full inertia rho J |e_1 dq_1 + e_2 dq_2 + beta B|^2 of a map-lane
        ! displacement with a parallel part, B = DX b/J: the packed matrix
        ! over (dq_1, dq_2, beta). With gam > 0 the parallel displacement
        ! compresses the plasma and its inertia counts.
        type(expr_t) :: rho, sigma, dx(3, 3), jac, cof(9), u(3, 3), out(6)
        character(8) :: names(9), en(6)
        integer :: i, k, n
        rho = sym('rho'); sigma = sym('sigma')
        call state_symbols(names, dx, jac, cof)
        do k = 1, 2
            do i = 1, 3
                write(en(i + 3*(k - 1)), '(a,i1,i1)') 'e', i, k
                u(i, k) = sym(trim(en(i + 3*(k - 1))))
            end do
        end do
        do i = 1, 3
            u(i, 3) = sigma*(dx(i, 1)*b(1) + dx(i, 2)*b(2) + dx(i, 3)*b(3))/jac
        end do
        n = 0
        do k = 1, 3
            do i = 1, k
                n = n + 1
                out(n) = rho*sigma*jac*(u(1, i)*u(1, k) + u(2, i)*u(2, k) &
                    + u(3, i)*u(3, k))
            end do
        end do
        call writer%emit('dw_point_inertia', [character(8) :: 'rho', 'sigma', &
            bnames(1:3), names, en], [character(8) :: 'm11', 'm12', 'm22', &
            'm13', 'm23', 'm33'], out)
    end subroutine emit_point_inertia

    subroutine prove(expression)
        type(expr_t), intent(in) :: expression
        type(engine_result_t) :: proof
        proof = writer%engine%zero_test(expression)
        if (proof%verdict /= VERDICT_TRUE) then
            print '(a,i0)', 'Unproved delta-W identity ', checks + 1
            error stop 1
        end if
        checks = checks + 1
    end subroutine prove
end program gen_ideal_dw
