program gen_dk_pitch
    use fortsym_expr, only: expr_t, sym, sqrt, &
        operator(+), operator(-), &
        operator(*), operator(/)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: t, b, nu, lambda, xi

    ! Pitch variable lambda = v_perp^2/(v^2 B) on [0, 1/B], written through
    ! t = sqrt(1/B - lambda), so |xi| = sqrt(1 - lambda B) = sqrt(B) t and
    ! d lambda = -2 t dt remove the reflection-point singularity of the
    ! measure B/|xi|.
    t = sym('t'); b = sym('b'); nu = sym('nu')
    lambda = 1/b - t*t
    xi = sqrt(b)*t

    call writer%open('gen_dk_pitch', 'src/generated/milca_dk_pitch_leaves.f90')
    call writer%line('! Generated by gen/gen_dk_pitch.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module milca_dk_pitch_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    ! Per unit dt: the mass weight of (B/|xi|) d lambda and the stiffness
    ! weight of 2 nu lambda |xi| d lambda in the Lorentz weak form
    !   int g C_L f (B/|xi|) d lambda = -2 nu int lambda |xi| g' f' d lambda.
    call writer%emit('dk_pitch_weights', ['t ', 'b ', 'nu'], &
        ['lambda   ', 'mass     ', 'stiffness'], &
        [lambda, (b/xi)*2*t, 2*nu*lambda*xi*2*t], ad=.true.)
    call writer%line('end module milca_dk_pitch_leaves')
    call writer%close()
end program gen_dk_pitch
