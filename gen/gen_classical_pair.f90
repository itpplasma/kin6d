program gen_classical_pair
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(*), operator(/)
    use kin6d_gen_support, only: leaf_writer_t
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: x, n, h
    call arena%init()
    x = sym(arena, 'x'); n = sym(arena, 'n'); h = sym(arena, 'h')
    call w%open(arena, 'gen_classical_pair', &
                'src/generated/kin6d_classical_pair_leaves.f90')
    call w%line('! Generated by gen/gen_classical_pair.f90; do not edit.')
    call w%line('! Periodic pair (C1) sampling law: 16-bin slab histogram g=16 x/n')
    call w%line('! and Hoeffding radius 16 sqrt(h/(2n)) for confidence 1-2 exp(-h).')
    call w%line('! Coulomb/Ewald physics: kin6d_coulomb_leaves.')
    call w%line('module kin6d_classical_pair_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('cp_statistic', ['x', 'n', 'h'], ['center', 'radius'], &
                [16*x/n, 16*sqrt(h/(2*n))])
    call w%line('end module kin6d_classical_pair_leaves')
    call w%close()
end program
