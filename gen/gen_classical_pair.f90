program gen_classical_pair
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, sin, cos, exp, erfc, abs, rat, pi_expr, &
                        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: x,y,z,alpha,g,r,kx,ky,kz,k2,phase,a,v,dt,n,p,h,c,s,c1,s1,cy,sy,cz,sz
    call arena%init()
    engine=make_native_engine(arena)
    x=sym(arena,'x'); y=sym(arena,'y'); z=sym(arena,'z')
    alpha=sym(arena,'alpha'); g=sym(arena,'g')
    kx=sym(arena,'kx'); ky=sym(arena,'ky'); kz=sym(arena,'kz')
    a=sym(arena,'a'); v=sym(arena,'v'); dt=sym(arena,'dt')
    n=sym(arena,'n'); p=sym(arena,'p'); h=sym(arena,'h')
    c=sym(arena,'c'); s=sym(arena,'s'); c1=sym(arena,'c1'); s1=sym(arena,'s1')
    cy=sym(arena,'cy'); sy=sym(arena,'sy'); cz=sym(arena,'cz'); sz=sym(arena,'sz')
    r=sqrt(x*x+y*y+z*z)
    k2=kx*kx+ky*ky+kz*kz
    phase=kx*x+ky*y+kz*z
    call w%open(arena, 'gen_classical_pair', 'src/generated/kin6d_classical_pair_leaves.f90')
    write (w%unit,'(a)') '! Generated by gen/gen_classical_pair.f90; do not edit.'
    write (w%unit,'(a)') '! Periodic L=2*pi Ewald Coulomb, zero reciprocal mode removed.'
    write (w%unit,'(a)') 'module kin6d_classical_pair_leaves'
    write (w%unit,'(a)') 'implicit none'
    write (w%unit,'(a)') 'contains'
    a=g*(erfc(alpha*r)/r**3+2*alpha*exp(-alpha*alpha*r*r)/(sqrt(pi_expr(arena))*r*r))
    call w%emit('cp_real',['x    ','y    ','z    ','alpha','g    '], &
        ['fx','fy','fz','u '],[a*x,a*y,a*z,g*erfc(alpha*r)/r],ad=.true.)
    a=g*exp(-k2/(4*alpha*alpha))/(2*pi_expr(arena)**2*k2)
    call w%emit('cp_weight',['kx   ','ky   ','kz   ','alpha','g    '],['weight'],[a],ad=.true.)
    a=sym(arena,'a')
    call w%emit('cp_recip',['x ','y ','z ','kx','ky','kz','a '], &
        ['fx','fy','fz','u '],[a*kx*sin(phase),a*ky*sin(phase),a*kz*sin(phase),a*cos(phase)],ad=.true.)
    call w%emit('cp_trig',['x'],['c','s'],[cos(x),sin(x)])
    call w%emit('cp_phasor',['c ','s ','c1','s1'],['nc','ns'],[c*c1-s*s1,s*c1+c*s1])
    call w%emit('cp_phase_product',['c ','s ','cy','sy','cz','sz'],['nc','ns'], &
        [(c*cy-s*sy)*cz-(s*cy+c*sy)*sz,(s*cy+c*sy)*cz+(c*cy-s*sy)*sz])
    call w%emit('cp_recip_phase',['kx','ky','kz','a ','c ','s '], &
        ['fx','fy','fz','u '],[a*kx*s,a*ky*s,a*kz*s,a*c])
    call w%emit('cp_background',['alpha','g    '],['u'],[-g/(8*pi_expr(arena)**2*alpha*alpha)],ad=.true.)
    call w%emit('cp_chart',['x','n'],['fraction'],[x/n+rat(arena,1_8,2_8)])
    call w%emit('cp_bin_index',['x'],['index'],[16*(x+rat(arena,1_8,2_8))])
    call w%emit('cp_axpy',['x ','v ','dt'],['next'],[x+v*dt],ad=.true.)
    call w%emit('cp_relative_kick',['x ','v ','dt'],['next'],[x+2*v*dt],ad=.true.)
    call w%emit('cp_position',['x','y'],['p1','p2'],[x+y/2,x-y/2],ad=.true.)
    call w%emit('cp_energy',['x','y','z','v'],['energy'],[(x*x+y*y+z*z)/4+v],ad=.true.)
    call w%emit('cp_difference',['x','y'],['d'],[x-y])
    call w%emit('cp_scale',['x'],['value'],[2*pi_expr(arena)*x])
    call w%emit('cp_bin_center',['x'],['value'],[(-17+2*x)/32])
    call w%emit('cp_fraction',['x','n'],['value'],[x/n])
    call w%emit('cp_statistic',['x','n','h'],['center','radius'], &
        [16*x/n,16*sqrt(h/(2*n))])
    call w%emit('cp_confidence_constant',['x'],['value'],[11+0*x])
    call w%emit('cp_padding',['x'],['padded'],[x+1])
    call w%emit('cp_time',['x'],['value'],[4*x/15])
    call w%emit('cp_defect',['x','y'],['value'],[abs(x-y)/(1+abs(y))])
    call w%emit('cp_norm',['x','y','z'],['value'],[sqrt(x*x+y*y+z*z)])
    call w%emit('cp_projection',['x','y','z'],['xp','yp'],[(x+z/4)/(2*pi_expr(arena)),(y+z/6)/(2*pi_expr(arena))])
    call w%emit('cp_view_margin',['x','y'],['upper'],[x+y+1])
    call w%emit('cp_cost',['x','y'],['factor'],[1+x/y])
    call w%emit('cp_step_scale',['x'],['value'],[sqrt(x*x*x/4)/50])
    write (w%unit,'(a)') 'end module kin6d_classical_pair_leaves'
    call w%close()
end program gen_classical_pair
