program gen_classical_pair
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, sin, cos, exp, erfc, abs, rat, pi_expr, &
                        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision='a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: x,y,z,alpha,g,r,kx,ky,kz,k2,phase,a,v,dt,n,p,h,c,s,c1,s1,cy,sy,cz,sz
    integer :: unit
    call arena%init()
    engine=make_native_engine(arena)
    x=sym(arena,'x'); y=sym(arena,'y'); z=sym(arena,'z')
    alpha=sym(arena,'alpha'); g=sym(arena,'g')
    kx=sym(arena,'kx'); ky=sym(arena,'ky'); kz=sym(arena,'kz')
    a=sym(arena,'a'); v=sym(arena,'v'); dt=sym(arena,'dt')
    n=sym(arena,'n'); p=sym(arena,'p'); h=sym(arena,'h')
    c=sym(arena,'c'); s=sym(arena,'s'); c1=sym(arena,'c1'); s1=sym(arena,'s1')
    cy=sym(arena,'cy'); sy=sym(arena,'sy'); cz=sym(arena,'cz'); sz=sym(arena,'sz')
    r=sqrt(x*x+y*y+z*z)
    k2=kx*kx+ky*ky+kz*kz
    phase=kx*x+ky*y+kz*z
    open(newunit=unit,file='src/generated/kin6d_classical_pair_leaves.f90',status='replace')
    write(unit,'(a)') '! Generated by gen/gen_classical_pair.f90; do not edit.'
    write(unit,'(a)') '! Periodic L=2*pi Ewald Coulomb, zero reciprocal mode removed.'
    write(unit,'(a)') 'module kin6d_classical_pair_leaves'
    write(unit,'(a)') 'implicit none'
    write(unit,'(a)') 'contains'
    a=g*(erfc(alpha*r)/r**3+2*alpha*exp(-alpha*alpha*r*r)/(sqrt(pi_expr(arena))*r*r))
    call emit('cp_real',['x    ','y    ','z    ','alpha','g    '], &
        ['fx','fy','fz','u '],[a*x,a*y,a*z,g*erfc(alpha*r)/r],ad=.true.)
    a=g*exp(-k2/(4*alpha*alpha))/(2*pi_expr(arena)**2*k2)
    call emit('cp_weight',['kx   ','ky   ','kz   ','alpha','g    '],['weight'],[a],ad=.true.)
    a=sym(arena,'a')
    call emit('cp_recip',['x ','y ','z ','kx','ky','kz','a '], &
        ['fx','fy','fz','u '],[a*kx*sin(phase),a*ky*sin(phase),a*kz*sin(phase),a*cos(phase)],ad=.true.)
    call emit('cp_trig',['x'],['c','s'],[cos(x),sin(x)])
    call emit('cp_phasor',['c ','s ','c1','s1'],['nc','ns'],[c*c1-s*s1,s*c1+c*s1])
    call emit('cp_phase_product',['c ','s ','cy','sy','cz','sz'],['nc','ns'], &
        [(c*cy-s*sy)*cz-(s*cy+c*sy)*sz,(s*cy+c*sy)*cz+(c*cy-s*sy)*sz])
    call emit('cp_recip_phase',['kx','ky','kz','a ','c ','s '], &
        ['fx','fy','fz','u '],[a*kx*s,a*ky*s,a*kz*s,a*c])
    call emit('cp_background',['alpha','g    '],['u'],[-g/(8*pi_expr(arena)**2*alpha*alpha)],ad=.true.)
    call emit('cp_chart',['x','n'],['fraction'],[x/n+rat(arena,1_8,2_8)])
    call emit('cp_bin_index',['x'],['index'],[16*(x+rat(arena,1_8,2_8))])
    call emit('cp_axpy',['x ','v ','dt'],['next'],[x+v*dt],ad=.true.)
    call emit('cp_relative_kick',['x ','v ','dt'],['next'],[x+2*v*dt],ad=.true.)
    call emit('cp_position',['x','y'],['p1','p2'],[x+y/2,x-y/2],ad=.true.)
    call emit('cp_energy',['x','y','z','v'],['energy'],[(x*x+y*y+z*z)/4+v],ad=.true.)
    call emit('cp_difference',['x','y'],['d'],[x-y])
    call emit('cp_scale',['x'],['value'],[2*pi_expr(arena)*x])
    call emit('cp_bin_center',['x'],['value'],[(-17+2*x)/32])
    call emit('cp_fraction',['x','n'],['value'],[x/n])
    call emit('cp_statistic',['x','n','h'],['center','radius'], &
        [16*x/n,16*sqrt(h/(2*n))])
    call emit('cp_confidence_constant',['x'],['value'],[11+0*x])
    call emit('cp_padding',['x'],['padded'],[x+1])
    call emit('cp_time',['x'],['value'],[4*x/15])
    call emit('cp_defect',['x','y'],['value'],[abs(x-y)/(1+abs(y))])
    call emit('cp_norm',['x','y','z'],['value'],[sqrt(x*x+y*y+z*z)])
    call emit('cp_projection',['x','y','z'],['xp','yp'],[(x+z/4)/(2*pi_expr(arena)),(y+z/6)/(2*pi_expr(arena))])
    call emit('cp_view_margin',['x','y'],['upper'],[x+y+1])
    call emit('cp_cost',['x','y'],['factor'],[1+x/y])
    call emit('cp_step_scale',['x'],['value'],[sqrt(x*x*x/4)/50])
    write(unit,'(a)') 'end module kin6d_classical_pair_leaves'
    close(unit)
contains
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_classical_pair; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_classical_pair')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_classical_pair from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_classical_pair
