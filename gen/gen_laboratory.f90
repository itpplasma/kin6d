program gen_laboratory
    use fortsym, only: arena_t, expr_t, sym, operator(+), operator(-), &
                       operator(*), operator(/), operator(**), exp, cos, sin
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use kin6d_gen_support, only: leaf_writer_t
    use kin6d_symbolic_physics, only: phase_rotation, free_streaming_rotation, &
        krook_node, krook_node_residual, p1_weight, p1_blend
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: v, t, x, amplitude, a, b, m, nu, sc, ss, dt, weight
    type(expr_t) :: lo, hi, index, count, da, db, dv, ddt, wa, wb, mm
    type(expr_t) :: cv, sv
    type(expr_t) :: f, rot(2), inputs(4), directions(4), tangent(2), adjoint(4)
    integer :: i, j
    call arena%init()
    v = sym(arena, 'v'); t = sym(arena, 't'); x = sym(arena, 'x')
    amplitude = sym(arena, 'amplitude'); a = sym(arena, 'a'); b = sym(arena, 'b')
    m = sym(arena, 'm'); nu = sym(arena, 'nu'); sc = sym(arena, 'sc')
    ss = sym(arena, 'ss'); dt = sym(arena, 'dt'); weight = sym(arena, 'weight')
    lo = sym(arena, 'lo'); hi = sym(arena, 'hi'); index = sym(arena, 'index')
    count = sym(arena, 'count'); da = sym(arena, 'da'); db = sym(arena, 'db')
    dv = sym(arena, 'dv'); ddt = sym(arena, 'ddt')
    wa = sym(arena, 'wa'); wb = sym(arena, 'wb')
    mm = sym(arena, "mm")
    call w%open(arena, 'gen_laboratory', 'src/generated/kin6d_leaves.f90')
    call w%line('! Generated by gen/gen_laboratory.f90; do not edit.')
    call w%line('module kin6d_leaves')
    call w%line('use iso_fortran_env, only: real128')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('clock_step', ['t ', 'dt'], ['value'], [t + dt])
    call w%emit('coordinate', ['lo   ', 'hi   ', 'index', 'count'], &
              ['value'], [lo + (hi - lo)*index/count])
    call w%emit('initial_coefficients', ['v        ', 'amplitude'], &
              ['m', 'a', 'b'], [exp(-v**2/2), amplitude*exp(-v**2/2), 0*v], ad=.true.)
    cv = sym(arena, 'cv'); sv = sym(arena, 'sv')
    call w%emit('stream_factors', ['v ', 'dt'], ['cv', 'sv'], [cos(v*dt), sin(v*dt)], ad=.true.)
    call w%emit('stream_cached', ['a ', 'b ', 'cv', 'sv'], ['an', 'bn'], &
              phase_rotation(a, b, cv, sv), ad=.true.)
    rot = free_streaming_rotation(a, b, v*dt)
    call w%emit('stream_step', ['a ', 'b ', 'v ', 'dt'], ['an', 'bn'], rot)
    inputs = [a, b, v, dt]; directions = [da, db, dv, ddt]
    do i = 1, 2
        tangent(i) = 0*a
        do j = 1, 4
            tangent(i) = tangent(i) + diff(rot(i), inputs(j))*directions(j)
        end do
    end do
    do j = 1, 4
        adjoint(j) = diff(rot(1), inputs(j))*wa + diff(rot(2), inputs(j))*wb
    end do
    call w%emit('stream_jvp', ['a  ', 'b  ', 'v  ', 'dt ', 'da ', 'db ', 'dv ', 'ddt'], &
              ['ja', 'jb'], tangent)
    call w%emit('stream_vjp', ['a ', 'b ', 'v ', 'dt', 'wa', 'wb'], &
              ['ga ', 'gb ', 'gv ', 'gdt'], adjoint)
    call w%emit('reconstruct', ['m', 'a', 'b', 'x'], ['value'], &
              [m + a*cos(x) + b*sin(x)], ad=.true.)
    call w%emit('interval_reconstruct', ['m', 'a', 'b', 'x'], ['value'], &
              [m + a*cos(x) + b*sin(x)], rigorous=.true.)
    call w%emit('interpolate', ['lo    ', 'hi    ', 'weight'], ['value'], &
              [p1_blend(lo, hi, weight)], ad=.true.)
    call w%emit('interpolation_weight', ['lo', 'hi', 'v '], ['value'], &
              [p1_weight(v, lo, hi)], ad=.true.)
    call w%emit('steady_source', ['v        ', 'nu       ', 'amplitude'], &
              ['sc', 'ss'], [nu*amplitude*exp(-v**2/2), -v*amplitude*exp(-v**2/2)], ad=.true.)
    call w%emit('steady_solve', ['v ', 'nu', 'sc', 'ss'], ['a', 'b'], &
              krook_node(nu, v, sc, ss), ad=.true.)
    call w%emit('steady_residual', ['a ', 'b ', 'v ', 'nu', 'sc', 'ss'], &
              ['rc', 'rs'], krook_node_residual(nu, v, a, b, sc, ss), ad=.true.)
    f = exp(-v**2/2)*(1 + amplitude*cos(x - v*t))
    call w%emit('characteristic_reference', ['x        ', 'v        ', 't        ', &
                                           'amplitude'], ['value'], [f])
    call w%emit('characteristic_reference_qp', ['x        ', 'v        ', 't        ', &
                                              'amplitude'], ['value'], [f], quad=.true.)
    call w%emit('exact_coefficients', ['v        ', 't        ', 'amplitude'], &
              ['m', 'a', 'b'], [exp(-v**2/2), amplitude*exp(-v**2/2)*cos(v*t), &
                                amplitude*exp(-v**2/2)*sin(v*t)], rigorous=.true.)
    ! Uniform-in-x second derivative bound, using absolute upper inputs vm, mm.
    ! |M''| <= (vm**2+1)*mm, |M'| <= vm*mm on each velocity cell.
    call w%emit('interpolation_radius', ['vm       ', 'mm       ', 't        ', &
                                       'amplitude', 'hi       ', 'lo       '], &
              ['radius'], &
              [subs((hi - lo)**2/8*mm*((1 + amplitude)*(v**2 + 1) + &
                                  2*amplitude*t*v + amplitude*t**2), v, &
                    sym(arena, 'vm'))], rigorous=.true.)
    ! The driver supplies nonnegative interval magnitudes to this sum leaf.
    call w%emit('radius_sum', ['a', 'b'], ['radius'], [a + b], rigorous=.true.)
    call w%emit('interval_band', ['lo', 'hi'], ['lower', 'upper'], &
              [lo - hi, lo + hi], rigorous=.true.)
    call w%emit('squared_norm', ['a', 'b'], ['value'], [a**2 + b**2])
    call w%emit('dot_four', ['a  ', 'b  ', 'v  ', 'dt ', 'da ', 'db ', 'dv ', 'ddt'], &
              ['value'], [a*da + b*db + v*dv + dt*ddt])
    call w%line('end module kin6d_leaves')
    call w%close()
end program
