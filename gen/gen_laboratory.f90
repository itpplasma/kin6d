program gen_laboratory
    use fortsym, only: arena_t, expr_t, sym, operator(+), operator(-), &
                       operator(*), operator(/), operator(**), exp, cos, sin
    use fortsym_diff, only: diff
    use fortsym_string, only: str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    type(arena_t), target :: arena
    type(expr_t) :: v, t, x, amplitude, a, b, m, nu, sc, ss, dt, weight
    type(expr_t) :: lo, hi, index, count, da, db, dv, ddt, wa, wb, mm
    type(expr_t) :: cv, sv
    type(expr_t) :: f, rot(2), inputs(4), directions(4), tangent(2), adjoint(4)
    integer :: unit, i, j
    call arena%init()
    v = sym(arena, 'v'); t = sym(arena, 't'); x = sym(arena, 'x')
    amplitude = sym(arena, 'amplitude'); a = sym(arena, 'a'); b = sym(arena, 'b')
    m = sym(arena, 'm'); nu = sym(arena, 'nu'); sc = sym(arena, 'sc')
    ss = sym(arena, 'ss'); dt = sym(arena, 'dt'); weight = sym(arena, 'weight')
    lo = sym(arena, 'lo'); hi = sym(arena, 'hi'); index = sym(arena, 'index')
    count = sym(arena, 'count'); da = sym(arena, 'da'); db = sym(arena, 'db')
    dv = sym(arena, 'dv'); ddt = sym(arena, 'ddt')
    wa = sym(arena, 'wa'); wb = sym(arena, 'wb')
    mm = sym(arena, "mm")
    open (newunit=unit, file='src/generated/kin6d_leaves.f90', status='replace')
    write (unit, '(a)') '! Generated by gen/gen_laboratory.f90; do not edit.'
    write (unit, '(a)') 'module kin6d_leaves'
    write (unit, '(a)') 'use iso_fortran_env, only: real128'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('clock_step', ['t ', 'dt'], ['value'], [t + dt])
    call emit('coordinate', ['lo   ', 'hi   ', 'index', 'count'], &
              ['value'], [lo + (hi - lo)*index/count])
    call emit('initial_coefficients', ['v        ', 'amplitude'], &
              ['m', 'a', 'b'], [exp(-v**2/2), amplitude*exp(-v**2/2), 0*v])
    cv = sym(arena, 'cv'); sv = sym(arena, 'sv')
    call emit('stream_factors', ['v ', 'dt'], ['cv', 'sv'], [cos(v*dt), sin(v*dt)])
    call emit('stream_cached', ['a ', 'b ', 'cv', 'sv'], ['an', 'bn'], &
              [a*cv - b*sv, a*sv + b*cv])
    rot = [a*cos(v*dt) - b*sin(v*dt), a*sin(v*dt) + b*cos(v*dt)]
    call emit('stream_step', ['a ', 'b ', 'v ', 'dt'], ['an', 'bn'], rot)
    inputs = [a, b, v, dt]; directions = [da, db, dv, ddt]
    do i = 1, 2
        tangent(i) = 0*a
        do j = 1, 4
            tangent(i) = tangent(i) + diff(rot(i), inputs(j))*directions(j)
        end do
    end do
    do j = 1, 4
        adjoint(j) = diff(rot(1), inputs(j))*wa + diff(rot(2), inputs(j))*wb
    end do
    call emit('stream_jvp', ['a  ', 'b  ', 'v  ', 'dt ', 'da ', 'db ', 'dv ', 'ddt'], &
              ['ja', 'jb'], tangent)
    call emit('stream_vjp', ['a ', 'b ', 'v ', 'dt', 'wa', 'wb'], &
              ['ga ', 'gb ', 'gv ', 'gdt'], adjoint)
    call emit('reconstruct', ['m', 'a', 'b', 'x'], ['value'], &
              [m + a*cos(x) + b*sin(x)])
    call emit('interval_reconstruct', ['m', 'a', 'b', 'x'], ['value'], &
              [m + a*cos(x) + b*sin(x)], rigorous=.true.)
    call emit('interpolate', ['lo    ', 'hi    ', 'weight'], ['value'], &
              [lo*(1 - weight) + hi*weight])
    call emit('interpolation_weight', ['lo', 'hi', 'v '], ['value'], &
              [(v - lo)/(hi - lo)])
    call emit('steady_source', ['v        ', 'nu       ', 'amplitude'], &
              ['sc', 'ss'], [nu*amplitude*exp(-v**2/2), -v*amplitude*exp(-v**2/2)])
    call emit('steady_solve', ['v ', 'nu', 'sc', 'ss'], ['a', 'b'], &
              [(nu*sc - v*ss)/(nu**2 + v**2), (v*sc + nu*ss)/(nu**2 + v**2)])
    call emit('steady_residual', ['a ', 'b ', 'v ', 'nu', 'sc', 'ss'], &
              ['rc', 'rs'], [nu*a + v*b - sc, nu*b - v*a - ss])
    f = exp(-v**2/2)*(1 + amplitude*cos(x - v*t))
    call emit('characteristic_reference', ['x        ', 'v        ', 't        ', &
                                           'amplitude'], ['value'], [f])
    call emit('characteristic_reference_qp', ['x        ', 'v        ', 't        ', &
                                              'amplitude'], ['value'], [f], quad=.true.)
    call emit('exact_coefficients', ['v        ', 't        ', 'amplitude'], &
              ['m', 'a', 'b'], [exp(-v**2/2), amplitude*exp(-v**2/2)*cos(v*t), &
                                amplitude*exp(-v**2/2)*sin(v*t)], rigorous=.true.)
    ! Uniform-in-x second derivative bound, using absolute upper inputs vm, mm.
    ! |M''| <= (vm**2+1)*mm, |M'| <= vm*mm on each velocity cell.
    call emit('interpolation_radius', ['vm       ', 'mm       ', 't        ', &
                                       'amplitude', 'hi       ', 'lo       '], &
              ['radius'], &
              [(hi - lo)**2/8*mm*((1 + amplitude)*(v**2 + 1) + &
                                  2*amplitude*t*v + amplitude*t**2)], rigorous=.true., &
              replace_v=.true.)
    ! The driver supplies nonnegative interval magnitudes to this sum leaf.
    call emit('radius_sum', ['a', 'b'], ['radius'], [a + b], rigorous=.true.)
    call emit('interval_band', ['lo', 'hi'], ['lower', 'upper'], &
              [lo - hi, lo + hi], rigorous=.true.)
    call emit('squared_norm', ['a', 'b'], ['value'], [a**2 + b**2])
    call emit('dot_four', ['a  ', 'b  ', 'v  ', 'dt ', 'da ', 'db ', 'dv ', 'ddt'], &
              ['value'], [a*da + b*db + v*dv + dt*ddt])
    write (unit, '(a)') 'end module kin6d_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, expressions, &
                              rigorous, quad, replace_v)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: expressions(:)
        logical, intent(in), optional :: rigorous, quad, replace_v
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(expr_t), allocatable :: roots(:)
        logical :: ok
        character(:), allocatable :: message
        integer :: k
        roots = expressions
        if (present(replace_v)) then
            block
                use fortsym_subs, only: subs
                do k = 1, size(roots)
                    roots(k) = subs(roots(k), v, sym(arena, 'vm'))
                end do
            end block
        end if
        if (present(rigorous)) then
            rspec%name = str(name); rspec%generator = str('gen_laboratory')
            rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
            rspec%runtime%exp = str('exp'); rspec%runtime%sin = str('sin')
            rspec%runtime%cos = str('cos')
            allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
            do k = 1, size(args)
                rspec%args(k) = str(trim(args(k)))
            end do
            do k = 1, size(outputs)
                rspec%outputs(k) = str(trim(outputs(k)))
            end do
            write (unit, '(a)') chars(emit_rigorous_kernel(roots, rspec, ok, message))
            if (.not. ok) error stop message
            return
        end if
        spec%name = str(name); spec%generator = str('gen_laboratory')
        spec%pure_procedure = .true.; spec%elemental_procedure = .true.
        spec%generator_revision = str('44da68f44c1ef3bc7617a307409c812a6ea4d515')
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do k = 1, size(args)
            spec%args(k) = str(trim(args(k)))
        end do
        do k = 1, size(outputs)
            spec%outputs(k) = str(trim(outputs(k)))
        end do
        if (present(quad)) spec%scalar_type = str('real(real128)')
        write (unit, '(a)') chars(emit_kernel(roots, spec))
        if (any(name == [character(24) :: 'initial_coefficients', &
                         'stream_factors', 'stream_cached', 'reconstruct', &
                         'interpolate', &
                         'interpolation_weight', &
                         'steady_source', 'steady_solve', 'steady_residual'])) &
            call emit_derivatives(name, args, outputs, roots)
    end subroutine
    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: jroots(:), vroots(:), parameters(:)
        character(64), allocatable :: jargs(:), jouts(:), vargs(:), vouts(:)
        integer :: k, l, narg, nout
        narg = size(args); nout = size(outputs)
        allocate (parameters(narg), jroots(nout), vroots(narg))
        allocate (jargs(2*narg), jouts(nout), vargs(narg + nout), vouts(narg))
        do k = 1, narg
            parameters(k) = sym(arena, trim(args(k)))
            jargs(k) = trim(args(k)); jargs(narg + k) = 'd_'//trim(args(k))
            vargs(k) = trim(args(k)); vouts(k) = 'g_'//trim(args(k))
        end do
        do l = 1, nout
            jouts(l) = 'd_'//trim(outputs(l))
            vargs(narg + l) = 'w_'//trim(outputs(l))
            jroots(l) = 0*roots(l)
            do k = 1, narg
                jroots(l) = jroots(l) + diff(roots(l), parameters(k))* &
                            sym(arena, trim(jargs(narg + k)))
            end do
        end do
        do k = 1, narg
            vroots(k) = 0*roots(1)
            do l = 1, nout
                vroots(k) = vroots(k) + diff(roots(l), parameters(k))* &
                            sym(arena, trim(vargs(narg + l)))
            end do
        end do
        call emit(name//'_jvp', jargs, jouts, jroots)
        call emit(name//'_vjp', vargs, vouts, vroots)
    end subroutine emit_derivatives

end program
