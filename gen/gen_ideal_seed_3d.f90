program gen_ideal_seed_3d
    ! Regular disk harmonics and a closed flux form from toroidal profiles.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/), operator(**), sin, cos
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: proof
    type(expr_t) :: u, v, a, b, rc, rs, zc, zs, s, c, value, flux, pi
    type(expr_t) :: integral, edge, iota, pressure, chi, gu, gv, b3
    type(expr_t) :: jet(3, 3), twisted(3, 3), bt, phase_s, density(3)
    integer :: row, column
    character(3), parameter :: jets(3, 3) = reshape([character(3) :: &
        'd11', 'd21', 'd31', 'd12', 'd22', 'd32', 'd13', 'd23', 'd33'], [3, 3])
    call arena%init()
    engine = make_native_engine(arena)
    call w%open(arena, 'gen_ideal_seed_3d', &
        'src/generated/kin6d_ideal_seed_3d_leaves.f90')
    call w%line('! Generated by gen/gen_ideal_seed_3d.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_ideal_seed_3d_leaves')
    call w%line('use, intrinsic :: iso_fortran_env, only: dp => real64')
    call w%line('implicit none')
    call w%line('contains')
    u = sym(arena, 'u'); v = sym(arena, 'v')
    s = sym(arena, 's'); pi = sym(arena, 'pi')
    a = sym(arena, 'r'); b = sym(arena, 'z')
    call w%emit('seed_disk_coordinates', ['r', 'z'], ['u', 'v', 's'], &
        [a - 2, b, (a - 2)**2 + b**2], ad=.true.)
    a = sym(arena, 't')
    call w%emit('seed_disk_boundary', ['t ', 'pi'], ['r', 'z'], &
        [2 + cos(2*pi*a), sin(2*pi*a)], ad=.true.)
    a = sym(arena, 'coefficient'); b = sym(arena, 'degree')
    call w%emit('seed_primitive_coefficient', &
        [character(11) :: 'coefficient', 'degree'], ['value'], [a/b], ad=.true.)
    a = sym(arena, 'value')
    call w%emit('seed_primitive_finish', ['s    ', 'value'], ['out'], [s*a], ad=.true.)
    a = sym(arena, 'a'); b = sym(arena, 'b')
    call w%emit('seed_complex_product', ['u', 'v', 'a', 'b'], &
        ['re', 'im'], [u*a - v*b, u*b + v*a], ad=.true.)
    rc = sym(arena, 'rc'); rs = sym(arena, 'rs')
    zc = sym(arena, 'zc'); zs = sym(arena, 'zs')
    call w%emit('seed_boundary_mode', &
        ['u ', 'v ', 'rc', 'rs', 'zc', 'zs'], &
        ['r_cos', 'r_sin', 'z_cos', 'z_sin'], &
        [rc*u + rs*v, rc*v - rs*u, zc*u + zs*v, zc*v - zs*u], ad=.true.)
    s = sym(arena, 's'); c = sym(arena, 'c'); value = sym(arena, 'value')
    call w%emit('seed_horner', [character(5) :: 's', 'c', 'value'], &
        ['out'], [value*s + c], ad=.true.)
    flux = sym(arena, 'flux'); pi = sym(arena, 'pi')
    integral = sym(arena, 'integral'); edge = sym(arena, 'edge')
    iota = sym(arena, 'iota'); pressure = sym(arena, 'pressure')
    chi = flux*(integral - edge)/(2*pi)
    gu = flux*iota*u/pi; gv = flux*iota*v/pi; b3 = flux/pi
    call w%emit('seed_toroidal_form', &
        [character(8) :: 'u', 'v', 'flux', 'pi', 'integral', 'edge', &
         'iota', 'pressure'], &
        [character(3) :: 'chi', 'gu', 'gv', 'b3', 'p'], &
        [chi, gu, gv, b3, pressure], ad=.true.)
    ! The contravariant density is (-gv,gu,b3). For arbitrary iota(s),
    ! s=u^2+v^2, the mixed terms cancel exactly. Verify the chain rule with
    ! an independent symbol for d iota/ds; no numerical probes enter.
    a = sym(arena, 'diota')
    proof = engine%zero_test(-diff(gv, u) - diff(gv, iota)*a*2*u &
        + diff(gu, v) + diff(gu, iota)*a*2*v)
    if (proof%verdict /= VERDICT_TRUE) error stop 'closed disk flux unproved'
    proof = engine%zero_test((u*gu + v*gv) &
        - (u**2 + v**2)*b3*iota)
    if (proof%verdict /= VERDICT_TRUE) error stop 'disk iota identity unproved'
    ! In (s,theta,phi), b=(0,iota*bt,bt). The relabelling
    ! theta'=theta+iota(s)*omega, phi'=phi+omega leaves this density
    ! invariant after division by its Jacobian, conditional on J>0.
    a=sym(arena,'omega_theta'); b=sym(arena,'omega_phi')
    value=(1+iota*a)*(1+b)-iota*b*a
    proof=engine%zero_test(value-(1+iota*a+b))
    if(proof%verdict/=VERDICT_TRUE) error stop 'position-gauge Jacobian unproved'
    proof=engine%zero_test((1+iota*a)*iota+iota*b-value*iota)
    if(proof%verdict/=VERDICT_TRUE) error stop 'position-gauge poloidal form unproved'
    proof=engine%zero_test(a*iota+1+b-value)
    if(proof%verdict/=VERDICT_TRUE) error stop 'position-gauge toroidal form unproved'
    ! A residual phi-fixed gauge is theta' = theta + f(s), f(1)=0.
    ! DG is a shear of determinant one; it preserves s, pressure and the
    ! density (0,iota(s)*bt(s),bt(s)). For arbitrary DX at the transformed
    ! point, both its determinant and DX*b are unchanged. This is a continuum
    ! identity, not a claim of an exact null in the discrete interpolation.
    phase_s = sym(arena, 'phase_s'); bt = sym(arena, 'bt')
    do column = 1, 3
        do row = 1, 3
            jet(row, column) = sym(arena, jets(row, column))
        end do
    end do
    twisted = jet
    do row = 1, 3
        twisted(row, 1) = jet(row, 1) + phase_s*jet(row, 2)
    end do
    density = [0*bt, iota*bt, bt]
    do row = 1, 3
        proof = engine%zero_test(dot(twisted(row, :), density) &
            - dot(jet(row, :), density))
        if (proof%verdict /= VERDICT_TRUE) error stop 'poloidal phase flux unproved'
    end do
    proof = engine%zero_test(determinant(twisted) - determinant(jet))
    if (proof%verdict /= VERDICT_TRUE) error stop 'poloidal phase volume unproved'
    call w%line('end module kin6d_ideal_seed_3d_leaves')
    call w%close()
    print '(a)', '[V] FortSym closed flux, iota and position/poloidal-phase gauge identities proved'
contains
    function dot(a, b) result(value)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: value
        value = a(1)*b(1) + a(2)*b(2) + a(3)*b(3)
    end function

    function determinant(a) result(value)
        type(expr_t), intent(in) :: a(3, 3)
        type(expr_t) :: value
        value = a(1, 1)*(a(2, 2)*a(3, 3) - a(2, 3)*a(3, 2)) &
            - a(1, 2)*(a(2, 1)*a(3, 3) - a(2, 3)*a(3, 1)) &
            + a(1, 3)*(a(2, 1)*a(3, 2) - a(2, 2)*a(3, 1))
    end function
end program
