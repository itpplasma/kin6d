! Threshold pionless EFT: source equations are recorded in docs/pp-fusion-eft.md.
program gen_pp_fusion_eft
    use fortsym_expr, only: expr_t, sym, exp, sqrt, log, sin, cos, &
        pi_expr, operator(+), operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: bd, mp, mn, hc, alpha, mu, gamma, chi, screen, euler
    type(expr_t) :: a, r, rho, la, ga, jc, den, lb, aa, bb, z, node, theta, y
    type(expr_t) :: lam, radius, c0, c1, c2, res, jp, ap, bp, cp, v, f, df, mpfm
    call w%open('gen_pp_fusion_eft', &
        'src/generated/kin6d_pp_fusion_eft_leaves.f90')
    call w%line('! Generated by gen/gen_pp_fusion_eft.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_pp_fusion_eft_leaves')
    call w%line('use, intrinsic :: iso_fortran_env, only: dp => real64')
    call w%line('implicit none')
    call w%line('contains')
    bd = sym('bd'); mp = sym('mp'); mn = sym('mn')
    hc = sym('hc'); alpha = sym('alpha'); mu = sym('mu')
    euler = sym('euler')
    gamma = sqrt(2*mp*mn*bd/(mp + mn))/hc
    chi = alpha*mp/(hc*gamma)
    screen = alpha*mp/hc*(log(mu*hc*sqrt(pi_expr())/(alpha*mp)) &
        + 1 - 3*euler/2)
    call w%emit('eft_scales', &
        ['bd   ', 'mp   ', 'mn   ', 'hc   ', 'alpha', 'mu   ', 'euler'], &
        ['gamma ', 'chi   ', 'screen'], [gamma, chi, screen], ad=.true.)
    gamma = sym('gamma'); chi = sym('chi')
    screen = sym('screen'); a = sym('app')
    r = sym('r'); rho = sym('rho'); la = sym('la')
    ga = sym('axial'); jc = sym('jc')
    den = 1/a - mu + screen
    ! Butler--Chen (9),(10): eliminate C0,C2 algebraically; all lengths in fm.
    lb = -(mu - gamma)*den/(4*pi_expr())* &
        (la/ga - pi_expr()*(r/den**2 + rho/(mu - gamma)**2))
    aa = exp(chi) - gamma*a*jc
    bb = -gamma**2*a*lb
    z = gamma*rho
    ! Coefficients of epsilon^0,1,2 in BC (7); no K1A/shape input at this order.
    call w%emit('eft_orders', &
        ['gamma ', 'app   ', 'r     ', 'rho   ', 'la    ', 'axial ', &
        'mu    ', 'chi   ', 'jc    ', 'screen'], &
        ['c0  ', 'c1  ', 'c2  ', 'res ', 'lbar'], &
        [aa, aa*z/2 + bb, 3*aa*z**2/8 + bb*z/2, (aa + bb)/sqrt(1 - z), lb], &
        ad=.true.)
    ! Kong--Ravndal (22): x=pi*chi*tan(theta), theta=pi*(node+1)/4.
    ! chi*I(chi) = (2/pi) integral C0^2(chi*tan(theta)/2)
    !                         *exp(chi*tan(theta)*(pi/2-theta)) dtheta.
    node = sym('node'); theta = pi_expr()*(node + 1)/4
    y = sin(theta)/cos(theta)
    call w%emit('eft_coulomb_node', ['node', 'chi '], ['eta   ', 'weight'], &
        [chi*y/2, exp(chi*y*(pi_expr()/2 - theta))/2], ad=.true.)
    ! p^2 derivative of the Coulomb Green integral in Chen--Liu--Yu (8).
    call w%emit('eft_coulomb_moment', ['node', 'chi '], ['moment'], &
        [exp(chi*y*(pi_expr()/2 - theta))*y**2/2], ad=.true.)
    ! Differentiate the defining E1 integral, not the quadrature algorithm.
    call w%emit('eft_coulomb_slope', ['chi', 'jc '], ['djc'], &
        [(1 + 1/chi)*jc - 1/chi], ad=.true.)
    c0 = sym('c0'); c1 = sym('c1')
    c2 = sym('c2'); res = sym('res')
    ! Expand the rate consistently, Chen--Liu--Yu (12), through epsilon^2.
    call w%emit('eft_rates', ['c0 ', 'c1 ', 'c2 ', 'res'], &
        ['lo ', 'nlo', 'nn ', 'rs '], &
        [c0**2, c0**2 + 2*c0*c1, c0**2 + 2*c0*c1 + c1**2 + 2*c0*c2, &
        res**2], ad=.true.)
    ! Differentiate the spectral integral and pp denominator at threshold.
    ! jp=dJ/d(p^2), mpfm=proton mass/hc; see the retained derivation.
    jp = sym('jp'); mpfm = sym('mpfm')
    alpha = sym('alpha'); f = sym('phase'); df = sym('phase_derivative')
    hc = sym('hc'); v = sym('v')
    ap = -exp(chi)*(1 + chi/3)/gamma**2 - gamma*a*jp &
        + gamma*a**2*jc/(3*alpha*mpfm)
    bp = gamma**2*a**2*lb/(3*alpha*mpfm) - gamma*a**2*r*jc/2
    cp = -gamma**2*a**2*r*lb/2
    ! The last term cp first enters at NNLO from the range correction to L1A.
    call w%emit('eft_energy_coefficients', &
        ['gamma ', 'app   ', 'r     ', 'rho   ', 'la    ', 'axial ', &
        'mu    ', 'chi   ', 'jc    ', 'screen', 'jp    ', 'alpha ', 'mpfm  '], &
        ['p0  ', 'p1  ', 'p2  ', 'pres'], &
        [ap, ap*z/2 + bp, 3*ap*z**2/8 + bp*z/2 + cp, &
        (ap + bp + cp)/sqrt(1 - z)], ad=.true.)
    lam = sym('lam')
    ! Scalar physical pairing: derivative of log S with respect to c.m. MeV.
    call w%emit('eft_energy_slope', [character(16) :: 'v', 'lam', 'phase', &
        'phase_derivative', 'mpfm', 'hc'], &
        ['slope'], [mpfm/hc*v/lam + df/f], ad=.true.)
    lam = sym('lam'); radius = sym('radius')
    call w%emit('eft_square_error', ['lam   ', 'radius'], ['value'], &
        [2*lam*radius + radius**2], ad=.true.)
    call w%line('end module kin6d_pp_fusion_eft_leaves')
    call w%close()
end program
