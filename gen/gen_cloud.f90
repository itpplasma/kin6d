program gen_cloud
    use fortsym_expr, only: expr_t, sym, sqrt, sin, cos, pi_expr, &
                        operator(+), operator(-), operator(*), operator(/)
    use milca_gen_support, only: leaf_writer_t
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: n, r, p, phase
    n = sym('n'); p = sym('p')
    call w%open('gen_cloud', 'src/generated/milca_cloud_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_cloud.f90; do not edit.'
    write (w%unit, '(a)') '! Initial data of the isolated electron cloud (C2): Fibonacci'
    write (w%unit, '(a)') '! sphere of radius 5/2 for n electrons; interactions live in'
    write (w%unit, '(a)') '! milca_coulomb_leaves (gen/milca_symbolic_physics.f90).'
    write (w%unit, '(a)') 'module milca_cloud_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    r = 1 - (2*p - 1)/n
    phase = pi_expr()*(3 - sqrt(5 + 0*p))*p
    call w%emit('cloud_initial_position', ['p', 'n'], ['x', 'y', 'z'], &
              [5*sqrt(1 - r*r)*cos(phase)/2, 5*sqrt(1 - r*r)*sin(phase)/2, 5*r/2])
    call w%emit('cloud_initial_velocity', ['p'], ['vx', 'vy', 'vz'], &
              [2*sin(7*p)/5, 2*cos(11*p)/5, 2*sin(13*p)/5])
    write (w%unit, '(a)') 'end module milca_cloud_leaves'
    call w%close()
end program gen_cloud
