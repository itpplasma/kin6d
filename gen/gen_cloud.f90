program gen_cloud
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, sin, cos, abs, pi_expr, &
                        operator(+), operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: x, y, z, n, radius, dt, rate, value, r, ix, iy, iz, p, energy, phase
    call arena%init()
    x = sym(arena, 'x'); y = sym(arena, 'y'); z = sym(arena, 'z')
    n = sym(arena, 'n'); radius = sym(arena, 'radius')
    dt = sym(arena, 'dt'); rate = sym(arena, 'rate'); value = sym(arena, 'value')
    ix = sym(arena, 'ix'); iy = sym(arena, 'iy'); iz = sym(arena, 'iz')
    p = sym(arena, 'p'); energy = sym(arena, 'energy')
    r = sqrt(x*x + y*y + z*z)
    call w%open(arena, 'gen_cloud', 'src/generated/kin6d_cloud_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_cloud.f90; do not edit.'
    write (w%unit, '(a)') '! Isolated electron cloud, m=1, q=-1, 1/(4 pi eps)=1.'
    write (w%unit, '(a)') '! Fixed sphere: positive total charge n, radius R; no wall.'
    write (w%unit, '(a)') '! Smooth branches: inside/outside R; Hessian changes at R.'
    write (w%unit, '(a)') 'module kin6d_cloud_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('cloud_background_inside', ['x     ', 'y     ', 'z     ', 'n     ', &
                      'radius'], ['fx       ', 'fy       ', 'fz       ', 'potential'], &
              [-n*x/radius**3, -n*y/radius**3, -n*z/radius**3, &
               -n*(3*radius**2 - x*x - y*y - z*z)/(2*radius**3)], ad=.true.)
    call w%emit('cloud_background_outside', ['x     ', 'y     ', 'z     ', 'n     ', &
                      'radius'], ['fx       ', 'fy       ', 'fz       ', 'potential'], &
              [-n*x/r**3, -n*y/r**3, -n*z/r**3, -n/r], ad=.true.)
    call w%emit('cloud_axpy', ['value', 'rate ', 'dt   '], ['next'], &
              [value + rate*dt], ad=.true.)
    call w%emit('cloud_norm', ['x', 'y', 'z'], ['r'], [r], ad=.true.)
    call w%emit('cloud_energy', ['energy', 'x     ', 'y     ', 'z     '], ['next'], &
              [energy + (x*x + y*y + z*z)/2], ad=.true.)
    call w%emit('cloud_projection', ['x', 'y', 'z'], ['xp', 'yp'], &
              [x + z/4, y + z/6], ad=.true.)
    r = 1 - (2*p - 1)/32
    phase = pi_expr(arena)*(3 - sqrt(5 + 0*p))*p
    call w%emit('cloud_initial_position', ['p'], ['x', 'y', 'z'], &
              [5*sqrt(1 - r*r)*cos(phase)/2, 5*sqrt(1 - r*r)*sin(phase)/2, 5*r/2])
    call w%emit('cloud_initial_velocity', ['p'], ['vx', 'vy', 'vz'], &
              [2*sin(7*p)/5, 2*cos(11*p)/5, 2*sin(13*p)/5])
    call w%emit('cloud_difference', ['value', 'rate '], ['delta'], [value - rate])
    call w%emit('cloud_frame_time', ['p ', 'n ', 'dt'], ['t'], [p*n*dt])
    call w%emit('cloud_phase', ['p'], ['phase'], [2*pi_expr(arena)*p/100])
    call w%emit('cloud_fraction', ['p', 'n'], ['value'], [p/n])
    call w%emit('cloud_circle', ['p     ', 'radius'], ['x', 'y'], &
              [radius*cos(p), radius*sin(p)])
    call w%emit('cloud_display_defect', ['value'], ['display'], [1000000*value])
    call w%emit('cloud_energy_defect', ['energy', 'value '], ['defect'], &
              [(energy - value)/abs(value)])
    write (w%unit, '(a)') 'end module kin6d_cloud_leaves'
    call w%close()
end program gen_cloud
