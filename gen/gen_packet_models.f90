program gen_packet_models
    ! Generates the canonical thawed-Gaussian (TDVP / wave-packet molecular
    ! dynamics) leaves of campaign case Q2 (src/quantum/packet_models.f90).
    !
    ! An isotropic Gaussian psi = (2 pi s)^(-3/4) exp(-(1/(4s) - i beta)|r-q|^2
    ! + i p.(r-q)/hbar + i gamma) has |psi|^2 variance s per axis. The
    ! Dirac-Frenkel Lagrangian is p.qdot + ps sdot - <H> with the canonical
    ! width momentum ps = 3 hbar beta, so the TDVP equations are Hamilton's
    ! equations of the expectation <H>(q, p, s, ps); the Dirac-Frenkel phase
    ! obeys hbar gammadot = p.qdot - s psdot - <H>. Motion is in the x-z plane.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, rat, &
                            operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: gaussian_coulomb_potential, gaussian_coulomb_series
    implicit none
    integer, parameter :: series_order = 7
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: qx, qz, px, pz, s, ps, g, kappa, mu, hbar, mass, h, v, q2
    type(expr_t) :: q1x, q1z, q2x, q2z, p1x, p1z, p2x, p2z, s1, s2, ps1, ps2, m
    type(expr_t) :: ds, dps, ar, ai, dar, dai, cre, cim, qdx, qdz, energy, r2
    type(expr_t) :: rates(6), rates2(12)

    call arena%init()
    qx = sym(arena, 'qx'); qz = sym(arena, 'qz'); px = sym(arena, 'px')
    pz = sym(arena, 'pz'); s = sym(arena, 's'); ps = sym(arena, 'ps')
    g = sym(arena, 'g'); kappa = sym(arena, 'kappa'); mu = sym(arena, 'mu')
    hbar = sym(arena, 'hbar'); mass = sym(arena, 'mass')

    call w%open(arena, 'gen_packet_models', 'src/generated/kin6d_packet_models_leaves.f90')
    call w%line('! Generated by gen/gen_packet_models.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Canonical isotropic thawed Gaussians (TDVP/WPMD) in the x-z plane:')
    call w%line('! state (q, p, s, ps), s = variance of |psi|^2 per axis, ps = 3 hbar beta.')
    call w%line('! Gaussian-averaged Coulomb from gen/kin6d_symbolic_physics.f90.')
    call w%line('! kappa: optional isotropic harmonic test potential kappa r^2/2.')
    call w%line('! JVP/VJP use Euclidean pairings of the listed real arguments.')
    call w%line('module kin6d_packet_models_leaves')
    call w%line('implicit none')
    call w%line('contains')

    ! M3: one Gaussian for the relative coordinate (reduced mass mu).
    q2 = qx**2 + qz**2
    v = gaussian_coulomb_potential(g, s, sqrt(q2))
    call emit_m3('pm_m3_rhs', v)
    v = gaussian_coulomb_series(g, s, q2/(2*s), series_order)
    call emit_m3('pm_m3_rhs_series', v)

    ! M2: product of two electron Gaussians (equal mass m); the pair Coulomb
    ! term sees the summed variance s1 + s2.
    q1x = sym(arena, 'q1x'); q1z = sym(arena, 'q1z'); q2x = sym(arena, 'q2x')
    q2z = sym(arena, 'q2z'); p1x = sym(arena, 'p1x'); p1z = sym(arena, 'p1z')
    p2x = sym(arena, 'p2x'); p2z = sym(arena, 'p2z'); s1 = sym(arena, 's1')
    s2 = sym(arena, 's2'); ps1 = sym(arena, 'ps1'); ps2 = sym(arena, 'ps2')
    m = sym(arena, 'm')
    r2 = (q1x - q2x)**2 + (q1z - q2z)**2
    v = gaussian_coulomb_potential(g, s1 + s2, sqrt(r2))
    call emit_m2('pm_m2_rhs', v)
    v = gaussian_coulomb_series(g, s1 + s2, r2/(2*(s1 + s2)), series_order)
    call emit_m2('pm_m2_rhs_series', v)

    ! Free kinetic expectation of one Gaussian and its complex width parameter
    ! alpha = ar + i ai = 1/(4 s) - i ps/(3 hbar) (JVP maps rates/tangents).
    call w%emit('pm_gaussian_energy', ['px  ', 'pz  ', 's   ', 'ps  ', 'mass', 'hbar'], &
                ['e'], [kinetic(px, pz, s, ps, mass)])
    call w%emit('pm_width_parameter', ['s   ', 'ps  ', 'hbar'], ['ar', 'ai'], &
                [1/(4*s), -ps/(3*hbar)], ad=.true.)
    ! Dirac-Frenkel phase rate for given parameter rates and energy.
    qdx = sym(arena, 'qdx'); qdz = sym(arena, 'qdz'); dps = sym(arena, 'dps')
    energy = sym(arena, 'energy')
    call w%emit('pm_df_phase', ['px    ', 'pz    ', 'qdx   ', 'qdz   ', 's     ', &
                                'dps   ', 'energy', 'hbar  '], ['dgamma'], &
                [(px*qdx + pz*qdz - s*dps - energy)/hbar])
    ! Free-Hamiltonian residual norm of a normalized Gaussian at rest (centroid
    ! following P/M, Dirac-Frenkel phase): ||r|| = sqrt(6) s |c2| with
    ! c2 = -i hbar alphadot + 2 hbar^2 alpha^2/M.
    ds = sym(arena, 'ds')
    ar = 1/(4*s); ai = -ps/(3*hbar); dar = -ds/(4*s**2); dai = -dps/(3*hbar)
    cre = hbar*dai + 2*hbar**2*(ar**2 - ai**2)/mass
    cim = -hbar*dar + 4*hbar**2*ar*ai/mass
    call w%emit('pm_free_residual', ['s   ', 'ps  ', 'ds  ', 'dps ', 'mass', 'hbar'], &
                ['r'], [sqrt(rat(arena, 6_8, 1_8))*s*sqrt(cre**2 + cim**2)])

    call w%line('end module kin6d_packet_models_leaves')
    call w%close()
contains
    function kinetic(pxv, pzv, sv, psv, mv) result(e)
        type(expr_t), intent(in) :: pxv, pzv, sv, psv, mv
        type(expr_t) :: e
        e = (pxv**2 + pzv**2)/(2*mv) + 3*hbar**2/(8*mv*sv) + 2*sv*psv**2/(3*mv)
    end function kinetic

    subroutine emit_m3(name, pot)
        character(*), intent(in) :: name
        type(expr_t), intent(in) :: pot
        type(expr_t) :: hh
        hh = kinetic(px, pz, s, ps, mu) + pot + kappa*(qx**2 + qz**2 + 3*s)/2
        rates = [diff(hh, px), diff(hh, pz), -diff(hh, qx), -diff(hh, qz), &
                 diff(hh, ps), -diff(hh, s)]
        call w%emit(name, ['qx   ', 'qz   ', 'px   ', 'pz   ', 's    ', 'ps   ', 'g    ', &
                           'kappa', 'mu   ', 'hbar '], &
                    ['dqx   ', 'dqz   ', 'dpx   ', 'dpz   ', 'ds    ', 'dps   ', &
                     'energy', 'dgamma'], &
                    [rates, hh, (px*rates(1) + pz*rates(2) - s*rates(6) - hh)/hbar], &
                    ad=.true.)
    end subroutine emit_m3

    subroutine emit_m2(name, pot)
        character(*), intent(in) :: name
        type(expr_t), intent(in) :: pot
        type(expr_t) :: hh, phase
        hh = kinetic(p1x, p1z, s1, ps1, m) + kinetic(p2x, p2z, s2, ps2, m) + pot
        rates2 = [diff(hh, p1x), diff(hh, p1z), diff(hh, p2x), diff(hh, p2z), &
                  -diff(hh, q1x), -diff(hh, q1z), -diff(hh, q2x), -diff(hh, q2z), &
                  diff(hh, ps1), diff(hh, ps2), -diff(hh, s1), -diff(hh, s2)]
        phase = (p1x*rates2(1) + p1z*rates2(2) + p2x*rates2(3) + p2z*rates2(4) &
                 - s1*rates2(11) - s2*rates2(12) - hh)/hbar
        call w%emit(name, ['q1x ', 'q1z ', 'q2x ', 'q2z ', 'p1x ', 'p1z ', 'p2x ', &
                           'p2z ', 's1  ', 's2  ', 'ps1 ', 'ps2 ', 'g   ', 'm   ', &
                           'hbar'], &
                    ['dq1x  ', 'dq1z  ', 'dq2x  ', 'dq2z  ', 'dp1x  ', 'dp1z  ', &
                     'dp2x  ', 'dp2z  ', 'ds1   ', 'ds2   ', 'dps1  ', 'dps2  ', &
                     'energy', 'dgamma'], [rates2, hh, phase])
    end subroutine emit_m2
end program gen_packet_models
