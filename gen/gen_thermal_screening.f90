program gen_thermal_screening
    ! Benchmarks B05-B07: leaves of the first-order (in grad T) spatial-moment
    ! equations of a test ion in B = B e_z and a background with T_b = T_0 + G.x,
    !   d_t N = L N + C^q[N] + G.d_T C[M],   d_t M = L M + v N,   L = C_T0 - Omega (v x b).grad_v.
    ! Every source is l = 1, so the state is f = c(v).n with n = v/|v|.
    ! Proved here (each for arbitrary radial functions, through jets):
    !   cq_source: C^q[f] = -div(A^T f) + div div(D^T f) equals s P(v), s = q.n, for an
    !     isotropic f, given the oracle identities lap G^T = 2 H^T and lap H^T = -4 pi K s;
    !     scr_cq_shell emits v^2 P from the same expression.
    !   lorentz_l1: -Omega (v x b).grad_v (c.n) = Omega (c_y n_x - c_x n_y), so
    !     zeta = c_x - i c_y obeys d_t zeta = ... + i Omega zeta, and c_z does not rotate.
    !   larmor: G.rho f_M = (G_y n_x - G_x n_y) v f_M / Omega for rho = b x v / Omega,
    !     the displacement that the guiding-centre variant removes from M.
    ! The l = 1 radial operator of d_T C is B04's per-l operator (gen_fp_relaxation
    ! proves it for arbitrary A_r, D_par, D_perp) with the T_b derivatives below.
    use fortsym_expr, only: expr_t, sym, rat, exp, sqrt, erf, pi_expr, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_check, only: suite_t, suite_begin, suite_end, check_identity
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    integer, parameter :: nfun = 5, ig = 1, iff = 2, icx = 3, icy = 4, icz = 5
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(symengine_engine_t) :: symengine
    type(suite_t) :: suite
    type(expr_t) :: v, tb, mb, ma, ta, nb, gam, mr, kq, fm0, fm1, fm2, dh, g0, g1, g2
    type(expr_t) :: pi_e, sq_pi, vte, hpot, gpot, dhv, dgv, d2gv, fmx, x2, kr, psrc
    type(expr_t) :: zero, half
    type(expr_t) :: CC(3), Rr, nn(3), jet(0:4, nfun), chart(3)

    engine = make_native_engine()
    symengine = make_symengine_engine()
    zero = rat(0_8, 1_8)
    half = rat(1_8, 2_8)
    pi_e = pi_expr()
    sq_pi = sqrt(pi_e)
    v = sym('v'); tb = sym('tb'); mb = sym('mb')
    ma = sym('ma'); ta = sym('ta'); nb = sym('nb')
    gam = sym('gam'); mr = sym('mr'); kq = sym('kq')
    fm0 = sym('fm0'); fm1 = sym('fm1'); fm2 = sym('fm2')
    dh = sym('dh'); g0 = sym('g0'); g1 = sym('g1')
    g2 = sym('g2')

    ! Radial l = 1 source of C^q[f_M] = P(v) (q.n) per unit q, in the oracle jets
    ! h1' = dh, g1 = g0, g1' = g1, g1'' = g2 and the distortion source K = kq.
    psrc = 4*pi_e*gam*mr*kq*fm0 + gam*(1 - mr)*dh*fm1 + &
        gam*half*(g2*fm2 + 2*(g1/v - g0/v**2)*fm1/v)

    call suite_begin(suite, 'thermal_screening_reductions')
    call setup_jets()
    call check_cq_source()
    call check_lorentz_l1()
    call check_larmor()
    call suite_end(suite)

    ! B04's Maxwellian-bath potentials with v_t = sqrt(2 T_b/m_b), as in
    ! gen_fp_relaxation; test_screening_moments compares their T_b derivatives
    ! with a difference quotient of the B04 leaves.
    vte = sqrt(2*tb/mb)
    hpot = nb*erf(v/vte)/v
    dhv = diff(hpot, v)
    gpot = nb*vte*((v/vte + vte/(2*v))*erf(v/vte) + exp(-(v/vte)**2)/sq_pi)
    dgv = diff(gpot, v)
    d2gv = diff(dgv, v)
    ! Unit-density test Maxwellian and the distortion source K: f_b^T = K(v) (q.n)
    ! (conventions.md Eq. 1, n_b cancels).
    fmx = sqrt(ma/(2*pi_e*ta))**3*exp(-ma*v**2/(2*ta))
    x2 = mb*v**2/(2*tb)
    kr = (2*mb/(5*tb**2))*sqrt(mb/(2*pi_e*tb))**3*exp(-x2)*(x2 - rat(5_8, 2_8))*v

    call w%open('gen_thermal_screening', 'src/generated/milca_thermal_screening_leaves.f90')
    w%simplify_roots = .true.
    call w%line('! Generated by gen/gen_thermal_screening.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Benchmarks B05-B07: T_b derivatives of the B04 Maxwellian-bath coefficients,')
    call w%line('! the distortion source K, and the cell integrands of the l=1 sources.')
    call w%line('module milca_thermal_screening_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('scr_friction_dt', [character(len=3) :: 'v', 'tb', 'mb', 'nb', 'gam', 'mr'], &
        ['value'], [diff(gam*(1 + mr)*dhv, tb)])
    call w%emit('scr_diff_par_dt', [character(len=3) :: 'v', 'tb', 'mb', 'nb', 'gam'], &
        ['value'], [diff(gam*half*d2gv, tb)])
    call w%emit('scr_diff_perp_dt', [character(len=3) :: 'v', 'tb', 'mb', 'nb', 'gam'], &
        ['value'], [diff(gam*half*dgv/v, tb)])
    call w%emit('scr_cross_dt', [character(len=3) :: 'v', 'tb', 'mb', 'nb', 'gam'], &
        ['value'], [diff(gam*(d2gv - dgv/v)/v, tb)])
    call w%emit('scr_distortion_k', [character(len=2) :: 'v', 'tb', 'mb'], ['value'], [kr])
    ! v^2 times the l = 1 coefficient v f_M of the M source v_x f_M.
    call w%emit('scr_vfm_shell', [character(len=2) :: 'v', 'ma', 'ta'], ['value'], [v**3*fmx])
    ! v^2 P with the proved P, the Maxwellian jets and K substituted.
    call w%emit('scr_cq_shell', [character(len=3) :: 'v', 'ma', 'ta', 'tb', 'mb', 'gam', 'mr', &
        'dh', 'g0', 'g1', 'g2'], ['value'], [v**2*subs(subs(subs(subs(psrc, kq, kr), &
        fm2, diff(diff(fmx, v), v)), fm1, diff(fmx, v)), fm0, fmx)])
    call w%line('end module milca_thermal_screening_leaves')
    call w%close()

contains

    subroutine setup_jets()
        character(len=2), parameter :: fname(nfun) = ['g ', 'f ', 'cx', 'cy', 'cz']
        type(expr_t) :: uu, ww, den
        integer :: m, o, i

        CC(1) = sym('x'); CC(2) = sym('y'); CC(3) = sym('z')
        Rr = sym('R')
        do m = 1, nfun
            do o = 0, 4
                jet(o, m) = sym(trim(fname(m))//'_'//achar(48 + o))
            end do
        end do
        do i = 1, 3
            nn(i) = CC(i)/Rr
        end do
        ! Stereographic chart of the sphere |x| = R, so no radical enters a zero test.
        uu = sym('u'); ww = sym('w')
        den = 1 + uu**2 + ww**2
        chart(1) = Rr*2*uu/den; chart(2) = Rr*2*ww/den; chart(3) = Rr*(1 - uu**2 - ww**2)/den
    end subroutine setup_jets

    ! Total derivative along x_k (k = 1..3) or R (k = 0): d_i R = x_i/R and
    ! d_i F_o = F_(o+1) x_i/R for the jet F_0 .. F_4 of each radial function.
    function chain(e, k) result(d)
        type(expr_t), intent(in) :: e
        integer, intent(in) :: k
        type(expr_t) :: d, radial
        integer :: m, o
        radial = zero
        do m = 1, nfun
            do o = 0, 3
                radial = radial + diff(e, jet(o, m))*jet(o + 1, m)
            end do
        end do
        if (k == 0) then
            d = diff(e, Rr) + radial
        else
            d = diff(e, CC(k)) + (diff(e, Rr) + radial)*nn(k)
        end if
    end function chain

    ! C^q[f] for q = e_z, s = z/R: G^T = g(R) s, H^T = h(R) s with h = L1(g)/2,
    ! L1(g) = g'' + 2g'/R - 2g/R^2 (lap G^T = 2 H^T), and K = -L1(h)/(4 pi)
    ! (lap H^T = -4 pi K s). The residual is bilinear in the jets of g and f, so
    ! each mixed second derivative is a separate, smaller zero test.
    subroutine check_cq_source()
        type(expr_t) :: hh, l1h, gfun, hfun, ffun, cart, bi, dd, psub, res
        integer :: i, j, k, o

        hh = half*(jet(2, ig) + 2*jet(1, ig)/Rr - 2*jet(0, ig)/Rr**2)
        l1h = chain(chain(hh, 0), 0) + 2*chain(hh, 0)/Rr - 2*hh/Rr**2
        gfun = jet(0, ig)*nn(3)
        hfun = hh*nn(3)
        ffun = jet(0, iff)
        cart = zero
        do i = 1, 3
            bi = -gam*(1 + mr)*chain(hfun, i)*ffun
            do j = 1, 3
                dd = gam*half*chain(chain(gfun, j), i)*ffun
                bi = bi + chain(dd, j)
            end do
            cart = cart + chain(bi, i)
        end do
        psub = subs(psrc, kq, -l1h/(4*pi_e))
        psub = subs(psub, dh, chain(hh, 0))
        psub = subs(psub, g2, jet(2, ig))
        psub = subs(psub, g1, jet(1, ig))
        psub = subs(psub, g0, jet(0, ig))
        psub = subs(psub, fm2, jet(2, iff))
        psub = subs(psub, fm1, jet(1, iff))
        psub = subs(psub, fm0, jet(0, iff))
        psub = subs(psub, v, Rr)
        do k = 0, 4
            do o = 0, 2
                res = diff(diff(cart - nn(3)*psub, jet(k, ig)), jet(o, iff))
                call check_zero(res, 'C^q[f] = s P: g_'//achar(48 + k)//' f_'//achar(48 + o))
            end do
        end do
    end subroutine check_cq_source

    ! (v x b).grad_v = v_y d_x - v_x d_y for b = e_z.
    subroutine check_lorentz_l1()
        type(expr_t) :: om, f, lor, rot
        om = sym('Omega')
        f = jet(0, icx)*nn(1) + jet(0, icy)*nn(2) + jet(0, icz)*nn(3)
        lor = -om*(CC(2)*chain(f, 1) - CC(1)*chain(f, 2))
        rot = om*(jet(0, icy)*nn(1) - jet(0, icx)*nn(2))
        call check_zero(lor - rot, 'Lorentz on l=1: d_t (c_x, c_y, c_z) = Omega (c_y, -c_x, 0)')
        call check_zero(-om*(CC(2)*chain(jet(0, iff), 1) - CC(1)*chain(jet(0, iff), 2)), &
            'Lorentz annihilates an isotropic f')
    end subroutine check_lorentz_l1

    ! rho = b x v / Omega with a symbolic b, then b = e_z.
    subroutine check_larmor()
        type(expr_t) :: om, gx, gy, gz, bx, by, bz, rho(3), lhs, rhs
        om = sym('Omega')
        gx = sym('G_x'); gy = sym('G_y'); gz = sym('G_z')
        bx = zero; by = zero; bz = rat(1_8, 1_8)
        rho(1) = (by*CC(3) - bz*CC(2))/om
        rho(2) = (bz*CC(1) - bx*CC(3))/om
        rho(3) = (bx*CC(2) - by*CC(1))/om
        lhs = (gx*rho(1) + gy*rho(2) + gz*rho(3))*jet(0, iff)
        rhs = (gy*nn(1) - gx*nn(2))*Rr*jet(0, iff)/om
        call check_zero(lhs - rhs, 'G.rho f_M = (G_y n_x - G_x n_y) v f_M / Omega')
    end subroutine check_larmor

    subroutine check_zero(e, label)
        type(expr_t), intent(in) :: e
        character(len=*), intent(in) :: label
        type(expr_t) :: r
        type(engine_result_t) :: zt
        integer :: i
        r = e
        do i = 1, 3
            r = subs(r, CC(i), chart(i))
        end do
        zt = engine%zero_test(r)
        if (zt%verdict == VERDICT_TRUE) then
            call check_identity(suite, engine, label, r)
        else
            call check_identity(suite, symengine, label, r)
        end if
    end subroutine check_zero

end program gen_thermal_screening
