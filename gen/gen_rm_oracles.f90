program gen_rm_oracles
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use fortsym_expr, only: expr_t, sym, sqrt, log, operator(+), &
        operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: k2, kb, b2, cross2, rho, mu, cs2, alf, total, disc, fast
    type(expr_t) :: delta, diffusivity, fp, jp, coefficient, rate, width
    type(expr_t) :: r, a, q0, nu, m, n, t, rotation, current, f, fpp
    type(expr_t) :: p, u, psi, dpsi, pole, x, flux, slope, p0, u0
    type(expr_t) :: small, dsmall, large, dlarge, c, d
    type(expr_t) :: kz, bt, bz, kt2, ktlog, numerator
    type(expr_t) :: curvature, alpha, asymmetry, rs
    integer :: j
    k2 = sym('k2'); kb = sym('kb'); b2 = sym('b2')
    rho = sym('rho'); mu = sym('mu'); cs2 = sym('cs2')
    cross2 = sym('cross2')
    delta = sym('delta'); diffusivity = sym('diffusivity')
    fp = sym('fp'); coefficient = sym('coefficient')
    jp = sym('jp')
    r = sym('r'); a = sym('a'); q0 = sym('q0')
    nu = sym('nu'); m = sym('m'); n = sym('n')
    p = sym('p'); u = sym('u')
    psi = sym('psi'); dpsi = sym('dpsi')
    pole = sym('pole'); x = sym('x')
    p0 = sym('p0'); u0 = sym('u0')
    kz = sym('kz'); bt = sym('bt'); bz = sym('bz')
    f = sym('f'); fpp = sym('fpp')
    width = sym('width'); curvature = sym('curvature')
    alpha = sym('alpha'); asymmetry = sym('asymmetry')
    rs = sym('rs')
    call w%open('gen_rm_oracles', &
        'src/generated/milca_rm_oracle_leaves.f90')
    call w%line('! Generated by gen/gen_rm_oracles.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_rm_oracle_leaves')
    call w%line('implicit none')
    call w%line('contains')
    alf = kb**2/(mu*rho)
    total = k2*(b2/(mu*rho) + cs2)
    disc = (k2*(b2/(mu*rho) - cs2))**2 &
        + 4*cs2*cross2*k2/(mu*rho)
    fast = (total + sqrt(disc))/2
    call w%emit('rm_wave_roots', ['k2    ', 'kb    ', 'b2    ', 'cross2', &
        'rho   ', 'mu    ', 'cs2   '], &
        ['alfven2', 'fast2  ', 'slow2  '], [alf, fast, cs2*k2*alf/fast])
    rate = (delta/coefficient)**(4.0_dp/5)*diffusivity**(3.0_dp/5) &
        *(fp**2/(mu*rho))**(1.0_dp/5)
    call w%emit('rm_fkr', ['delta      ', 'coefficient', 'diffusivity', &
        'fp         ', 'mu         ', 'rho        '], ['growth'], [rate])
    call w%emit('rm_internal_kink', ['diffusivity', 'fp         ', &
        'mu         ', 'rho        '], ['growth'], &
        [(diffusivity*fp**2/(mu*rho))**(1.0_dp/3)])
    call w%emit('rm_rutherford', ['diffusivity', 'delta      '], &
        ['speed'], [1.22_dp*diffusivity*delta])
    call w%emit('rm_symmetric_saturation', ['delta    ', 'curvature'], &
        ['width'], [0 - delta/(0.41_dp*curvature)])
    call w%emit('rm_cylinder_saturation', ['width    ', 'delta    ', &
        'a        ', 'alpha    ', 'curvature', 'asymmetry', &
        'rs       '], ['effective_delta'], &
        [delta + width/1.22_dp*(alpha/2*(alpha*log(width/a) + asymmetry/2) &
        - 2.21_dp*alpha**2 + 0.40_dp*alpha/rs + curvature/2)])
    t = (r/a)**2
    current = 2/q0*(1 - t)**nu
    do j = 1, 2
        if (j == 1) then
            rotation = (1 - (1 - t)**(nu + 1))/((nu + 1)*q0*t)
        else
            ! The axis expansion avoids subtracting almost equal powers.
            rotation = (1 - nu*t/2 + nu*(nu - 1)*t**2/6 &
                - nu*(nu - 1)*(nu - 2)*t**3/24)/q0
        end if
        call w%emit('rm_wesson'//merge('_series', '_radial', j == 2), &
            ['r ', 'a ', 'q0', 'nu', 'm ', 'n '], &
            ['f    ', 'fp   ', 'fpp  ', 'jp   ', 'jstar'], &
            [m*rotation - n, m*diff(rotation, r), &
            m*diff(diff(rotation, r), r), diff(current, r), &
            current - 2*n/m])
    end do
    call w%emit('rm_wesson_curvature', ['r ', 'a ', 'q0', 'nu'], &
        ['jpp'], [diff(diff(current, r), r)])
    call w%emit('rm_outer_rhs', ['p   ', 'u   ', 'psi ', 'dpsi'], &
        ['second'], [u*psi - p*dpsi])
    call w%emit('rm_reduced_coefficients', ['r ', 'm ', 'f ', 'jp'], &
        ['p', 'u'], [1/r, m**2/r**2 + m*jp/(r*f)])
    c = pole*(pole - p0)/2
    d = (u0 - p0*pole - 3*c)/2
    large = 1 + pole*x*log(sqrt(x*x)/a) + c*x**2*log(sqrt(x*x)/a) + d*x**2
    small = x + (pole - p0)*x**2/2
    dlarge = diff(large, x); dsmall = diff(small, x)
    flux = (psi*dsmall - dpsi*small)/(large*dsmall - dlarge*small)
    slope = (large*dpsi - dlarge*psi)/(psi*dsmall - dpsi*small)
    call w%emit('rm_frobenius_fit', ['psi ', 'dpsi', 'x   ', 'a   ', 'pole', &
        'p0  ', 'u0  '], &
        ['flux ', 'slope'], [flux, slope])
    kt2 = m**2/r**2 + kz**2
    ktlog = diff(kt2, r)/kt2
    numerator = fpp - (ktlog - 1/r)*fp &
        + 2*kz**2/(r**2*kt2)*(kz*bz - m*bt/r)
    call w%emit('rm_newcomb_coefficients', ['r  ', 'm  ', 'kz ', 'bt ', &
        'bz ', 'fp ', 'fpp'], ['p      ', 'regular', 'residue'], &
        [0 - 1/r - ktlog, kt2 - 2/r**2 - ktlog/r, numerator])
    call w%line('end module milca_rm_oracle_leaves')
    call w%close()
end program gen_rm_oracles
