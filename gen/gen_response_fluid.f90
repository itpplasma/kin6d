program gen_response_fluid
    !! Non-rotating, single-fluid R2-R4 in Cartesian physical components.
    !! The discretisation supplies jets; no rational denominator occurs here.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
                            operator(*)
    use fortsym_products, only: jvp, vjp
    use fortsym_eval, only: collect_free_symbols
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_string, only: str_t, str, chars
    implicit none
    type(arena_t), target :: arena
    type(expr_t) :: p, adiabatic, rho, eta, gp(3), hp(3, 3)
    type(expr_t) :: xi(3), dx(3, 3), gd(3), divxi, pressure(4)
    type(expr_t) :: b0(3), j0(3), acc(3), electric(3), velocity(3)
    type(expr_t) :: current(3), magnetic(3), force(6)
    type(expr_t) :: jb(3), j0b(3), vb(3)
    type(expr_t) :: p1, inv_mu, normal(3), stress(4), bn, b0n, total
    type(expr_t) :: inner, outer, xin, grad_jump
    type(expr_t), allocatable :: vars(:)
    character(12), allocatable :: names(:)
    character(12) :: label
    integer :: a, k, unit, status

    call arena%init()
    open (newunit=unit, file='src/generated/kin6d_response_fluid_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_response_fluid.f90; do not edit.'
    write (unit, '(a)') 'module kin6d_response_fluid_leaves'
    write (unit, '(a)') '    implicit none'
    write (unit, '(a)') 'contains'
    allocate (vars(0), names(0))
    p = variable('p'); adiabatic = variable('adiabatic')
    do a = 1, 3
        write (label, '(a,i1)') 'gp', a
        gp(a) = variable(label)
        write (label, '(a,i1)') 'xi', a
        xi(a) = variable(label)
        write (label, '(a,i1)') 'gd', a
        gd(a) = variable(label)
        do k = 1, 3
            write (label, '(a,2i1)') 'hp', a, k
            hp(a, k) = variable(label)
            write (label, '(a,2i1)') 'dx', a, k
            dx(a, k) = variable(label)
        end do
    end do
    divxi = dx(1, 1) + dx(2, 2) + dx(3, 3)
    pressure(1) = -adiabatic*p*divxi
    do a = 1, 3
        pressure(1) = pressure(1) - xi(a)*gp(a)
    end do
    do k = 1, 3
        pressure(k + 1) = -adiabatic*(gp(k)*divxi + p*gd(k))
        do a = 1, 3
            pressure(k + 1) = pressure(k + 1) &
                              - dx(a, k)*gp(a) - xi(a)*hp(a, k)
        end do
    end do
    call emit('fluid_pressure', [character(12) :: 'p1', 'g1', 'g2', 'g3'], &
              pressure)
    vars = vars(1:0); names = names(1:0)
    rho = variable('rho'); eta = variable('eta')
    do a = 1, 3
        write (label, '(a,i1)') 'b0', a
        b0(a) = variable(label)
        write (label, '(a,i1)') 'j0', a
        j0(a) = variable(label)
        write (label, '(a,i1)') 'acc', a
        acc(a) = variable(label)
        write (label, '(a,i1)') 'electric', a
        electric(a) = variable(label)
        write (label, '(a,i1)') 'velocity', a
        velocity(a) = variable(label)
        write (label, '(a,i1)') 'current', a
        current(a) = variable(label)
        write (label, '(a,i1)') 'magnetic', a
        magnetic(a) = variable(label)
        write (label, '(a,i1)') 'gp', a
        gp(a) = variable(label)
    end do
    jb = cross(current, b0)
    j0b = cross(j0, magnetic)
    vb = cross(velocity, b0)
    do a = 1, 3
        force(a) = rho*acc(a) - jb(a) - j0b(a) + gp(a)
        force(a + 3) = electric(a) + vb(a) - eta*current(a)
    end do
    call emit('fluid_force', [character(12) :: 'm1', 'm2', 'm3', &
                              'o1', 'o2', 'o3'], force)
    vars = vars(1:0); names = names(1:0)
    p1 = variable('p1'); inv_mu = variable('inv_mu')
    do a = 1, 3
        write (label, '(a,i1)') 'b0', a
        b0(a) = variable(label)
        write (label, '(a,i1)') 'normal', a
        normal(a) = variable(label)
        write (label, '(a,i1)') 'magnetic', a
        magnetic(a) = variable(label)
    end do
    total = p1; bn = magnetic(1)*normal(1); b0n = b0(1)*normal(1)
    do a = 1, 3
        total = total + inv_mu*b0(a)*magnetic(a)
        if (a == 1) cycle
        bn = bn + magnetic(a)*normal(a)
        b0n = b0n + b0(a)*normal(a)
    end do
    do a = 1, 3
        stress(a) = inv_mu*(b0(a)*bn + magnetic(a)*b0n) - total*normal(a)
    end do
    stress(4) = total
    call emit('fluid_stress', &
        [character(12) :: 'traction1', 'traction2', 'traction3', 'total'], stress)
    vars = vars(1:0); names = names(1:0)
    inner = variable('inner'); outer = variable('outer')
    xin = variable('xin'); grad_jump = variable('grad_jump')
    call emit('fluid_cut_balance', [character(12) :: 'balance'], &
        [inner - outer + xin*grad_jump])
    write (unit, '(a)') 'end module kin6d_response_fluid_leaves'
    close (unit)
    call execute_command_line('fprettify --disable-indent -i 4 -l 88 '// &
                       'src/generated/kin6d_response_fluid_leaves.f90', exitstat=status)
    if (status /= 0) error stop 'format generated response leaves'
contains
    function variable(name) result(e)
        character(*), intent(in) :: name
        type(expr_t) :: e
        e = sym(arena, trim(name))
        vars = [vars, e]
        names = [names, trim(name)]
    end function variable

    function cross(x, y) result(z)
        type(expr_t), intent(in) :: x(3), y(3)
        type(expr_t) :: z(3)
        z = [x(2)*y(3) - x(3)*y(2), x(3)*y(1) - x(1)*y(3), &
             x(1)*y(2) - x(2)*y(1)]
    end function cross

    subroutine emit(name, outputs, roots)
        character(*), intent(in) :: name, outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_spec_t) :: spec
        type(expr_t), allocatable :: directions(:), seeds(:), derivatives(:)
        integer :: i
        spec%name = str(name)
        spec%generator = str('gen_response_fluid')
        spec%regenerate_command = str('gen_response_fluid from the repository root')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        allocate (spec%args(size(names)), spec%outputs(size(outputs)))
        do i = 1, size(names)
            spec%args(i) = str(trim(names(i)))
        end do
        do i = 1, size(outputs)
            spec%outputs(i) = str(trim(outputs(i)))
        end do
        call write_kernel(roots, spec)
        allocate (directions(size(vars)), seeds(size(roots)))
        do i = 1, size(vars)
            directions(i) = sym(arena, 'd_'//trim(names(i)))
        end do
        derivatives = jvp(roots, vars, directions)
        spec%name = str(name//'_jvp')
        do i = 1, size(names)
            spec%args = [spec%args, str('d_'//trim(names(i)))]
        end do
        call write_kernel(derivatives, spec)
        deallocate (spec%args, spec%outputs)
        allocate (spec%args(size(names)), spec%outputs(size(names)))
        do i = 1, size(names)
            spec%args(i) = str(trim(names(i)))
            spec%outputs(i) = str('v_'//trim(names(i)))
        end do
        do i = 1, size(outputs)
            seeds(i) = sym(arena, 's_'//trim(outputs(i)))
            spec%args = [spec%args, str('s_'//trim(outputs(i)))]
        end do
        derivatives = vjp(roots, vars, seeds)
        spec%name = str(name//'_vjp')
        call write_kernel(derivatives, spec)
    end subroutine emit

    subroutine write_kernel(roots, spec)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_spec_t), intent(in) :: spec
        type(kernel_spec_t) :: lean
        type(str_t), allocatable :: free(:)
        logical :: keep(size(spec%args))
        integer :: i, j, k
        ! Derivatives of linear terms do not need the primal term as input.
        keep = .false.
        do i = 1, size(roots)
            call collect_free_symbols(roots(i), free)
            do j = 1, size(free)
                do k = 1, size(keep)
                    if (chars(free(j)) == chars(spec%args(k))) keep(k) = .true.
                end do
            end do
        end do
        lean = spec
        lean%args = pack(spec%args, keep)
        call write_source(chars(emit_kernel(roots, lean)))
    end subroutine write_kernel

    subroutine write_source(source)
        character(*), intent(in) :: source
        character(:), allocatable :: line
        integer :: first, next, cut, k, statement_indent
        logical :: continuing
        ! FortSym emits at 100 columns. Wrap at token boundaries before the
        ! project formatter; changing layout never changes the expressions.
        first = 1
        continuing = .false.
        statement_indent = 0
        do while (first <= len(source))
            next = index(source(first:), new_line('a'))
            if (next == 0) next = len(source) - first + 2
            line = source(first:first + next - 2)
            if (continuing) then
                line = repeat(' ', statement_indent + 4)//trim(adjustl(line))
            else
                statement_indent = len(line) - len_trim(adjustl(line))
            end if
            continuing = .false.
            if (len_trim(line) > 0) continuing = line(len_trim(line):) == '&'
            do while (len_trim(line) > 80)
                if (index(adjustl(line), '!') == 1) exit
                cut = 0
                do k = 1, 78
                    if (line(k:k) == ',' .or. line(k:k) == ' ') cut = k
                end do
                if (cut <= 8) error stop 'cannot wrap generated Fortran token'
                write (unit, '(a)') '    '//trim(line(:cut))//' &'
                line = repeat(' ', statement_indent + 4)// &
                       trim(adjustl(line(cut + 1:)))
            end do
            if (len_trim(line) == 0) then
                write (unit, '(a)') ''
            else
                write (unit, '(a)') '    '//line
            end if
            first = first + next
        end do
    end subroutine write_source
end program gen_response_fluid
