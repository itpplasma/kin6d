program gen_streaming
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, func, abs, sin, cos, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
        emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = '549aed77be10297beb80d602d714d30166fbeb08'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: t, v, k, a0, b0, phase, x, x0, acc, a, b
    type(expr_t) :: vl, vr, al, ar, bl, br, radius, value, measure, weight
    type(expr_t) :: index, count, j, nv, bound, ac, bc, curvature, left, right
    integer :: unit

    call arena%init()
    engine = make_native_engine(arena)
    t = sym(arena, 't'); v = sym(arena, 'v'); k = sym(arena, 'k')
    a0 = sym(arena, 'a0'); b0 = sym(arena, 'b0')
    x = sym(arena, 'x'); x0 = sym(arena, 'x0'); acc = sym(arena, 'acc')
    a = sym(arena, 'a'); b = sym(arena, 'b')
    vl = sym(arena, 'vl'); vr = sym(arena, 'vr')
    al = sym(arena, 'al'); ar = sym(arena, 'ar')
    bl = sym(arena, 'bl'); br = sym(arena, 'br')
    radius = sym(arena, 'radius'); value = sym(arena, 'value')
    measure = sym(arena, 'measure'); weight = sym(arena, 'weight')
    index = sym(arena, 'i'); count = sym(arena, 'nx')
    j = sym(arena, 'j'); nv = sym(arena, 'nv')
    ac = sym(arena, 'ac'); bc = sym(arena, 'bc')
    bound = sym(arena, 'bound'); curvature = sym(arena, 'curvature')
    phase = k*v*t

    open (newunit=unit, file='src/generated/kin6d_streaming_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_streaming.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, '(a)') '! f_t+v*f_x=0, x periodic2pi, v[-1,1], E=0.'
    write (unit, '(a)') '! Initial data: supplied finite Fourier-x/P1-v coefficients.'
    write (unit, '(a)') '! Rotation advances coefficients; characteristic is unwrapped.'
    write (unit, '(a)') '! JVP/VJP: smooth leaves, Euclidean input/output pairings.'
    write (unit, '(a)') '! Display wrap has events at period crossings; no derivative.'
    write (unit, '(a)') '! C2 bound applies to each physical harmonic at fixed x.'
    write (unit, '(a)') 'module kin6d_streaming_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('streaming_rotation', ['t ', 'v ', 'k ', 'a0', 'b0'], ['a', 'b'], &
        [a0*cos(phase) - b0*sin(phase), a0*sin(phase) + b0*cos(phase)], &
        ad=.true., interval=.true.)
    call emit('streaming_characteristic', ['x0', 'v ', 't '], ['x'], &
        [x0 + v*t], ad=.true., interval=.true.)
    call emit('streaming_interpolate', ['v ', 'vl', 'vr', 'al', 'ar'], ['value'], &
        [al + (ar - al)*(v - vl)/(vr - vl)], ad=.true., interval=.true.)
    call emit('streaming_mode_accumulate', ['x  ', 'k  ', 'a  ', 'b  ', 'acc'], &
        ['next'], [acc + a*cos(k*x) + b*sin(k*x)], ad=.true., interval=.true.)
    call emit('streaming_add', ['acc  ', 'value'], ['next'], [acc + value], &
        interval=.true.)
    call emit('streaming_enlarge_interval', ['value ', 'radius'], ['lower', 'upper'], &
        [value - radius, value + radius], rigorous=.true.)
    ! At fixed x, P=a0(v)cos(k(x-vt))+b0(v)sin(k(x-vt)). On each cell
    ! a0,b0 are affine: |P_vv| <= 2|kt|(|a0'|+|b0'|)+(kt)^2 max(|a0|+|b0|).
    ! The same M bounds each rotated coefficient separately, but not their sum.
    left = abs(al) + abs(bl)
    right = abs(ar) + abs(br)
    ! Exact max(A,B)=(A+B+abs(A-B))/2 uses the supported rigorous abs hook.
    curvature = 2*abs(k*t)*(abs((ar - al)/(vr - vl)) + &
        abs((br - bl)/(vr - vl))) + (k*t)**2* &
        (left + right + abs(left - right))/2
    call emit('streaming_cell_curvature_interval', &
        ['t ', 'k ', 'vl', 'vr', 'al', 'ar', 'bl', 'br'], ['bound'], &
        [curvature], rigorous=.true.)
    call emit('streaming_density_cell', ['vl ', 'vr ', 'al ', 'ar ', 'acc'], &
        ['next'], [acc + (vr - vl)*(al + ar)/4], ad=.true., interval=.true.)
    call emit('streaming_density_radius_interval', ['vl    ', 'vr    ', &
        'radius', 'acc   '], ['next'], [acc + (vr - vl)*radius/2], rigorous=.true.)
    call emit('streaming_x_curvature_interval', ['k  ', 'a  ', 'b  ', 'acc'], &
        ['next'], [acc + k**2*(abs(a) + abs(b))], rigorous=.true.)
    call emit('streaming_frame_time', ['j     ', 'frames', 'tmax  '], ['t'], &
        [j*sym(arena, 'tmax')/(sym(arena, 'frames') - 1)])
    call emit('streaming_plot_x', ['j     ', 'points'], ['x'], &
        [2*pi_expr(arena)*j/(sym(arena, 'points') - 1)])
    call emit('streaming_velocity_coordinate', ['j    ', 'cells'], ['v'], &
        [-1 + 2*j/sym(arena, 'cells')])
    call emit('streaming_particle_midpoint', ['i ', 'nx', 'j ', 'nv'], &
        ['x0     ', 'v      ', 'measure'], &
        [pi_expr(arena)*(2*index + 1)/count, &
         -1 + (2*j + 1)/nv, 4*pi_expr(arena)/(count*nv)], interval=.true.)
    call emit('streaming_particle_cell_midpoint', &
        ['i ', 'nx', 'j ', 'nv', 'vl', 'vr'], ['x0     ', 'v      ', 'measure'], &
        [pi_expr(arena)*(2*index + 1)/count, &
         vl + (vr - vl)*(2*j + 1)/(2*nv), &
         2*pi_expr(arena)*(vr - vl)/(count*nv)], interval=.true.)
    call emit('streaming_particle_cell_error_interval', &
        ['vl   ', 'vr   ', 'nv   ', 'bound'], ['error'], &
        [(vr - vl)**3*bound/(48*nv**2)], rigorous=.true.)
    call emit('streaming_particle_coefficient_band_interval', &
        ['center', 'error '], ['lower', 'upper'], &
        [sym(arena, 'center') - sym(arena, 'error'), &
         sym(arena, 'center') + sym(arena, 'error')], rigorous=.true.)
    call emit('streaming_particle_weight', ['measure', 'value  '], ['weight'], &
        [measure*value], ad=.true., interval=.true.)
    call emit('streaming_particle_glyph_size', ['weight ', 'measure'], ['size'], &
        [12*weight/measure])
    call emit('streaming_particle_mode', ['x     ', 'k     ', 'weight', 'ac    ', &
        'bc    '], ['an', 'bn'], [ac + weight*cos(k*x)/(2*pi_expr(arena)), &
        bc + weight*sin(k*x)/(2*pi_expr(arena))], ad=.true., interval=.true.)
    call emit('streaming_particle_mean', ['weight', 'acc   '], ['next'], &
        [acc + weight/(4*pi_expr(arena))], interval=.true.)
    call emit('streaming_display_shift', ['x    ', 'turns'], ['wrapped'], &
        [x - 2*pi_expr(arena)*sym(arena, 'turns')])
    write (unit, '(a)') 'end module kin6d_streaming_leaves'
    close (unit)

contains
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_streaming; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_streaming')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_streaming from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_streaming
