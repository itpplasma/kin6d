program gen_map_3d_readback
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
                            operator(*), operator(/), sin, cos
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: proof
    type(expr_t) :: identity, phi, z, br, bz, bp
    type(expr_t) :: q(3, 3), g(2, 2), cg(2), b3, r, sigma, detq, detg, jac
    type(expr_t) :: pulled(3), field(3), gradient(3), cofactor(3, 3), master(3)
    character(8) :: names(18)
    integer :: a, k, l, i, j, indices(2), columns(2)
    call arena%init()
    engine = make_native_engine(arena)
    call w%open(arena, 'gen_map_3d_readback', &
                'src/generated/kin6d_map_3d_readback_leaves.f90')
    call w%line('! Generated by gen/gen_map_3d_readback.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_map_3d_readback_leaves')
    call w%line('use, intrinsic :: iso_fortran_env, only: dp => real64')
    call w%line('implicit none')
    call w%line('contains')
    do k = 1, 3
        do a = 1, 3
            l = a + 3*(k - 1)
            write (names(l), '(a,2i1)') 'q', a, k
            q(a, k) = sym(arena, trim(names(l)))
        end do
    end do
    do k = 1, 2
        do a = 1, 2
            l = 9 + a + 2*(k - 1)
            write (names(l), '(a,2i1)') 'g', a, k
            g(a, k) = sym(arena, trim(names(l)))
        end do
    end do
    names(14:) = [character(8)::'chi1', 'chi2', 'b3', 'r', 'sigma']
    cg(1) = sym(arena, 'chi1'); cg(2) = sym(arena, 'chi2')
    b3 = sym(arena, 'b3'); r = sym(arena, 'r'); sigma = sym(arena, 'sigma')
    detg = g(1, 1)*g(2, 2) - g(1, 2)*g(2, 1)
    do k = 1, 3
        do a = 1, 3
            indices = pack([1, 2, 3], [1, 2, 3] /= a)
            columns = pack([1, 2, 3], [1, 2, 3] /= k)
            i = indices(1); j = indices(2)
            cofactor(a, k) = (-1)**(a + k)*(q(i, columns(1))*q(j, columns(2)) &
                                            - q(i, columns(2))*q(j, columns(1)))
        end do
    end do
    detq = q(1, 1)*cofactor(1, 1) + q(2, 1)*cofactor(2, 1) + q(3, 1)*cofactor(3, 1)
    do k=1,3
        do a=1,3
            identity=0*r
            do i=1,3
                identity=identity+q(a,i)*cofactor(k,i)
            end do
            if(a==k) identity=identity-detq
            proof=engine%zero_test(identity)
            if (proof%verdict /= VERDICT_TRUE) &
                error stop 'coordinate inverse identity unproved'
        end do
    end do
    call w%emit('map_3d_determinant' , names(:9), ['det'], [detq], ad=.true.)
    jac = -sigma*r*detq
    master = [g(1, 1)*cg(1) + g(2, 1)*cg(2), &
              g(1, 2)*cg(1) + g(2, 2)*cg(2), 0*r]
    pulled = [-master(2), master(1), b3*detg]
    do a = 1, 3
        field(a) = (q(a, 1)*pulled(1) + q(a, 2)*pulled(2) + q(a, 3)*pulled(3))/jac
        gradient(a) = (cofactor(a, 1)*master(1) + cofactor(a, 2)*master(2) &
                       + cofactor(a, 3)*master(3))/detq
    end do
    field(3) = r*field(3)
    call w%emit('map_3d_field', names, &
               [character(8)::'br', 'bz', 'bphi', 'chi_r', 'chi_z', 'chi_phi', 'jac'], &
                [field, gradient, jac], ad=.true.)
    phi=sym(arena,'phi'); z=sym(arena,'z')
    br=sym(arena,'br'); bz=sym(arena,'bz'); bp=sym(arena,'bp')
    call w%emit('map_3d_cartesian',[character(8)::'r','z','phi','br','bz','bp'], &
        [character(8)::'x','y','height','bx','by','bheight'], &
        [r*cos(phi),r*sin(phi),z,br*cos(phi)-bp*sin(phi), &
         br*sin(phi)+bp*cos(phi),bz],ad=.true.)
    ! Root solves use the same coordinate Jacobian, independent of physics.
    cg(1) = sym(arena, 'res1'); cg(2) = sym(arena, 'res2'); b3 = sym(arena, 'res3')
    do a = 1, 3
       field(a) = (cofactor(1, a)*cg(1) + cofactor(2, a)*cg(2) + cofactor(3, a)*b3)/detq
    end do
 call w%emit('map_3d_inverse_step', [character(8)::names(:9), 'res1', 'res2', 'res3'], &
                [character(8)::'dxi', 'deta', 'dphi'], field, ad=.true.)
    call w%line('end module kin6d_map_3d_readback_leaves')
    call w%close()
    print '(a)', '[V] FortSym coordinate inverse identities proved (9/9)'
end program
