program gen_fermion_ensemble
    ! Finite-N ideal fermion ensembles (campaign case Q3). Periodic box of side
    ! L: orbitals k=2*pi*n/L, energy unit eu=(hbar**2/(2*m))*(2*pi/L)**2,
    ! levels |n|**2. Harmonic trap: levels k*hbar*omega (zero point omitted),
    ! degeneracy (k+1)*(k+2)/2. b=eu/(kB*T) is the dimensionless inverse
    ! temperature; weights carry a declared exact energy shift c.
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, pi_expr, exp, log, sqrt, sin, cos, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use fortsym_diff, only: diff
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(expr_t) :: b, level, shift, y, particles, ef, theta, energy, variance
    type(expr_t) :: e, p, dedtheta, x, a, cutoff, delta, gauss(0:6), mills
    type(expr_t) :: tails(0:2), k1, first, ratio(0:2), q, rho, u, occupation, s
    type(expr_t) :: ya, yb, na, nb, sinc_series, cold, cold_series, three, deficit
    integer :: unit, j

    call arena%init()
    engine = make_native_engine(arena)
    b = sym(arena, 'b'); level = sym(arena, 'level'); shift = sym(arena, 'shift')
    particles = sym(arena, 'particles'); ef = sym(arena, 'ef')
    theta = sym(arena, 'theta'); energy = sym(arena, 'energy')
    variance = sym(arena, 'variance'); x = sym(arena, 'x')
    cutoff = sym(arena, 'cutoff'); q = sym(arena, 'q'); u = sym(arena, 'u')
    occupation = sym(arena, 'occupation'); s = sym(arena, 's'); rho = sym(arena, 'rho')
    ya = sym(arena, 'ya'); yb = sym(arena, 'yb'); na = sym(arena, 'na')
    nb = sym(arena, 'nb')
    three = rat(arena, 3_int64, 1_int64)

    ! Shifted Boltzmann weight and its exact b-jet: dy/db=-(level-shift)*y.
    y = exp(-b*(level - shift))
    call prove(diff(y, b) + (level - shift)*y, 'weight jet')
    call prove(diff(diff(y, b), b) - (level - shift)**2*y, 'weight second jet')

    open (newunit=unit, file='src/generated/kin6d_fermion_ensemble_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_fermion_ensemble.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, '(a)') '! Finite-N ideal spin-1/2 fermions: periodic box / harmonic trap.'
    write (unit, '(a)') '! Box levels |n|^2 in eu=(hbar^2/2m)(2pi/L)^2; b=eu/(kB T).'
    write (unit, '(a)') '! Normalization: EF=(3N/(8pi))^(2/3) eu for N electrons, two spins.'
    write (unit, '(a)') 'module kin6d_fermion_ensemble_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('fermion_weight_jet', ['b    ', 'level', 'shift'], ['y  ', 'dy ', 'd2y'], &
              [y, diff(y, b), diff(diff(y, b), b)], ad=.true., interval=.true.)
    ! Thermodynamic-limit Fermi energy of the same total density, and theta.
    call emit('fermion_box_fermi_energy', ['particles'], ['ef'], &
              [exp(2*log(3*particles/(8*pi_expr(arena)))/3)], ad=.true., &
              interval=.true.)
    call emit('fermion_inverse_temperature', ['theta', 'ef   '], ['b'], &
              [1/(theta*ef)], ad=.true., interval=.true.)
    ! Box EOS per particle in EF units from total E (eu) and Var(E)=d2lnZ/db2.
    ! P=2E/(3V) exactly for levels scaling as L**-2; e=E/(N*EF); de/dtheta=
    ! b**2*Var/N (heat capacity C/(N*kB)); bulk modulus B/(n*EF)=n*dP/dn|T/(n*EF)
    ! =5p/3-(2/3)*theta*dp/dtheta.
    e = energy/(particles*ef)
    dedtheta = b**2*variance/particles
    p = 2*e/3
    call emit('fermion_box_eos', [character(9) :: 'energy', 'variance', 'b', &
              'particles', 'ef'], [character(14) :: 'energy_ratio', 'pressure_ratio', 'dedtheta', &
              'dpdtheta', 'bulk_modulus'], [e, p, dedtheta, 2*dedtheta/3, &
              5*p/3 - 2*(1/(b*ef))*(2*dedtheta/3)/3], ad=.true., interval=.true.)
    ! Box remainder for omitted orbitals |n|**2>=cutoff+1. Unit cubes around
    ! lattice points give sum_{|n|>=R0} h(|n|) <= 4*pi*int_a^oo (t+d)**2 h(t)dt,
    ! d=sqrt(3)/2, a=R0-sqrt(3), h(t)=t**(2k)*exp(-b*(t*t-c)) decreasing for
    ! b*a*a>=k. Gm=int_a^oo t^m exp(-b t^2): G1 exact, G0 Mills bound,
    ! Gm=a**(m-1)*exp(-b*a*a)/(2b)+(m-1)/(2b)*G(m-2). The caller proves
    ! a>0 and b*a*a>=2 through fermion_box_tail_margin.
    a = sqrt(cutoff + 1) - sqrt(three)
    delta = sqrt(three)/2
    mills = exp(-b*a**2)
    gauss(0) = mills/(2*b*a)
    gauss(1) = mills/(2*b)
    do j = 2, 6
        gauss(j) = a**(j - 1)*mills/(2*b) + (j - 1)*gauss(j - 2)/(2*b)
    end do
    do j = 0, 2
        tails(j) = 4*pi_expr(arena)*exp(b*shift)*(gauss(2*j + 2) + &
                   2*delta*gauss(2*j + 1) + delta**2*gauss(2*j))
    end do
    ! |eps-c|**m<=(eps+d)**m with deficit d=max(0,-c) and eps>=c.
    deficit = sym(arena, 'deficit')
    call emit('fermion_box_tail', ['b      ', 'shift  ', 'cutoff ', 'deficit'], &
              ['tau0', 'tau1', 'tau2'], [tails(0), tails(1) + deficit*tails(0), &
              tails(2) + 2*deficit*tails(1) + deficit**2*tails(0)], rigorous=.true.)
    call emit('fermion_box_tail_margin', ['b     ', 'cutoff'], ['a     ', 'margin'], &
              [a, b*a**2 - 2], interval=.true.)
    ! Trap remainder for levels k>=K+1: consecutive term ratios are bounded by
    ! rho_j=(K+4)/(K+2)*((K+2)/(K+1))**j*exp(-b); geometric sum if rho_j<1.
    k1 = cutoff + 1
    first = (k1 + 1)*(k1 + 2)/2*exp(-b*(k1 - shift))
    do j = 0, 2
        ratio(j) = (k1 + 3)/(k1 + 1)*((k1 + 1)/k1)**j*exp(-b)
        tails(j) = first*k1**j/(1 - ratio(j))
    end do
    call emit('fermion_trap_tail', ['b      ', 'shift  ', 'cutoff ', 'deficit'], &
              ['tau0 ', 'tau1 ', 'tau2 ', 'ratio'], &
              [tails(0), tails(1) + deficit*tails(0), &
              tails(2) + 2*deficit*tails(1) + deficit**2*tails(0), ratio(2)], &
              rigorous=.true.)
    ! Grand-canonical shell terms at exponent z=b*(mu-eps): occupation and
    ! log(1+exp(z)), in two overflow-safe charts (z>=0 and z<0).
    call emit('fermion_grand_positive', ['x'], ['occupation', 'log_factor'], &
              [1/(1 + exp(-x)), x + log(1 + exp(-x))])
    call emit('fermion_grand_negative', ['x'], ['occupation', 'log_factor'], &
              [exp(x)/(1 + exp(x)), log(1 + exp(x))])
    ! Fermion pair occupation in the canonical ensemble for distinct weights:
    ! <n_a n_b>=(ya*nb-yb*na)/(ya-yb).
    call emit('fermion_pair_occupation', ['ya', 'yb', 'na', 'nb'], ['pair'], &
              [(ya*nb - yb*na)/(ya - yb)])
    ! Sphere average of exp(i*k.r) is sin(z)/z; series chart for |z|<0.05.
    sinc_series = 1 - x**2/6 + x**4/120 - x**6/5040
    call emit('fermion_sinc', ['x'], ['value'], [sin(x)/x])
    call emit('fermion_sinc_series', ['x'], ['value'], [sinc_series])
    call emit('fermion_lattice_argument', ['q', 'x'], ['z'], &
              [2*pi_expr(arena)*sqrt(q)*x])
    ! Zero-temperature thermodynamic-limit density matrix rho/n=3*j1(x)/x and
    ! exchange hole g=1-rho**2, x=kF*r. Series chart for |x|<0.05.
    cold = 3*(sin(x) - x*cos(x))/x**3
    cold_series = 1 - x**2/10 + x**4/280 - x**6/15120
    call emit('fermion_cold_density_matrix', ['x'], ['rho'], [cold])
    call emit('fermion_cold_density_matrix_series', ['x'], ['rho'], [cold_series])
    call emit('fermion_exchange_hole', ['rho'], ['g'], [1 - rho**2], ad=.true., &
              interval=.true.)
    ! Nondegenerate (Boltzmann) limit of the same-spin hole: 1-exp(-theta*x**2/2).
    call emit('fermion_boltzmann_hole', ['theta', 'x    '], ['g'], &
              [1 - exp(-theta*x**2/2)], ad=.true.)
    ! Thermodynamic-limit density matrix integrand 3*u**2*f(u)*sinc(u*x).
    call emit('fermion_density_matrix_term', ['u         ', 'occupation', &
              's         '], ['term'], [3*u**2*occupation*s])
    ! Classical ideal gas at the same density and temperature, EF units:
    ! e=3*theta/2, p=theta, Maxwell-Boltzmann occupation per spin orbital.
    call emit('fermion_classical_limits', ['theta', 'u    '], &
              ['energy    ', 'pressure  ', 'occupation'], [3*theta/2, theta, &
              4/(3*sqrt(pi_expr(arena)))*theta**(-rat(arena, 3_int64, 2_int64))* &
              exp(-u**2/theta)], ad=.true.)
    write (unit, '(a)') 'end module kin6d_fermion_ensemble_leaves'
    close (unit)

contains

    subroutine prove(expression, label)
        type(expr_t), intent(in) :: expression
        character(*), intent(in) :: label
        identity = engine%zero_test(expression)
        if (identity%verdict /= VERDICT_TRUE) &
            error stop 'fermion ensemble identity unproved: '//label
    end subroutine prove

    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_fermion_ensemble; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%exp = str('exp')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sqrt = str('sqrt')
                rspec%runtime%log = str('log')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_fermion_ensemble')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_fermion_ensemble from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) call emit(name//'_interval', args, outputs, roots, &
                                    rigorous=.true.)
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: vars(:), dirs(:), weights(:), derived(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: targs(:), touts(:), aargs(:), aouts(:)
        integer :: j, n, m

        n = size(args); m = size(outputs)
        allocate (vars(n), dirs(n), weights(m), targs(2*n), touts(m), &
                  aargs(n + m), aouts(n))
        do j = 1, n
            vars(j) = sym(arena, trim(args(j)))
            dirs(j) = sym(arena, 'd'//trim(args(j)))
            targs(j) = args(j); targs(n + j) = 'd'//trim(args(j))
            aargs(j) = args(j); aouts(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            touts(j) = 'd'//trim(outputs(j)); aargs(n + j) = 'b'//trim(outputs(j))
        end do
        derived = jvp(roots, vars, dirs)
        do j = 1, size(derived)
            simplified = engine%simplify(derived(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derived(j) = simplified%value
        end do
        call emit(name//'_jvp', targs, touts, derived)
        derived = vjp(roots, vars, weights)
        do j = 1, size(derived)
            simplified = engine%simplify(derived(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derived(j) = simplified%value
        end do
        call emit(name//'_vjp', aargs, aouts, derived)
    end subroutine emit_derivatives
end program gen_fermion_ensemble
