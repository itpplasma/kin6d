program gen_current_sheet
    ! Linear ideal current-sheet references (docs/current-sheet-equilibrium.md
    ! section 5.1): sheared slab, frozen rotational-transform jump at x = 0.
    ! Per side sigma = +-1 with t = sigma*x in [0, a]: psi = F*xi solves
    ! psi'' = k^2 psi, psi(0) = F(0 sigma) xi0, psi(a) = F(sigma a) delta_sigma.
    ! xi0 solves the Lagrangian total-pressure condition [[F^2 xi']] = 0.
    ! Nonlinear slab map (section 4, stage 2): the frozen-in energy of
    ! kin6d_ideal_map for Y = Phi(X), X = (X1, X2, s3) z invariant, with the
    ! chart Phi = (x + (l0 + l1 x) G(y) + (m0 + m1 x) cos(k y), y), frozen
    ! b = (0, b2, b3) and p. G (interface shape) enters through its value gv
    ! and derivative gd at y = X2; the caller applies the chain rule in X2.
    ! z = (X1, X2, dX1/ds1, dX2/ds1, dX1/ds2, dX2/ds2, gv, gd).
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sinh, cosh, sin, cos, operator(+), operator(-), &
        operator(*), operator(/)
    use fortsym_diff, only: diff
    use kin6d_symbolic_ideal, only: frozen_energy
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(expr_t) :: t, k, a, psi0, psia, psi, b0, dp, dm, wp, wm
    type(expr_t) :: fp, fm, fap, fam, fprime, s, c, lhs, rhs
    type(expr_t) :: z(8), b2, b3, p, l0, l1, m0, m1, dphi(2, 2), dy(2, 2)
    type(expr_t) :: d(3, 3), bb(3), energy, jac, zero, grad(8), hess(36)
    type(expr_t) :: mh, kz, rr, phx, phu, r1, r2
    character(8) :: zn(8), gn(8), hn(36), args(16), pargs(17)
    integer :: i, j, m
    call arena%init()
    t = sym(arena, 't'); k = sym(arena, 'k'); a = sym(arena, 'a')
    psi0 = sym(arena, 'psi0'); psia = sym(arena, 'psia')
    psi = (psi0*sinh(k*(a - t)) + psia*sinh(k*t))/sinh(k*a)
    b0 = sym(arena, 'b0'); dp = sym(arena, 'dp'); dm = sym(arena, 'dm')
    wp = sym(arena, 'wp'); wm = sym(arena, 'wm')
    ! F = k B_y, B_y = b0 (x/a + dp) for x > 0, b0 (x/a - dm) for x < 0.
    fp = k*b0*dp; fm = -(k*b0*dm)
    fap = k*b0*(1 + dp); fam = -(k*b0*(1 + dm))
    fprime = k*b0/a
    s = sinh(k*a); c = cosh(k*a)
    ! F+ (psi+'(0) - F' xi0) = F- (psi-'(0) - F' xi0), written as lhs*xi0 = rhs.
    lhs = -(fp*fp*k*c/s) - fp*fprime - fm*fm*k*c/s + fm*fprime
    rhs = -(fm*k*fam*wm/s) - fp*k*fap*wp/s
    zn = [character(8) :: 'x1', 'x2', 'u11', 'u21', 'u12', 'u22', 'gv', 'gd']
    do i = 1, 8
        z(i) = sym(arena, trim(zn(i)))
        write (gn(i), '(a,i1)') 'g', i
    end do
    b2 = sym(arena, 'b2'); b3 = sym(arena, 'b3'); p = sym(arena, 'p')
    l0 = sym(arena, 'l0'); l1 = sym(arena, 'l1')
    m0 = sym(arena, 'm0'); m1 = sym(arena, 'm1')
    zero = 0*z(1)
    dphi(1, 1) = 1 + l1*z(7) + m1*cos(k*z(2))
    dphi(1, 2) = (l0 + l1*z(1))*z(8) - (m0 + m1*z(1))*k*sin(k*z(2))
    dphi(2, 1) = zero; dphi(2, 2) = 1 + zero
    do i = 1, 2
        do j = 1, 2
            dy(i, j) = dphi(i, 1)*z(2 + j*2 - 1) + dphi(i, 2)*z(2 + j*2)
        end do
    end do
    d = zero
    d(1:2, 1:2) = dy; d(3, 3) = 1 + zero
    bb = [zero, b2, b3]
    energy = frozen_energy(d, bb, p, 1 + zero, 1 + zero, jac)
    do i = 1, 8
        grad(i) = diff(energy, z(i))
    end do
    m = 0
    do j = 1, 8
        do i = 1, j
            m = m + 1
            hess(m) = diff(grad(i), z(j))
            write (hn(m), '(a,i1,i1)') 'h', i, j
        end do
    end do
    args = [character(8) :: zn, 'b2', 'b3', 'p', 'k', 'l0', 'l1', 'm0', 'm1']
    call w%open(arena, 'gen_current_sheet', &
        'src/generated/kin6d_current_sheet_leaves.f90')
    call w%line('! Generated by gen/gen_current_sheet.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Slab current-sheet references, docs/current-sheet-equilibrium.md 5.1.')
    call w%line('module kin6d_current_sheet_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('sheet_slab_side', ['t   ', 'k   ', 'a   ', 'psi0', 'psia'], &
        ['psi    ', 'dpsi_dt'], [psi, diff(psi, t)], ad=.true.)
    call w%emit('sheet_slab_interface', ['k ', 'a ', 'b0', 'dp', 'dm', 'wp', 'wm'], &
        ['lhs', 'rhs'], [lhs, rhs], ad=.true.)
    call w%emit('sheet_map_energy', args, ['w  ', 'jac'], [energy, jac])
    call w%emit('sheet_map_gradient', args, gn, grad)
    call w%emit('sheet_map_hessian', args, hn, hess)
    call w%emit('sheet_map_position', ['x1', 'x2', 'gv', 'k ', 'l0', 'l1', 'm0', 'm1'], &
        ['y1'], [z(1) + (l0 + l1*z(1))*z(7) + (m0 + m1*z(1))*cos(k*z(2))])
    call w%emit('sheet_map_field', args, ['bx', 'by', 'bz'], &
        [(dy(1, 2)*b2)/jac, (dy(2, 2)*b2)/jac, b3/jac])
    ! Helical screw pinch (section 5.2): the same chart in (r, u), u =
    ! m theta + k z, physical point (R cos Theta, R sin Theta, Z), R = Phi1,
    ! Theta = (X2 - k s3)/m, Z = s3; d in the orthonormal (e_R, e_Theta, e_Z)
    ! frame (|d b| and det d are frame invariant).
    mh = sym(arena, 'mh'); kz = sym(arena, 'kz')
    rr = z(1) + (l0 + l1*z(1))*z(7) + (m0 + m1*z(1))*cos(z(2))
    phx = 1 + l1*z(7) + m1*cos(z(2))
    phu = (l0 + l1*z(1))*z(8) - (m0 + m1*z(1))*sin(z(2))
    r1 = phx*z(3) + phu*z(4)
    r2 = phx*z(5) + phu*z(6)
    d = zero
    d(1, 1) = r1; d(1, 2) = r2
    d(2, 1) = rr*z(4)/mh; d(2, 2) = rr*z(6)/mh; d(2, 3) = -(kz*rr/mh)
    d(3, 3) = 1 + zero
    energy = frozen_energy(d, bb, p, 1 + zero, 1 + zero, jac)
    do i = 1, 8
        grad(i) = diff(energy, z(i))
    end do
    m = 0
    do j = 1, 8
        do i = 1, j
            m = m + 1
            hess(m) = diff(grad(i), z(j))
        end do
    end do
    pargs = [character(8) :: zn, 'b2', 'b3', 'p', 'mh', 'kz', 'l0', 'l1', 'm0', 'm1']
    call w%emit('sheet_pinch_energy', pargs, ['w  ', 'jac'], [energy, jac])
    call w%emit('sheet_pinch_gradient', pargs, gn, grad)
    call w%emit('sheet_pinch_hessian', pargs, hn, hess)
    call w%emit('sheet_pinch_position', ['x1', 'x2', 'gv', 'l0', 'l1', 'm0', 'm1'], &
        ['r'], [rr])
    call w%emit('sheet_pinch_field', pargs, ['br', 'bt', 'bz'], &
        [(d(1, 2)*b2)/jac, (d(2, 2)*b2 + d(2, 3)*b3)/jac, b3/jac])
    call w%line('end module kin6d_current_sheet_leaves')
    call w%close()
end program gen_current_sheet
