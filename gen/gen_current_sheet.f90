program gen_current_sheet
    ! Linear ideal current-sheet references (docs/current-sheet-equilibrium.md
    ! section 5.1): sheared slab, frozen rotational-transform jump at x = 0.
    ! Per side sigma = +-1 with t = sigma*x in [0, a]: psi = F*xi solves
    ! psi'' = k^2 psi, psi(0) = F(0 sigma) xi0, psi(a) = F(sigma a) delta_sigma.
    ! xi0 solves the Lagrangian total-pressure condition [[F^2 xi']] = 0.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sinh, cosh, operator(+), operator(-), &
        operator(*), operator(/)
    use fortsym_diff, only: diff
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(expr_t) :: t, k, a, psi0, psia, psi, b0, dp, dm, wp, wm
    type(expr_t) :: fp, fm, fap, fam, fprime, s, c, lhs, rhs
    call arena%init()
    t = sym(arena, 't'); k = sym(arena, 'k'); a = sym(arena, 'a')
    psi0 = sym(arena, 'psi0'); psia = sym(arena, 'psia')
    psi = (psi0*sinh(k*(a - t)) + psia*sinh(k*t))/sinh(k*a)
    b0 = sym(arena, 'b0'); dp = sym(arena, 'dp'); dm = sym(arena, 'dm')
    wp = sym(arena, 'wp'); wm = sym(arena, 'wm')
    ! F = k B_y, B_y = b0 (x/a + dp) for x > 0, b0 (x/a - dm) for x < 0.
    fp = k*b0*dp; fm = -(k*b0*dm)
    fap = k*b0*(1 + dp); fam = -(k*b0*(1 + dm))
    fprime = k*b0/a
    s = sinh(k*a); c = cosh(k*a)
    ! F+ (psi+'(0) - F' xi0) = F- (psi-'(0) - F' xi0), written as lhs*xi0 = rhs.
    lhs = -(fp*fp*k*c/s) - fp*fprime - fm*fm*k*c/s + fm*fprime
    rhs = -(fm*k*fam*wm/s) - fp*k*fap*wp/s
    call w%open(arena, 'gen_current_sheet', &
        'src/generated/kin6d_current_sheet_leaves.f90')
    call w%line('! Generated by gen/gen_current_sheet.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Slab current-sheet references, docs/current-sheet-equilibrium.md 5.1.')
    call w%line('module kin6d_current_sheet_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('sheet_slab_side', ['t   ', 'k   ', 'a   ', 'psi0', 'psia'], &
        ['psi    ', 'dpsi_dt'], [psi, diff(psi, t)], ad=.true.)
    call w%emit('sheet_slab_interface', ['k ', 'a ', 'b0', 'dp', 'dm', 'wp', 'wm'], &
        ['lhs', 'rhs'], [lhs, rhs], ad=.true.)
    call w%line('end module kin6d_current_sheet_leaves')
    call w%close()
end program gen_current_sheet
