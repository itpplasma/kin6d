program gen_nested_oracles
    ! Landreman 2609.26742 and Issan et al. 2610.07304, v1, mu0 = 1.
    ! tau = 0 is Landreman; nonzero tau is Issan. See docs/nested-oracles.md.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, sin, cos, exp, asin, atan, &
               pi_expr, operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_string, only: chars
    use fortsym_print, only: print_expr
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(native_engine_t) :: eng
    type(engine_result_t) :: check
    type(leaf_writer_t) :: w
    type(expr_t) :: x(3), eps, tau, pa, saxis, lam, b(3), db(3, 3), j(3), gp(3)
    type(expr_t) :: psi, p, a, bb, s, f, om2, q, kr, ki, d, u, v, ch, sh, wr, wi
    type(expr_t) :: rho, theta, t, xy(3), jac, h, g, xx, yy, sig, l, nu, rhs
    type(expr_t) :: re, im, root, delta, vol, pavg, bavg, paxes(2)
    type(expr_t) :: dkx(2), dky(2), du(3), dv(3), core(3), corep, corepsi
    character(8), parameter :: names(20) = [character(8) :: 'psi', 'p', &
                                 'bx', 'by', 'bz', 'jx', 'jy', 'jz', 'px', 'py', 'pz', &
                          'bxx', 'byx', 'bzx', 'bxy', 'byy', 'bzy', 'bxz', 'byz', 'bzz']
    integer :: k, m
    call arena%init()
    eng = make_native_engine(arena)
    x = [sym(arena, 'x'), sym(arena, 'y'), sym(arena, 'z')]
    eps = sym(arena, 'eps'); tau = sym(arena, 'tau'); pa = sym(arena, 'pa')
    saxis = sym(arena, 'saxis'); lam = sym(arena, 'lam')
    rho = sym(arena, 'rho'); theta = sym(arena, 'theta'); t = sym(arena, 't')
    delta = sym(arena, 'delta')
    a = sqrt(1 + eps); bb = sqrt(1 - eps); om2 = 1 - tau**2
    s = x(1)**2/(1 + eps) + x(2)**2/(1 - eps)
    f = sqrt(s*(2 - s) - 4*x(3)**2 - 4*tau*s*x(3))
    b = [((2*x(3) + tau*s)*x(1) - (1 + eps)/sqrt(1 - eps**2)*f*x(2))/s, &
      ((2*x(3) + tau*s)*x(2) + (1 - eps)/sqrt(1 - eps**2)*f*x(1))/s, 1 - s - 2*tau*x(3)]
    q = om2*(x(1)**2 + x(2)**2 + 4*x(3)**2)/2 + 2*tau*x(3)
    psi = om2*(q + dot(b, b)/2 - 1 + tau**2/(2*om2) + om2*eps**2/2)/2
    p = pa - 2*psi/om2
    call jets()
    call prove_integer()
    call w%open(arena, 'gen_nested_oracles', &
                'src/generated/kin6d_nested_oracle_leaves.f90')
    call w%line('! Generated by gen/gen_nested_oracles.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! mu0=1. Domain and branch contract: docs/nested-oracles.md.')
    call w%line('module kin6d_nested_oracle_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('nested_integer_field', &
                [character(8) :: 'x', 'y', 'z', 'eps', 'tau', 'pa'], names, &
                [psi, p, b, j, gp, reshape(db, [9])], ad=.true., interval=.true.)
    ! Integer-family material chart. Constant signed (u,v,t) determinant;
    ! polar coordinates contribute rho to the positive volume density.
    u = -om2*eps/2 + rho*cos(theta); v = rho*sin(theta)
    l = sqrt((1 + sqrt(1 - 4*(u*u + v*v)))/2)
    xy = [a/sqrt(om2)*(l*cos(t) + (u*cos(t) + v*sin(t))/l), &
          bb/sqrt(om2)*(l*sin(t) + (v*cos(t) - u*sin(t))/l), &
          -tau/(2*om2) + (v*(sqrt(om2)*cos(2*t) - tau*sin(2*t)) &
                          - u*(sqrt(om2)*sin(2*t) + tau*cos(2*t)))/om2]
    jac = rho*a*bb/(om2*sqrt(om2))
    call w%emit('nested_integer_surface', &
                [character(8) :: 'rho', 'theta', 't', 'eps', 'tau'], &
                [character(8) :: 'x', 'y', 'z', 'jac'], [xy, jac], ad=.true.)
    vol = 2*pi_expr(arena)**2*a*bb*delta/(om2*sqrt(om2))
    pavg = pa - delta/om2; bavg = 1 - om2*eps**2/2 + delta/om2
    call w%emit('nested_integer_averages', &
                [character(8) :: 'eps', 'tau', 'pa', 'delta'], &
                [character(8) :: 'volume', 'pavg', 'b2avg', 'beta', 'iota', 'flux'], &
             [vol, pavg, bavg, 2*pavg/bavg, 2 + 0*eps, pi_expr(arena)*a*bb*delta/om2], &
                ad=.true., interval=.true.)
    ! Sheared family: work first in the differential extension K^2=wbar^2+eps.
    ! K_x=wbar/K, K_y=-i*wbar/K. No branch choice enters these local identities.
    kr = sym(arena, 'kr'); ki = sym(arena, 'ki'); d = kr**2 + ki**2
    dkx = [(x(1)*kr - x(2)*ki)/d, (-x(2)*kr - x(1)*ki)/d]
    dky = [dkx(2), 0 - dkx(1)]
    u = sym(arena, 'phase'); v = sym(arena, 'nu')
    du = [kr + x(1)*dkx(1) - x(2)*dkx(2), &
          -ki + x(1)*dky(1) - x(2)*dky(2), 0*kr]
    dv = [ki + x(1)*dkx(2) + x(2)*dkx(1), &
          kr + x(1)*dky(2) + x(2)*dky(1), 0*ki]
    ch = (exp(v) + exp(0 - v))/2; sh = (exp(v) - exp(0 - v))/2
    wr = (sin(u)*sh*kr + cos(u)*ch*ki)/(2*d)
    wi = (cos(u)*ch*kr - sin(u)*sh*ki)/(2*d)
    b = [cos(lam*x(3))*wr + sin(lam*x(3))*wi, &
         cos(lam*x(3))*wi - sin(lam*x(3))*wr, &
         (-sin(u)*ch*cos(lam*x(3)) - cos(u)*sh*sin(lam*x(3)))/lam]
    psi = (sin(lam*x(3))**2 + lam**2*b(3)**2)/2
    p = pa - psi/lam**2
    q = -(wr**2 + wi**2)/2 + sin(lam*x(3))**2/(2*lam**2)
    do k = 1, 3
        do m = 1, 3
            db(k, m) = total(b(k), m)
        end do
    end do
    call prove_sheared()
    j = [db(3, 2) - db(2, 3), db(1, 3) - db(3, 1), db(2, 1) - db(1, 2)]
    do k = 1, 3
        gp(k) = total(p, k)
    end do
    ! Smooth real representation of K=wbar*sqrt(1+eps/wbar^2), positive
    ! real part of the square root, away from the focal segment.
    s = x(1)**2 + x(2)**2
    re = 1 + eps*(x(1)**2 - x(2)**2)/s**2
    im = 2*eps*x(1)*x(2)/s**2
    root = sqrt((sqrt(re**2 + im**2) + re)/2)
    core = b; corep = p; corepsi = psi
    do k = 1, 3
        b(k) = replace_k(core(k))
    end do
    p = replace_k(corep); psi = replace_k(corepsi)
    do k = 1, 3
        j(k) = replace_k(j(k)); gp(k) = replace_k(gp(k))
        do m = 1, 3
            db(k, m) = replace_k(db(k, m))
        end do
    end do
    call w%emit('nested_sheared_field', &
           [character(8) :: 'x', 'y', 'z', 'eps', 'tau', 'saxis', 'lam', 'pa'], names, &
                [psi, p, b, j, gp, reshape(db, [9])], ad=.true., interval=.true.)
    ! Inverse elliptic chart, principal inverse trigonometric functions.
    xx = -rho*cos(theta); yy = rho*sin(theta)
    nu = eps*sin(2*t)/2 + tau
    ch = (exp(nu) + exp(0 - nu))/2; sh = (exp(nu) - exp(0 - nu))/2
    sig = saxis + atan(sh*yy/(ch*sqrt(1 - yy**2))) &
          - asin(xx/sqrt(ch**2 - yy**2))
    h = sqrt(4*sig**2 + eps**2)
    g = (h + eps*cos(2*t))/2
    xy = [sqrt((h - eps)/2)*cos(t), sqrt((h + eps)/2)*sin(t), -asin(yy)/lam]
    jac = rho*g/(lam*h*sqrt((ch**2 - rho**2)*(1 - yy**2)))
    rhs = 2*g*sqrt((1 - yy**2)/(ch**2 - rho**2))
    call w%emit('nested_sheared_surface', &
                [character(8) :: 'rho', 'theta', 't', 'eps', 'tau', 'saxis', 'lam'], &
               [character(8) :: 'x', 'y', 'z', 'jac', 'rhs'], [xy, jac, rhs], ad=.true.)
    ! Axis rotation integrand, valid also for Issan's shifted phase.
    call w%emit('nested_sheared_axis_iota', &
                [character(8) :: 't', 'eps', 'tau', 'saxis'], ['rhs'], &
                [(sqrt(4*saxis**2 + eps**2) + eps*cos(2*t))/ch], ad=.true.)
    ! Small numerical leaves of validation, quadrature and boundary adapters.
    q = sym(arena, 'edge'); f = sym(arena, 'factor')
    paxes = [q + 2*delta/(1 - tau**2), q + delta/lam**2]
    call w%emit('nested_setup', &
                [character(8)::'eps', 'tau', 'delta', 'lam', 'edge'], &
                [character(8)::'limit', 'extent', 'pa1', 'pa2'], &
                [(1 - (1 - tau**2)*eps)**2/4, asin(sqrt(2*delta)), &
                 paxes])
    s = x(1)**2/(1 + eps) + x(2)**2/(1 - eps)
    call w%emit('nested_integer_domain', &
                [character(8)::'x', 'y', 'z', 'eps', 'tau'], ['s ', 'f2'], &
                [s, s*(2 - s) - 4*x(3)**2 - 4*tau*s*x(3)])
    call w%emit('nested_ray', ['x  ', 'y  ', 'phi'], ['ray   ', 'radius'], &
                [x(2)*cos(sym(arena, 'phi')) - x(1)*sin(sym(arena, 'phi')), &
                 x(1)*cos(sym(arena, 'phi')) + x(2)*sin(sym(arena, 'phi'))])
    call w%emit('nested_reduce', &
                [character(8)::'p', 'bx', 'by', 'bz', 'factor'], &
                [character(8)::'volume', 'pint', 'b2int'], &
                [f, f*sym(arena, 'p'), f*(sym(arena, 'bx')**2 + sym(arena, 'by')**2 &
                                          + sym(arena, 'bz')**2)])
    call w%emit('nested_rotation_number', ['theta', 'turns'], ['iota'], &
                [theta/(2*pi_expr(arena)*sym(arena, 'turns'))])
    u = sym(arena, 'radius'); v = sym(arena, 'height')
    q = sym(arena, 'm')*theta - 2*sym(arena, 'n')*sym(arena, 'phi')
    call w%emit('nested_boundary_harmonic', &
                [character(8)::'radius', 'height', 'theta', 'phi', 'm', 'n'], &
                ['rc', 'rs', 'zc', 'zs'], [u*cos(q), u*sin(q), v*cos(q), v*sin(q)])
    call w%emit('nested_boundary_phase', &
                [character(8)::'theta', 'phi', 'm', 'n'], ['c', 's'], [cos(q), sin(q)])
    call w%emit('nested_boundary_radius', ['x', 'y'], ['radius'], &
                [sqrt(x(1)**2 + x(2)**2)])
    call w%emit('nested_pressure_axis', &
                [character(8)::'tau', 'delta', 'lam', 'edge'], ['pa1', 'pa2'], &
                paxes, interval=.true.)
    call w%line('end module kin6d_nested_oracle_leaves')
    call w%close()
    print '(a)', '[V] Eight exact FortSym div/tension proof lemmas PASS; no probes.'
contains
    subroutine prove_integer()
        ! A constant diagonal horizontal stretch preserves divergence and
        ! conjugates the tension. It commutes with diag(Omega^2,Omega^2,4Omega^2).
        type(expr_t) :: r, z, ff, br, bt, bz, rr
        r = sym(arena, 'r'); z = sym(arena, 'zz')
        ff = sqrt(r**2*(2 - r**2) - 4*z**2 - 4*tau*r**2*z)
        br = (2*z + tau*r**2)/r; bt = ff/r; bz = 1 - r**2 - 2*tau*z
        call prove(diff(r*br, r)/r + diff(bz, z), 'integer cylindrical div B')
        rr = br*diff(br, r) + bz*diff(br, z) - bt**2/r + om2*r
        call prove(rr, 'integer radial tension')
        rr = br*diff(bt, r) + bz*diff(bt, z) + br*bt/r
        call prove(rr, 'integer toroidal tension')
        rr = br*diff(bz, r) + bz*diff(bz, z) + 4*om2*z + 2*tau
        call prove(rr, 'integer vertical tension')
    end subroutine
    subroutine prove_sheared()
        ! Complex differential proof, valid for complex integration constant c.
        ! W=i V, Xi=w K+c. K_w=0, K_wbar=wbar/K. These four exact
        ! identities imply div B=0 and tension=-grad Q (Landreman eqs. 34-37).
        ! The proof is factored before real/imag expansion; no probe is accepted.
        type(expr_t)::ww, kk, wb, cc, xi, vv, vw, vww
        ww = sym(arena, 'omega'); kk = sym(arena, 'kk')
        wb = sym(arena, 'wbar'); cc = sym(arena, 'constant')
        xi = ww*kk + cc; vv = sin(xi)/(2*kk)
        vw = diff(vv, ww); vww = diff(vw, ww)
        call prove(2*vw - cos(xi), 'sheared divergence lemma')
        call prove(vww + kk**2*vv, 'sheared pure Wirtinger derivative')
        call prove(diff(vw, kk)*wb/kk + ww*wb*vv, 'sheared mixed derivative')
        call prove(vw**2 - vv*vww - (1 + 0*kk)/4, 'sheared tension invariant')
    end subroutine
    function dot(a, b) result(r)
        type(expr_t), intent(in)::a(3), b(3)
        type(expr_t)::r
        r = a(1)*b(1) + a(2)*b(2) + a(3)*b(3)
    end function
    subroutine jets()
        integer::i, jj
        do jj = 1, 3
            gp(jj) = diff(p, x(jj))
            do i = 1, 3
                db(i, jj) = diff(b(i), x(jj))
            end do
        end do
        j = [db(3, 2) - db(2, 3), db(1, 3) - db(3, 1), db(2, 1) - db(1, 2)]
    end subroutine
    function total(e, k) result(r)
        type(expr_t), intent(in)::e
        integer, intent(in)::k
        type(expr_t)::r
        r = diff(e, x(k)) + diff(e, u)*du(k) + diff(e, v)*dv(k)
        if (k == 1) r = r + diff(e, kr)*dkx(1) + diff(e, ki)*dkx(2)
        if (k == 2) r = r + diff(e, kr)*dky(1) + diff(e, ki)*dky(2)
    end function
    function replace_k(e) result(r)
        type(expr_t), intent(in)::e
        type(expr_t)::r
        r = subs(subs(e, u, x(1)*kr - x(2)*ki - saxis), &
                 v, x(1)*ki + x(2)*kr + tau)
        r = subs(subs(r, kr, x(1)*root + x(2)*im/(2*root)), &
                 ki, x(1)*im/(2*root) - x(2)*root)
    end function
    subroutine prove(e, label)
        type(expr_t), intent(in)::e
        character(*), intent(in)::label
        print '(a)', '[H] Proving '//label
        check = eng%zero_test(e)
        if (check%verdict /= VERDICT_TRUE) then
            print *, chars(check%message)
            print *, chars(print_expr(check%value))
            error stop label//' unproved'
        end if
        print '(a)', '[V] '//label//' exactly zero'
    end subroutine
end program
