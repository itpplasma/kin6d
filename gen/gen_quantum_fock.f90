program gen_quantum_fock
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, func, &
                            operator(+), operator(-), operator(*), &
                            operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, &
                                     interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    character(*), &
        parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: acc, coef, value, phase, length, hbar, mass, &
                    norm2, coupling
    type(expr_t) :: ar, ai, br, bi, kr, ki, epsilon, radius, wr, wi, pr, pim
    integer :: unit
    call arena%init(); engine = make_native_engine(arena)
    acc = sym(arena, 'acc'); coef = sym(arena, &
 'coef'); value = sym(arena, 'value')
    phase = sym(arena, 'phase'); length = sym(arena, 'length')
    hbar = sym(arena, 'hbar'); mass = sym(arena, &
 'mass'); norm2 = sym(arena, 'norm2')
    coupling = sym(arena, 'coupling'); ar = sym(arena, &
 'ar'); ai = sym(arena, 'ai')
    br = sym(arena, 'br')
    bi = sym(arena, 'bi')
    kr = sym(arena, 'kr')
    ki = sym(arena, 'ki')
    epsilon = sym(arena, 'epsilon'); radius = sym(arena, 'radius')
    open (newunit=unit, &
          file='src/generated/kin6d_quantum_fock_leaves.f90', &
          status='replace')
    write (unit, &
           '(a)') '! Generated by gen/gen_quantum_fock.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, &
           '(a)') '! Fermionic finite-basis parent; CAR phases a'// &
        're exact integ'// &
        'er scheduling.'
    write (unit, &
           '(a)') '! Periodic 3D jellium: V=L^3, k=2*pi*n/L; q=0'// &
        ' removed by ne'// &
        'utral background.'
    write (unit, &
           '(a)') '! Real Hamiltonian; complex states use real/i'// &
        'maginary coordinates.'
    write (unit, '(a)') 'module kin6d_quantum_fock_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('qf_accumulate', ['acc  ', 'coef ', 'value', &
                                'phase'], ['next'], &
              [acc + phase*coef*value], ad=.true., interval=.true.)
    call emit('qf_add', ['left ', 'right'], ['next'], &
              [sym(arena, 'left') + sym(arena, 'right')], &
              ad=.true., interval=.true.)
    call emit('qf_average', ['left ', 'right'], ['next'], &
              [(sym(arena, 'left') + sym(arena, 'right'))/2], ad=.true.)
    call emit('qf_kinetic', ['length', 'hbar  ', 'mass  ', &
                             'norm2 '], ['energy'], &
              [hbar**2*(2*pi_expr(arena)/length)**2*norm2/(2*mass)], ad=.true., &
              interval=.true.)
    call emit('qf_coulomb', ['length  ', 'coupling', &
                             'norm2   '], ['value'], &
           [4*pi_expr(arena)*coupling/(length**3*(2*pi_expr(arena)/length)**2*norm2)], &
              ad=.true., interval=.true.)
    call emit('qf_pair_integral', ['direct  ', 'exchange'], ['value'], &
              [sym(arena, 'direct') - sym(arena, 'exchange')], &
              ad=.true., interval=.true.)
    call emit('qf_expect', ['ar   ', 'ai   ', 'br   ', 'bi   ', &
                            'kr   ', 'ki   ', &
                            'phase'], &
              ['nr', 'ni'], [ar + phase*(br*kr + bi*ki), &
                             ai + phase*(br*ki - bi*kr)], &
              ad=.true., interval=.true.)
    wr = sym(arena, 'fr')*sym(arena, 'sr') - sym(arena, &
                                                 'fi')*sym(arena, 'si')
    wi = sym(arena, 'fr')*sym(arena, 'si') + sym(arena, &
                                                 'fi')*sym(arena, 'sr')
    pr = sym(arena, 'pr'); pim = sym(arena, 'pi')
    call emit('qf_pair_action_accumulate', ['ar   ', 'ai   ', &
                                            'fr   ', 'fi   ', &
                                            'sr   ', 'si   ', 'pr   ', 'pi   ', &
                                            'phase'], ['nr', 'ni'], &
              [ar + phase*(wr*pr - wi*pim), ai + phase*(wr*pim + wi*pr)], &
              ad=.true., interval=.true.)
    call emit('qf_density_contribution', ['ar   ', 'ai   ', &
                                          'coef ', 'phase', &
                                          'kr   ', 'ki   ', &
                                          'hbar '], ['nr', 'ni'], &
              [ar + phase*coef*ki/hbar, ai - phase*coef*kr/hbar], &
              ad=.true., interval=.true.)
    call emit('qf_norm_accumulate', ['acc', 're ', 'im '], ['next'], &
              [acc + sym(arena, 're')**2 + sym(arena, 'im')**2], &
              ad=.true., interval=.true.)
    call emit('qf_observable_radius', ['norm2  ', 'epsilon'], ['radius'], &
              [(2*func('sqrt', [norm2]) + epsilon)*epsilon], &
              ad=.true., interval=.true.)
    call emit('qf_enclose_interval', ['value ', 'radius'], &
              ['lower', 'upper'], &
              [value - radius, value + radius], rigorous=.true.)
    write (unit, '(a)') 'end module kin6d_quantum_fock_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, roots, ad, &
                              interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_quantum_fock; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), &
                          rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_quantum_fock')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_quantum_fock from pin'// &
                                      'ned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, &
                          roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, &
                  derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, &
                  derivative_roots)
    end subroutine emit_derivatives
end program gen_quantum_fock
