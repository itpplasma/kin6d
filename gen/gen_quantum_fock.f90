program gen_quantum_fock
    use fortsym_expr, only: expr_t, sym, pi_expr, func, &
                            operator(+), operator(-), operator(*), &
                            operator(/), operator(**)
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    use milca_symbolic_physics, only: jellium_coefficient
    implicit none
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(expr_t) :: acc, coef, value, phase, length, hbar, mass, &
                    norm2, coupling
    type(expr_t) :: ar, ai, br, bi, kr, ki, epsilon, radius, wr, wi, pr, pim
    engine = make_native_engine()
    acc = sym('acc'); coef = sym('coef'); value = sym('value')
    phase = sym('phase'); length = sym('length')
    hbar = sym('hbar'); mass = sym('mass'); norm2 = sym('norm2')
    coupling = sym('coupling'); ar = sym('ar'); ai = sym('ai')
    br = sym('br')
    bi = sym('bi')
    kr = sym('kr')
    ki = sym('ki')
    epsilon = sym('epsilon'); radius = sym('radius')
    call w%open('gen_quantum_fock', 'src/generated/kin6d_quantum_fock_leaves.f90')
    write (w%unit, &
           '(a)') '! Generated by gen/gen_quantum_fock.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, &
           '(a)') '! Fermionic finite-basis parent; CAR phases a'// &
        're exact integ'// &
        'er scheduling.'
    write (w%unit, &
           '(a)') '! Periodic 3D jellium: V=L^3, k=2*pi*n/L; q=0'// &
        ' removed by ne'// &
        'utral background.'
    write (w%unit, &
           '(a)') '! Real Hamiltonian; complex states use real/i'// &
        'maginary coordinates.'
    write (w%unit, '(a)') 'module kin6d_quantum_fock_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('qf_accumulate', ['acc  ', 'coef ', 'value', &
                                'phase'], ['next'], &
              [acc + phase*coef*value], ad=.true., interval=.true.)
    call w%emit('qf_add', ['left ', 'right'], ['next'], &
              [sym('left') + sym('right')], &
              ad=.true., interval=.true.)
    call w%emit('qf_average', ['left ', 'right'], ['next'], &
        [(sym('left') + sym('right'))/2], ad=.true.)
    call w%emit('qf_kinetic', ['length', 'hbar  ', 'mass  ', &
                             'norm2 '], ['energy'], &
              [hbar**2*(2*pi_expr()/length)**2*norm2/(2*mass)], ad=.true., &
              interval=.true.)
    call w%emit('qf_coulomb', ['length  ', 'coupling', &
                             'norm2   '], ['value'], &
        [jellium_coefficient(coupling, length**3, (2*pi_expr()/length)**2*norm2)], &
              ad=.true., interval=.true.)
    call w%emit('qf_pair_integral', ['direct  ', 'exchange'], ['value'], &
              [sym('direct') - sym('exchange')], &
              ad=.true., interval=.true.)
    call w%emit('qf_expect', ['ar   ', 'ai   ', 'br   ', 'bi   ', &
                            'kr   ', 'ki   ', &
                            'phase'], &
              ['nr', 'ni'], [ar + phase*(br*kr + bi*ki), &
                             ai + phase*(br*ki - bi*kr)], &
              ad=.true., interval=.true.)
    wr = sym('fr')*sym('sr') - sym('fi')*sym('si')
    wi = sym('fr')*sym('si') + sym('fi')*sym('sr')
    pr = sym('pr'); pim = sym('pi')
    call w%emit('qf_pair_action_accumulate', ['ar   ', 'ai   ', &
                                            'fr   ', 'fi   ', &
                                            'sr   ', 'si   ', 'pr   ', 'pi   ', &
                                            'phase'], ['nr', 'ni'], &
              [ar + phase*(wr*pr - wi*pim), ai + phase*(wr*pim + wi*pr)], &
              ad=.true., interval=.true.)
    call w%emit('qf_density_contribution', ['ar   ', 'ai   ', &
                                          'coef ', 'phase', &
                                          'kr   ', 'ki   ', &
                                          'hbar '], ['nr', 'ni'], &
              [ar + phase*coef*ki/hbar, ai - phase*coef*kr/hbar], &
              ad=.true., interval=.true.)
    call w%emit('qf_norm_accumulate', ['acc', 're ', 'im '], ['next'], &
              [acc + sym('re')**2 + sym('im')**2], &
              ad=.true., interval=.true.)
    call w%emit('qf_observable_radius', ['norm2  ', 'epsilon'], ['radius'], &
              [(2*func('sqrt', [norm2]) + epsilon)*epsilon], &
              ad=.true., interval=.true.)
    call w%emit('qf_enclose_interval', ['value ', 'radius'], &
              ['lower', 'upper'], &
              [value - radius, value + radius], rigorous=.true.)
    write (w%unit, '(a)') 'end module kin6d_quantum_fock_leaves'
    call w%close()
end program gen_quantum_fock
