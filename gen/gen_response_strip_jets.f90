program gen_response_strip_jets
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_eval, only: collect_free_symbols
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_string, only: str_t, str, chars
    implicit none
    type(arena_t), target :: arena
    type(expr_t) :: r, depth, sg, pr, pz, prr, prz, pzz, f, fx, px, pxx
    type(expr_t) :: b(3), db(3, 3), gp(3), hp(3, 3), current(3), invmu
    type(expr_t) :: u, ray, c, s, a, h, ht, htt, q, ru, rt, ruu, rut, rtt
    type(expr_t) :: xt(2), hxt(2), jac(2, 2), inv(2, 2), hh(2, 3)
    type(expr_t), allocatable :: vars(:)
    character(12), allocatable :: names(:)
    integer :: unit, status, k
    call arena%init()
    open (newunit=unit, file='src/generated/kin6d_response_strip_jets_leaves.f90', &
        status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_response_strip_jets.f90; do not edit.'
    write (unit, '(a)') 'module kin6d_response_strip_jets_leaves'
    write (unit, '(a)') '    implicit none'
    write (unit, '(a)') 'contains'
    allocate (vars(0), names(0))
    r = variable('r'); depth = variable('depth'); sg = variable('sg')
    pr = variable('pr'); pz = variable('pz'); prr = variable('prr')
    prz = variable('prz'); pzz = variable('pzz')
    f = variable('f'); fx = variable('fx'); px = variable('px'); pxx = variable('pxx')
    invmu = variable('invmu')
    b = [sg*pz/r, f/r, -sg*pr/r]
    db(1, :) = [sg*(prz/r - pz/r**2), -f/r**2, sg*pzz/r]
    db(2, :) = [fx*pr/(depth*r) - f/r**2, sg*pz/r**2, fx*pz/(depth*r)]
    db(3, :) = [-sg*(prr/r - pr/r**2), r - r, -sg*prz/r]
    gp = [px*pr/depth, r - r, px*pz/depth]
    hp(1, :) = [pxx*(pr/depth)**2 + px*prr/depth, r - r, &
        pxx*pr*pz/depth**2 + px*prz/depth]
    hp(2, :) = [r - r, gp(1)/r, r - r]
    hp(3, :) = [hp(1, 3), r - r, pxx*(pz/depth)**2 + px*pzz/depth]
    current = [db(3, 2) - db(2, 3), db(1, 3) - db(3, 1), db(2, 1) - db(1, 2)]
    do k = 1, 3
        current(k) = invmu*current(k)
    end do
    call emit('strip_field_jets', [character(12) :: &
        'db11', 'db21', 'db31', 'db12', 'db22', 'db32', 'db13', 'db23', 'db33', &
        'gp1', 'gp2', 'gp3', 'hp11', 'hp21', 'hp31', 'hp12', 'hp22', 'hp32', &
        'hp13', 'hp23', 'hp33', 'jc1', 'jc2', 'jc3'], &
        [reshape(db, [9]), gp, reshape(hp, [9]), current])
    vars = vars(1:0); names = names(1:0)
    u = variable('u'); depth = variable('depth'); ray = variable('ray')
    c = variable('c'); s = variable('s'); pr = variable('pr'); pz = variable('pz')
    prr = variable('prr'); prz = variable('prz'); pzz = variable('pzz')
    a = pr*c + pz*s
    h = prr*c**2 + 2*prz*c*s + pzz*s**2
    ru = 2*u*depth/a
    rt = -ray*(-pr*s + pz*c)/a
    xt = [rt*c - ray*s, rt*s + ray*c]
    hxt = [prr*xt(1) + prz*xt(2), prz*xt(1) + pzz*xt(2)]
    ht = c*hxt(1) + s*hxt(2)
    htt = xt(1)*hxt(1) + xt(2)*hxt(2)
    ruu = (2*depth - ru**2*h)/a
    rut = -ru*(ht - pr*s + pz*c)/a
    q = pr*(-2*rt*s - ray*c) + pz*(2*rt*c - ray*s)
    rtt = -(htt + q)/a
    jac(:, 1) = [ru*c, ru*s]; jac(:, 2) = xt
    inv(1, :) = [pr/(2*u*depth), pz/(2*u*depth)]
    inv(2, :) = [-s/ray, c/ray]
    hh(:, 1) = [ruu*c, ruu*s]
    hh(:, 2) = [rut*c - ru*s, rut*s + ru*c]
    hh(:, 3) = [(rtt - ray)*c - 2*rt*s, (rtt - ray)*s + 2*rt*c]
    call emit('strip_map_jets', [character(12) :: &
        'j11', 'j21', 'j12', 'j22', 'i11', 'i21', 'i12', 'i22', &
        'h1uu', 'h2uu', 'h1ut', 'h2ut', 'h1tt', 'h2tt'], &
        [reshape(jac, [4]), reshape(inv, [4]), reshape(hh, [6])])
    write (unit, '(a)') 'end module kin6d_response_strip_jets_leaves'
    close (unit)
    call execute_command_line('fprettify --disable-indent -i 4 -l 88 '// &
        'src/generated/kin6d_response_strip_jets_leaves.f90', exitstat=status)
    if (status /= 0) error stop 'format generated strip jets'
contains
    function variable(name) result(e)
        character(*), intent(in) :: name
        type(expr_t) :: e
        e = sym(arena, trim(name))
        vars = [vars, e]; names = [names, trim(name)]
    end function variable
    subroutine emit(name, outputs, roots)
        character(*), intent(in) :: name, outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_spec_t) :: spec
        type(expr_t), allocatable :: directions(:), seeds(:), derivatives(:)
        integer :: i
        spec%name = str(name)
        spec%generator = str('gen_response_strip_jets')
        spec%regenerate_command = &
            str('gen_response_strip_jets from the repository root')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        allocate (spec%args(size(names)), spec%outputs(size(outputs)))
        do i = 1, size(names)
            spec%args(i) = str(trim(names(i)))
        end do
        do i = 1, size(outputs)
            spec%outputs(i) = str(trim(outputs(i)))
        end do
        call write_kernel(roots, spec)
        allocate (directions(size(vars)), seeds(size(roots)))
        do i = 1, size(vars)
            directions(i) = sym(arena, 'd_'//trim(names(i)))
        end do
        derivatives = jvp(roots, vars, directions)
        spec%name = str(name//'_jvp')
        do i = 1, size(names)
            spec%args = [spec%args, str('d_'//trim(names(i)))]
        end do
        call write_kernel(derivatives, spec)
        deallocate (spec%args, spec%outputs)
        allocate (spec%args(size(names)), spec%outputs(size(names)))
        do i = 1, size(names)
            spec%args(i) = str(trim(names(i)))
            spec%outputs(i) = str('v_'//trim(names(i)))
        end do
        do i = 1, size(outputs)
            seeds(i) = sym(arena, 's_'//trim(outputs(i)))
            spec%args = [spec%args, str('s_'//trim(outputs(i)))]
        end do
        derivatives = vjp(roots, vars, seeds)
        spec%name = str(name//'_vjp')
        call write_kernel(derivatives, spec)
    end subroutine emit

    subroutine write_kernel(roots, spec)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_spec_t), intent(in) :: spec
        type(kernel_spec_t) :: lean
        type(str_t), allocatable :: free(:)
        logical :: keep(size(spec%args))
        integer :: i, j, k
        ! Derivatives of linear terms do not need the primal term as input.
        keep = .false.
        do i = 1, size(roots)
            call collect_free_symbols(roots(i), free)
            do j = 1, size(free)
                do k = 1, size(keep)
                    if (chars(free(j)) == chars(spec%args(k))) keep(k) = .true.
                end do
            end do
        end do
        lean = spec
        lean%args = spec%args
        call write_source(chars(emit_kernel(roots, lean)))
    end subroutine write_kernel

    subroutine write_source(source)
        character(*), intent(in) :: source
        character(:), allocatable :: line
        integer :: first, next, cut, k, statement_indent
        logical :: continuing
        ! FortSym emits at 100 columns. Wrap at token boundaries before the
        ! project formatter; changing layout never changes the expressions.
        first = 1
        continuing = .false.
        statement_indent = 0
        do while (first <= len(source))
            next = index(source(first:), new_line('a'))
            if (next == 0) next = len(source) - first + 2
            line = source(first:first + next - 2)
            if (continuing) then
                line = repeat(' ', statement_indent + 4)//trim(adjustl(line))
            else
                statement_indent = len(line) - len_trim(adjustl(line))
            end if
            continuing = .false.
            if (len_trim(line) > 0) continuing = line(len_trim(line):) == '&'
            do while (len_trim(line) > 80)
                if (index(adjustl(line), '!') == 1) exit
                cut = 0
                do k = 1, 78
                    if (line(k:k) == ',' .or. line(k:k) == ' ') cut = k
                end do
                if (cut <= 8) error stop 'cannot wrap generated Fortran token'
                write (unit, '(a)') '    '//trim(line(:cut))//' &'
                line = repeat(' ', statement_indent + 4)// &
                    trim(adjustl(line(cut + 1:)))
            end do
            if (len_trim(line) == 0) then
                write (unit, '(a)') ''
            else
                write (unit, '(a)') '    '//line
            end if
            first = first + next
        end do
    end subroutine write_source
end program gen_response_strip_jets
