program gen_gs_error
    !! Physical factors and scalar compositions for GS energy error control.
    !! Domains: positive R and box widths; alpha > 0 for goal division.
    !! Geometry, topology, solves and status checks belong to the caller.
    use fortsym
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: writer
    type(expr_t) :: r, grad_r, grad_z, rmax, width, height, pi
    type(expr_t) :: source_lipschitz, friedrichs_squared, alpha
    type(expr_t) :: primal_majorant, adjoint_majorant, goal_value, residual_adjoint
    type(expr_t) :: mu0, r_max, r_min, pp_slope_max, ff_slope_max
    type(expr_t) :: residual_majorant, c1, c2, c3

    call arena%init()
    r = sym(arena, 'r')
    grad_r = sym(arena, 'grad_r'); grad_z = sym(arena, 'grad_z')
    rmax = sym(arena, 'rmax')
    width = sym(arena, 'width'); height = sym(arena, 'height')
    ! Retain pi as a symbolic mathematical constant, not a rounded input.
    pi = pi_expr(arena)
    source_lipschitz = sym(arena, 'source_lipschitz')
    friedrichs_squared = sym(arena, 'friedrichs_squared')
    alpha = sym(arena, 'alpha')
    primal_majorant = sym(arena, 'primal_majorant')
    adjoint_majorant = sym(arena, 'adjoint_majorant')
    mu0 = sym(arena, 'mu0'); r_max = sym(arena, 'r_max')
    r_min = sym(arena, 'r_min')
    pp_slope_max = sym(arena, 'pp_slope_max')
    ff_slope_max = sym(arena, 'ff_slope_max')
    residual_majorant = sym(arena, 'residual_majorant')
    c1 = sym(arena, 'c1'); c2 = sym(arena, 'c2'); c3 = sym(arena, 'c3')
    goal_value = sym(arena, 'goal_value')
    residual_adjoint = sym(arena, 'residual_adjoint')

    call writer%open(arena, 'gen_gs_error', &
        'src/generated/kin6d_gs_error_leaves.f90')
    call writer%line('! Generated by gen/gen_gs_error.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('! GS weak form: -div(grad psi/R)=source, positive major R.')
    call writer%line('module kin6d_gs_error_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('gs_error_coefficient', ['r'], ['coefficient'], &
        [1/r], ad=.true., interval=.true.)
    call writer%emit('gs_error_flux', ['r     ', 'grad_r', 'grad_z'], &
        ['flux_r', 'flux_z'], [grad_r/r, grad_z/r], ad=.true.)
    ! Domain monotonicity from enclosing W x H rectangle, and A_min=1/Rmax.
    call writer%emit('gs_error_friedrichs', ['rmax  ', 'width ', 'height'], &
        ['cf'], [sqrt(rmax)/(pi*sqrt(1/width**2 + 1/height**2))], &
        ad=.true., interval=.true.)
    call writer%emit('gs_error_friedrichs_squared', &
        ['rmax  ', 'width ', 'height'], ['constant_squared'], &
        [rmax/(pi**2*(1/width**2 + 1/height**2))], ad=.true., interval=.true.)
    call writer%emit('gs_error_coercivity', &
        ['source_lipschitz  ', 'friedrichs_squared'], ['alpha'], &
        [1 - source_lipschitz*friedrichs_squared], ad=.true., interval=.true.)
    call writer%emit('gs_error_source_lipschitz', &
        ['mu0         ', 'r_max       ', 'r_min       ', &
         'pp_slope_max', 'ff_slope_max'], ['lipschitz'], &
        [mu0*r_max*pp_slope_max + ff_slope_max/r_min], ad=.true., interval=.true.)
    call writer%emit('gs_error_state', ['residual_majorant', 'alpha            '], &
        ['state_radius'], [residual_majorant/alpha], ad=.true., interval=.true.)
    call writer%emit('gs_error_goal', &
        ['primal_majorant ', 'adjoint_majorant', 'alpha           '], &
        ['goal_radius'], [primal_majorant*adjoint_majorant/alpha], ad=.true.)
    call writer%emit('gs_error_goal_corrected', &
        ['goal_value      ', 'residual_adjoint'], ['corrected_value'], &
        [goal_value + residual_adjoint], ad=.true.)
    ! Critical point of the quadratic derivative of a cubic profile piece.
    ! The caller checks c3 /= 0 and whether this point lies in its piece.
    call writer%emit('gs_error_slope_vertex', ['c2', 'c3'], ['x'], &
        [-c2/(3*c3)], ad=.true.)
    ! Global maximum of c1+2*c2*x+3*c3*x^2 for c3 < 0.
    call writer%emit('gs_error_slope_max', ['c1', 'c2', 'c3'], ['upper'], &
        [c1 - c2**2/(3*c3)], ad=.true., interval=.true.)
    ! Bernstein coefficients on an affine cell (vertex major radii r1..r3)
    ! of the source numerator s = R*source = mu0*pprime*R^2 + ffprime, in
    ! FortFEM's verified Bernstein order (2,0,0), (1,1,0), (1,0,1), (0,2,0),
    ! (0,1,1), (0,0,2): descending first, then second barycentric power.
    call source_numerator()
    call writer%line('end module kin6d_gs_error_leaves')
    call writer%close()

contains

    subroutine source_numerator()
        type(expr_t) :: r1, r2, r3, pp, ff, l1, l2, l3, rr, b(6), total
        type(engine_result_t) :: proved
        r1 = sym(arena, 'r1'); r2 = sym(arena, 'r2'); r3 = sym(arena, 'r3')
        pp = sym(arena, 'pprime'); ff = sym(arena, 'ffprime')
        l1 = sym(arena, 'l1'); l2 = sym(arena, 'l2'); l3 = sym(arena, 'l3')
        b = [mu0*pp*r1*r1 + ff, mu0*pp*r1*r2 + ff, mu0*pp*r1*r3 + ff, &
             mu0*pp*r2*r2 + ff, mu0*pp*r2*r3 + ff, mu0*pp*r3*r3 + ff]
        ! Homogeneous identity in the barycentric coordinates: the quadratic
        ! Bernstein form equals mu0*pprime*R^2 + ffprime*(l1+l2+l3)^2.
        rr = r1*l1 + r2*l2 + r3*l3
        total = b(1)*l1**2 + 2*b(2)*l1*l2 + 2*b(3)*l1*l3 + b(4)*l2**2 &
                + 2*b(5)*l2*l3 + b(6)*l3**2
        proved = writer%engine%zero_test(mu0*pp*rr**2 + ff*(l1 + l2 + l3)**2 - total)
        if (proved%verdict /= VERDICT_TRUE) error stop 'source numerator unproved'
        call writer%emit('gs_error_source_numerator_interval', &
            ['mu0    ', 'pprime ', 'ffprime', 'r1     ', 'r2     ', 'r3     '], &
            ['b1', 'b2', 'b3', 'b4', 'b5', 'b6'], b, rigorous=.true.)
    end subroutine source_numerator
end program gen_gs_error
