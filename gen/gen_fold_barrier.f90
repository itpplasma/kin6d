program gen_fold_barrier
   ! Fold barrier of the 3D free-boundary shell map (ideal_fb_t%fold_barrier).
   ! DX = dX/ds at a shell quadrature point (row a: Cartesian component,
   ! column i: abstract direction), J = sigma*det(DX) and u = J/(t0*det0),
   ! where det0 is the reference area factor of the point (the cell Jacobian
   ! ratio of the escape guard is J/det0) and t0 the activation ratio. For
   ! u < 1 the density is
   !   b = mu*det0*phi(u),  phi(u) = -log(u) + (u - 1) - (u - 1)^2/2,
   ! and b = 0 for u >= 1. phi(1) = phi'(1) = phi''(1) = 0, so the barrier is
   ! C2 across the activation and vanishes identically on states whose cell
   ! Jacobian ratios all exceed t0; phi'' = 1/u^2 - 1 > 0 below it and
   ! phi -> +inf as J -> 0+. Leaves: b, the 9-gradient over DX and the upper
   ! triangle of the 9x9 Hessian, for the active branch u < 1 (the caller
   ! skips u >= 1).
   use fortsym_arena, only: arena_t
   use fortsym_expr, only: expr_t, sym, log, operator(+), operator(-), &
                           operator(*), operator(/), operator(**)
   use fortsym_diff, only: diff
   use fortsym_engine, only: engine_result_t, VERDICT_TRUE
   use fortsym_engine_native, only: native_engine_t, make_native_engine
   use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
   implicit none
   type(arena_t), target :: arena
   type(leaf_writer_t) :: w
   type(native_engine_t) :: engine
   type(engine_result_t) :: check
   type(expr_t) :: d(3, 3), sigma, det0, t0, mu, det, u, density
   type(expr_t) :: vars(9), gradient(9), hessian(45), x, phi
   character(8) :: names9(9), names45(45)
   integer :: a, i, j, n
   call arena%init()
   engine = make_native_engine(arena)
   do i = 1, 3
      do a = 1, 3
         write (names9(a + 3*(i - 1)), '(a,i1,i1)') 'd', a, i
         d(a, i) = sym(arena, trim(names9(a + 3*(i - 1))))
      end do
   end do
   sigma = sym(arena, 'sigma'); det0 = sym(arena, 'det0')
   t0 = sym(arena, 't0'); mu = sym(arena, 'mu')
   det = d(1, 1)*(d(2, 2)*d(3, 3) - d(2, 3)*d(3, 2)) &
      - d(1, 2)*(d(2, 1)*d(3, 3) - d(2, 3)*d(3, 1)) &
      + d(1, 3)*(d(2, 1)*d(3, 2) - d(2, 2)*d(3, 1))
   u = sigma*det/(t0*det0)
   density = mu*det0*(0 - log(u) + (u - 1) - (u - 1)**2/2)
   ! C2 activation: phi(1) = phi'(1) = phi''(1) = 0 and phi'' = 1/x^2 - 1.
   x = sym(arena, 'x')
   phi = 0 - log(x) + (x - 1) - (x - 1)**2/2
   check = engine%zero_test(diff(diff(phi, x), x) - (1/x**2 - 1))
   if (check%verdict /= VERDICT_TRUE) error stop 'barrier curvature unproved'
   check = engine%zero_test(diff(phi, x) - (x - 1)**2*(0 - 1)/x)
   if (check%verdict /= VERDICT_TRUE) error stop 'barrier slope unproved'
   do i = 1, 9
      vars(i) = d(1 + mod(i - 1, 3), 1 + (i - 1)/3)
   end do
   do i = 1, 9
      gradient(i) = diff(density, vars(i))
   end do
   n = 0
   do j = 1, 9
      do i = 1, j
         n = n + 1
         write (names45(n), '(a,i1,i1)') 'h', i, j
         hessian(n) = diff(gradient(i), vars(j))
      end do
   end do
   call w%open(arena, 'gen_fold_barrier', 'src/generated/kin6d_fold_barrier_leaves.f90')
   call w%line('! Generated by gen/gen_fold_barrier.f90; do not edit.')
   call w%line('! FortSym revision: '//fortsym_revision)
   call w%line('! b = mu det0 (-log u + (u - 1) - (u - 1)^2/2), u = sigma det DX/(t0 det0),')
   call w%line('! active branch u < 1; d(a,i) = dX_a/ds_i ordered (d11, d21, .., d33).')
   call w%line('module kin6d_fold_barrier_leaves')
   call w%line('implicit none')
   call w%line('contains')
   call w%emit('fold_barrier_density', [character(8) :: names9, 'sigma', 'det0', &
      't0', 'mu'], ['b'], [density])
   call w%emit('fold_barrier_gradient', [character(8) :: names9, 'sigma', 'det0', &
      't0', 'mu'], [character(8) :: ('q'//trim(names9(i)), i=1, 9)], gradient)
   call w%emit('fold_barrier_hessian', [character(8) :: names9, 'sigma', 'det0', &
      't0', 'mu'], names45, hessian)
   call w%line('end module kin6d_fold_barrier_leaves')
   call w%close()
end program gen_fold_barrier
