program gen_dk_collop
    use fortsym_expr, only: expr_t, sym, rat, pi_expr, erf, exp, sqrt, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: x, rinv, tau, y, pi, chandra, series, l, mu, t, s
    type(expr_t) :: kh, kg, k1_lo, k1_hi, a0, a2, b0, b2, m0, m2, p0, p2
    integer, parameter :: nseries = 17
    integer(8) :: fact
    integer :: k

    ! Linearised Landau operator of species a on Maxwellian species b, speed
    ! x = v/v_ta, rinv = v_ta/v_tb, tau = T_a/T_b. Pairing with
    ! a test polynomial g and f = F_a h (F_a Maxwellian), per unit
    ! n_a nuhat_ab pi^(-3/2) 4 pi/(2l + 1), nuhat_ab = n_b e_a^2 e_b^2 lnL /
    ! (4 pi eps0^2 m_a^2 v_ta^3):
    !   test particle  -l(l+1)/2 int g h lorentz dx - int g' (energy h'
    !                  + thermal h) dx,
    ! lorentz = exp(-x^2) (erf(y) - G(y))/x, energy = exp(-x^2) x G(y),
    ! thermal = 2 (tau - 1) exp(-x^2) x^2 G(y), y = rinv x, G the Chandrasekhar
    ! function. The thermal weight is the energy exchange with a background of
    ! another temperature and vanishes for tau = 1.
    x = sym('x'); rinv = sym('rinv'); tau = sym('tau')
    pi = pi_expr()
    y = rinv*x
    chandra = (erf(y) - 2*y*exp(-y**2)/sqrt(pi))/(2*y**2)
    ! G(y) = (2/sqrt(pi)) sum_k (-1)^k y^(2k+1)/(k! (2k + 3)) avoids the
    ! cancellation of the closed form for y < 1; the first omitted term is
    ! below 1e-17 of the sum there.
    fact = 1
    series = rat(0_8, 1_8)
    do k = 0, nseries
        if (k > 0) fact = fact*k
        series = series + rat((-1_8)**k, fact)*y**(2*k + 1)/(2*k + 3)
    end do
    series = 2*series/sqrt(pi)

    ! Field-particle kernel per Legendre degree l: the Rosenbluth potentials
    ! H = int f/|v - v'|, G = int f |v - v'| of the l-component have the
    ! kernels kh = r<^l/r>^(l+1) and kg = r<^(l+2)/((2l+3) r>^(l+1))
    ! - r<^l/((2l-1) r>^(l-1)). Since (grad grad G).v = grad(v d_v G - G),
    ! the flux of C(F_a, f_b) is F_a times the gradient of
    ! psi P_l with psi ~ x d_x G - G + mu H, and its weak form pairs
    ! (g', psi') and l(l+1) g psi: the kernels are
    !   k1 = x d_x kg - kg + mu kh  and  k1x = d_x k1,
    ! derivatives at fixed source speed s (units of v_ta). For s < x the
    ! kernels are written in t = s/x, for s > x in t = x/s, so the powers of t
    ! never exceed one for any l.
    l = sym('l'); mu = sym('mu'); t = sym('t'); s = sym('s')
    kh = t**l/x
    kg = g0(x)*t**l + g2(x)*t**(l + 2)
    k1_lo = x*dx(kg) - kg + mu*kh
    kh = t**l/s
    kg = g0(s)*t**l + g2(s)*t**(l + 2)
    ! x = t s, d_x = d_t/s at fixed s.
    k1_hi = t*diff(kg, t) - kg + mu*kh

    call writer%open('gen_dk_collop', 'src/generated/kin6d_dk_collop_leaves.f90')
    call writer%line('! Generated by gen/gen_dk_collop.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module kin6d_dk_collop_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('collop_tp', ['x   ', 'rinv', 'tau '], &
        ['lorentz', 'energy ', 'thermal'], &
        [exp(-x**2)*(erf(y) - chandra)/x, exp(-x**2)*x*chandra, &
        2*(tau - 1)*exp(-x**2)*x**2*chandra], ad=.true.)
    call writer%emit('collop_tp_series', ['x   ', 'rinv', 'tau '], &
        ['lorentz', 'energy ', 'thermal'], &
        [exp(-x**2)*(erf(y) - series)/x, exp(-x**2)*x*series, &
        2*(tau - 1)*exp(-x**2)*x**2*series], ad=.true.)
    call writer%emit('collop_fp_lo', ['x ', 't ', 'l ', 'mu'], ['k1 ', 'k1x'], &
        [k1_lo, dx(k1_lo)], ad=.true.)
    call writer%emit('collop_fp_hi', ['s ', 't ', 'l ', 'mu'], ['k1 ', 'k1x'], &
        [k1_hi, diff(k1_hi, t)/s], ad=.true.)
    ! Integrate the two powers before evaluating the potential. Lower moments
    ! use (s/x)^l and (s/x)^(l+2); upper moments use (x/s)^(l-1) and
    ! (x/s)^(l+1). Their coefficients follow from the same G kernel.
    m0 = sym('m0'); m2 = sym('m2')
    p0 = l; p2 = l + 2
    a0 = clean(x*diff(g0(x), x) - (p0 + 1)*g0(x) + mu/x)
    a2 = clean(x*diff(g2(x), x) - (p2 + 1)*g2(x))
    b0 = clean(diff(a0, x) - p0*a0/x)
    b2 = clean(diff(a2, x) - p2*a2/x)
    call writer%emit('collop_fp_lo_moments', ['x ', 'l ', 'mu', 'm0', 'm2'], &
        ['psi ', 'psix'], [a0*m0 + a2*m2, b0*m0 + b2*m2], ad=.true.)
    p0 = l - 1; p2 = l + 1
    a0 = clean(x*diff(g0(x), x) + (p0 - 1)*g0(x))
    a2 = clean(x*diff(g2(x), x) + (p2 - 1)*g2(x) + mu/x)
    b0 = clean(diff(a0, x) + p0*a0/x)
    b2 = clean(diff(a2, x) + p2*a2/x)
    call writer%emit('collop_fp_hi_moments', ['x ', 'l ', 'mu', 'm0', 'm2'], &
        ['psi ', 'psix'], [a0*m0 + a2*m2, b0*m0 + b2*m2], ad=.true.)
    call writer%line('end module kin6d_dk_collop_leaves')
    call writer%close()

contains

    function clean(f) result(g)
        type(expr_t), intent(in) :: f
        type(expr_t) :: g
        type(engine_result_t) :: r
        r = writer%engine%expand(f)
        if (.not. r%ok) error stop 'moment coefficient expansion failed'
        r = writer%engine%simplify(r%value)
        if (.not. r%ok) error stop 'moment coefficient simplification failed'
        g = r%value
        r = writer%engine%zero_test(f - g)
        if (r%verdict /= VERDICT_TRUE) error stop 'unproved moment coefficient'
    end function clean

    function g0(r) result(g)
        type(expr_t), intent(in) :: r
        type(expr_t) :: g
        g = -r/(2*l - 1)
    end function g0

    function g2(r) result(g)
        type(expr_t), intent(in) :: r
        type(expr_t) :: g
        g = r/(2*l + 3)
    end function g2

    !> d/dx at fixed s = t x, for an expression in x and t = s/x.
    function dx(f) result(g)
        type(expr_t), intent(in) :: f
        type(expr_t) :: g
        g = diff(f, x) - t/x*diff(f, t)
    end function dx

end program gen_dk_collop
