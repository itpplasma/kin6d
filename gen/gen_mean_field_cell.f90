program gen_mean_field_cell
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, log, sqrt, operator(+), &
                            operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: f, rho, sigma, beta, rs, energy, entropy, temperature

    call arena%init()
    f = sym(arena, 'f'); rho = sym(arena, 'rho'); sigma = sym(arena, 'sigma')
    beta = sym(arena, 'beta'); rs = sym(arena, 'rs'); energy = sym(arena, 'energy')
    entropy = sym(arena, 'entropy'); temperature = sym(arena, 'temperature')
    call w%open(arena, 'gen_mean_field_cell', &
                'src/generated/kin6d_mean_field_cell_leaves.f90')
    call w%line('! Generated by gen/gen_mean_field_cell.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Mean-field (Hartree/HF/Mermin/TDHF) models of the jellium cell.')
    call w%line('! Fermion orbital entropy s(f) = -(f ln f + (1-f) ln(1-f)) (k_B=1);')
    call w%line('! Mermin free energy F = E - T S. Temple lower bound for the lowest')
    call w%line('! eigenvalue: rho - sigma^2/(beta - rho), valid when rho < beta <= E1,')
    call w%line('! rho = <H>, sigma = ||(H - rho) phi||, |phi| = 1.')
    call w%line('! Perdew-Zunger (1981) fit of the Ceperley-Alder unpolarized jellium')
    call w%line('! correlation energy per electron [Ha]: rs < 1 and rs >= 1 branches.')
    call w%line('module kin6d_mean_field_cell_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('mf_entropy', ['f'], ['s'], [-(f*log(f) + (1 - f)*log(1 - f))], &
                ad=.true.)
    call w%emit('mf_free_energy', ['energy     ', 'entropy    ', 'temperature'], &
                ['free'], [energy - temperature*entropy], ad=.true.)
    call w%emit('mf_temple', ['rho  ', 'sigma', 'beta '], ['lower'], &
                [rho - sigma**2/(beta - rho)], ad=.true., interval=.true.)
    call w%emit('mf_pz81_high', ['rs'], ['ec'], &
                [rat(arena, 311_8, 10000_8)*log(rs) - rat(arena, 48_8, 1000_8) + &
                 rat(arena, 20_8, 10000_8)*rs*log(rs) - rat(arena, 116_8, 10000_8)*rs], &
                ad=.true.)
    call w%emit('mf_pz81_low', ['rs'], ['ec'], &
                [-rat(arena, 1423_8, 10000_8)/(1 + rat(arena, 10529_8, 10000_8)*sqrt(rs) &
                 + rat(arena, 3334_8, 10000_8)*rs)], ad=.true.)
    call w%line('end module kin6d_mean_field_cell_leaves')
    call w%close()
end program gen_mean_field_cell
