program gen_debye_sphere
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, exp, abs, sin, cos, sqrt, pi_expr, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
        emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: r, k, z, series, term, prefactor, matching, phi, exterior
    type(expr_t) :: tail(0:3), eg, ecurv, egcurv, dg, curvature, gcurvature
    type(expr_t) :: index, count, value, radius, chi, x, y, angle
    integer :: unit, n, j

    call arena%init()
    engine = make_native_engine(arena)
    r = sym(arena, 'r'); k = sym(arena, 'k')
    index = sym(arena, 'index'); count = sym(arena, 'count')
    value = sym(arena, 'value'); radius = sym(arena, 'radius')
    chi = sym(arena, 'chi'); x = sym(arena, 'x'); y = sym(arena, 'y')
    angle = sym(arena, 'angle')
    z = k*r
    ! Fixed uniform permeable 3D sphere R=1. Phi unit Q/(4*pi*epsilon0*R).
    ! Exact regular interior: 3/k^2 [1-(1+k) exp(-k) sinh(k*r)/(k*r)].
    ! S_12=sum_{j=0}^{12} z^(2j)/(2j+1)!; positive tail at z>=0.
    ! For derivative order m<=3, |(S-S_12)^(m)| <= exp(z)z^(26-m)/(27-m)!.
    ! This follows termwise from (2j)_m/(2j+1)! <= 1/(2j+1-m)!
    ! and the exponential Taylor remainder. Includes r=0 by continuity.
    series = sym(arena, 'r')*0 + 1
    term = series
    do j = 1, 12
        term = term*z**2/(2*j*(2*j + 1))
        series = series + term
    end do
    do n = 0, 3
        tail(n) = exp(z)*z**(26 - n)
        do j = 2, 27 - n
            tail(n) = tail(n)/j
        end do
    end do
    prefactor = 3/k**2
    matching = (1 + k)*exp(-k)
    phi = prefactor*(1 - matching*series)
    dg = diff(phi, k)
    curvature = diff(diff(phi, r), r)
    gcurvature = diff(curvature, k)
    ! |d_k(prefactor*matching)|; both factors positive in admitted domain.
    term = 3*exp(-k)*(2*(1 + k)/k**3 + 1/k)
    eg = term*tail(0) + prefactor*matching*r*tail(1)
    ecurv = prefactor*matching*k**2*tail(2)
    egcurv = term*k**2*tail(2) + prefactor*matching* &
        (2*k*tail(2) + k**2*r*tail(3))
    exterior = 3*((k - 1)*exp(-k*(r - 1)) + &
        (k + 1)*exp(-k*(r + 1)))/(2*k**3*r)

    open (newunit=unit, file='src/generated/kin6d_debye_sphere_leaves.f90', &
        status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_debye_sphere.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, '(a)') '! ANALYTICAL REFERENCE: matched linear Debye equilibrium.'
    write (unit, '(a)') '! No numerical BVP solve or transient.'
    write (unit, '(a)') '! R=1; r/R in [0,6], k=R/lambdaD in [0.5,2]; infinity gauge.'
    write (unit, '(a)') '! Interior S12 has explicit positive-series remainder.'
    write (unit, '(a)') '! Smooth branch JVP/VJP: Euclidean pairing, fixed R boundary.'
    write (unit, '(a)') 'module kin6d_debye_sphere_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('sphere_inside', ['r', 'k'], ['phi'], [phi], ad=.true.)
    call emit('sphere_outside', ['r', 'k'], ['phi'], [exterior], ad=.true.)
    call emit('sphere_inside_tangent', ['r', 'k'], ['g'], [dg])
    call emit('sphere_outside_tangent', ['r', 'k'], ['g'], [diff(exterior, k)])
    call emit('sphere_inside_packet', ['r', 'k'], &
        ['phi   ', 'g     ', 'm     ', 'mg    ', 'ephi  ', 'eg    '], &
        [phi, dg, abs(curvature) + ecurv, abs(gcurvature) + egcurv, &
         prefactor*matching*tail(0), eg], rigorous=.true.)
    call emit('sphere_outside_packet', ['r', 'k'], &
        ['phi', 'g  ', 'm  ', 'mg '], &
        [exterior, diff(exterior, k), abs(diff(diff(exterior, r), r)), &
         abs(diff(diff(diff(exterior, r), r), k))], rigorous=.true.)
    call emit('sphere_bare_inside', ['r'], ['phi'], [(3 - r**2)/2], &
        ad=.true., interval=.true.)
    call emit('sphere_bare_outside', ['r'], ['phi'], [1/r], &
        ad=.true., interval=.true.)
    call emit('sphere_bare_curvature', ['r'], ['m'], [2/r**3], rigorous=.true.)
    call emit('sphere_widen', ['value ', 'radius'], ['lower', 'upper'], &
        [value - radius, value + radius], rigorous=.true.)
    call emit('sphere_response', ['value', 'chi  '], ['density'], &
        [1 + chi*value], ad=.true., interval=.true.)
    call emit('sphere_coordinate', ['index', 'count'], ['r'], &
        [6*index/count])
    call emit('sphere_parameter', ['index', 'count'], ['k'], &
        [(1 + 3*index/(count - 1))/2])
    call emit('sphere_marker', ['index', 'count'], ['x'], &
        [-2 + 4*index/(count - 1)])
    call emit('sphere_radius', ['x', 'y'], ['r'], [sqrt(x**2 + y**2)])
    call emit('sphere_circle', ['angle'], ['x', 'y'], [cos(angle), sin(angle)])
    call emit('sphere_angle', ['index', 'count'], ['angle'], &
        [2*pi_expr(arena)*index/(count - 1)])
    write (unit, '(a)') 'end module kin6d_debye_sphere_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        type(expr_t), allocatable :: clean(:)
        type(engine_result_t) :: simplified
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        allocate (clean(size(roots)))
        do j = 1, size(roots)
            simplified = engine%simplify(roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            clean(j) = simplified%value
        end do

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_debye_sphere; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%exp = str('exp')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(clean, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_debye_sphere')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_debye_sphere from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(clean, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, clean)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_debye_sphere
