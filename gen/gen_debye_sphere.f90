program gen_debye_sphere
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, exp, abs, sin, cos, sqrt, pi_expr, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: r, k, z, series, term, prefactor, matching, phi, exterior
    type(expr_t) :: tail(0:3), eg, ecurv, egcurv, dg, curvature, gcurvature
    type(expr_t) :: index, count, value, radius, chi, x, y, angle
    integer :: n, j

    call arena%init()
    r = sym(arena, 'r'); k = sym(arena, 'k')
    index = sym(arena, 'index'); count = sym(arena, 'count')
    value = sym(arena, 'value'); radius = sym(arena, 'radius')
    chi = sym(arena, 'chi'); x = sym(arena, 'x'); y = sym(arena, 'y')
    angle = sym(arena, 'angle')
    z = k*r
    ! Fixed uniform permeable 3D sphere R=1. Phi unit Q/(4*pi*epsilon0*R).
    ! Exact regular interior: 3/k^2 [1-(1+k) exp(-k) sinh(k*r)/(k*r)].
    ! S_12=sum_{j=0}^{12} z^(2j)/(2j+1)!; positive tail at z>=0.
    ! For derivative order m<=3, |(S-S_12)^(m)| <= exp(z)z^(26-m)/(27-m)!.
    ! This follows termwise from (2j)_m/(2j+1)! <= 1/(2j+1-m)!
    ! and the exponential Taylor remainder. Includes r=0 by continuity.
    series = sym(arena, 'r')*0 + 1
    term = series
    do j = 1, 12
        term = term*z**2/(2*j*(2*j + 1))
        series = series + term
    end do
    do n = 0, 3
        tail(n) = exp(z)*z**(26 - n)
        do j = 2, 27 - n
            tail(n) = tail(n)/j
        end do
    end do
    prefactor = 3/k**2
    matching = (1 + k)*exp(-k)
    phi = prefactor*(1 - matching*series)
    dg = diff(phi, k)
    curvature = diff(diff(phi, r), r)
    gcurvature = diff(curvature, k)
    ! |d_k(prefactor*matching)|; both factors positive in admitted domain.
    term = 3*exp(-k)*(2*(1 + k)/k**3 + 1/k)
    eg = term*tail(0) + prefactor*matching*r*tail(1)
    ecurv = prefactor*matching*k**2*tail(2)
    egcurv = term*k**2*tail(2) + prefactor*matching* &
        (2*k*tail(2) + k**2*r*tail(3))
    exterior = 3*((k - 1)*exp(-k*(r - 1)) + &
        (k + 1)*exp(-k*(r + 1)))/(2*k**3*r)

    call w%open(arena, 'gen_debye_sphere', 'src/generated/kin6d_debye_sphere_leaves.f90')
    w%simplify_roots = .true.
    write (w%unit, '(a)') '! Generated by gen/gen_debye_sphere.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, '(a)') '! ANALYTICAL REFERENCE: matched linear Debye equilibrium.'
    write (w%unit, '(a)') '! No numerical BVP solve or transient.'
    write (w%unit, '(a)') '! R=1; r/R in [0,6], k=R/lambdaD in [0.5,2]; infinity gauge.'
    write (w%unit, '(a)') '! Interior S12 has explicit positive-series remainder.'
    write (w%unit, '(a)') '! Smooth branch JVP/VJP: Euclidean pairing, fixed R boundary.'
    write (w%unit, '(a)') 'module kin6d_debye_sphere_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('sphere_inside', ['r', 'k'], ['phi'], [phi], ad=.true.)
    call w%emit('sphere_outside', ['r', 'k'], ['phi'], [exterior], ad=.true.)
    call w%emit('sphere_inside_tangent', ['r', 'k'], ['g'], [dg])
    call w%emit('sphere_outside_tangent', ['r', 'k'], ['g'], [diff(exterior, k)])
    call w%emit('sphere_inside_packet', ['r', 'k'], &
        ['phi   ', 'g     ', 'm     ', 'mg    ', 'ephi  ', 'eg    '], &
        [phi, dg, abs(curvature) + ecurv, abs(gcurvature) + egcurv, &
         prefactor*matching*tail(0), eg], rigorous=.true.)
    call w%emit('sphere_outside_packet', ['r', 'k'], &
        ['phi', 'g  ', 'm  ', 'mg '], &
        [exterior, diff(exterior, k), abs(diff(diff(exterior, r), r)), &
         abs(diff(diff(diff(exterior, r), r), k))], rigorous=.true.)
    call w%emit('sphere_bare_inside', ['r'], ['phi'], [(3 - r**2)/2], &
        ad=.true., interval=.true.)
    call w%emit('sphere_bare_outside', ['r'], ['phi'], [1/r], &
        ad=.true., interval=.true.)
    call w%emit('sphere_bare_curvature', ['r'], ['m'], [2/r**3], rigorous=.true.)
    call w%emit('sphere_widen', ['value ', 'radius'], ['lower', 'upper'], &
        [value - radius, value + radius], rigorous=.true.)
    call w%emit('sphere_response', ['value', 'chi  '], ['density'], &
        [1 + chi*value], ad=.true., interval=.true.)
    call w%emit('sphere_coordinate', ['index', 'count'], ['r'], &
        [6*index/count])
    call w%emit('sphere_parameter', ['index', 'count'], ['k'], &
        [(1 + 3*index/(count - 1))/2])
    call w%emit('sphere_marker', ['index', 'count'], ['x'], &
        [-2 + 4*index/(count - 1)])
    call w%emit('sphere_radius', ['x', 'y'], ['r'], [sqrt(x**2 + y**2)])
    call w%emit('sphere_circle', ['angle'], ['x', 'y'], [cos(angle), sin(angle)])
    call w%emit('sphere_angle', ['index', 'count'], ['angle'], &
        [2*pi_expr(arena)*index/(count - 1)])
    write (w%unit, '(a)') 'end module kin6d_debye_sphere_leaves'
    call w%close()
end program gen_debye_sphere
