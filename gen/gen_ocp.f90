program gen_ocp
    ! Leaves of the periodic one-component plasma cases (C3, C4):
    ! cardinal B-spline assignment weights of the particle-mesh Ewald action,
    ! the alias terms of its influence function, the periodic screened-Poisson
    ! (Debye) Green function and the weak-coupling oracles. Physics formulas
    ! come from gen/kin6d_symbolic_physics.f90.
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, exp, sqrt, sin, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: ewald_real_potential, ewald_real_force, &
        ewald_reciprocal_weight, yukawa_potential, &
        yukawa_zero_mode, debye_structure_factor, bohm_gross_frequency
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: t, x(3), g, kappa, volume, k2, alpha, order, m, length, d
    type(expr_t) :: r, r1, r2, sw, dsw, fe(3), phi
    integer :: p

    call arena%init()
    t = sym(arena, 't')
    x = [sym(arena, 'dx'), sym(arena, 'dy'), sym(arena, 'dz')]
    g = sym(arena, 'g'); kappa = sym(arena, 'kappa'); volume = sym(arena, 'volume')
    k2 = sym(arena, 'k2'); alpha = sym(arena, 'alpha'); order = sym(arena, 'order')
    m = sym(arena, 'm'); length = sym(arena, 'length')
    call w%open(arena, 'gen_ocp', 'src/generated/kin6d_ocp_leaves.f90')
    call w%line('! Generated by gen/gen_ocp.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Particle-mesh Ewald weights, influence alias terms, periodic')
    call w%line('! screened-Poisson Green function and weak-coupling OCP oracles.')
    call w%line('module kin6d_ocp_leaves')
    call w%line('implicit none')
    call w%line('contains')
    ! Cardinal B-spline M_p on [0,p]: a particle at grid coordinate u with
    ! t = u - floor(u) gives weight M_p(t+j) to mesh index floor(u)-j,
    ! j = 0..p-1, with M_p(s) = sum_{l<=j} (-1)^l C(p,l) (s-l)^(p-1)/(p-1)!.
    ! Outputs: weights w, first derivatives d = dw/dt, second s = d2w/dt2.
    do p = 4, 8, 2
        call emit_bspline(p)
    end do
    ! Influence function G(k) = sum_M U^2(k_M) R(k_M) / (sum_M U^2(k_M))^2
    ! (energy-optimal for the assignment, Hockney-Eastwood), alias vectors
    ! k_M = k + 2 pi M/h, U = prod_a sinc(k_{M,a} h/2)^p and R the Ewald
    ! reciprocal weight. One axis factor sinc(x)^(2p), x = k_a h/2 /= 0.
    call w%emit('pme_assignment_factor', ['x    ', 'order'], ['factor'], &
                [((sin(sym(arena, 'x'))/sym(arena, 'x'))**2)**order])
    ! Near/far encounter splitting of the real-space Ewald pair: near part
    ! S(r) g erfc(alpha r)/r with the C2 switch S = 1 - 10 s^3 + 15 s^4 - 6 s^5,
    ! s = (r - r1)/(r2 - r1), on r1 < r < r2 (S = 1 below r1, 0 above r2).
    ! The far part is the remainder; their sum is the bare Ewald pair.
    r1 = sym(arena, 'r1'); r2 = sym(arena, 'r2')
    r = sqrt(x(1)**2 + x(2)**2 + x(3)**2)
    t = (r - r1)/(r2 - r1)
    sw = 1 - 10*t**3 + 15*t**4 - 6*t**5
    dsw = (-30*t**2 + 60*t**3 - 30*t**4)/(r2 - r1)
    phi = ewald_real_potential(g, alpha, r)
    fe = ewald_real_force(g, alpha, x)
    call w%emit('near_switch_pair', ['dx   ', 'dy   ', 'dz   ', 'alpha', 'g    ', &
                                     'r1   ', 'r2   '], &
                ['fx       ', 'fy       ', 'fz       ', 'potential'], &
                [sw*fe(1) - dsw*phi*x(1)/r, sw*fe(2) - dsw*phi*x(2)/r, &
                 sw*fe(3) - dsw*phi*x(3)/r, sw*phi], ad=.true.)
    t = sym(arena, 't')
    ! Periodic screened-Poisson Green function of a unit-coupling source in
    ! a neutral cube: G(r) = sum_n yukawa(r + n L) - 4 pi g/(V kappa^2).
    call w%emit('debye_image', ['dx   ', 'dy   ', 'dz   ', 'g    ', 'kappa'], &
                ['potential'], &
                [yukawa_potential(g, 1/kappa, sqrt(x(1)**2 + x(2)**2 + x(3)**2))], &
                ad=.true.)
    call w%emit('debye_zero_mode', ['g     ', 'kappa ', 'volume'], ['constant'], &
                [yukawa_zero_mode(g, kappa, volume)], ad=.true.)
    ! Image shell m (max-norm index) of a separation wrapped into [-L/2,L/2]^3:
    ! 24 m^2 + 2 images, each at distance >= (m-1/2) L, and exp(-kappa d)/d
    ! decreases in d, so the shell term bounds the shell per unit g.
    d = (m - rat(arena, 1_int64, 2_int64))*length
    call w%emit('debye_shell_bound', ['m     ', 'kappa ', 'length'], ['potential'], &
                [(24*m**2 + 2)*exp(-kappa*d)/d])
    call w%emit('debye_structure', ['k2    ', 'kappa2'], ['s'], &
                [debye_structure_factor(k2, sym(arena, 'kappa2'))])
    call w%emit('bohm_gross', ['omega_p', 'k      ', 'lambda '], ['omega'], &
                [bohm_gross_frequency(sym(arena, 'omega_p'), sym(arena, 'k'), &
                                      sym(arena, 'lambda'))])
    call w%line('end module kin6d_ocp_leaves')
    call w%close()
contains
    subroutine emit_bspline(p)
        integer, intent(in) :: p
        type(expr_t) :: roots(3*p)
        character(8) :: names(3*p)
        character(16) :: label
        integer(int64) :: c(0:p - 1), factorial
        integer :: j, l, k
        factorial = 1
        do l = 2, p - 1
            factorial = factorial*l
        end do
        do j = 0, p - 1
            ! Exact monomial coefficients (times (p-1)!) of M_p(t+j), evaluated
            ! in Horner form: well conditioned on t in [0,1), unlike the
            ! truncated-power sum.
            c = 0
            do l = 0, j
                do k = 0, p - 1
                    c(k) = c(k) + (-1)**l*binomial(p, l)*binomial(p - 1, k)* &
                           int(j - l, int64)**(p - 1 - k)
                end do
            end do
            roots(j + 1) = horner(c, factorial)
            roots(p + j + 1) = horner([(c(k)*k, k = 1, p - 1)], factorial)
            roots(2*p + j + 1) = horner([(c(k)*k*(k - 1), k = 2, p - 1)], factorial)
            write (names(j + 1), '(a,i0)') 'w', j
            write (names(p + j + 1), '(a,i0)') 'd', j
            write (names(2*p + j + 1), '(a,i0)') 's', j
        end do
        write (label, '(a,i0)') 'pme_bspline', p
        call w%emit(trim(label), ['t'], names, roots)
    end subroutine

    !> sum_k c(k) t^k / den in Horner form, c indexed from 0.
    function horner(c, den) result(e)
        integer(int64), intent(in) :: c(0:), den
        type(expr_t) :: e
        integer :: k
        e = rat(arena, c(ubound(c, 1)), den)
        do k = ubound(c, 1) - 1, 0, -1
            e = e*t + rat(arena, c(k), den)
        end do
    end function

    integer(int64) function binomial(n, k) result(c)
        integer, intent(in) :: n, k
        integer :: i
        c = 1
        do i = 1, k
            c = c*(n - k + i)/i
        end do
    end function
end program gen_ocp
