program gen_gs_symmetry
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs_many
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(symengine_engine_t) :: engine
    type(leaf_writer_t) :: w
    type(expr_t) :: x, y, k, r, mu, pp, ff, f, fp, px, py, hxx, hxy, hyy
    type(expr_t) :: s, a11, a12, a22, source, twist
    type(expr_t) :: gx, gy, hx, hy, g(3), h(2, 3), xi(3), b(3)
    type(expr_t) :: db(3, 3), curl(3), force(3), residual, divergence, t
    type(expr_t) :: q, puu, prr, pr, polar, literature, r2, divb, published
    type(expr_t) :: c, dpp, dff
    integer :: i, j, identities = 0
    call arena%init()
    engine = make_symengine_engine(arena)
    x = sym(arena, 'x'); y = sym(arena, 'y'); k = sym(arena, 'k')
    r = sym(arena, 'r'); mu = sym(arena, 'mu0'); pp = sym(arena, 'pprime')
    ff = sym(arena, 'ffprime'); f = sym(arena, 'f'); fp = sym(arena, 'fprime')
    px = sym(arena, 'psi_x'); py = sym(arena, 'psi_y')
    hxx = sym(arena, 'hxx'); hxy = sym(arena, 'hxy'); hyy = sym(arena, 'hyy')
    gx = sym(arena, 'da1'); gy = sym(arena, 'da2')
    hx = sym(arena, 'db1'); hy = sym(arena, 'db2')
    r2 = x*x + y*y; s = 1 + k*k*r2
    xi = [-k*y, k*x, rat(arena, 1_int64, 1_int64)]
    t = -y*px + x*py
    g = [px, py, -k*t]
    h(:, 1) = [hxx, hxy]; h(:, 2) = [hxy, hyy]
    h(:, 3) = [k*y*hxx - k*py - k*x*hxy, k*px + k*y*hxy - k*x*hyy]
    ! Invariance fixes the derivatives in the orbit direction; no angle is used.
    b = cross(g, xi)
    do i = 1, 3
        b(i) = (b(i) + f*xi(i))/s
    end do
    do i = 1, 3
        do j = 1, 3
            db(i, j) = diff(b(i), px)*h(1, j) + diff(b(i), py)*h(2, j) &
                + diff(b(i), f)*fp*g(j)
        end do
        db(i, 1) = db(i, 1) + diff(b(i), x)
        db(i, 2) = db(i, 2) + diff(b(i), y)
    end do
    curl = [db(3, 2) - db(2, 3), db(1, 3) - db(3, 1), db(2, 1) - db(1, 2)]
    a11 = (1 + k*k*y*y)/s; a12 = -k*k*x*y/s; a22 = (1 + k*k*x*x)/s
    divergence = a11*hxx + 2*a12*hxy + a22*hyy &
        + (diff(a11, x) + diff(a12, y))*px + (diff(a12, x) + diff(a22, y))*py
    twist = -2*k/s**2
    source = mu*pp + ff/s + twist*f
    residual = divergence + mu*pp + f*fp/s + twist*f
    force = cross(curl, b)
    do i = 1, 3
        force(i) = force(i) - mu*pp*g(i)
    end do
    do i = 1, 3
        call prove(force(i) + residual*g(i), 'Cartesian J x B reduction')
    end do
    divb = db(1, 1) + db(2, 2) + db(3, 3)
    call prove(divb, 'solenoidal helical ansatz')
    call prove(b(1)*g(1) + b(2)*g(2) + b(3)*g(3), 'magnetic surfaces')
    call prove(b(1)*xi(1) + b(2)*xi(2) + b(3)*xi(3) - f, 'Killing field component')
    call prove(subs_many(divergence, [k], [rat(arena, 0_int64, 1_int64)]) - hxx - hyy, &
        'zero pitch gives translation')
    ! Taylor/Newton, JPP (2015), Eq. (2.28): l=1, k_T=-k, Psi_T=-psi.
    ! Their pressure is mu0*p; the flux reversal preserves the field convention.
    q = sym(arena, 'q'); pr = sym(arena, 'pr')
    prr = sym(arena, 'prr'); puu = sym(arena, 'puu')
    polar = prr/(1 + k*k*r*r) &
        + (1 - k*k*r*r)*pr/(r*(1 + k*k*r*r)**2) + puu/(r*r)
    literature = (prr + pr/r)/(1 + k*k*r*r) &
        - 2*k*k*r*pr/(1 + k*k*r*r)**2 + puu/(r*r)
    call prove(polar - literature, 'published helical diffusion operator')
    ! Rotational covariance permits comparison on the y=0 ray.
    c = sym(arena, 'c')
    call prove(subs_many(divergence, [x, y, px, py, hxx, hxy, hyy], &
        [r, rat(arena, 0_int64, 1_int64), pr, q/r, prr, c, pr/r + puu/(r*r)]) &
        - literature, 'Cartesian to polar helical operator')
    published = literature + mu*pp + ff/(1 + k*k*r*r) - 2*k*f/(1 + k*k*r*r)**2
    call prove(subs_many(divergence + source, [x, y, px, py, hxx, hxy, hyy], &
        [r, rat(arena, 0_int64, 1_int64), pr, q/r, prr, c, pr/r + puu/(r*r)]) &
        - published, 'published full helical equation including twist')
    call prove(xi(1)**2 + xi(2)**2 + xi(3)**2 - s, 'Killing norm')
    call prove(a11*a22 - a12*a12 - 1/s, 'quotient metric determinant')
    call w%open(arena, 'gen_gs_symmetry', 'src/generated/kin6d_gs_symmetry_leaves.f90')
    call w%line('! Generated by gen/gen_gs_symmetry.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_gs_symmetry_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('gs_rotation_weights', ['r'], &
        ['measure', 'invs   ', 'twist  '], [r, 1/r**2, rat(arena, 0_int64, 1_int64)], ad=.true.)
    call w%emit('gs_screw_weights', ['x', 'y', 'k'], &
        ['a11  ', 'a12  ', 'a22  ', 'invs ', 'twist'], &
        [a11, a12, a22, 1/s, twist], ad=.true.)
    call w%emit('gs_screw_source', &
        ['x      ', 'y      ', 'k      ', 'mu0    ', 'pprime ', 'ffprime', 'f      '], &
        ['source'], [source], ad=.true.)
    dpp = sym(arena, 'dpp'); dff = sym(arena, 'dff')
    call w%emit('gs_screw_profile_source', &
        ['x      ', 'y      ', 'k      ', 'mu0    ', 'pprime ', 'ffprime', 'f      ', &
        'dpp    ', 'dff    '], &
        ['source ', 'tangent'], [source, mu*dpp + dff/s + twist*ff/f], ad=.true.)
    call w%emit('gs_screw_field', &
        ['x    ', 'y    ', 'k    ', 'psi_x', 'psi_y', 'f    '], &
        ['bx', 'by', 'bz'], b, ad=.true.)
    call w%emit('gs_screw_bilinear', ['x  ', 'y  ', 'k  ', 'da1', 'da2', 'db1', 'db2'], &
        ['value'], [a11*gx*hx + a12*(gx*hy + gy*hx) + a22*gy*hy], ad=.true.)
    call w%emit('gs_translation_source', ['mu0    ', 'pprime ', 'ffprime'], &
        ['source'], [mu*pp + ff], ad=.true.)
    call w%emit('gs_translation_field', ['psi_x', 'psi_y', 'f    '], &
        ['bx', 'by', 'bz'], [py, -px, f], ad=.true.)
    call w%line('end module kin6d_gs_symmetry_leaves')
    call w%close()
    print '(a,i0,a)', 'GS symmetry: ',identities,' exact identities passed; leaves emitted'
contains
    function cross(a, b) result(c)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: c(3)
        c = [a(2)*b(3) - a(3)*b(2), a(3)*b(1) - a(1)*b(3), a(1)*b(2) - a(2)*b(1)]
    end function
    subroutine prove(expression, label)
        type(expr_t), intent(in) :: expression
        character(*), intent(in) :: label
        type(engine_result_t) :: result
        result = engine%zero_test(expression)
        identities = identities + 1
        if (result%verdict /= VERDICT_TRUE) then
            print '(a)', label
            error stop 'GS symmetry identity unproved'
        end if
    end subroutine
end program gen_gs_symmetry
