program gen_dk_energy
    use fortsym_expr, only: expr_t, sym, rat, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: d31, d32, k, n, t, dn, dt, b, bz, r, vz, q, r0, charge, c
    d31 = sym('d31'); d32 = sym('d32'); k = sym('k')
    n = sym('n'); t = sym('t'); dn = sym('nr'); dt = sym('tr')
    b = sym('b'); bz = sym('bz'); r = sym('r'); vz = sym('vz')
    q = sym('q'); r0 = sym('r0'); charge = sym('charge')
    c = rat(29979245800_8, 1_8)
    call writer%open('gen_dk_energy', 'src/generated/kin6d_dk_energy_leaves.f90')
    call writer%line('! Generated by gen/gen_dk_energy.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module kin6d_dk_energy_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('dk_energy_rotation', ['d31', 'd32'], ['k'], &
        [rat(5_8, 2_8) - d32/d31], ad=.true.)
    ! KAMEL single-ion force balance in Gaussian units: T in erg, lengths
    ! in cm, density in cm^-3, B in G, charge in statC and velocity in cm/s.
    ! nr and tr are derivatives with respect to the same physical radius.
    call writer%emit('dk_energy_force_balance', &
        ['k     ', 'n     ', 't     ', 'nr    ', 'tr    ', 'b     ', 'bz    ', &
        'r     ', 'vz    ', 'q     ', 'r0    ', 'charge'], ['er ', 'vth'], &
        [t*dn/(charge*n) + (1 - k)*dt/charge - r*b*vz/(c*q*r0), &
        k*c*bz*dt/(charge*b**2)], ad=.true.)
    call writer%line('end module kin6d_dk_energy_leaves')
    call writer%close()
end program gen_dk_energy
