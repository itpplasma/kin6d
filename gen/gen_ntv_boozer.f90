program gen_ntv_boozer
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: bmod, bmod_t, bmod_s, bref, iota, iota_s, g, i, g_s, i_s, psi_s
    type(expr_t) :: b, stream, jac

    ! NTV field-line coefficients on a Boozer surface (dk_ntv module header),
    ! from |B|, d|B|/dtheta and d|B|/ds at the point and the flux functions
    ! iota, the covariant components G, I [T m], their s derivatives and
    ! psi_s = dpsi/ds [T m^2] (psi the toroidal flux over 2 pi):
    !   b.grad theta = iota B/(G + iota I),
    !   drift (weight 1 + xi^2) = -(1/iota) (dB/ds)/(psi_s B), the grad-B and
    !     low-beta curvature binormal drift (b x grad ln B).grad alpha/B with
    !     (b x grad ln B).grad alpha = -q dB/dpsi, alpha = phi - q theta and
    !     the radial covariant component dropped,
    !   drift2 (weight xi^2) = 2 (I' + (q G)')/(psi_s (G + iota I)), the
    !     current and shear term of NEO-2-QL (a2b - a1b),
    ! both per unit m v^2/(2 e) [1/(T m^2)]. The Jacobian ~ 1/B^2 gives the
    ! flux measure 2/b^3 with b = B/B_ref.
    bmod = sym('bmod'); bmod_t = sym('bmod_t'); bmod_s = sym('bmod_s')
    bref = sym('bref'); iota = sym('iota'); iota_s = sym('iota_s')
    g = sym('g'); i = sym('i'); g_s = sym('g_s'); i_s = sym('i_s'); psi_s = sym('psi_s')
    b = bmod/bref
    jac = g + iota*i
    stream = iota*bmod/jac

    call writer%open('gen_ntv_boozer', 'src/generated/kin6d_ntv_boozer_leaves.f90')
    call writer%line('! Generated by gen/gen_ntv_boozer.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module kin6d_ntv_boozer_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('ntv_boozer_point', ['bmod  ', 'bmod_t', 'bmod_s', 'bref  ', &
        'iota  ', 'iota_s', 'g     ', 'i     ', 'g_s   ', 'i_s   ', 'psi_s '], &
        ['stream ', 'mirror ', 'drift  ', 'drift2 ', 'source ', 'measure'], &
        [stream, stream*bmod_t/(2*bmod), &
        (0 - bmod_s)/(iota*psi_s*bmod), &
        2*(i_s + g_s/iota - g*iota_s/(iota*iota))/(psi_s*jac), &
        2/(3*b), 2/(b*b*b)], ad=.true.)
    call writer%line('end module kin6d_ntv_boozer_leaves')
    call writer%close()
end program gen_ntv_boozer
