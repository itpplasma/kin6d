!> Leaves of the 1D electromagnetic plasma-slab case (docs/em-slab-reflection.md).
!> Normalization: t omega_pe, x omega_pe/c, E e/(m c omega_pe), cB e/(m c omega_pe),
!> u = p/(m c), J/(e n0 c), energy densities n0 m c^2. Electron q/m = -1.
!> Production leaves: relativistic Boris map, velocity, CIC weights, Yee
!> curl updates, Mur boundary, sheet source, energy densities and the
!> vacuum characteristic split. Independent oracle leaves: cold-plasma index,
!> Fresnel coefficients, evanescent reflection and steady envelopes. The
!> generator proves the structural identities it relies on before emitting.
program gen_em_slab
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, sqrt, sin, cos, exp, atan, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: ux, uy, ex, ey, bz, h, gamma, umx, umy, tz, s, upx, upy
    type(expr_t) :: px, py, mx, my, frac, e, bl, br, j, r, b, el, er, c
    type(expr_t) :: t, omega, amplitude, envelope, ramp, n, rr, tt, kappa
    type(expr_t) :: rre, rim, tre, tim, x, kap
    call arena%init()
    engine = make_native_engine(arena)
    ux = sym(arena, 'ux'); uy = sym(arena, 'uy')
    ex = sym(arena, 'ex'); ey = sym(arena, 'ey'); bz = sym(arena, 'bz')
    h = sym(arena, 'h')
    frac = sym(arena, 'frac'); e = sym(arena, 'e')
    bl = sym(arena, 'bl'); br = sym(arena, 'br'); j = sym(arena, 'j')
    r = sym(arena, 'r'); b = sym(arena, 'b'); el = sym(arena, 'el')
    er = sym(arena, 'er'); c = sym(arena, 'c')
    t = sym(arena, 't'); omega = sym(arena, 'omega')
    amplitude = sym(arena, 'amplitude'); envelope = sym(arena, 'envelope')
    ramp = sym(arena, 'ramp'); n = sym(arena, 'n'); x = sym(arena, 'x')
    kappa = sym(arena, 'kappa')

    ! Relativistic Boris map for an electron (q/m = -1) in E = (ex, ey, 0),
    ! B = (0, 0, bz): half electric kick, exact-norm magnetic rotation, half
    ! kick; h = dt/2 enters with the electron sign.
    umx = ux - h*ex; umy = uy - h*ey
    gamma = sqrt(1 + umx**2 + umy**2)
    tz = -h*bz/gamma
    s = 2*tz/(1 + tz**2)
    px = umx + umy*tz; py = umy - umx*tz
    upx = umx + py*s; upy = umy - px*s
    ! The rotation preserves |u|, hence gamma, for every rotation parameter.
    mx = sym(arena, 'mx'); my = sym(arena, 'my')
    call prove((rot_x(mx, my, kappa)**2 + rot_y(mx, my, kappa)**2) - &
               (mx**2 + my**2), 'Boris rotation preserves |u|')

    ! Fresnel matching at a sharp edge with a real index n (transmission).
    rr = (1 - n)/(1 + n); tt = 2/(1 + n)
    call prove(1 + rr - tt, 'E_y continuity (transmission)')
    call prove(1 - rr - n*tt, 'B_z continuity (transmission)')
    call prove(rr**2 + n*tt**2 - 1, 'Poynting balance (transmission)')
    ! Evanescent matching, n = i kappa: R = (1 - i kappa)/(1 + i kappa), T = 1 + R.
    rre = (1 - kappa**2)/(1 + kappa**2); rim = -2*kappa/(1 + kappa**2)
    tre = 1 + rre; tim = rim
    call prove(rre**2 + rim**2 - 1, 'total reflection |R| = 1')
    ! B_z continuity 1 - R = i kappa T, split into real and imaginary parts.
    call prove((1 - rre) + kappa*tim, 'B_z continuity real part (evanescent)')
    call prove(-rim - kappa*tre, 'B_z continuity imaginary part (evanescent)')
    ! The emitted omega forms equal the kappa forms for kappa^2 = 1/omega^2 - 1.
    kap = sqrt(1/omega**2 - 1)
    call prove((2 - 1/omega**2)*omega**2 - (1 - kap**2)/(1 + kap**2), &
               'R_re in terms of omega')
    call prove(-2*omega**2*kap - (-2*kap/(1 + kap**2)), 'R_im in terms of omega')
    ! |T|^2 = |1 + R|^2 = 4 omega^2, so |T| = 2 omega for omega > 0.
    call prove((1 + (1 - kap**2)/(1 + kap**2))**2 + (2*kap/(1 + kap**2))**2 &
               - 4*omega**2, '|T|^2 = 4 omega^2')
    ! Cold-fluid transverse dispersion omega^2 = 1 + k^2 with k = omega n.
    call prove(omega**2*(1 - 1/omega**2) + 1 - omega**2, 'cold dispersion')

    call w%open(arena, 'gen_em_slab', 'src/generated/kin6d_em_slab_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_em_slab.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, '(a)') '! 1D3V relativistic Vlasov-Maxwell slab, normal incidence,'
    write (w%unit, '(a)') &
        '! units t omega_pe, x omega_pe/c, E e/(m c omega_pe), q/m = -1.'
    write (w%unit, '(a)') &
        '! Oracle leaves (index, Fresnel, evanescent) are not called by'
    write (w%unit, '(a)') '! the solver; they are independent linear-theory references.'
    write (w%unit, '(a)') 'module kin6d_em_slab_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('em_slab_boris', ['ux', 'uy', 'ex', 'ey', 'bz', 'h '], &
                ['ux_new', 'uy_new'], [upx - h*ex, upy - h*ey], ad=.true.)
    call w%emit('em_slab_velocity', ['ux', 'uy'], ['vx   ', 'vy   ', 'gamma'], &
                [ux/sqrt(1 + ux**2 + uy**2), uy/sqrt(1 + ux**2 + uy**2), &
                 sqrt(1 + ux**2 + uy**2)], ad=.true.)
    call w%emit('em_slab_cic', ['frac'], ['w0', 'w1'], [1 - frac, frac], ad=.true.)
    ! Faraday: b <- b - r (er - el); Ampere: e <- e - r (br - bl) - h j.
    call w%emit('em_slab_faraday', ['b ', 'el', 'er', 'r '], ['b_new'], &
                [b - r*(er - el)], ad=.true.)
    call w%emit('em_slab_ampere', ['e ', 'bl', 'br', 'j ', 'r ', 'h '], ['e_new'], &
                [e - r*(br - bl) - h*j], ad=.true.)
    ! First-order Mur outgoing condition, c = Courant number.
    call w%emit('em_slab_mur', ['e_edge_old ', 'e_inner_old', 'e_inner_new', &
                                'c          '], ['e_edge_new'], &
                [sym(arena, 'e_inner_old') + (c - 1)/(c + 1)* &
                 (sym(arena, 'e_inner_new') - sym(arena, 'e_edge_old'))], ad=.true.)
    ! Sheet current K radiating E_y = -K/2 to both sides; sin^2 ramp.
    call w%emit('em_slab_ramp', ['t   ', 'ramp'], ['envelope'], &
                [sin(pi_expr(arena)*t/(2*ramp))**2], ad=.true.)
    call w%emit('em_slab_sheet_current', ['t        ', 'omega    ', 'amplitude', &
                                          'envelope '], ['k'], &
                [-2*amplitude*envelope*sin(omega*t)], ad=.true.)
    call w%emit('em_slab_field_energy', ['ex', 'ey', 'bz'], ['w'], &
                [(ex**2 + ey**2 + bz**2)/2], ad=.true.)
    call w%emit('em_slab_kinetic_energy', ['ux', 'uy'], ['k'], &
                [sqrt(1 + ux**2 + uy**2) - 1], ad=.true.)
    ! Vacuum characteristics: right-going (E + cB)/2, left-going (E - cB)/2.
    call w%emit('em_slab_characteristics', ['ey', 'bz'], ['forward ', 'backward'], &
                [(ey + bz)/2, (ey - bz)/2], ad=.true.)
    ! --- independent linear-theory oracles ---
    call w%emit('em_slab_index_squared', ['omega'], ['n2'], [1 - 1/omega**2], &
                ad=.true.)
    call w%emit('em_slab_fresnel', ['omega'], ['n         ', 'r         ', &
                                               't         ', 'k         ', &
                                               'wavelength'], &
                [sqrt(1 - 1/omega**2), (1 - sqrt(1 - 1/omega**2))/ &
                 (1 + sqrt(1 - 1/omega**2)), 2/(1 + sqrt(1 - 1/omega**2)), &
                 sqrt(omega**2 - 1), 2*pi_expr(arena)/sqrt(omega**2 - 1)], ad=.true.)
    call w%emit('em_slab_evanescent', ['omega'], ['kappa     ', 'skin_depth', &
                                                  'r_re      ', 'r_im      ', &
                                                  'phase     ', 't_abs     '], &
                [sqrt(1/omega**2 - 1), 1/sqrt(1 - omega**2), &
                 (2 - 1/omega**2)*omega**2, -2*omega**2*sqrt(1/omega**2 - 1), &
                 -2*atan(sqrt(1/omega**2 - 1)), 2*omega], ad=.true.)
    ! Steady |E_y|/A: vacuum standing wave (edge at x = 0, x < 0) and plasma.
    call w%emit('em_slab_vacuum_envelope', ['x    ', 'omega', 'r_re ', 'r_im '], &
                ['amplitude'], [sqrt(1 + sym(arena, 'r_re')**2 + &
                                    sym(arena, 'r_im')**2 + &
                                    2*(sym(arena, 'r_re')*cos(2*omega*x) + &
                                       sym(arena, 'r_im')*sin(2*omega*x)))], ad=.true.)
    call w%emit('em_slab_evanescent_envelope', ['x    ', 'omega'], ['amplitude'], &
                [2*omega*exp(-x*sqrt(1 - omega**2))], ad=.true.)
    write (w%unit, '(a)') 'end module kin6d_em_slab_leaves'
    call w%close()

contains

    function rot_x(ax, ay, tq) result(v)
        type(expr_t), intent(in) :: ax, ay, tq
        type(expr_t) :: v
        v = ax + (ay - ax*tq)*2*tq/(1 + tq**2)
    end function

    function rot_y(ax, ay, tq) result(v)
        type(expr_t), intent(in) :: ax, ay, tq
        type(expr_t) :: v
        v = ay - (ax + ay*tq)*2*tq/(1 + tq**2)
    end function

    subroutine prove(expression, what)
        type(expr_t), intent(in) :: expression
        character(*), intent(in) :: what
        type(engine_result_t) :: verdict
        verdict = engine%zero_test(expression)
        if (verdict%verdict /= VERDICT_TRUE) error stop 'unproved identity: '//what
        print '(2a)', 'proved: ', what
    end subroutine
end program gen_em_slab
