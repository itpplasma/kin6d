program gen_gs_coarea
    use fortsym_expr, only: expr_t, sym, sqrt, atan2, &
                            operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use kin6d_gen_support, only: leaf_writer_t, &
                                 fortsym_revision
    implicit none
    type(leaf_writer_t)::writer
    type(expr_t)::radius, r, radial_gradient, dlevel, &
                   dpsi_fixed, value, slope, curvature, &
                   offset, trace
    type(expr_t)::delta_psi, gr, gz, hrr, hrz, hzz, dgr, dgz, dr, &
                   dz, va, vm, vb, length, bgr, bgz
    type(expr_t) :: x, y, c(10), polynomial
    integer :: i
    character(3), parameter :: names(10) = [character(3) :: &
        "c00", "c10", "c01", "c20", "c11", "c02", "c30", "c21", "c12", "c03"]
    radius = sym('radius'); r = sym('r'); radial_gradient = sym('radial_gradient')
    dlevel = sym('dlevel'); dpsi_fixed = sym('dpsi_fixed')
    value = sym('value'); slope = sym('slope'); curvature = sym('curvature'); offset = sym('offset')
    delta_psi = sym('delta_psi'); gr = sym('gr'); gz = sym('gz')
    hrr = sym('hrr'); hrz = sym('hrz'); hzz = sym('hzz')
    dgr = sym('tg_r'); dgz = sym('tg_z'); dr = sym('dr'); dz = sym('dz')
    va = sym('va'); vm = sym('vm'); vb = sym('vb'); length = sym('length')
    bgr = sym('bgrad_r'); bgz = sym('bgrad_z')
    trace = value + slope*offset + &
            curvature*offset*offset/2
    call writer%open('gen_gs_coarea', &
                     'src/generated/kin6d_gs_coarea_leaves.f90')
    call writer%line('! Generated by gen/gen_gs_coarea.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('! P2 positive-outward flux, R>0, regular star-shaped cell arcs.')
    call writer%line('module kin6d_gs_coarea_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('gs_contour_weight', &
                     ['radius         ', 'r              ', &
                      'radial_gradient'], &
                     ['weight'], [radius/(r*radial_gradient)], ad=.true.)
    call writer%emit('gs_ray_trace', &
                     ['value    ', 'slope    ', 'curvature', 'offset   '], &
                     ['psi            ', 'radial_gradient'], [trace, &
                                                              diff(trace, offset)], &
            ad=.true.)
    call writer%emit('gs_contour_root_response', &
                     ['radial_gradient', 'dlevel         ', &
                      'dpsi_fixed     '], &
                     ['dradius'], [(dlevel - dpsi_fixed)/radial_gradient], &
                     ad=.true.)
    call writer%emit('gs_moving_jet_response', &
                     ['gr       ', 'gz       ', 'hrr      ', 'hrz      ', &
                      'hzz      ', &
                      'delta_psi', 'tg_r     ', 'tg_z     ', 'dr       ', &
                      'dz       '], &
                     ['value_tangent ', 'grad_r_tangent', &
                      'grad_z_tangent'], &
                     [delta_psi + gr*dr + gz*dz, dgr + hrr*dr + hrz*dz, &
                      dgz + hrz*dr + hzz*dz], ad=.true.)
    call writer%emit('gs_edge_trace_coefficients', ['va', &
                                                    'vm', 'vb'], &
                     ['linear   ', 'quadratic'], [-3*va + 4*vm - vb, 2*va - &
                                                  4*vm + 2*vb], ad=.true.)
    call writer%emit('gs_quadratic_translate', &
                     ['value', 'gr   ', 'gz   ', 'hrr  ', 'hrz  ', &
                      'hzz  ', 'dr   ', 'dz   '], &
                     ['shift_value ', 'shift_grad_r', 'shift_grad_z'], &
                     [value + gr*dr + gz*dz + (hrr*dr*dr + 2*hrz*dr*dz + &
                                               hzz*dz*dz)/2, &
                      gr + hrr*dr + hrz*dz, gz + hrz*dr + hzz*dz], ad=.true.)
    call writer%emit('gs_polar_angle', ['dr', 'dz'], &
                     ['angle'], [atan2(dz, dr)], ad=.true.)
    call writer%emit('gs_boundary_weight', ['length ', &
                                            'r      ', 'bgrad_r', 'bgrad_z'], &
                     ['weight'], [length/(r*sqrt(bgr*bgr + bgz*bgz))], &
                     ad=.true.)
    ! Cache the same P3 FE scalar in a local Taylor schedule. Coefficients
    ! are contractions of FortFEM's basis jets; this is not a new field fit.
    x = sym('xi'); y = sym('eta')
    do i = 1, 10
        c(i) = sym(names(i))
    end do
    polynomial = c(1) + x*c(2) + y*c(3) + x*x*c(4) + x*y*c(5) &
        + y*y*c(6) + x*x*x*c(7) + x*x*y*c(8) + x*y*y*c(9) + y*y*y*c(10)
    call writer%emit('gs_cubic_flux', [character(3) :: 'xi', 'eta', names], &
        [character(3) :: 'psi', 'gx', 'gy'], &
        [polynomial, diff(polynomial, x), diff(polynomial, y)], ad=.true.)
    call writer%line('end module kin6d_gs_coarea_leaves')
    call writer%close()
end program gen_gs_coarea
