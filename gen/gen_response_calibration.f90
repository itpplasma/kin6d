program gen_response_calibration
    !! Equivalent sheet: b = -Phi_unit jump/(area jump_unit).
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
                            operator(*), operator(/)
    use fortsym_products, only: jvp, vjp
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_string, only: str, chars
    implicit none
    type(arena_t), target :: arena
    type(expr_t) :: x(7), y(2), d(7), s(2), a, b, den
    type(expr_t) :: location(3), direction(3), radius(1), seed(1)
    type(kernel_spec_t) :: spec
    character(4), parameter :: names(7) = &
                            [character(4) :: 'jr', 'ji', 'ur', 'ui', 'fr', 'fi', 'area']
    integer :: i, u
    call arena%init()
    allocate (spec%args(7), spec%outputs(2))
    do i = 1, 7
        x(i) = sym(arena, trim(names(i)))
        d(i) = sym(arena, 'd_'//trim(names(i)))
        spec%args(i) = str(trim(names(i)))
    end do
    a = x(1)*x(3) + x(2)*x(4)
    b = x(2)*x(3) - x(1)*x(4)
    den = (x(3)*x(3) + x(4)*x(4))*x(7)
    y = [-(x(5)*a - x(6)*b)/den, -(x(5)*b + x(6)*a)/den]
    spec%outputs = [str('br'), str('bi')]
    spec%pure_procedure = .true.
    spec%elemental_procedure = .true.
    spec%generator = str('gen_response_calibration')
    spec%regenerate_command = str('gen_response_calibration from repository root')
    open (newunit=u, file='src/generated/kin6d_response_calibration_leaves.f90', &
          status='replace')
    write (u, '(a)') '! Generated by gen/gen_response_calibration.f90; do not edit.'
    write (u, '(a)') 'module kin6d_response_calibration_leaves'
    write (u, '(a)') '    implicit none'
    write (u, '(a)') 'contains'
    spec%name = str('sheet_field')
    call output(chars(emit_kernel(y, spec)))
    do i = 1, 7
        spec%args = [spec%args, str('d_'//trim(names(i)))]
    end do
    spec%name = str('sheet_field_jvp')
    call output(chars(emit_kernel(jvp(y, x, d), spec)))
    deallocate (spec%args, spec%outputs)
    allocate (spec%args(9), spec%outputs(7))
    do i = 1, 7
        spec%args(i) = str(trim(names(i)))
        spec%outputs(i) = str('v_'//trim(names(i)))
    end do
    s = [sym(arena, 's_br'), sym(arena, 's_bi')]
    spec%args(8:) = [str('s_br'), str('s_bi')]
    spec%name = str('sheet_field_vjp')
    call output(chars(emit_kernel(vjp(y, x, s), spec)))
    deallocate (spec%args, spec%outputs)
    allocate (spec%args(3), spec%outputs(1))
    location = [sym(arena, 'nmag'), sym(arena, 'qmag'), sym(arena, 'spot')]
    direction = [sym(arena, 'd_nmag'), sym(arena, 'd_qmag'), sym(arena, 'd_spot')]
    radius = [location(3)/(location(1)*location(2))]
    spec%args = [str('nmag'), str('qmag'), str('spot')]
    spec%outputs = [str('xs')]
    spec%name = str('spot_distance')
    call output(chars(emit_kernel(radius, spec)))
    spec%args = [spec%args, str('d_nmag'), str('d_qmag'), str('d_spot')]
    spec%name = str('spot_distance_jvp')
    call output(chars(emit_kernel(jvp(radius, location, direction), spec)))
    deallocate (spec%args, spec%outputs)
    allocate (spec%args(4), spec%outputs(3))
    seed = [sym(arena, 's_xs')]
    spec%args = [str('nmag'), str('qmag'), str('spot'), str('s_xs')]
    spec%outputs = [str('v_nmag'), str('v_qmag'), str('v_spot')]
    spec%name = str('spot_distance_vjp')
    call output(chars(emit_kernel(vjp(radius, location, seed), spec)))
    write (u, '(a)') 'end module kin6d_response_calibration_leaves'
    close (u)
contains
    subroutine output(source)
        character(*), intent(in) :: source
        character(:), allocatable :: line
        integer :: first, next, cut, k
        first = 1
        do while (first <= len(source))
            next = index(source(first:), new_line('a'))
            if (next == 0) next = len(source) - first + 2
            line = source(first:first + next - 2)
            do while (len_trim(line) > 84)
                if (index(adjustl(line), '!') == 1) exit
                cut = 0
                do k = 1, 80
                    if (line(k:k) == ',' .or. line(k:k) == ' ') cut = k
                end do
                if (cut <= 8) error stop 'cannot wrap token'
                write (u, '(a)') trim(line(:cut))//' &'
                line = '        '//trim(adjustl(line(cut + 1:)))
            end do
            write (u, '(a)') line
            first = first + next
        end do
    end subroutine output
end program gen_response_calibration
