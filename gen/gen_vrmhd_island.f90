program gen_vrmhd_island
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_expr, only: expr_t, sym, rat, cos, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(symengine_engine_t) :: engine
    type(engine_result_t) :: verdict
    type(expr_t) :: x, y, a, wave, amplitude, zero, one, pressure, az, ay, by, jz
    type(expr_t) :: roots(6)
    engine = make_symengine_engine()
    zero = rat(0_int64, 1_int64)
    one = rat(1_int64, 1_int64)
    x = sym('x'); y = sym('y'); a = sym('a')
    wave = sym('wave'); amplitude = sym('amplitude')
    az = -x*x/2; ay = 2*x
    by = -diff(az, x); jz = diff(by, x)
    pressure = 2 - by*by/2
    verdict = engine%zero_test(diff(pressure, x) + jz*by)
    if (verdict%verdict /= VERDICT_TRUE) error stop 'slab force balance'
    roots = [pressure/2, ay, az, by, jz, diff(ay, x)]
    call w%open('gen_vrmhd_island', 'test/support/vrmhd_island_leaves.f90')
    call w%line('! Generated by gen/gen_vrmhd_island.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module vrmhd_island_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('island_shear_equilibrium', [character(16) :: 'x'], &
        [character(16) :: 'rho', 'ay', 'az', 'by', 'jz', 'bz'], roots)
    az = az + amplitude*(one - (x/a)**2)**3*cos(wave*y)
    roots = [az, diff(az, y), -diff(az, x), &
        -diff(diff(az, x), x) - diff(diff(az, y), y), zero, zero]
    call w%emit('island_seed', &
        [character(16) :: 'x', 'y', 'a', 'wave', 'amplitude'], &
        [character(16) :: 'az', 'bx', 'by', 'jz'], roots(:4))
    call w%line('end module vrmhd_island_leaves')
    call w%close()
    print '(a)', 'slab force balance: verified symbolically'
end program gen_vrmhd_island
