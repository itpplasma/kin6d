program gen_s0
    ! Physical inertia and analytic shear-Alfven / rigid screw-pinch oracles.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*), &
        operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_products, only: jvp, vjp
    use fortsym_kernel, only: kernel_spec_t, emit_kernel, &
        PRECISION_REAL32, PRECISION_REAL64
    use fortsym_string, only: str, chars
    use kin6d_gen_support, only: fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(engine_result_t) :: check
    type(expr_t) :: x(7), d(7), seed(1), root(1), rho, bz, mu, k, q
    type(expr_t) :: kinetic, tension, frequency, checks(4)
    type(expr_t), allocatable :: tangent(:), adjoint(:)
    character(8) :: names(7), dn(7), gn(7)
    character(3) :: suffix
    integer :: i, unit, precision
    call arena%init()
    engine = make_native_engine(arena)
    names = [character(8) :: 'rho','x1','x2','x3','y1','y2','y3']
    do i = 1, 7
        x(i) = sym(arena, trim(names(i)))
        dn(i) = 'd'//trim(names(i)); gn(i) = 'g'//trim(names(i))
        d(i) = sym(arena, trim(dn(i)))
    end do
    rho = x(1); bz = sym(arena,'bz'); mu = sym(arena,'mu')
    k = sym(arena,'k'); q = sym(arena,'q')
    root(1) = rho*(x(2)*x(5)+x(3)*x(6)+x(4)*x(7))
    kinetic = rho*x(2)**2/2
    tension = bz**2*k**2*x(2)**2/(2*mu)
    frequency = k**2*bz**2/(mu*rho)
    ! Euler-Lagrange force / inertia, and existing rigid m=1 free-boundary split.
    checks(1) = diff(tension,x(2))-frequency*diff(kinetic,x(2))
    checks(2) = diff(kinetic,x(2))-rho*x(2)
    checks(3) = q*q+(q-1)**2-1-2*q*(q-1)
    checks(4) = 2*q*(1-q)/rho+2*q*(q-1)/rho
    do i = 1, size(checks)
        check = engine%zero_test(checks(i))
        if (check%verdict /= VERDICT_TRUE) error stop 'unproved S0 identity'
    end do
    seed(1) = sym(arena,'seed')
    tangent = jvp(root,x,d); adjoint = vjp(root,x,seed)
    open(newunit=unit,file='src/generated/kin6d_s0_leaves.f90',status='replace')
    write(unit,'(a)') '! Generated by gen/gen_s0.f90; do not edit.'
    write(unit,'(a)') '! FortSym revision: '//fortsym_revision
    write(unit,'(a)') 'module kin6d_s0_leaves'
    write(unit,'(a)') 'implicit none'
    write(unit,'(a)') 'contains'
    do precision = PRECISION_REAL64, PRECISION_REAL32
        suffix = '_dp'
        if (precision == PRECISION_REAL32) suffix = '_sp'
        call emit('s0_mass'//suffix,names,['value'],root)
        call emit('s0_mass_jvp'//suffix,[names,dn],['dvalue'],tangent)
        call emit('s0_mass_vjp'//suffix,[character(8) :: names,'seed'],gn,adjoint)
        call emit('s0_alfven'//suffix,[character(8) :: 'k','bz','mu','rho'], &
            ['omega2'],[frequency])
        call emit('s0_kink'//suffix,[character(8) :: 'q','rho'], &
            ['gamma2'],[2*q*(1-q)/rho])
        call toroidal_continuum()
    end do
    write(unit,'(a)') 'end module kin6d_s0_leaves'
    close(unit)
    print '(a)', 'PASS: four S0 and five toroidal identities per kind (no probes)'
contains
    subroutine toroidal_continuum()
        ! Cold, large-aspect circular two-harmonic field-line model:
        ! -D_parallel^2 Phi = omega^2/vA^2 (1+2*epsilon*cos(theta)) Phi.
        ! Keep the adjacent harmonics; omitted harmonics and O(epsilon^2)
        ! geometry are model error, not a discretization certificate.
        type(expr_t) :: a(5), da(5), roots(4), modes(2), back(2), source
        type(expr_t) :: z, u, v, eps, lam, center, polynomial, checks(5)
        type(expr_t) :: test(1), seeds(4)
        type(expr_t), allocatable :: jt(:), va(:)
        character(8) :: names(5), dn(5), gn(5), sn(4)
        integer :: j
        names = [character(8) :: 'kleft','kright','eps','density','alfven2']
        do j = 1, 5
            a(j) = sym(arena,trim(names(j)))
            dn(j) = 'd'//trim(names(j)); gn(j) = 'g'//trim(names(j))
            da(j) = sym(arena,trim(dn(j)))
        end do
        do j = 1, 4
            sn(j) = 'seed'//achar(iachar('0')+j)
            seeds(j) = sym(arena,trim(sn(j)))
        end do
        z = sym(arena,'z'); u = sym(arena,'u'); v = sym(arena,'v')
        eps = a(3); center = sym(arena,'center'); lam = sym(arena,'lam')
        modes = [u+v*z,u+v/z]
        back = [a(1)*u+a(2)*v*z,a(1)*u+a(2)*v/z]
        source = (1+eps*(z+1/z))*modes(1)*modes(2)
        checks(1) = source-(u*u+v*v+2*eps*u*v) &
            -(u*v+eps*(u*u+v*v))*(z+1/z)-eps*u*v*(z*z+1/(z*z))
        checks(2) = back(1)*back(2)-a(1)**2*u*u-a(2)**2*v*v &
            -a(1)*a(2)*u*v*(z+1/z)
        polynomial = (center-lam)**2-eps**2*lam**2
        test(1) = (center-center/(1+eps))**2-eps**2*(center/(1+eps))**2
        checks(3) = test(1)
        checks(4) = (center-center/(1-eps))**2-eps**2*(center/(1-eps))**2
        checks(5) = polynomial-((1-eps**2)*lam**2-2*center*lam+center**2)
        do j = 1, size(checks)
            check = engine%zero_test(checks(j))
            if (check%verdict /= VERDICT_TRUE) then
                print *, 'unproved toroidal identity',j
                error stop 1
            end if
        end do
        ! The retained Laurent constant is the exact angular Galerkin block.
        ! Derive K and M from the quadratic energy, rather than copying it.
        source = a(4)*a(5)*(a(1)**2*u*u+a(2)**2*v*v)/2
        roots(1) = diff(diff(source,u),u)
        roots(2) = diff(diff(source,v),v)
        source = a(4)*(u*u+v*v+2*eps*u*v)/2
        roots(3) = diff(diff(source,u),u)
        roots(4) = diff(diff(source,u),v)
        jt = jvp(roots,a,da); va = vjp(roots,a,seeds)
        call emit('s0_tae_block'//suffix,names, &
            [character(8) :: 'k11','k22','m11','m12'],roots)
        call emit('s0_tae_block_jvp'//suffix,[names,dn], &
            [character(8) :: 'dk11','dk22','dm11','dm12'],jt)
        call emit('s0_tae_block_vjp'//suffix,[names,sn],gn,va)
        call emit('s0_tae_edges'//suffix,[character(8) :: 'center','eps'], &
            [character(8) :: 'lower','upper'],[center/(1+eps),center/(1-eps)])
    end subroutine toroidal_continuum

    subroutine emit(name,args,outputs,roots)
        character(*), intent(in) :: name,args(:),outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_spec_t) :: spec
        type(expr_t) :: clean(size(roots))
        type(engine_result_t) :: simplified
        logical :: ok
        character(:), allocatable :: message
        integer :: j
        spec%name = str(name); spec%generator = str('gen_s0')
        spec%generator_revision = str(fortsym_revision)
        spec%regenerate_command = str('gen_s0 from pinned FortSym build')
        spec%pure_procedure = .true.; spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        allocate(spec%args(size(args)),spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
            simplified = engine%simplify(roots(j))
            if (.not. simplified%ok) error stop 'S0 simplification failed'
            clean(j) = simplified%value
        end do
        spec%precision = precision
        write(unit,'(a)') chars(emit_kernel(clean,spec,ok,message=message))
        if (.not. ok) error stop message
    end subroutine emit
end program gen_s0
