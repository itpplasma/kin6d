program gen_jellium_cell
    use fortsym_expr, only: expr_t, sym, sin, cos, exp, operator(+), &
                            operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: fk, fq, ek, eq, chi0, coefficient, cellsum, energy, ground
    type(expr_t) :: beta, mu, q, ra, rb, value, ns, nsp, overlap, volume
    type(expr_t) :: cr, ci, time, weight, slope, emean, smean, count, xx

    fk = sym('fk'); fq = sym('fq')
    ek = sym('ek'); eq = sym('eq')
    chi0 = sym('chi0'); coefficient = sym('coefficient')
    cellsum = sym('cellsum'); energy = sym('energy')
    ground = sym('ground'); beta = sym('beta'); mu = sym('mu')
    q = sym('q'); ra = sym('ra'); rb = sym('rb')
    value = sym('value'); ns = sym('ns'); nsp = sym('nsp')
    overlap = sym('overlap'); volume = sym('volume')
    cr = sym('cr'); ci = sym('ci'); time = sym('time')
    weight = sym('weight'); slope = sym('slope')
    emean = sym('emean'); smean = sym('smean')
    count = sym('count'); xx = sym('x')
    call w%open('gen_jellium_cell', 'src/generated/kin6d_jellium_cell_leaves.f90')
    call w%line('! Generated by gen/gen_jellium_cell.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Interacting periodic jellium cell observables (consumer of the Fock')
    call w%line('! engine). Static response per volume: chi=(2/V) d<A>/d lambda for')
    call w%line('! H+lambda*integral(cos(q.x) n), A=integral(cos(q.x) n).')
    call w%line('! Lindhard cell sum S0=sum_k,s (f_k-f_k+q)/(e_k-e_k+q), chi0=S0/V;')
    call w%line('! RPA chi=chi0/(1-c S0), c=4 pi g/(V q^2) the jellium coefficient.')
    call w%line('! Radial shell kernel: average of exp(i q.r) over a ra<|r|<rb shell.')
    call w%line('module kin6d_jellium_cell_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('jc_lindhard_term', ['fk', 'fq', 'ek', 'eq'], ['term'], &
                [(fk - fq)/(ek - eq)], ad=.true.)
    call w%emit('jc_rpa', ['chi0       ', 'coefficient', 'cellsum    '], ['chi'], &
                [chi0/(1 - coefficient*cellsum)], ad=.true.)
    call w%emit('jc_boltzmann', ['energy', 'ground', 'beta  '], ['weight'], &
                [exp(-beta*(energy - ground))], ad=.true.)
    call w%emit('jc_fermi', ['energy', 'mu    ', 'beta  '], ['occupation'], &
                [1/(1 + exp(beta*(energy - mu)))], ad=.true.)
    ! Shell average 3 (F(q rb) - F(q ra))/(q^3 (rb^3 - ra^3)), F(x) = sin x - x cos x;
    ! the Taylor form of F (through x^9, relative remainder < x^8/4e6) avoids
    ! cancellation for x < 0.1.
    call w%emit('jc_shell_moment', ['x'], ['moment'], [sin(xx) - xx*cos(xx)], ad=.true.)
    call w%emit('jc_shell_moment_series', ['x'], ['moment'], &
                [xx**3/3 - xx**5/30 + xx**7/840 - xx**9/45360], ad=.true.)
    call w%emit('jc_shell_average', ['fa', 'fb', 'q ', 'ra', 'rb'], ['kernel'], &
                [3*(sym('fb') - sym('fa'))/(q**3*(rb**3 - ra**3))], &
                ad=.true.)
    call w%emit('jc_pair_correlation', ['value', 'ns   ', 'nsp  '], ['g'], &
                [value/(ns*nsp)], ad=.true.)
    call w%emit('jc_susceptibility', ['overlap', 'volume '], ['chi'], &
                [-4*overlap/volume], ad=.true.)
    call w%emit('jc_half', ['value'], ['half'], [value/2], interval=.true.)
    call w%emit('jc_kick_response', ['cr    ', 'ci    ', 'energy', 'time  '], &
                ['response'], [2*(sin(energy*time)*cr + cos(energy*time)*ci)], &
                ad=.true.)
    call w%emit('jc_thermal_term', ['weight', 'energy', 'slope ', 'emean ', &
                                    'smean ', 'beta  '], ['term'], &
                [weight*(slope - beta*(energy - emean)*(slope - smean))], ad=.true.)
    call w%emit('jc_truncation', ['count ', 'energy', 'ground', 'beta  '], &
                ['weight'], [count*exp(-beta*(energy - ground))], interval=.true.)
    call w%line('end module kin6d_jellium_cell_leaves')
    call w%close()
end program gen_jellium_cell
