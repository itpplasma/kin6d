program gen_poisson
    ! Normalized slab: x in [0,2*pi], v in [-1,1], q=m=epsilon0=1.
    ! k fixed positive integer; nu,beta>=0; theta>0; nu+3*beta*theta>0.
    ! |drive/(nu+3*beta*theta)|<1.
    ! B=3(1-v^2)/4 has unit density. Fixed neutralizing charge has rho=-1.
    ! f=B(1+a*cos(k*x)); zero Dirichlet velocity data; open heat bath.
    ! C=beta*d_v(v*f+theta*d_v f), plus optional Krook -nu*(f-B).
    ! Source contains the exact quadratic E*d_v f harmonic at 2*k.
    ! The direct solver uses the cosine source moment drive, not reference a.
    ! No whole-line tail, closed-system invariant, or general uniqueness claim.
    ! Physical derivatives fix k; generated k partials are algebraic extensions.
    ! Smooth parameter domain has nu+3*beta*theta>0 and |a|<1; beta=0 is a limit.
    use fortsym, only: arena_t, expr_t, sym, num, operator(+), operator(-), &
                       operator(*), operator(/), operator(**), cos, sin
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use kin6d_gen_support, only: leaf_writer_t
    use kin6d_symbolic_physics, only: modal_poisson
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: k, eps, rc, rs, pc, ps, ec, es, x, v, a, nu, drive, source
    type(expr_t) :: da, dp, de, base, primitive, mass, f, exact, electric, forcing
    type(expr_t) :: beta, theta, denominator, collision, exact_collision
    call arena%init()
    k = sym(arena, 'k'); eps = sym(arena, 'eps')
    rc = sym(arena, 'rc'); rs = sym(arena, 'rs')
    pc = sym(arena, 'pc'); ps = sym(arena, 'ps')
    ec = sym(arena, 'ec'); es = sym(arena, 'es')
    x = sym(arena, 'x'); v = sym(arena, 'v'); a = sym(arena, 'a')
    nu = sym(arena, 'nu'); drive = sym(arena, 'drive')
    beta = sym(arena, 'beta'); theta = sym(arena, 'theta')
    source = sym(arena, 'source')
    da = sym(arena, 'da'); dp = sym(arena, 'dp'); de = sym(arena, 'de')
    base = 3*(1 - v**2)/4
    primitive = 3*(v - v**3/3)/4
    mass = subs(primitive, v, num(arena, 1)) - &
           subs(primitive, v, num(arena, -1))
    f = base*(1 + a*cos(k*x))
    denominator = nu + 3*beta*theta
    exact = subs(f, a, drive/denominator)
    electric = drive/(denominator*k)*sin(k*x)
    collision = beta*diff(v*f + theta*diff(f, v), v)
    exact_collision = subs(collision, a, drive/denominator)
    forcing = v*diff(exact, x) + electric*diff(exact, v) + nu*(exact - base) &
              - exact_collision
    call w%open(arena, 'gen_poisson', 'src/generated/kin6d_poisson_leaves.f90')
    call w%line('! Generated by gen/gen_poisson.f90; do not edit.')
    call w%line('module kin6d_poisson_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('poisson_coefficients', ['k  ', 'eps', 'rc ', 'rs '], &
              ['pc', 'ps', 'ec', 'es'], modal_poisson(eps, k, rc, rs), ad=.true.)
    call w%emit('poisson_coefficients_interval', ['k  ', 'eps', 'rc ', 'rs '], &
              ['pc', 'ps', 'ec', 'es'], modal_poisson(eps, k, rc, rs), &
              rigorous=.true.)
    call w%emit('poisson_reconstruct', ['k ', 'pc', 'ps', 'ec', 'es', 'x '], &
              ['potential', 'electric '], &
              [pc*cos(k*x) + ps*sin(k*x), ec*cos(k*x) + es*sin(k*x)], ad=.true.)
    call w%emit('poisson_reconstruct_interval', &
              ['k ', 'pc', 'ps', 'ec', 'es', 'x '], ['potential', 'electric '], &
              [pc*cos(k*x) + ps*sin(k*x), ec*cos(k*x) + es*sin(k*x)], &
              rigorous=.true.)
    call w%emit('poisson_energy_interval', ['k  ', 'eps', 'rc ', 'rs '], &
              ['energy'], [(rc**2 + rs**2)/(4*eps*k**2)], rigorous=.true.)
    call w%emit('coupled_denominator', ['nu   ', 'beta ', 'theta'], ['value'], &
              [denominator], ad=.true.)
    call w%emit('coupled_amplitude', ['drive', 'nu   ', 'beta ', 'theta'], ['a'], &
              [drive/denominator], ad=.true.)
    call w%emit('coupled_amplitude_interval', ['drive', 'nu   ', 'beta ', 'theta'], &
              ['a'], [drive/denominator], rigorous=.true.)
    call w%emit('coupled_density', ['a'], ['mean  ', 'cosine'], [mass, mass*a], ad=.true.)
    call w%emit('coupled_distribution', ['a', 'k', 'x', 'v'], ['value'], [f], ad=.true.)
    call w%emit('coupled_distribution_interval', ['a', 'k', 'x', 'v'], &
              ['value'], [f], rigorous=.true.)
    call w%emit('coupled_reference_value', &
              ['drive', 'nu   ', 'beta ', 'theta', 'k    ', 'x    ', 'v    '], &
              ['distribution', 'electric    ', 'potential   '], &
              [exact, electric, drive/(denominator*k**2)*cos(k*x)], ad=.true.)
    call w%emit('coupled_collision', ['a    ', 'k    ', 'x    ', 'v    ', &
                                    'beta ', 'theta'], ['value'], [collision], ad=.true.)
    call w%emit('coupled_source', ['drive', 'nu   ', 'k    ', 'x    ', 'v    ', &
                                 'beta ', 'theta'], &
              ['source'], [forcing], ad=.true.)
    call w%emit('coupled_residual', &
              ['a     ', 'k     ', 'nu    ', 'x     ', 'v     ', 'ec    ', &
               'es    ', 'source', 'beta  ', 'theta '], ['residual'], &
              [v*diff(f, x) + (ec*cos(k*x) + es*sin(k*x))*diff(f, v) + &
               nu*(f - base) - collision - source], ad=.true.)
    ! Uniform bounds: B<=3/4, |sin|,|cos|<=1 on the entire declared domain.
    call w%emit('coupled_radius_interval', ['da', 'dp', 'de'], &
              ['distribution', 'potential   ', 'electric    '], &
              [3*da/4, dp, de], rigorous=.true.)
    call w%emit('difference_interval', ['a', 'v'], ['difference'], [a - v], &
              rigorous=.true.)
    call w%emit('sum_interval', ['a', 'v'], ['total'], [a + v], rigorous=.true.)
    call w%line('end module kin6d_poisson_leaves')
    call w%close()
end program
