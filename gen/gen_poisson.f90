program gen_poisson
    ! Normalized slab: x in [0,2*pi], v in [-1,1], q=m=epsilon0=1.
    ! k fixed positive integer; nu,beta>=0; theta>0; nu+3*beta*theta>0.
    ! |drive/(nu+3*beta*theta)|<1.
    ! B=3(1-v^2)/4 has unit density. Fixed neutralizing charge has rho=-1.
    ! f=B(1+a*cos(k*x)); zero Dirichlet velocity data; open heat bath.
    ! C=beta*d_v(v*f+theta*d_v f), plus optional Krook -nu*(f-B).
    ! Source contains the exact quadratic E*d_v f harmonic at 2*k.
    ! The direct solver uses the cosine source moment drive, not reference a.
    ! No whole-line tail, closed-system invariant, or general uniqueness claim.
    ! Physical derivatives fix k; generated k partials are algebraic extensions.
    ! Smooth parameter domain has nu+3*beta*theta>0 and |a|<1; beta=0 is a limit.
    use fortsym, only: arena_t, expr_t, sym, num, operator(+), operator(-), &
                       operator(*), operator(/), operator(**), cos, sin
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_string, only: str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    type(arena_t), target :: arena
    type(expr_t) :: k, eps, rc, rs, pc, ps, ec, es, x, v, a, nu, drive, source
    type(expr_t) :: da, dp, de, base, primitive, mass, f, exact, electric, forcing
    type(expr_t) :: beta, theta, denominator, collision, exact_collision
    integer :: unit
    call arena%init()
    k = sym(arena, 'k'); eps = sym(arena, 'eps')
    rc = sym(arena, 'rc'); rs = sym(arena, 'rs')
    pc = sym(arena, 'pc'); ps = sym(arena, 'ps')
    ec = sym(arena, 'ec'); es = sym(arena, 'es')
    x = sym(arena, 'x'); v = sym(arena, 'v'); a = sym(arena, 'a')
    nu = sym(arena, 'nu'); drive = sym(arena, 'drive')
    beta = sym(arena, 'beta'); theta = sym(arena, 'theta')
    source = sym(arena, 'source')
    da = sym(arena, 'da'); dp = sym(arena, 'dp'); de = sym(arena, 'de')
    base = 3*(1 - v**2)/4
    primitive = 3*(v - v**3/3)/4
    mass = subs(primitive, v, num(arena, 1)) - &
           subs(primitive, v, num(arena, -1))
    f = base*(1 + a*cos(k*x))
    denominator = nu + 3*beta*theta
    exact = subs(f, a, drive/denominator)
    electric = drive/(denominator*k)*sin(k*x)
    collision = beta*diff(v*f + theta*diff(f, v), v)
    exact_collision = subs(collision, a, drive/denominator)
    forcing = v*diff(exact, x) + electric*diff(exact, v) + nu*(exact - base) &
              - exact_collision
    open (newunit=unit, file='src/generated/kin6d_poisson_leaves.f90', &
          status='replace')
    write (unit, '(a)') '! Generated by gen/gen_poisson.f90; do not edit.'
    write (unit, '(a)') 'module kin6d_poisson_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('poisson_coefficients', ['k  ', 'eps', 'rc ', 'rs '], &
              ['pc', 'ps', 'ec', 'es'], &
              [rc/(eps*k**2), rs/(eps*k**2), -rs/(eps*k), rc/(eps*k)])
    call emit('poisson_coefficients_interval', ['k  ', 'eps', 'rc ', 'rs '], &
              ['pc', 'ps', 'ec', 'es'], &
              [rc/(eps*k**2), rs/(eps*k**2), -rs/(eps*k), rc/(eps*k)], &
              rigorous=.true.)
    call emit('poisson_reconstruct', ['k ', 'pc', 'ps', 'ec', 'es', 'x '], &
              ['potential', 'electric '], &
              [pc*cos(k*x) + ps*sin(k*x), ec*cos(k*x) + es*sin(k*x)])
    call emit('poisson_reconstruct_interval', &
              ['k ', 'pc', 'ps', 'ec', 'es', 'x '], ['potential', 'electric '], &
              [pc*cos(k*x) + ps*sin(k*x), ec*cos(k*x) + es*sin(k*x)], &
              rigorous=.true.)
    call emit('poisson_energy_interval', ['k  ', 'eps', 'rc ', 'rs '], &
              ['energy'], [(rc**2 + rs**2)/(4*eps*k**2)], rigorous=.true.)
    call emit('coupled_denominator', ['nu   ', 'beta ', 'theta'], ['value'], &
              [denominator])
    call emit('coupled_amplitude', ['drive', 'nu   ', 'beta ', 'theta'], ['a'], &
              [drive/denominator])
    call emit('coupled_amplitude_interval', ['drive', 'nu   ', 'beta ', 'theta'], &
              ['a'], [drive/denominator], rigorous=.true.)
    call emit('coupled_density', ['a'], ['mean  ', 'cosine'], [mass, mass*a])
    call emit('coupled_distribution', ['a', 'k', 'x', 'v'], ['value'], [f])
    call emit('coupled_distribution_interval', ['a', 'k', 'x', 'v'], &
              ['value'], [f], rigorous=.true.)
    call emit('coupled_reference_value', &
              ['drive', 'nu   ', 'beta ', 'theta', 'k    ', 'x    ', 'v    '], &
              ['distribution', 'electric    ', 'potential   '], &
              [exact, electric, drive/(denominator*k**2)*cos(k*x)])
    call emit('coupled_collision', ['a    ', 'k    ', 'x    ', 'v    ', &
                                    'beta ', 'theta'], ['value'], [collision])
    call emit('coupled_source', ['drive', 'nu   ', 'k    ', 'x    ', 'v    ', &
                                 'beta ', 'theta'], &
              ['source'], [forcing])
    call emit('coupled_residual', &
              ['a     ', 'k     ', 'nu    ', 'x     ', 'v     ', 'ec    ', &
               'es    ', 'source', 'beta  ', 'theta '], ['residual'], &
              [v*diff(f, x) + (ec*cos(k*x) + es*sin(k*x))*diff(f, v) + &
               nu*(f - base) - collision - source])
    ! Uniform bounds: B<=3/4, |sin|,|cos|<=1 on the entire declared domain.
    call emit('coupled_radius_interval', ['da', 'dp', 'de'], &
              ['distribution', 'potential   ', 'electric    '], &
              [3*da/4, dp, de], rigorous=.true.)
    call emit('difference_interval', ['a', 'v'], ['difference'], [a - v], &
              rigorous=.true.)
    call emit('sum_interval', ['a', 'v'], ['total'], [a + v], rigorous=.true.)
    write (unit, '(a)') 'end module kin6d_poisson_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, roots, rigorous, derived)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: rigorous, derived
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        logical :: ok
        character(:), allocatable :: message
        integer :: i
        if (present(rigorous)) then
            rspec%name = str(name); rspec%generator = str('gen_poisson')
            rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
            rspec%runtime%sin = str('sin'); rspec%runtime%cos = str('cos')
            allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
            do i = 1, size(args)
                rspec%args(i) = str(trim(args(i)))
            end do
            do i = 1, size(outputs)
                rspec%outputs(i) = str(trim(outputs(i)))
            end do
            write (unit, '(a)') chars(emit_rigorous_kernel(roots, rspec, ok, message))
            if (.not. ok) error stop message
            return
        end if
        spec%name = str(name); spec%generator = str('gen_poisson')
        spec%generator_revision = str('549aed77be10297beb80d602d714d30166fbeb08')
        spec%pure_procedure = .true.; spec%elemental_procedure = .true.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do i = 1, size(args)
            spec%args(i) = str(trim(args(i)))
        end do
        do i = 1, size(outputs)
            spec%outputs(i) = str(trim(outputs(i)))
        end do
        write (unit, '(a)') chars(emit_kernel(roots, spec, ok, message=message))
        if (.not. ok) error stop message
        if (present(derived)) return
        call emit_derivatives(name, args, outputs, roots)
    end subroutine

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: jroots(:), vroots(:), parameters(:)
        character(64), allocatable :: jargs(:), jouts(:), vargs(:), vouts(:)
        integer :: i, j, narg, nout
        narg = size(args); nout = size(outputs)
        allocate (parameters(narg), jroots(nout), vroots(narg))
        allocate (jargs(2*narg), jouts(nout), vargs(narg + nout), vouts(narg))
        do i = 1, narg
            parameters(i) = sym(arena, trim(args(i)))
            jargs(i) = trim(args(i)); jargs(narg + i) = 'd_'//trim(args(i))
            vargs(i) = trim(args(i)); vouts(i) = 'g_'//trim(args(i))
        end do
        do j = 1, nout
            jouts(j) = 'd_'//trim(outputs(j))
            vargs(narg + j) = 'w_'//trim(outputs(j))
            jroots(j) = 0*roots(j)
            do i = 1, narg
                jroots(j) = jroots(j) + diff(roots(j), parameters(i))* &
                            sym(arena, trim(jargs(narg + i)))
            end do
        end do
        do i = 1, narg
            vroots(i) = 0*roots(1)
            do j = 1, nout
                vroots(i) = vroots(i) + diff(roots(j), parameters(i))* &
                            sym(arena, trim(vargs(narg + j)))
            end do
        end do
        call emit(name//'_jvp', jargs, jouts, jroots, derived=.true.)
        call emit(name//'_vjp', vargs, vouts, vroots, derived=.true.)
    end subroutine
end program
