program gen_equilibrium_core
    ! Leaves of the common equilibrium core (docs/equilibrium-core.md).
    ! Chart (D1): the cylindrical chart X = H(q), q = (R, Z, phi),
    ! X = (R cos phi, R sin phi, Z), with its first, second and third
    ! q-derivatives d1(a,k) = dH_a/dq_k, d2(a,k,l), d3(a,k,l,m).
    ! Residual (D3): the weak Maxwell-stress form of an axisymmetric state
    ! against an axisymmetric displacement xi = (xi_R, 0, xi_Z),
    !   R[xi] = int (B.grad xi.B/mu0 - (B^2/(2 mu0) + p) div xi) dV,
    ! with the curl-free background B0 = F0/R e_phi removed analytically
    ! (T(B) - T(B0)). The leaf returns the coefficients per dR dZ (the 2 pi
    ! of dV stays with the caller) of the jet (xi_R, d_R xi_R, d_Z xi_R,
    ! d_R xi_Z, d_Z xi_Z). Proved here: for B = grad psi x grad phi +
    ! F(psi) grad phi and p(psi) the Euler-Lagrange form of these
    ! coefficients is the Grad-Shafranov residual times grad psi/(mu0 R).
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sin, cos, operator(+), operator(*), &
        operator(-), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(expr_t) :: q(3), x(3), dx(9), d2x(27), d3x(81)
    type(expr_t) :: r, br, bz, bphi, b0, p, mu0, jet(5), density, coefficient(5)
    type(expr_t) :: b2, divergence, stress, gs(5), psi_r, psi_z, psi_rr, psi_rz
    type(expr_t) :: psi_zz, f, fp, f0, pp, residual
    character(8) :: names9(9), names27(27), names81(81)
    character(8), parameter :: jet_names(5) = [character(8) :: 'cxr', 'cxr_r', &
        'cxr_z', 'cxz_r', 'cxz_z']
    integer :: a, j, k, l, m
    call arena%init()
    engine = make_native_engine(arena)
    q(1) = sym(arena, 'q1'); q(2) = sym(arena, 'q2'); q(3) = sym(arena, 'q3')
    x = [q(1)*cos(q(3)), q(1)*sin(q(3)), q(2)]
    do k = 1, 3
        do a = 1, 3
            write (names9(a + 3*(k - 1)), '(a,2i1)') 'c', a, k
            dx(a + 3*(k - 1)) = diff(x(a), q(k))
            do l = 1, 3
                m = a + 3*(k - 1) + 9*(l - 1)
                write (names27(m), '(a,3i1)') 'e', a, k, l
                d2x(m) = diff(dx(a + 3*(k - 1)), q(l))
                do j = 1, 3
                    write (names81(m + 27*(j - 1)), '(a,4i1)') 't', a, k, l, j
                    d3x(m + 27*(j - 1)) = diff(d2x(m), q(j))
                end do
            end do
        end do
    end do
    r = sym(arena, 'r'); br = sym(arena, 'br'); bz = sym(arena, 'bz')
    bphi = sym(arena, 'bphi'); b0 = sym(arena, 'b0'); p = sym(arena, 'p')
    mu0 = sym(arena, 'mu0')
    jet = [sym(arena, 'xr'), sym(arena, 'xr_r'), sym(arena, 'xr_z'), &
        sym(arena, 'xz_r'), sym(arena, 'xz_z')]
    b2 = br**2 + bz**2 + bphi**2 - b0**2
    divergence = jet(2) + jet(1)/r + jet(5)
    stress = (br**2*jet(2) + br*bz*(jet(4) + jet(3)) + bz**2*jet(5) &
        + (bphi**2 - b0**2)*jet(1)/r)/mu0
    density = r*(stress - (b2/(2*mu0) + p)*divergence)
    do j = 1, 5
        coefficient(j) = diff(density, jet(j))
    end do
    ! Euler-Lagrange form with B, p from a flux psi(R, Z): D_R and D_Z are
    ! total derivatives through the psi jet, F(psi) and p(psi).
    psi_r = sym(arena, 'psi_r'); psi_z = sym(arena, 'psi_z')
    psi_rr = sym(arena, 'psi_rr'); psi_rz = sym(arena, 'psi_rz')
    psi_zz = sym(arena, 'psi_zz'); f = sym(arena, 'f'); fp = sym(arena, 'fp')
    f0 = sym(arena, 'f0'); pp = sym(arena, 'pp')
    do j = 1, 5
        gs(j) = substitute(coefficient(j))
    end do
    residual = psi_rr - psi_r/r + psi_zz + mu0*r**2*pp + f*fp
    identity = engine%zero_test(gs(1) - total_r(gs(2)) - total_z(gs(3)) &
        - psi_r*residual/(mu0*r))
    if (identity%verdict /= VERDICT_TRUE) error stop 'stress residual R unproved'
    identity = engine%zero_test(0*r - total_r(gs(4)) - total_z(gs(5)) &
        - psi_z*residual/(mu0*r))
    if (identity%verdict /= VERDICT_TRUE) error stop 'stress residual Z unproved'
    call w%open(arena, 'gen_equilibrium_core', &
        'src/generated/kin6d_equilibrium_core_leaves.f90')
    call w%line('! Generated by gen/gen_equilibrium_core.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_equilibrium_core_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('cylindrical_chart_position', ['q1', 'q2', 'q3'], &
        ['x1', 'x2', 'x3'], x)
    call w%emit('cylindrical_chart_first', ['q1', 'q2', 'q3'], names9, dx)
    call w%emit('cylindrical_chart_second', ['q1', 'q2', 'q3'], names27, d2x)
    call w%emit('cylindrical_chart_third', ['q1', 'q2', 'q3'], names81, d3x)
    call w%emit('stress_residual_density', [character(8) :: 'r', 'br', 'bz', &
        'bphi', 'b0', 'p', 'mu0'], jet_names, coefficient)
    call w%line('end module kin6d_equilibrium_core_leaves')
    call w%close()
contains
    function substitute(e) result(value)
        ! B = grad psi x grad phi + F grad phi, B0 = F0 grad phi.
        type(expr_t), intent(in) :: e
        type(expr_t) :: value
        value = subs(subs(subs(subs(e, br, 0 - psi_z/r), bz, psi_r/r), bphi, &
            f/r), b0, f0/r)
    end function

    function total_r(e) result(value)
        type(expr_t), intent(in) :: e
        type(expr_t) :: value
        value = diff(e, r) + psi_rr*diff(e, psi_r) + psi_rz*diff(e, psi_z) &
            + psi_r*(fp*diff(e, f) + pp*diff(e, p))
    end function

    function total_z(e) result(value)
        type(expr_t), intent(in) :: e
        type(expr_t) :: value
        value = psi_rz*diff(e, psi_r) + psi_zz*diff(e, psi_z) &
            + psi_z*(fp*diff(e, f) + pp*diff(e, p))
    end function
end program gen_equilibrium_core
