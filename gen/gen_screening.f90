program gen_screening
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, exp, log, sin, abs, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: x, y, u, r, occ, e, mu, theta, z, s, wt, f0, q, kappa2, g
    type(expr_t) :: radius, smax, qmax, ks, inner, outer
    integer :: n

    call arena%init()
    x = sym(arena, 'x'); y = sym(arena, 'y'); r = sym(arena, 'r')
    occ = sym(arena, 'occupation'); e = sym(arena, 'e'); mu = sym(arena, 'mu')
    theta = sym(arena, 'theta'); s = sym(arena, 's'); wt = sym(arena, 'weight')
    f0 = sym(arena, 'f0'); q = sym(arena, 'q'); kappa2 = sym(arena, 'kappa2')
    g = sym(arena, 'g'); radius = sym(arena, 'radius'); smax = sym(arena, 'smax')
    qmax = sym(arena, 'qmax'); ks = sym(arena, 'ks')

    call w%open(arena, 'gen_screening', 'src/generated/kin6d_screening_leaves.f90')
    call w%line('! Generated by gen/gen_screening.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Static ideal-gas (RPA, no local-field correction) Lindhard response')
    call w%line('! of a 3D spin-two electron gas. Units: kF = 1, EF = 1, x = q/(2 kF).')
    call w%line('! G(x) = -chi0(q)/N(0), N(0) = m kF/(pi^2 hbar^2). T=0: G = F(x).')
    call w%line('! eps(q) = 1 + kappa2 G(q/2)/q^2, kappa2 = (kTF0/kF)^2.')
    call w%line('! phi/phi_bare = 1 - integral_0^inf potential_term dq.')
    call w%line('module kin6d_screening_leaves')
    call w%line('implicit none')
    call w%line('contains')
    ! T=0 Lindhard function, two log charts without abs and two series charts.
    ! F = 1 - sum_{n>=1} x^(2n)/((2n-1)(2n+1)) for x<1;
    ! F = sum_{n>=0} y^(-2n-2)/((2n+1)(2n+3)) for y>1.
    call w%emit('screening_lindhard_inner', ['x'], ['f'], &
        [(2*x + (1 - x**2)*log((1 + x)/(1 - x)))/(4*x)], ad=.true.)
    call w%emit('screening_lindhard_outer', ['x'], ['f'], &
        [(2*x + (1 - x**2)*log((x + 1)/(x - 1)))/(4*x)], ad=.true.)
    inner = 1 + 0*x
    do n = 1, 10
        inner = inner - x**(2*n)/((2*n - 1)*(2*n + 1))
    end do
    call w%emit('screening_lindhard_small', ['x'], ['f'], [inner], ad=.true.)
    u = 1/y**2
    outer = 0*y
    do n = 0, 10
        outer = outer + u**(n + 1)/((2*n + 1)*(2*n + 3))
    end do
    call w%emit('screening_lindhard_large', ['y'], ['f'], [outer], ad=.true.)
    ! Momentum route: G = integral_0^inf r f(r) log|(r+x)/(r-x)| dr/(2x).
    call w%emit('screening_momentum_below', [character(10) :: 'r', 'x', &
        'occupation'], ['value'], [r*occ*log((x + r)/(x - r))/(2*x)])
    call w%emit('screening_momentum_above', [character(10) :: 'r', 'x', &
        'occupation'], ['value'], [r*occ*log((r + x)/(r - x))/(2*x)])
    ! Maldague route: G = integral_0^inf w(e) sqrt(e) F(x/sqrt(e)) de with
    ! w = -df/de = 1/(4 theta cosh^2((e-mu)/(2 theta))); e = s^2.
    z = abs(e - mu)/theta
    call w%emit('screening_maldague_weight', ['e    ', 'mu   ', 'theta'], &
        ['weight'], [exp(-z)/(theta*(1 + exp(-z))**2)])
    call w%emit('screening_maldague_term', ['s     ', 'weight', 'f0    '], &
        ['value'], [2*s**2*f0*wt])
    call w%emit('screening_dielectric', ['q     ', 'kappa2', 'g     '], ['eps'], &
        [1 + kappa2*g/q**2], ad=.true.)
    call w%emit('screening_potential_term', ['q     ', 'r     ', 'kappa2', 'g     '], &
        ['value'], [2*sin(q*r)*kappa2*g/(pi_expr(arena)*q*(q**2 + kappa2*g))], &
        ad=.true.)
    call w%emit('screening_yukawa', ['r ', 'ks'], ['ratio'], [exp(-ks*r)], ad=.true.)
    ! Rigorous truncation bounds (proofs in docs/screening-wigner.md).
    ! Momentum tail, R >= 2x: f <= exp((mu-r^2)/theta), log(..) <= 4x/r.
    call w%emit('screening_momentum_tail_interval', ['theta ', 'mu    ', 'radius'], &
        ['bound'], [theta*exp((mu - radius**2)/theta)/radius], rigorous=.true.)
    ! Maldague tail, smax^2 > mu: w <= exp(-(e-mu)/theta)/theta, F <= 1.
    call w%emit('screening_maldague_tail_interval', ['theta', 'mu   ', 'smax '], &
        ['bound'], [exp((mu - smax**2)/theta)*(smax + theta/(2*smax))], &
        rigorous=.true.)
    ! Inversion tail: G(q/2) <= 8/(3 q^2) for every theta (kF = 1).
    call w%emit('screening_inversion_tail_interval', ['kappa2', 'qmax  '], &
        ['bound'], [4*kappa2/(3*pi_expr(arena)*qmax**4)], rigorous=.true.)
    call w%line('end module kin6d_screening_leaves')
    call w%close()
end program gen_screening
