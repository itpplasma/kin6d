program gen_vrmhd_mms
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, sin, cos, operator(+), &
        operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs_many
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(symengine_engine_t) :: engine
    type(leaf_writer_t) :: w
    type(expr_t) :: xyz(3), x, y, k, q1, q2, ct, st, radius, zero, one
    type(expr_t) :: u(36), force(12), roots(48), a(3), b(3), jv(3), v(3), xi(3), aa
    type(expr_t) :: rho, te, ti, number, pressure, eta, nu, chi(2), stress(3, 3), &
        gv(3, 3)
    type(expr_t) :: strain(3, 3), unitb(3), flux(3), mom(3, 3), divv, heat(2), &
        temperature
    type(expr_t) :: section_a(3), local_v(3), normalization
    type(engine_result_t) :: simplified
    character(16) :: names(48), suffix, index_text
    integer :: kind, i, l, s
    call arena%init(); engine = make_symengine_engine(arena)
    zero = rat(arena, 0_int64, 1_int64); one = rat(arena, 1_int64, 1_int64)
    x = sym(arena, 'x'); y = sym(arena, 'y'); k = sym(arena, 'k')
    xyz = [sym(arena, 'xx'), sym(arena, 'yy'), sym(arena, 'zz')]
    do i = 1, 48
        write (names(i), '(a,i0)') 'out', i
    end do
    call w%open(arena, 'gen_vrmhd_mms', 'test/support/vrmhd_mms_leaves.f90')
    call w%line('! Generated by gen/gen_vrmhd_mms.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module vrmhd_mms_leaves')
    call w%line('implicit none')
    call w%line('contains')
    do kind = 1, 2
        if (kind == 1) then
            suffix = 'rotation'
            radius = (xyz(1)**2 + xyz(2)**2)**rat(arena, 1_int64, 2_int64)
            q1 = radius; q2 = xyz(3); ct = xyz(1)/radius; st = xyz(2)/radius
            xi = [zero, radius, zero]
        else
            suffix = 'screw'
            ct = cos(k*xyz(3)); st = sin(k*xyz(3))
            q1 = ct*xyz(1) + st*xyz(2); q2 = -st*xyz(1) + ct*xyz(2)
            xi = [-k*q2, k*q1, one]
        end if
        rho = 2 + sin(q1)*cos(q2)/10
        te = one + sin(q1)*sin(q2)/10; ti = one + cos(q1)*sin(q2)/10
        local_v = [sin(q1)*cos(q2)/10, cos(q1)*sin(q2)/10, &
            one/5 + cos(q1 + q2)/20]
        v = rotate(local_v)
        aa = one + cos(q1)*cos(q2)/10
        if (kind == 1) then
            section_a = [sin(q1 + q2)/10, aa/q1, cos(q1 - q2)/10]
        else
            section_a = [sin(q1 + q2)/10, cos(q1 - q2)/10, &
                k*(q2*sin(q1 + q2) - q1*cos(q1 - q2))/10]
            do i = 1, 3
                section_a(i) = section_a(i) + aa*xi(i)/(one + k*k*(q1*q1 + q2*q2))
            end do
        end if
        a = rotate(section_a); b = curl(a); jv = curl(b)
        number = rho; pressure = number*(te + ti)
        eta = te**rat(arena, -3_int64, 2_int64)/5
        nu = ti**rat(arena, -3_int64, 2_int64)/5
        chi = [te**rat(arena, 5_int64, 2_int64)/5, ti**rat(arena, 5_int64, 2_int64)/5]
        do l = 1, 3
            do i = 1, 3
                gv(i, l) = diff(v(i), xyz(l))
                mom(i, l) = rho*v(i)*v(l)
            end do
        end do
        divv = gv(1, 1) + gv(2, 2) + gv(3, 3)
        do l = 1, 3
            do i = 1, 3
                strain(i, l) = (gv(i, l) + gv(l, i))/2
                if (i == l) strain(i, l) = strain(i, l) - divv/3
                stress(i, l) = 2*nu*strain(i, l)
            end do
        end do
        normalization = (b(1)**2 + b(2)**2 + b(3)**2 + one/100)**rat(arena, &
            1_int64, 2_int64)
        do i = 1, 3
            unitb(i) = b(i)/normalization
            flux(i) = rho*v(i) - diff(rho, xyz(i))/10
        end do
        force(1) = divergence(flux)
        force(2:4) = cross(jv, b)
        force(5:7) = cross(v, b)
        do i = 2, 7
            force(i) = -force(i)
        end do
        do i = 1, 3
            force(1 + i) = force(1 + i) + diff(pressure, xyz(i))
            force(4 + i) = force(4 + i) + eta*jv(i)
            do l = 1, 3
                force(1 + i) = force(1 + i) + diff(mom(i, l) - stress(i, l), xyz(l))
            end do
        end do
        force(8:10) = zero
        heat(1) = eta*(jv(1)**2 + jv(2)**2 + jv(3)**2)
        heat(2) = zero
        do l = 1, 3
            do i = 1, 3
                heat(2) = heat(2) + stress(i, l)*gv(i, l)
            end do
        end do
        do s = 1, 2
            temperature = te
            if (s == 2) temperature = ti
            flux = gradient(temperature)
            aa = unitb(1)*flux(1) + unitb(2)*flux(2) + unitb(3)*flux(3)
            do i = 1, 3
                flux(i) = 3*number*temperature*v(i)/2 &
                    - number*(flux(i)/20 + (chi(s) - one/20)*unitb(i)*aa)
            end do
            force(10 + s) = divergence(flux) + number*temperature*divv - heat(s)
        end do
        u(1) = rho; u(2:4) = v; u(5:7) = a; u(8:10) = jv
        u(11) = te; u(12) = ti; u(13:15) = gradient(rho)
        u(16:24) = reshape(gv, [9]); u(25:27) = b
        u(28:30) = gradient(te); u(31:33) = gradient(ti); u(34:36) = curl(jv)
        roots = [u, force]
        do i = 1, 48
            if (kind == 1) then
                roots(i) = subs_many(roots(i), xyz, [x, zero, y])
            else
                roots(i) = subs_many(roots(i), xyz, [x, y, zero])
            end if
            ! Thermal sources remain factored to avoid symbolic expansion.
            if (i < 47) then
                simplified = engine%simplify(roots(i)); roots(i) = simplified%value
            end if
            print '(a,2i4)', 'manufactured expression ', kind, i
        end do
        call w%emit('vrmhd_mms_'//trim(suffix), [character(16) :: 'x', 'y', 'k'], &
            names, roots)
        call w%line('subroutine mms_'//trim(suffix)//'(x,y,k,u)')
        call w%line('real(8), intent(in) :: x,y,k')
        call w%line('real(8), intent(out) :: u(48)')
        call w%line('call vrmhd_mms_'//trim(suffix)//'(x,y,k, &')
        do i = 1, 48
            write (index_text, '(i0)') i
            if (i < 48) then
                call w%line('u('//trim(index_text)//'), &')
            else
                call w%line('u('//trim(index_text)//'))')
            end if
        end do
        call w%line('end subroutine')
    end do
    call w%line('end module vrmhd_mms_leaves'); call w%close()
contains
    function rotate(local) result(global)
        type(expr_t), intent(in) :: local(3)
        type(expr_t) :: global(3)
        global = [ct*local(1) - st*local(2), st*local(1) + ct*local(2), local(3)]
    end function
    function gradient(f) result(g)
        type(expr_t), intent(in) :: f
        type(expr_t) :: g(3)
        integer :: j
        do j = 1, 3
            g(j) = diff(f, xyz(j))
        end do
    end function
    function divergence(v) result(d)
        type(expr_t), intent(in) :: v(3)
        type(expr_t) :: d
        d = diff(v(1), xyz(1)) + diff(v(2), xyz(2)) + diff(v(3), xyz(3))
    end function
    function curl(v) result(c)
        type(expr_t), intent(in) :: v(3)
        type(expr_t) :: c(3)
        c = [diff(v(3), xyz(2)) - diff(v(2), xyz(3)), &
            diff(v(1), xyz(3)) - diff(v(3), xyz(1)), &
            diff(v(2), xyz(1)) - diff(v(1), xyz(2))]
    end function
    function cross(a, b) result(c)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: c(3)
        c = [a(2)*b(3) - a(3)*b(2), a(3)*b(1) - a(1)*b(3), a(1)*b(2) - a(2)*b(1)]
    end function
end program gen_vrmhd_mms
