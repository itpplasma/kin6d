program gen_fermi_gas
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, exp, log, sqrt, abs, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(expr_t) :: r, theta, mu, z, occupation, fr, fm, ft, physical
    type(expr_t) :: moments(8), curvature(8), eof(6), gradient(6)
    type(expr_t) :: iv(8), dmu, directions(3), variables(3)
    type(expr_t) :: radius, tail2, tail4, tail6, factor, index, cells
    type(expr_t) :: acc, term, lower, upper, step, seed, g(6)
    type(expr_t) :: density, temperature, mass, hbar, kb, charge, epsilon
    type(expr_t) :: mass_density, electron_fraction, atomic_mass, speed
    type(expr_t) :: pf, ef, pressure, energy, susceptibility
    integer :: unit, j
    character(10), parameter :: names(8) = [character(10) :: &
        'i2', 'i4', 'i2mu', 'i2theta', 'i4mu', 'i4theta', 'i2mumu', 'i2mutheta']

    call arena%init()
    engine = make_native_engine(arena)
    r = sym(arena, 'r'); theta = sym(arena, 'theta'); mu = sym(arena, 'mu')
    z = sym(arena, 'z'); occupation = sym(arena, 'occupation')
    radius = sym(arena, 'radius'); index = sym(arena, 'index')
    cells = sym(arena, 'cells'); acc = sym(arena, 'acc'); term = sym(arena, 'term')
    lower = sym(arena, 'lower'); upper = sym(arena, 'upper')
    step = sym(arena, 'step'); seed = sym(arena, 'seed')
    ! Differential identities of the exact smooth Fermi occupation. Numerical
    ! evaluation uses two overflow-safe algebraic charts, not an abs-based AD.
    fr = -2*r/theta*occupation*(1 - occupation)
    fm = occupation*(1 - occupation)/theta
    ft = (r**2 - mu)/theta**2*occupation*(1 - occupation)
    physical = 1/(1 + exp((r**2 - mu)/theta))
    call prove(subs(fr, occupation, physical) - diff(physical, r))
    call prove(subs(fm, occupation, physical) - diff(physical, mu))
    call prove(subs(ft, occupation, physical) - diff(physical, theta))
    moments(1) = r**2*occupation
    moments(2) = r**4*occupation
    moments(3) = d_mu(moments(1)); moments(4) = d_theta(moments(1))
    moments(5) = d_mu(moments(2)); moments(6) = d_theta(moments(2))
    moments(7) = d_mu(moments(3)); moments(8) = d_theta(moments(3))
    do j = 1, 8
        curvature(j) = d_r(d_r(moments(j)))
        iv(j) = sym(arena, trim(names(j)))
    end do
    eof = [mu, 2*iv(2), 3*iv(2), 3*iv(3), sqrt(2*iv(3)), 1/(3*iv(3))]
    dmu = -iv(4)/iv(3)
    variables = [mu, iv(2), iv(3)]
    directions = [dmu, iv(6) + iv(5)*dmu, iv(8) + iv(7)*dmu]
    gradient = jvp(eof, variables, directions)

    open (newunit=unit, file='src/generated/kin6d_fermi_gas_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_fermi_gas.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, '(a)') '! Ideal homogeneous nonrelativistic 3D spin-two Fermi gas.'
    write (unit, '(a)') '! r=p/pF; theta=kBT/EF>0; mu=chemical_potential/EF.'
    write (unit, '(a)') '! Fixed density: 3*integral(r^2*f)=1. No exact mu input.'
    write (unit, '(a)') '! AD smooth theta>0; root products use implicit equations.'
    write (unit, '(a)') 'module kin6d_fermi_gas_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('fermi_argument', ['r    ', 'theta', 'mu   '], ['z'], &
              [(r**2 - mu)/theta], ad=.true., interval=.true.)
    call emit('fermi_positive', ['z'], ['value'], &
              [exp(-z)/(1 + exp(-z))], ad=.true., interval=.true.)
    call emit('fermi_negative', ['z'], ['value'], &
              [1/(1 + exp(z))], ad=.true., interval=.true.)
    call emit('fermi_integrands', ['r         ', 'theta     ', 'mu        ', &
                                  'occupation'], names, moments, &
              ad=.true., interval=.true.)
    call emit('fermi_density_integrand', ['r         ', 'theta     ', &
                                          'mu        ', 'occupation'], &
              ['i2  ', 'i2mu'], [moments(1), moments(3)], interval=.true.)
    call emit('fermi_density_curvature_interval', ['r         ', 'theta     ', &
                                                   'mu        ', 'occupation'], &
              ['curvature'], [curvature(1)], rigorous=.true.)
    call emit('fermi_curvature_interval', ['r         ', 'theta     ', &
                                           'mu        ', 'occupation'], &
              names, curvature, rigorous=.true.)
    call emit('fermi_eos', ['mu  ', 'i4  ', 'i2mu'], [character(16) :: &
              'chemical', 'pressure', 'energy', 'susceptibility', &
              'screening_ratio', 'bulk_modulus'], eof, ad=.true., interval=.true.)
    call emit('fermi_theta_derivative', names, [character(16) :: &
              'chemical', 'pressure', 'energy', 'susceptibility', &
              'screening_ratio', 'bulk_modulus'], gradient, interval=.true.)
    call emit('fermi_root_bracket', ['theta'], ['lower ', 'upper ', 'radius'], &
              [-theta*(4 + 2*log(1 + theta)), 4 + 4*theta, sqrt(4 + 36*theta)], &
              interval=.true.)
    call emit('fermi_grid', ['index ', 'cells ', 'radius'], ['coordinate'], &
              [radius*index/cells], interval=.true.)
    call emit('fermi_weighted_add', ['acc   ', 'term  ', 'weight'], ['next'], &
              [acc + term*sym(arena, 'weight')])
    call emit('fermi_residual', ['i2'], ['value'], [3*iv(1) - 1], &
              interval=.true.)
    call emit('fermi_add_interval', ['acc ', 'term'], ['next'], &
              [acc + term], rigorous=.true.)
    call emit('fermi_difference_interval', ['term', 'acc '], ['error'], &
              [term - acc], rigorous=.true.)
    call emit('fermi_root_band', ['mu  ', 'step'], ['lower', 'upper'], &
              [mu - step, mu + step], interval=.true.)
    call emit('fermi_half', ['lower', 'upper'], ['midpoint'], [(lower + upper)/2], &
              interval=.true.)
    call emit('fermi_scaled_tolerance', ['theta', 'scale'], ['value'], &
              [theta*sym(arena, 'scale')])

    factor = exp((mu - radius**2)/theta)
    tail2 = factor*(theta*radius/2 + theta**2/(4*radius))
    tail4 = factor*(theta*radius**3/2 + 3*theta**2*radius/4 + &
                   3*theta**3/(8*radius))
    tail6 = factor*(theta*radius**5/2 + 5*theta**2*radius**3/4 + &
                   15*theta**3*radius/8 + 15*theta**4/(16*radius))
    call emit('fermi_tail_interval', ['theta ', 'mu    ', 'radius'], names, &
              [tail2, tail4, tail2/theta, (tail4 + abs(mu)*tail2)/theta**2, &
               tail4/theta, (tail6 + abs(mu)*tail4)/theta**2, &
               tail2/theta**2, (tail4 + abs(mu)*tail2)/theta**3 + &
               tail2/theta**2], rigorous=.true.)
    do j = 1, 6
        g(j) = sym(arena, 'g'//achar(iachar('0') + j))
        gradient(j) = seed*g(j)
    end do
    call emit('fermi_apply_direction', [character(4) :: 'seed', &
              'g1', 'g2', 'g3', 'g4', 'g5', 'g6'], [character(2) :: &
              'o1', 'o2', 'o3', 'o4', 'o5', 'o6'], gradient, &
              ad=.true., interval=.true.)
    density = sym(arena, 'density'); temperature = sym(arena, 'temperature')
    mass = sym(arena, 'mass'); hbar = sym(arena, 'hbar'); kb = sym(arena, 'kb')
    charge = sym(arena, 'charge'); epsilon = sym(arena, 'epsilon')
    pressure = sym(arena, 'pressure'); energy = sym(arena, 'energy')
    susceptibility = sym(arena, 'susceptibility')
    mass_density = sym(arena, 'mass_density')
    electron_fraction = sym(arena, 'electron_fraction')
    atomic_mass = sym(arena, 'atomic_mass'); speed = sym(arena, 'speed')
    call emit('fermi_electron_density', [character(17) :: &
              'mass_density', 'electron_fraction', 'atomic_mass'], ['density'], &
              [mass_density*electron_fraction/atomic_mass], ad=.true., interval=.true.)
    call emit('fermi_relativity_indicator', ['pf   ', 'mass ', 'speed'], ['value'], &
              [sym(arena, 'pf')/(mass*speed)], ad=.true., interval=.true.)
    pf = hbar*exp(log(3*pi_expr(arena)**2*density)/3)
    ef = pf**2/(2*mass)
    call emit('fermi_si_parameters', [character(11) :: &
              'density', 'temperature', 'mass', 'hbar', 'kb'], &
              ['pf   ', 'ef   ', 'theta'], [pf, ef, kb*temperature/ef], &
              ad=.true., interval=.true.)
    ef = sym(arena, 'ef')
    call emit('fermi_si_eos', [character(14) :: 'density', 'ef', 'mu', &
              'pressure', 'energy', 'susceptibility', 'charge', 'epsilon'], &
              [character(18) :: 'chemical', 'physical_pressure', 'energy_density', &
               'compressibility', 'screening', 'bulk_modulus'], &
              [mu*ef, density*ef*pressure, density*ef*energy, &
               susceptibility/(density*ef), &
               sqrt(charge**2*density*susceptibility/(epsilon*ef)), &
               density*ef/susceptibility], ad=.true., interval=.true.)
    write (unit, '(a)') 'end module kin6d_fermi_gas_leaves'
    close (unit)

contains

    subroutine prove(expression)
        type(expr_t), intent(in) :: expression
        identity = engine%zero_test(expression)
        if (identity%verdict /= VERDICT_TRUE) &
            error stop 'Fermi differential identity unproved'
    end subroutine prove

    function d_r(expression) result(derivative)
        type(expr_t), intent(in) :: expression
        type(expr_t) :: derivative
        derivative = diff(expression, r) + diff(expression, occupation)*fr
    end function d_r

    function d_mu(expression) result(derivative)
        type(expr_t), intent(in) :: expression
        type(expr_t) :: derivative
        derivative = diff(expression, mu) + diff(expression, occupation)*fm
    end function d_mu

    function d_theta(expression) result(derivative)
        type(expr_t), intent(in) :: expression
        type(expr_t) :: derivative
        derivative = diff(expression, theta) + diff(expression, occupation)*ft
    end function d_theta
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_fermi_gas; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%exp = str('exp')
                rspec%runtime%log = str('log')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sqrt = str('sqrt')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_fermi_gas')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_fermi_gas from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
        if (name == 'fermi_apply_direction') then
            call emit(name//'_vjp_interval', adjoint_args, adjoint_outputs, &
                      derivative_roots, rigorous=.true.)
        end if
    end subroutine emit_derivatives
end program gen_fermi_gas
