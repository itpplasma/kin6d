program gen_ideal_xi
    ! Exact local D5 Hessian identity; no sampled/probe evidence is accepted.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*), &
        operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_products, only: jvp, vjp
    use fortsym_kernel, only: kernel_spec_t, emit_kernel, &
        PRECISION_REAL32, PRECISION_REAL64
    use fortsym_string, only: str, chars
    use kin6d_symbolic_ideal, only: frozen_energy
    use kin6d_gen_support, only: fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: d(3, 3), b(3), a(3, 3), c(3, 3), ab(3), cb(3)
    type(expr_t) :: p, mu, jac, density, one, zero, ta, tc, ac, b2, ba, bc
    type(expr_t) :: form, coeff, expected, h, identity(3, 3)
    type(expr_t) :: vars(23), direction(23), seed(1), roots(1)
    type(expr_t), allocatable :: tangent(:), adjoint(:)
    type(engine_result_t) :: result
    character(8) :: names(23), dn(23), gn(23)
    character(16) :: suffix
    integer :: i, j, k, l, row, col, unit, precision, checks
    call arena%init()
    engine = make_native_engine(arena)
    b(1) = sym(arena, 'b1'); b(2) = sym(arena, 'b2')
    b(3) = sym(arena, 'b3'); p = sym(arena, 'p'); mu = sym(arena, 'mu')
    one = 1 + 0*p; zero = 0*p
    identity = zero
    names(1:5) = [character(8) :: 'b1', 'b2', 'b3', 'p', 'mu']
    vars(1:5) = [b, p, mu]
    do j = 1, 3
        identity(j, j) = one
        do i = 1, 3
            k = i + 3*(j - 1)
            write(names(5 + k), '(a,i1,i1)') 'a', i, j
            write(names(14 + k), '(a,i1,i1)') 'c', i, j
            a(i, j) = sym(arena, trim(names(5 + k)))
            c(i, j) = sym(arena, trim(names(14 + k)))
            vars(5 + k) = a(i, j); vars(14 + k) = c(i, j)
            block
                character(8) :: name
                write(name, '(a,i1,i1)') 'f', i, j
                d(i, j) = sym(arena, trim(name))
            end block
        end do
    end do
    ! Independent xi-form (A=grad xi, C=grad eta), gamma=0:
    ! (AB).(CB)/mu - [(B.AB)tr C+(B.CB)tr A]/mu
    ! + (B^2/(2mu)-p)tr A tr C + (B^2/(2mu)+p)tr(AC).
    ta = zero; tc = zero; ac = zero; b2 = zero
    ba = zero; bc = zero
    ab = zero; cb = zero
    do i = 1, 3
        ta = ta + a(i, i); tc = tc + c(i, i)
        b2 = b2 + b(i)**2
        do j = 1, 3
            ac = ac + a(i, j)*c(j, i)
            ab(i) = ab(i) + a(i, j)*b(j)
            cb(i) = cb(i) + c(i, j)*b(j)
        end do
        ba = ba + b(i)*ab(i); bc = bc + b(i)*cb(i)
    end do
    form = -(ba*tc + bc*ta)/mu &
        + (b2/(2*mu) - p)*ta*tc + (b2/(2*mu) + p)*ac
    do i = 1, 3
        form = form + ab(i)*cb(i)/mu
    end do
    density = frozen_energy(d, b, p, mu, one, jac)
    roots = [zero]; checks = 0
    do j = 1, 9
        row = 1 + mod(j - 1, 3); col = 1 + (j - 1)/3
        do i = 1, 9
            k = 1 + mod(i - 1, 3); l = 1 + (i - 1)/3
            h = diff(diff(density, d(k, l)), d(row, col))
            do l = 1, 3
                do k = 1, 3
                    h = subs(h, d(k, l), identity(k, l))
                end do
            end do
            expected = diff(diff(form, vars(5 + i)), vars(14 + j))
            call prove(h - expected)
            result = engine%simplify(h)
            if (.not. result%ok) error stop 'Hessian simplification failed'
            coeff = result%value
            roots(1) = roots(1) + coeff*vars(5 + i)*vars(14 + j)
        end do
    end do
    call prove(roots(1) - form)
    ! Generated JVP/VJP cover background and both test gradients.
    do i = 1, 23
        dn(i) = 'd'//trim(names(i)); gn(i) = 'g'//trim(names(i))
        direction(i) = sym(arena, trim(dn(i)))
    end do
    seed(1) = sym(arena, 'seed')
    tangent = jvp(roots, vars, direction)
    adjoint = vjp(roots, vars, seed)
    open(newunit=unit, file='src/generated/kin6d_ideal_xi_leaves.f90', &
        status='replace', action='write')
    write(unit, '(a)') '! Generated by gen/gen_ideal_xi.f90; do not edit.'
    write(unit, '(a)') 'module kin6d_ideal_xi_leaves'
    write(unit, '(a)') 'implicit none'
    write(unit, '(a)') 'contains'
    do precision = PRECISION_REAL64, PRECISION_REAL32
        suffix = '_dp'
        if (precision == PRECISION_REAL32) suffix = '_sp'
        call emit('xi_form'//trim(suffix), names, ['value'], roots)
        call emit('xi_form_jvp'//trim(suffix), [names, dn], ['dvalue'], tangent)
        call emit('xi_form_vjp'//trim(suffix), [character(8) :: names, 'seed'], &
            gn, adjoint)
    end do
    call emit_gradient()
    write(unit, '(a)') 'end module kin6d_ideal_xi_leaves'
    close(unit)
    print '(a,i0,a)', 'PASS: ', checks, ' exact Hess W = L4 coefficient identities (no probes)'
contains
    subroutine emit_gradient()
        ! Cylindrical orthonormal components, exp(+i n phi), row component,
        ! column physical derivative. Both basis-rotation terms are retained.
        type(expr_t) :: x(3, 2), dr(3, 2), dz(3, 2), g(3, 3, 2), rr, nn
        type(expr_t) :: inputs(20), tangents(20), values(18), weight(18)
        type(expr_t), allocatable :: tj(:), tv(:)
        character(8) :: args(20), dargs(20), outs(18), douts(18), &
            seeds(18), grads(20)
        integer :: i, j, k, phase, other, sign, at
        args(19:20) = [character(8) :: 'r', 'n']
        rr = sym(arena, 'r'); nn = sym(arena, 'n')
        inputs(19:20) = [rr, nn]
        do phase = 1, 2
            do i = 1, 3
                k = i + 3*(phase - 1)
                write(args(k), '(a,i1,i1)') 'x', i, phase
                write(args(k+6), '(a,i1,i1)') 'r', i, phase
                write(args(k+12), '(a,i1,i1)') 'z', i, phase
                x(i, phase) = sym(arena, trim(args(k)))
                dr(i, phase) = sym(arena, trim(args(k+6)))
                dz(i, phase) = sym(arena, trim(args(k+12)))
                inputs(k) = x(i, phase); inputs(k+6) = dr(i, phase)
                inputs(k+12) = dz(i, phase)
            end do
        end do
        do phase = 1, 2
            other = 3 - phase; sign = 2*phase - 3
            g(:, 1, phase) = dr(:, phase)
            g(:, 3, phase) = dz(:, phase)
            g(1, 2, phase) = (sign*nn*x(1, other) - x(2, phase))/rr
            g(2, 2, phase) = (sign*nn*x(2, other) + x(1, phase))/rr
            g(3, 2, phase) = sign*nn*x(3, other)/rr
            do j = 1, 3
                do i = 1, 3
                    at = i + 3*(j-1) + 9*(phase-1)
                    values(at) = g(i, j, phase)
                    write(outs(at), '(a,i1,i1,i1)') 'g', i, j, phase
                    douts(at) = 'd'//trim(outs(at))
                    seeds(at) = 'b'//trim(outs(at))
                    weight(at) = sym(arena, trim(seeds(at)))
                end do
            end do
        end do
        do i = 1, 20
            dargs(i) = 'd'//trim(args(i)); grads(i) = 'g'//trim(args(i))
            tangents(i) = sym(arena, trim(dargs(i)))
        end do
        tj = jvp(values, inputs, tangents)
        tv = vjp(values, inputs, weight)
        do precision = PRECISION_REAL64, PRECISION_REAL32
            suffix = '_dp'
            if (precision == PRECISION_REAL32) suffix = '_sp'
            call emit('xi_gradient'//trim(suffix), args, outs, values)
            call emit('xi_gradient_jvp'//trim(suffix), [args,dargs], douts, tj)
            call emit('xi_gradient_vjp'//trim(suffix), [args,seeds], grads, tv)
        end do
    end subroutine emit_gradient

    subroutine prove(expression)
        type(expr_t), intent(in) :: expression
        type(engine_result_t) :: proof
        proof = engine%zero_test(expression)
        if (proof%verdict /= VERDICT_TRUE) then
            print *, 'Unproved xi identity', checks + 1
            error stop 1
        end if
        checks = checks + 1
    end subroutine prove

    subroutine emit(name, args, outputs, values)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: values(:)
        type(kernel_spec_t) :: spec
        type(expr_t) :: clean(size(values))
        type(engine_result_t) :: simplified
        logical :: ok
        character(:), allocatable :: message
        integer :: n
        spec%name = str(name); spec%generator = str('gen_ideal_xi')
        spec%generator_revision = str(fortsym_revision)
        spec%regenerate_command = str('gen_ideal_xi from pinned FortSym build')
        spec%precision = precision
        spec%pure_procedure = .true.; spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        allocate(spec%args(size(args)), spec%outputs(size(outputs)))
        do n = 1, size(args)
            spec%args(n) = str(trim(args(n)))
        end do
        do n = 1, size(outputs)
            spec%outputs(n) = str(trim(outputs(n)))
            simplified = engine%simplify(values(n))
            if (.not. simplified%ok) error stop 'xi leaf simplification failed'
            clean(n) = simplified%value
        end do
        write(unit, '(a)') chars(emit_kernel(clean, spec, ok, message=message))
        if (.not. ok) error stop message
    end subroutine emit
end program gen_ideal_xi
