program gen_coulomb_encounter
    ! Generates the project-owned numerical leaves of the Q1/Q1b localized
    ! two-body quantum Coulomb encounter (src/quantum/coulomb_encounter.f90).
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, sin, cos, exp, log, erfc, rat, pi_expr, &
                            operator(+), operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: coulomb_potential, partial_wave_potential, &
                                      sommerfeld_parameter, rydberg_energy
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: r, l, g, mu, hbar, x, y, z, b, z0, sigma, k, eta, t, e, ej, ek
    type(expr_t) :: theta, s2, c2, amp, a, n, nbar, rc, s, mass, xc, m1, m2, xcm, xrel
    type(expr_t) :: ct, st, cp, sp, e0, rho, b1, b2, phi, sinc, energy, speed, lam

    call arena%init()
    r = sym(arena, 'r'); l = sym(arena, 'l'); g = sym(arena, 'g')
    mu = sym(arena, 'mu'); hbar = sym(arena, 'hbar')
    x = sym(arena, 'x'); y = sym(arena, 'y'); z = sym(arena, 'z')
    b = sym(arena, 'b'); z0 = sym(arena, 'z0'); sigma = sym(arena, 'sigma')
    k = sym(arena, 'k'); eta = sym(arena, 'eta'); t = sym(arena, 't')
    e = sym(arena, 'e'); ej = sym(arena, 'ej'); ek = sym(arena, 'ek')
    theta = sym(arena, 'theta'); n = sym(arena, 'n'); nbar = sym(arena, 'nbar')
    rc = sym(arena, 'rc'); s = sym(arena, 's'); mass = sym(arena, 'mass')
    xc = sym(arena, 'xc'); m1 = sym(arena, 'm1'); m2 = sym(arena, 'm2')
    xcm = sym(arena, 'xcm'); xrel = sym(arena, 'xrel')
    ct = sym(arena, 'ct'); st = sym(arena, 'st'); cp = sym(arena, 'cp')
    sp = sym(arena, 'sp'); e0 = sym(arena, 'e0'); rho = sym(arena, 'rho')
    b1 = sym(arena, 'b1'); b2 = sym(arena, 'b2'); sinc = sym(arena, 'sinc')

    call w%open(arena, 'gen_coulomb_encounter', &
                'src/generated/kin6d_coulomb_encounter_leaves.f90')
    call w%line('! Generated by gen/gen_coulomb_encounter.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Two-body relative motion, reduced mass mu, bare Coulomb g/r.')
    call w%line('! Partial waves u_l(r)/r Y_lm; no softening or screening.')
    call w%line('! Physics from gen/kin6d_symbolic_physics.f90; reduced mass, Bohr')
    call w%line('! radius and Sommerfeld eta come from kin6d_species.')
    call w%line('! JVP/VJP use Euclidean pairings of the listed real arguments.')
    call w%line('module kin6d_coulomb_encounter_leaves')
    call w%line('implicit none')
    call w%line('contains')

    ! Physical operator: radial effective potential from the shared definition.
    call w%emit('ce_radial_potential', ['r   ', 'l   ', 'g   ', 'mu  ', 'hbar'], ['v'], &
              [partial_wave_potential(g, hbar, mu, l, r)], ad=.true.)
    call w%emit('ce_coulomb_potential', ['r', 'g'], ['v'], [coulomb_potential(g, r)], &
              ad=.true.)
    call w%emit('ce_kinetic_scale', ['mu  ', 'hbar'], ['c'], [hbar**2/(2*mu)])

    ! Normalized relative Gaussian packet; |psi|^2 has rms sigma per axis.
    amp = (2*pi_expr(arena)*sigma**2)**(rat(arena, -3_8, 4_8))* &
          exp(-((x - b)**2 + y**2 + (z + z0)**2)/(4*sigma**2))
    call w%emit('ce_packet', ['x    ', 'y    ', 'z    ', 'b    ', 'z0   ', 'sigma', &
                            'k    '], ['re', 'im'], [amp*cos(k*z), amp*sin(k*z)], ad=.true.)
    call w%emit('ce_cartesian', ['r ', 'ct', 'st', 'cp', 'sp'], ['x', 'y', 'z'], &
              [r*st*cp, r*st*sp, r*ct])

    ! Physical scales: Sommerfeld eta, reduced wavelength, head-on turning radius.
    energy = hbar**2*k**2/(2*mu)
    speed = hbar*k/mu
    lam = 1/k
    call w%emit('ce_scales', ['g   ', 'mu  ', 'hbar', 'k   '], &
              ['lambdabar', 'r0       ', 'energy   ', 'speed    '], &
              [lam, 2*sommerfeld_parameter(g, hbar, speed)*lam, energy, speed], ad=.true.)
    call w%emit('ce_wave_number', ['eta ', 'g   ', 'mu  ', 'hbar'], ['k'], &
              [g*mu/(hbar**2*eta)])
    call w%emit('ce_total_mass', ['m1', 'm2'], ['mtotal'], [m1 + m2])
    call w%emit('ce_lab_positions', ['xcm ', 'xrel', 'm1  ', 'm2  '], ['x1', 'x2'], &
              [xcm + m2*xrel/(m1 + m2), xcm - m1*xrel/(m1 + m2)], ad=.true.)
    call w%emit('ce_pair_widths', ['sigma'], ['sigma_rel', 'sigma_cm '], &
              [sqrt(rat(arena, 2_8, 1_8))*sigma, sigma/sqrt(rat(arena, 2_8, 1_8))])
    call w%emit('ce_momentum_width', ['sigma', 'hbar '], ['width'], [hbar/(2*sigma)])

    ! Exact discrete-space evolution: phase and Duhamel (Daleckii-Krein) kernel.
    call w%emit('ce_phase', ['e   ', 't   ', 'hbar'], ['c', 's'], &
              [cos(e*t/hbar), -sin(e*t/hbar)], ad=.true.)
    phi = (ej + ek)*t/(2*hbar)
    call w%emit('ce_duhamel', ['ej  ', 'ek  ', 't   ', 'hbar', 'sinc'], ['re', 'im'], &
              [-(t/hbar)*sinc*sin(phi), -(t/hbar)*sinc*cos(phi)])
    call w%emit('ce_sinc_argument', ['ej  ', 'ek  ', 't   ', 'hbar'], ['x'], &
              [(ej - ek)*t/(2*hbar)])
    call w%emit('ce_sinc', ['x'], ['s'], [sin(x)/x])
    call w%emit('ce_sinc_series', ['x'], ['s'], &
              [1 - x**2/6 + x**4/120 - x**6/5040 + x**8/362880])

    ! Asymptotic plane-wave references (oracles for late-time angular bins).
    s2 = sin(theta/2)**2
    c2 = cos(theta/2)**2
    a = (eta/(2*k))**2
    call w%emit('ce_rutherford', ['theta', 'eta  ', 'k    '], ['dsdo'], [a/s2**2])
    call w%emit('ce_mott', ['theta', 'eta  ', 'k    '], ['direct  ', 'exchange', 'cross   '], &
              [a/s2**2, a/c2**2, 2*a*cos(eta*log(s2/c2))/(s2*c2)])
    call w%emit('ce_impact_parameter', ['theta', 'r0   '], ['b'], &
              [r0_half()*cos(theta/2)/sin(theta/2)])
    call w%emit('ce_transverse_fluence', ['b1   ', 'b2   ', 'sigma'], ['p'], &
              [exp(-b1**2/(2*sigma**2)) - exp(-b2**2/(2*sigma**2))])

    ! Q1b: hydrogen-like bound spectrum, Kepler period and revival time.
    call w%emit('ce_hydrogen_level', ['n   ', 'mu  ', 'g   ', 'hbar'], ['e'], &
              [-rydberg_energy(hbar, mu, g)/n**2], ad=.true.)
    ! T_K = 2 pi hbar/(dE/dn) and T_rev = 2 pi hbar/(|d2E/dn2|/2) at nbar.
    call w%emit('ce_kepler', ['nbar', 'mu  ', 'g   ', 'hbar'], ['period ', 'revival'], &
              [pi_expr(arena)*hbar*nbar**3/rydberg_energy(hbar, mu, g), &
               4*pi_expr(arena)*hbar*nbar**4/(3*2*rydberg_energy(hbar, mu, g))])
    a = sym(arena, 'a')
    call w%emit('ce_outer_turning', ['nbar', 'l   ', 'a   '], ['r'], &
              [a*nbar**2*(1 + sqrt(1 - l*(l + 1)/nbar**2))])
    ! Design estimate: radial packet at rest at r_out with rms width s has an
    ! energy spread |dV/dr| s, i.e. rms Delta n ~ s/(4 nbar a) for l << nbar.
    call w%emit('ce_kepler_width', ['nbar', 'a   ', 'dn  '], ['s'], [4*nbar*a*sym(arena, 'dn')])
    call w%emit('ce_radial_packet', ['r ', 'rc', 's '], ['u'], &
              [(2*pi_expr(arena)*s**2)**(rat(arena, -1_8, 4_8))* &
               exp(-(r - rc)**2/(4*s**2))])

    ! Probability of an isotropic 3D Gaussian (rms 1 per axis) beyond radius x.
    call w%emit('ce_radial_tail', ['x'], ['p'], &
              [erfc(x/sqrt(rat(arena, 2_8, 1_8))) + &
               sqrt(2/pi_expr(arena))*x*exp(-x**2/2)])

    ! Free centre-of-mass Gaussian (analytic; rms width of |Phi|^2).
    call w%emit('ce_free_width', ['sigma', 'mass ', 'hbar ', 't    '], ['width'], &
              [sigma*sqrt(1 + (hbar*t/(2*mass*sigma**2))**2)], ad=.true.)
    call w%emit('ce_gaussian_density', ['x ', 'xc', 's '], ['p'], &
              [exp(-(x - xc)**2/(2*s**2))/(sqrt(2*pi_expr(arena))*s)])

    ! Finite-space unitary residual bound and bounded-observable radius.
    call w%emit('ce_state_bound_interval', ['e0  ', 'rho ', 't   ', 'hbar'], ['e'], &
              [e0 + t*rho/hbar], rigorous=.true.)
    call w%emit('ce_observable_radius_interval', ['e'], ['radius'], [2*e + e**2], &
              rigorous=.true.)
    ! Normalized sector probability P=num/den with state error e and den=nrm.
    call w%emit('ce_sector_radius_interval', ['nrm', 'p  ', 'e  '], ['radius'], &
              [sector_radius()], rigorous=.true.)
    call w%emit('ce_sector_radius', ['nrm', 'p  ', 'e  '], ['radius'], [sector_radius()])
    call w%emit('ce_state_bound', ['e0  ', 'rho ', 't   ', 'hbar'], ['e'], [e0 + t*rho/hbar])
    call w%emit('ce_observable_radius', ['e'], ['radius'], [2*e + e**2])

    call w%line('end module kin6d_coulomb_encounter_leaves')
    call w%close()
contains
    function sector_radius() result(v)
        type(expr_t) :: v, d
        d = 2*sqrt(sym(arena, 'nrm'))*e + e**2
        v = d*(1 + sym(arena, 'p'))/(sym(arena, 'nrm') - d)
    end function sector_radius

    function r0_half() result(v)
        type(expr_t) :: v
        v = sym(arena, 'r0')/2
    end function r0_half
end program gen_coulomb_encounter
