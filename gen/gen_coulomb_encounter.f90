program gen_coulomb_encounter
    ! Generates the project-owned numerical leaves of the Q1/Q1b localized
    ! two-body quantum Coulomb encounter (src/coulomb_encounter.f90).
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, sin, cos, exp, log, erfc, rat, pi_expr, &
                            operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    use kin6d_symbolic_physics, only: coulomb_potential, radial_effective_potential
    implicit none
    character(*), parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: r, l, g, mu, hbar, x, y, z, b, z0, sigma, k, eta, t, e, ej, ek
    type(expr_t) :: theta, s2, c2, amp, a, n, nbar, rc, s, mass, xc, m1, m2, xcm, xrel
    type(expr_t) :: ct, st, cp, sp, e0, rho, b1, b2, phi, sinc, energy, speed, lam
    integer :: unit

    call arena%init()
    engine = make_native_engine(arena)
    r = sym(arena, 'r'); l = sym(arena, 'l'); g = sym(arena, 'g')
    mu = sym(arena, 'mu'); hbar = sym(arena, 'hbar')
    x = sym(arena, 'x'); y = sym(arena, 'y'); z = sym(arena, 'z')
    b = sym(arena, 'b'); z0 = sym(arena, 'z0'); sigma = sym(arena, 'sigma')
    k = sym(arena, 'k'); eta = sym(arena, 'eta'); t = sym(arena, 't')
    e = sym(arena, 'e'); ej = sym(arena, 'ej'); ek = sym(arena, 'ek')
    theta = sym(arena, 'theta'); n = sym(arena, 'n'); nbar = sym(arena, 'nbar')
    rc = sym(arena, 'rc'); s = sym(arena, 's'); mass = sym(arena, 'mass')
    xc = sym(arena, 'xc'); m1 = sym(arena, 'm1'); m2 = sym(arena, 'm2')
    xcm = sym(arena, 'xcm'); xrel = sym(arena, 'xrel')
    ct = sym(arena, 'ct'); st = sym(arena, 'st'); cp = sym(arena, 'cp')
    sp = sym(arena, 'sp'); e0 = sym(arena, 'e0'); rho = sym(arena, 'rho')
    b1 = sym(arena, 'b1'); b2 = sym(arena, 'b2'); sinc = sym(arena, 'sinc')

    open (newunit=unit, file='src/generated/kin6d_coulomb_encounter_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_coulomb_encounter.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, '(a)') '! Two-body relative motion, reduced mass mu, bare Coulomb g/r.'
    write (unit, '(a)') '! Partial waves u_l(r)/r Y_lm; no softening or screening.'
    write (unit, '(a)') '! JVP/VJP use Euclidean pairings of the listed real arguments.'
    write (unit, '(a)') 'module kin6d_coulomb_encounter_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'

    ! Physical operator: radial effective potential from the shared definition.
    call emit('ce_radial_potential', ['r   ', 'l   ', 'g   ', 'mu  ', 'hbar'], ['v'], &
              [radial_effective_potential(g, r, l, mu, hbar)], ad=.true.)
    call emit('ce_coulomb_potential', ['r', 'g'], ['v'], [coulomb_potential(g, r)], &
              ad=.true.)
    call emit('ce_kinetic_scale', ['mu  ', 'hbar'], ['c'], [hbar**2/(2*mu)])

    ! Normalized relative Gaussian packet; |psi|^2 has rms sigma per axis.
    amp = (2*pi_expr(arena)*sigma**2)**(rat(arena, -3_8, 4_8))* &
          exp(-((x - b)**2 + y**2 + (z + z0)**2)/(4*sigma**2))
    call emit('ce_packet', ['x    ', 'y    ', 'z    ', 'b    ', 'z0   ', 'sigma', &
                            'k    '], ['re', 'im'], [amp*cos(k*z), amp*sin(k*z)], ad=.true.)
    call emit('ce_cartesian', ['r ', 'ct', 'st', 'cp', 'sp'], ['x', 'y', 'z'], &
              [r*st*cp, r*st*sp, r*ct])

    ! Physical scales: Sommerfeld eta, reduced wavelength, head-on turning radius.
    energy = hbar**2*k**2/(2*mu)
    speed = hbar*k/mu
    lam = 1/k
    call emit('ce_scales', ['g   ', 'mu  ', 'hbar', 'k   '], &
              ['eta      ', 'lambdabar', 'r0       ', 'energy   ', 'speed    '], &
              [g/(hbar*speed), lam, 2*g/(hbar*speed)*lam, energy, speed], ad=.true.)
    call emit('ce_wave_number', ['eta ', 'g   ', 'mu  ', 'hbar'], ['k'], &
              [g*mu/(hbar**2*eta)])
    call emit('ce_reduced_mass', ['m1', 'm2'], ['mtotal', 'mu    '], &
              [m1 + m2, m1*m2/(m1 + m2)])
    call emit('ce_lab_positions', ['xcm ', 'xrel', 'm1  ', 'm2  '], ['x1', 'x2'], &
              [xcm + m2*xrel/(m1 + m2), xcm - m1*xrel/(m1 + m2)], ad=.true.)
    call emit('ce_pair_widths', ['sigma'], ['sigma_rel', 'sigma_cm '], &
              [sqrt(rat(arena, 2_8, 1_8))*sigma, sigma/sqrt(rat(arena, 2_8, 1_8))])
    call emit('ce_momentum_width', ['sigma', 'hbar '], ['width'], [hbar/(2*sigma)])

    ! Exact discrete-space evolution: phase and Duhamel (Daleckii-Krein) kernel.
    call emit('ce_phase', ['e   ', 't   ', 'hbar'], ['c', 's'], &
              [cos(e*t/hbar), -sin(e*t/hbar)], ad=.true.)
    phi = (ej + ek)*t/(2*hbar)
    call emit('ce_duhamel', ['ej  ', 'ek  ', 't   ', 'hbar', 'sinc'], ['re', 'im'], &
              [-(t/hbar)*sinc*sin(phi), -(t/hbar)*sinc*cos(phi)])
    call emit('ce_sinc_argument', ['ej  ', 'ek  ', 't   ', 'hbar'], ['x'], &
              [(ej - ek)*t/(2*hbar)])
    call emit('ce_sinc', ['x'], ['s'], [sin(x)/x])
    call emit('ce_sinc_series', ['x'], ['s'], &
              [1 - x**2/6 + x**4/120 - x**6/5040 + x**8/362880])

    ! Asymptotic plane-wave references (oracles for late-time angular bins).
    s2 = sin(theta/2)**2
    c2 = cos(theta/2)**2
    a = (eta/(2*k))**2
    call emit('ce_rutherford', ['theta', 'eta  ', 'k    '], ['dsdo'], [a/s2**2])
    call emit('ce_mott', ['theta', 'eta  ', 'k    '], ['direct  ', 'exchange', 'cross   '], &
              [a/s2**2, a/c2**2, 2*a*cos(eta*log(s2/c2))/(s2*c2)])
    call emit('ce_impact_parameter', ['theta', 'r0   '], ['b'], &
              [r0_half()*cos(theta/2)/sin(theta/2)])
    call emit('ce_transverse_fluence', ['b1   ', 'b2   ', 'sigma'], ['p'], &
              [exp(-b1**2/(2*sigma**2)) - exp(-b2**2/(2*sigma**2))])

    ! Q1b: hydrogen-like bound spectrum, Kepler period and revival time.
    call emit('ce_hydrogen_level', ['n   ', 'mu  ', 'g   ', 'hbar'], ['e'], &
              [-mu*g**2/(2*hbar**2*n**2)], ad=.true.)
    call emit('ce_kepler', ['nbar', 'mu  ', 'g   ', 'hbar'], ['period ', 'revival'], &
              [2*pi_expr(arena)*hbar**3*nbar**3/(mu*g**2), &
               2*nbar/3*2*pi_expr(arena)*hbar**3*nbar**3/(mu*g**2)])
    a = sym(arena, 'a')
    call emit('ce_bohr_radius', ['mu  ', 'g   ', 'hbar'], ['a'], [hbar**2/(mu*sqrt(g**2))])
    call emit('ce_outer_turning', ['nbar', 'l   ', 'a   '], ['r'], &
              [a*nbar**2*(1 + sqrt(1 - l*(l + 1)/nbar**2))])
    ! Design estimate: radial packet at rest at r_out with rms width s has an
    ! energy spread |dV/dr| s, i.e. rms Delta n ~ s/(4 nbar a) for l << nbar.
    call emit('ce_kepler_width', ['nbar', 'a   ', 'dn  '], ['s'], [4*nbar*a*sym(arena, 'dn')])
    call emit('ce_radial_packet', ['r ', 'rc', 's '], ['u'], &
              [(2*pi_expr(arena)*s**2)**(rat(arena, -1_8, 4_8))* &
               exp(-(r - rc)**2/(4*s**2))])

    ! Probability of an isotropic 3D Gaussian (rms 1 per axis) beyond radius x.
    call emit('ce_radial_tail', ['x'], ['p'], &
              [erfc(x/sqrt(rat(arena, 2_8, 1_8))) + &
               sqrt(2/pi_expr(arena))*x*exp(-x**2/2)])

    ! Free centre-of-mass Gaussian (analytic; rms width of |Phi|^2).
    call emit('ce_free_width', ['sigma', 'mass ', 'hbar ', 't    '], ['width'], &
              [sigma*sqrt(1 + (hbar*t/(2*mass*sigma**2))**2)], ad=.true.)
    call emit('ce_gaussian_density', ['x ', 'xc', 's '], ['p'], &
              [exp(-(x - xc)**2/(2*s**2))/(sqrt(2*pi_expr(arena))*s)])

    ! Finite-space unitary residual bound and bounded-observable radius.
    call emit('ce_state_bound_interval', ['e0  ', 'rho ', 't   ', 'hbar'], ['e'], &
              [e0 + t*rho/hbar], rigorous=.true.)
    call emit('ce_observable_radius_interval', ['e'], ['radius'], [2*e + e**2], &
              rigorous=.true.)
    ! Normalized sector probability P=num/den with state error e and den=nrm.
    call emit('ce_sector_radius_interval', ['nrm', 'p  ', 'e  '], ['radius'], &
              [sector_radius()], rigorous=.true.)
    call emit('ce_sector_radius', ['nrm', 'p  ', 'e  '], ['radius'], [sector_radius()])
    call emit('ce_state_bound', ['e0  ', 'rho ', 't   ', 'hbar'], ['e'], [e0 + t*rho/hbar])
    call emit('ce_observable_radius', ['e'], ['radius'], [2*e + e**2])

    write (unit, '(a)') 'end module kin6d_coulomb_encounter_leaves'
    close (unit)
contains
    function sector_radius() result(v)
        type(expr_t) :: v, d
        d = 2*sqrt(sym(arena, 'nrm'))*e + e**2
        v = d*(1 + sym(arena, 'p'))/(sym(arena, 'nrm') - d)
    end function sector_radius

    function r0_half() result(v)
        type(expr_t) :: v
        v = sym(arena, 'r0')/2
    end function r0_half
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_coulomb_encounter; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_coulomb_encounter')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_coulomb_encounter from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_coulomb_encounter
