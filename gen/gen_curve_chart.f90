program gen_curve_chart
    ! Periodic projected-guide G-frame. Mathematics is local; Fourier sums,
    ! tensor symmetry and admission sampling are assembled by the chart owner.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sin, cos, sqrt, operator(+), &
                            operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: VERDICT_TRUE, engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(expr_t) :: v(3, 0:3), u(3, 0:3), z(3, 0:3), f(0:4)
    type(expr_t) :: g(0:3), n(0:3), b(0:3), q1, q2, t, c, s, m, e, r
    type(expr_t) :: out(10), cr(3), speed2, curvature2
    character(8) :: vn(12), un(12), zn(12), fn(5)
    character(8) :: args(14), on(10)
    integer :: i, j, k
    type(expr_t) :: radius, lower, accel, vmax, step, far, cnorm, snorm
    type(expr_t) :: min_speed, min_gap, guide0, guide1
    call arena%init()
    w%simplify_roots = .true.
    call w%open(arena, 'gen_curve_chart', &
                'src/generated/kin6d_curve_chart_leaves.f90')
    call w%line('! Generated by gen/gen_curve_chart.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_curve_chart_leaves')
    call w%line('use, intrinsic :: iso_fortran_env, only: dp => real64')
    call w%line('implicit none')
    call w%line('contains')
    c = sym(arena, 'c'); s = sym(arena, 's'); m = sym(arena, 'm')
    t = sym(arena, 't')
    f(0) = c*cos(m*t) + s*sin(m*t)
    fn(1) = 'f0'
    do j = 1, 4
        f(j) = diff(f(j - 1), t)
        write (fn(j + 1), '(a,i1)') 'f', j
    end do
    call w%emit('curve_fourier_mode', ['c', 's', 'm', 't'], fn, f)
    do j = 0, 3
        do i = 1, 3
            k = i + 3*j
            write (vn(k), '(a,2i1)') 'v', i, j
            write (un(k), '(a,2i1)') 'u', i, j
            write (zn(k), '(a,2i1)') 'z', i, j
            v(i, j) = sym(arena, trim(vn(k)))
            u(i, j) = sym(arena, trim(un(k)))
        end do
    end do
    r = sqrt(dot(v(:, 0), v(:, 0)))
    do i = 1, 3
        z(i, 0) = v(i, 0)/r
        do j = 1, 3
            z(i, j) = total(z(i, j - 1))
        end do
    end do
    call w%emit('curve_normalize_scalar', vn, zn, reshape(z, [12]))
    call array_wrapper('curve_normalize', .false.)
    z(:, 0) = cross(v(:, 0), u(:, 0))
    do j = 1, 3
        do i = 1, 3
            z(i, j) = total(z(i, j - 1))
        end do
    end do
    call w%emit('curve_cross_scalar', [vn, un], zn, reshape(z, [12]))
    call array_wrapper('curve_cross', .true.)
    q1 = sym(arena, 'q1'); q2 = sym(arena, 'q2')
    do j = 0, 3
        write (args(j + 1), '(a,i1)') 'g', j
        write (args(j + 5), '(a,i1)') 'n', j
        write (args(j + 9), '(a,i1)') 'b', j
        g(j) = sym(arena, trim(args(j + 1)))
        n(j) = sym(arena, trim(args(j + 5)))
        b(j) = sym(arena, trim(args(j + 9)))
    end do
    args(13:14) = ['q1', 'q2']
    ! Total q3 derivative through the supplied axis/frame jets.
    e = g(0) + q1*n(0) + q2*b(0)
    out(1) = e; out(2) = diff(e, q1); out(3) = diff(e, q2)
    out(4) = along(e)
    out(5) = diff(out(4), q1); out(6) = diff(out(4), q2)
    out(7) = along(out(4))
    out(8) = diff(out(7), q1); out(9) = diff(out(7), q2)
    out(10) = along(out(7))
    on = [character(8) :: 'x', 'd1', 'd2', 'd3', 'd13', 'd23', 'd33', &
          'd133', 'd233', 'd333']
    call w%emit('curve_compose', args, on, out)
    ! Independent of frame twist: kappa = |Gamma' x Gamma''|/|Gamma'|^3.
    speed2 = dot(v(:, 0), v(:, 0))
    cr = cross(v(:, 0), v(:, 1))
    curvature2 = dot(cr, cr)/speed2**3
    call w%emit('curve_geometry', vn(1:6), ['speed', 'kappa'], &
                [sqrt(speed2), sqrt(curvature2)])
    call w%emit('curve_norm', vn(1:3), ['norm'], [sqrt(speed2)])
    call w%emit('curve_rotate', [vn(1:3), 't       '], &
                ['x', 'y', 'z'], [v(1, 0)*cos(t) - v(2, 0)*sin(t), &
                                  v(1, 0)*sin(t) + v(2, 0)*cos(t), v(3, 0)])
    cnorm = sym(arena, 'cnorm'); snorm = sym(arena, 'snorm')
    call w%emit('curve_mode_bounds', ['cnorm', 'snorm', 'm    '], &
           ['b0', 'b1', 'b2'], [cnorm + snorm, m*(cnorm + snorm), m**2*(cnorm + snorm)])
    lower = sym(arena, 'lower'); accel = sym(arena, 'accel')
    vmax = sym(arena, 'vmax'); step = sym(arena, 'step'); far = sym(arena, 'far')
    call w%emit('curve_tube_bounds', &
                [character(5) :: 'lower', 'accel', 'vmax', 'step', 'far'], &
                ['local', 'apart'], [lower**2/(4*accel), (far - vmax*step)/2])
    min_speed = sym(arena, 'min_speed'); min_gap = sym(arena, 'min_gap')
    guide0 = sym(arena, 'guide0'); guide1 = sym(arena, 'guide1')
    call w%emit('curve_admission_bounds', &
                [character(9) :: 'min_speed', 'min_gap', 'accel', 'vmax', &
                 'guide0', 'guide1', 'step'], [character(5) :: 'lower', 'gap'], &
              [min_speed - accel*step/2, min_gap - (accel*guide0 + vmax*guide1)*step/2])
    call w%emit('curve_fourier_shift', ['c', 's', 't'], ['cs', 'ss'], &
                [c*cos(t) + s*sin(t), -c*sin(t) + s*cos(t)])
    ! Native proof of the fixed affine circular relabelling, and positive
    ! determinant. This specialization assumes radius > 0, radius + q2 > 0.
    radius = sym(arena, 'radius')
    engine = make_native_engine(arena)
    out(1:3) = [radius*cos(t) + q2*cos(t), &
                radius*sin(t) + q2*sin(t), q1]
    f(0:2) = [(radius + q2)*cos(t), (radius + q2)*sin(t), q1]
    do i = 1, 3
        identity = engine%zero_test(out(i) - f(i - 1))
        if (identity%verdict /= VERDICT_TRUE) &
            error stop 'gen/gen_curve_chart.f90: circular relabelling unproved'
    end do
    v(:, 0) = [0*t, 0*t, 1 + 0*t]
    v(:, 1) = [cos(t), sin(t), 0*t]
    v(:, 2) = [-(radius + q2)*sin(t), (radius + q2)*cos(t), 0*t]
    identity = engine%zero_test(dot(v(:, 0), cross(v(:, 1), v(:, 2))) - radius - q2)
    if (identity%verdict /= VERDICT_TRUE) &
        error stop 'gen/gen_curve_chart.f90: circular determinant unproved'
    call w%line('end module kin6d_curve_chart_leaves')
    call w%close()
    print '(a)', 'VERIFIED FortSym circular relabelling and determinant identities'
contains
    function dot(a, b) result(value)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: value
        value = a(1)*b(1) + a(2)*b(2) + a(3)*b(3)
    end function
    function cross(a, b) result(value)
        type(expr_t), intent(in) :: a(3), b(3)
        type(expr_t) :: value(3)
        value = [a(2)*b(3) - a(3)*b(2), a(3)*b(1) - a(1)*b(3), &
                 a(1)*b(2) - a(2)*b(1)]
    end function
    function total(value) result(d)
        type(expr_t), intent(in) :: value
        type(expr_t) :: d
        integer :: a, l
        d = 0*v(1, 0)
        do l = 0, 2
            do a = 1, 3
                d = d + diff(value, v(a, l))*v(a, l + 1) &
                    + diff(value, u(a, l))*u(a, l + 1)
            end do
        end do
    end function
    function along(value) result(d)
        type(expr_t), intent(in) :: value
        type(expr_t) :: d
        integer :: l
        d = 0*g(0)
        do l = 0, 2
            d = d + diff(value, g(l))*g(l + 1) + diff(value, n(l))*n(l + 1) &
                + diff(value, b(l))*b(l + 1)
        end do
    end function
    subroutine array_wrapper(name, two)
        character(*), intent(in) :: name
        logical, intent(in) :: two
        character(50) :: line
        integer :: a, l
        if (two) then
            call w%line('pure subroutine '//name//'(v,u,z)')
            call w%line('real(dp), intent(in) :: v(3,0:3),u(3,0:3)')
        else
            call w%line('pure subroutine '//name//'(v,z)')
            call w%line('real(dp), intent(in) :: v(3,0:3)')
        end if
        call w%line('real(dp), intent(out) :: z(3,0:3)')
        call w%line('call '//name//'_scalar( &')
        do l = 0, 3
            do a = 1, 3
                write (line, '(a,i1,a,i1,a)') 'v(', a, ',', l, '), &'
                call w%line(trim(line))
            end do
        end do
        if (two) then
            do l = 0, 3
                do a = 1, 3
                    write (line, '(a,i1,a,i1,a)') 'u(', a, ',', l, '), &'
                    call w%line(trim(line))
                end do
            end do
        end if
        do l = 0, 3
            do a = 1, 3
                write (line, '(a,i1,a,i1,a)') 'z(', a, ',', l, '), &'
                if (a == 3 .and. l == 3) &
                    write (line, '(a,i1,a,i1,a)') 'z(', a, ',', l, '))'
                call w%line(trim(line))
            end do
        end do
        call w%line('end subroutine')
    end subroutine
end program
