! One mathematical source for Reid68 nuclear potentials and fusion leaves.
program gen_pp_fusion
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, exp, sqrt, log, pi_expr, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(expr_t) :: r, x, vc, vt, vls, vs, kin, alpha, mp, hc, hb, ga
    type(expr_t) :: gamma, lam2, phase, ft, ep, endpoint, p, v, q, me, gv
    type(expr_t) :: c2, k, eta, h, aa, bb, f, g, fp, gp, deriv, node, z
    call arena%init()
    r = sym(arena, 'r'); x = 7*r/10
    kin = sym(arena, 'kin')
    vs = (-rat(arena, 10463_8, 1000_8)*exp(-x) &
        - rat(arena, 16506_8, 10_8)*exp(-4*x) &
        + rat(arena, 64842_8, 10_8)*exp(-7*x))/x
    vc = (-rat(arena, 10463_8, 1000_8)*exp(-x) &
        + rat(arena, 105468_8, 1000_8)*exp(-2*x) &
        - rat(arena, 31878_8, 10_8)*exp(-4*x) &
        + rat(arena, 99243_8, 10_8)*exp(-6*x))/x
    vt = -rat(arena, 10463_8, 1000_8)*((1 + 3/x + 3/x**2)*exp(-x) &
        - (12/x + 3/x**2)*exp(-4*x))/x &
        + (rat(arena, 35177_8, 100_8)*exp(-4*x) &
        - rat(arena, 16735_8, 10_8)*exp(-6*x))/x
    vls = (rat(arena, 70891_8, 100_8)*exp(-4*x) &
        - rat(arena, 27131_8, 10_8)*exp(-6*x))/x
    call w%open(arena, 'gen_pp_fusion', 'src/generated/kin6d_pp_fusion_leaves.f90')
    call w%line('! Generated by gen/gen_pp_fusion.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_pp_fusion_leaves')
    call w%line('use, intrinsic :: iso_fortran_env, only: dp => real64')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('pp_reid', ['r  ', 'kin'], ['vs ', 'vss', 'vsd', 'vdd'], &
        [vs, vc, sqrt(rat(arena, 8_8, 1_8))*vt, vc - 2*vt - 3*vls + 6*kin/r**2], &
        ad=.true.)
    gamma = sym(arena, 'gamma'); lam2 = sym(arena, 'lam2')
    phase = sym(arena, 'phase'); ft = sym(arena, 'ft')
    mp = sym(arena, 'mp'); alpha = sym(arena, 'alpha')
    hc = sym(arena, 'hc'); hb = sym(arena, 'hb'); ga = sym(arena, 'ga')
    ! Natural-unit Eq.20 converted to MeV barn; gamma in fm^-1, hbar MeV s.
    call w%emit('pp_sfactor', &
        ['mp   ', 'alpha', 'hb   ', 'hc   ', 'ga   ', 'gamma', 'lam2 ', 'phase', &
        'ft   '], &
        ['s'], [6*pi_expr(arena)**2*mp*alpha*log(rat(arena, 2_8, 1_8))* &
        hb/hc*ga**2*lam2*phase/(gamma**3*ft*100)], ad=.true.)
    ep = sym(arena, 'ep'); endpoint = sym(arena, 'endpoint'); p = sqrt(ep**2 - 1)
    v = sym(arena, 'v')
    call w%emit('pp_phase_integrand', ['ep      ', 'endpoint', 'v       '], &
        ['value'], [ep*p*(endpoint - ep)**2*v], ad=.true.)
    q = sym(arena, 'q'); me = sym(arena, 'me'); gv = sym(arena, 'gv')
    call w%emit('pp_ft', ['gv', 'me', 'hb'], ['ft'], &
        [2*pi_expr(arena)**3*log(rat(arena, 2_8, 1_8))*hb/(gv**2*me**5)], &
        ad=.true.)
    call w%emit('pp_lambda_integrand', ['gamma', 'q    ', 'r    '], &
        ['value'], [sqrt(gamma**3/2)*q*r], ad=.true.)
    c2 = sym(arena, 'c2'); k = sym(arena, 'k'); eta = sym(arena, 'eta')
    h = sym(arena, 'h'); aa = sym(arena, 'aa'); bb = sym(arena, 'bb')
    f = sym(arena, 'f'); g = sym(arena, 'g'); fp = sym(arena, &
        'fp'); gp = sym(arena, 'gp')
    deriv = sym(arena, 'deriv')
    call w%emit('pp_match', ['f    ', 'g    ', 'fp   ', 'gp   ', 'deriv', 'k    '], &
        ['aa', 'bb'], [g*deriv/k - gp, fp - f*deriv/k], ad=.true.)
    call w%emit('pp_match_norm', ['aa', 'bb'], ['norm'], &
        [sqrt(aa**2 + bb**2)], ad=.true.)
    call w%emit('pp_effective_range', ['aa ', 'bb ', 'c2 ', 'k  ', 'eta', 'h  '], &
        ['value'], [c2*k*aa/bb + 2*k*eta*h], ad=.true.)
    call w%emit('pp_overlap', ['gamma', 'q    ', 'c2   ', 'k    '], &
        ['lam2'], [gamma**3*q**2/(2*c2*k**2)], ad=.true.)
    call w%emit('pp_gv', ['ft', 'me', 'hb'], ['gv'], &
        [sqrt(2*pi_expr(arena)**3*log(rat(arena, 2_8, 1_8))*hb/(ft*me**5))], &
        ad=.true.)
    node = sym(arena, 'node')
    ep = 1 + (endpoint - 1)*(node + 1)/2
    p = sqrt(ep**2 - 1)
    z = 2*pi_expr(arena)*alpha*ep/p
    call w%emit('pp_phase_quad', ['node    ', 'endpoint', 'alpha   '], ['value'], &
        [ep*p*(endpoint - ep)**2*z/(exp(z) - 1)*(endpoint - 1)/2], ad=.true.)
    call w%line('end module kin6d_pp_fusion_leaves')
    call w%close()
end program
