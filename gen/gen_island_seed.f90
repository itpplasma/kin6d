program gen_island_seed
    ! Pointwise leaves of the energy-criterion island seeding
    ! (src/mhd/island_seed.f90, docs/island-seed.md).
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(expr_t) :: rmajor, rminor, c, s, br, bz, bphi, xi, alpha, babs
    type(expr_t) :: dbr, m, diota
    call arena%init()
    rmajor = sym(arena, 'rmajor'); rminor = sym(arena, 'rminor')
    c = sym(arena, 'c'); s = sym(arena, 's')
    br = sym(arena, 'br'); bz = sym(arena, 'bz'); bphi = sym(arena, 'bphi')
    xi = sym(arena, 'xi')
    dbr = sym(arena, 'dbr'); m = sym(arena, 'm'); diota = sym(arena, 'diota')
    call w%open(arena, 'gen_island_seed', &
        'src/generated/kin6d_island_seed_leaves.f90')
    call w%line('! Generated by gen/gen_island_seed.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_island_seed_leaves')
    call w%line('implicit none')
    call w%line('contains')
    ! Field-line rotation dtheta/dphi on the circle of minor radius rminor
    ! about the chart centre (cos theta, sin theta) = (c, s), and the radial
    ! field. rmajor is the metric radius (R, or R0 on the periodic cylinder).
    call w%emit('circle_rotation', &
        ['rmajor', 'rminor', 'c     ', 's     ', 'br    ', 'bz    ', 'bphi  '], &
        ['rotation', 'radial  '], &
        [rmajor*(c*bz - s*br)/(rminor*bphi), c*br + s*bz], ad=.true.)
    ! Resonant seed potential before its Fourier phase: alpha(xi) B/|B|
    ! with the C1 compact profile alpha = (1 - xi^2)^2, xi = (r - r_mn)/w.
    ! The caller applies the support |xi| < 1 and the phase.
    babs = sqrt(br**2 + bphi**2 + bz**2)
    alpha = (1 - xi**2)**2
    call w%emit('seed_potential', ['br  ', 'bphi', 'bz  ', 'xi  '], &
        ['ar', 'ap', 'az'], [alpha*br/babs, alpha*bphi/babs, alpha*bz/babs], &
        ad=.true.)
    ! Pendulum full width of an (m, n) chain with resonant radial field
    ! amplitude dbr, rotational-transform shear diota = d iota/dr and
    ! toroidal field bphi (all positive magnitudes):
    ! w = 4 sqrt(rmajor dbr / (m diota bphi)).
    call w%emit('pendulum_width', ['rmajor', 'dbr   ', 'm     ', 'diota ', &
        'bphi  '], ['width'], [4*sqrt(rmajor*dbr/(m*diota*bphi))], ad=.true.)
    call w%line('end module kin6d_island_seed_leaves')
    call w%close()
end program gen_island_seed
