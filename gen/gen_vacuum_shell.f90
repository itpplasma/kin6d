program gen_vacuum_shell
   ! Magnetic energy density of a curl-free vacuum field B = grad Phi pulled
   ! back by a map X from abstract coordinates (s1, s2, s3) into Cartesian
   ! space (3D free boundary, DESIGN 7.3, core note D6). g_i = dPhi/ds_i is the
   ! covariant (1-form) data, DX = dX/ds (row a: Cartesian component, column
   ! i: abstract direction), J = sigma*det(DX) > 0 and C = cof(DX), so that
   ! B = DX^{-T} g = C g/det(DX) and
   !   w = |B|^2 J/(2*mu0) = |C g|^2/(2*mu0*J).
   ! It is the 1-form counterpart of the frozen 2-form density |DX b|^2/(2 mu0 J)
   ! of gen_ideal_map. Leaves: w and J, the 12-gradient over (DX, g) and the
   ! upper triangle of the 12x12 Hessian.
   use fortsym_arena, only: arena_t
   use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
                           operator(*), operator(/), operator(**)
   use fortsym_diff, only: diff
   use fortsym_engine, only: engine_result_t, VERDICT_TRUE
   use fortsym_engine_native, only: native_engine_t, make_native_engine
   use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
   implicit none
   type(arena_t), target :: arena
   type(leaf_writer_t) :: w
   type(native_engine_t) :: engine
   type(engine_result_t) :: identity
   type(expr_t) :: d(3, 3), g(3), mu0, sigma, det, jac, density, cof(3, 3), bx(3)
   type(expr_t) :: vars(12), gradient(12), hessian(78), r, cyl(3, 3)
   character(8) :: names12(12), names78(78)
   integer :: a, i, j, n
   call arena%init()
   engine = make_native_engine(arena)
   do i = 1, 3
      do a = 1, 3
         write (names12(a + 3*(i - 1)), '(a,i1,i1)') 'd', a, i
         d(a, i) = sym(arena, trim(names12(a + 3*(i - 1))))
      end do
   end do
   do i = 1, 3
      write (names12(9 + i), '(a,i1)') 'g', i
      g(i) = sym(arena, trim(names12(9 + i)))
   end do
   mu0 = sym(arena, 'mu0'); sigma = sym(arena, 'sigma')
   call cofactors(d, cof, det)
   jac = sigma*det
   do a = 1, 3
      bx(a) = cof(a, 1)*g(1) + cof(a, 2)*g(2) + cof(a, 3)*g(3)
   end do
   density = (bx(1)**2 + bx(2)**2 + bx(3)**2)/(2*mu0*jac)
   ! Identity cylindrical map at phi = 0, columns d/dR, d/dZ, d/dphi and
   ! g = (Phi_R, Phi_Z, Phi_phi): w = R (Phi_R^2 + Phi_Z^2 + Phi_phi^2/R^2)/(2 mu0).
   r = sym(arena, 'r')
   cyl = 0*r
   cyl(1, 1) = 1 + 0*r; cyl(3, 2) = 1 + 0*r; cyl(2, 3) = r
   identity = engine%zero_test(identity_density() &
      - r*(g(1)**2 + g(2)**2 + g(3)**2/r**2)/(2*mu0))
   if (identity%verdict /= VERDICT_TRUE) error stop 'vacuum energy reduction unproved'
   do i = 1, 9
      vars(i) = d(1 + mod(i - 1, 3), 1 + (i - 1)/3)
   end do
   vars(10:12) = g
   do i = 1, 12
      gradient(i) = diff(density, vars(i))
   end do
   n = 0
   do j = 1, 12
      do i = 1, j
         n = n + 1
         write (names78(n), '(a,i2.2,i2.2)') 'h', i, j
         hessian(n) = diff(gradient(i), vars(j))
      end do
   end do
   call w%open(arena, 'gen_vacuum_shell', 'src/generated/kin6d_vacuum_shell_leaves.f90')
   call w%line('! Generated by gen/gen_vacuum_shell.f90; do not edit.')
   call w%line('! FortSym revision: '//fortsym_revision)
   call w%line('! w = |cof(DX) g|^2/(2 mu0 J), J = sigma det DX; d(a,i) = dX_a/ds_i,')
   call w%line('! g_i = dPhi/ds_i. Variables ordered (d11, d21, .., d33, g1, g2, g3).')
   call w%line('module kin6d_vacuum_shell_leaves')
   call w%line('implicit none')
   call w%line('contains')
   call w%emit('vacuum_energy_density', [character(8) :: names12, 'mu0', 'sigma'], &
      ['w  ', 'jac'], [density, jac])
   call w%emit('vacuum_energy_gradient', [character(8) :: names12, 'mu0', 'sigma'], &
      [character(8) :: ('q'//trim(names12(i)), i=1, 12)], gradient)
   call w%emit('vacuum_energy_hessian', [character(8) :: names12, 'mu0', 'sigma'], &
      names78, hessian)
   call w%line('end module kin6d_vacuum_shell_leaves')
   call w%close()
contains
   subroutine cofactors(m, c, dm)
      type(expr_t), intent(in) :: m(3, 3)
      type(expr_t), intent(out) :: c(3, 3), dm
      c(1, 1) = m(2, 2)*m(3, 3) - m(2, 3)*m(3, 2)
      c(1, 2) = m(2, 3)*m(3, 1) - m(2, 1)*m(3, 3)
      c(1, 3) = m(2, 1)*m(3, 2) - m(2, 2)*m(3, 1)
      c(2, 1) = m(1, 3)*m(3, 2) - m(1, 2)*m(3, 3)
      c(2, 2) = m(1, 1)*m(3, 3) - m(1, 3)*m(3, 1)
      c(2, 3) = m(1, 2)*m(3, 1) - m(1, 1)*m(3, 2)
      c(3, 1) = m(1, 2)*m(2, 3) - m(1, 3)*m(2, 2)
      c(3, 2) = m(1, 3)*m(2, 1) - m(1, 1)*m(2, 3)
      c(3, 3) = m(1, 1)*m(2, 2) - m(1, 2)*m(2, 1)
      dm = m(1, 1)*c(1, 1) + m(1, 2)*c(1, 2) + m(1, 3)*c(1, 3)
   end subroutine

   function identity_density() result(value)
      ! density with d -> cyl, sigma = -1
      type(expr_t) :: value, c(3, 3), dm, v(3)
      integer :: k
      call cofactors(cyl, c, dm)
      do k = 1, 3
         v(k) = c(k, 1)*g(1) + c(k, 2)*g(2) + c(k, 3)*g(3)
      end do
      value = (v(1)**2 + v(2)**2 + v(3)**2)/(2*mu0*(0 - dm))
   end function
end program gen_vacuum_shell
