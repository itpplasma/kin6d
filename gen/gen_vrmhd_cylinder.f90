program gen_vrmhd_cylinder
    !! Pointwise leaves of the helically symmetric straight-cylinder case
    !! (docs/vrmhd-cylinder.md): source shapes and the screw-section
    !! representation of axisymmetric cylinder fields.
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_expr, only: expr_t, sym, rat, tanh, exp, operator(+), &
        operator(-), operator(*), operator(/)
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(symengine_engine_t) :: engine
    type(engine_result_t) :: verdict
    type(expr_t) :: x, y, k, polar, axial, psin, centre, width, half
    type(expr_t) :: u1, u2, a
    engine = make_symengine_engine()
    half = rat(1_int64, 2_int64)
    x = sym('x'); y = sym('y'); k = sym('k')
    polar = sym('polar_over_r'); axial = sym('axial')
    psin = sym('psin'); centre = sym('centre'); width = sym('width')
    ! Screw chart with xi = (-k y, k x, 1); closed coordinate coframe of
    ! docs/vrmhd-section.md: A = (u1, u2, k (y u1 - x u2) + a), a = xi.A.
    ! The polar component enters divided by r, which is regular on the axis.
    u1 = -y*polar; u2 = x*polar
    a = axial + k*(x*x + y*y)*polar
    verdict = engine%zero_test(k*(y*u1 - x*u2) + a - axial)
    if (verdict%verdict /= VERDICT_TRUE) error stop 'coframe axial component'
    verdict = engine%zero_test(-k*y*u1 + k*x*u2 + axial - a)
    if (verdict%verdict /= VERDICT_TRUE) error stop 'orbit component xi.A'
    call w%open('gen_vrmhd_cylinder', 'src/generated/milca_vrmhd_cylinder_leaves.f90')
    call w%line('! Generated by gen/gen_vrmhd_cylinder.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_vrmhd_cylinder_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('vrmhd_cylinder_section', &
        [character(16) :: 'x', 'y', 'k', 'polar_over_r', 'axial'], &
        [character(16) :: 'u1', 'u2', 'a'], [u1, u2, a])
    ! Tanh heat-source shape and the Gaussian central current source.
    call w%emit('vrmhd_cylinder_heat_shape', &
        [character(16) :: 'psin', 'centre', 'width'], [character(16) :: 'shape'], &
        [half - half*tanh((psin - centre)/width)])
    call w%emit('vrmhd_cylinder_source_shape', &
        [character(16) :: 'psin', 'width'], [character(16) :: 'shape'], &
        [exp(-psin/(width*width))])
    call w%line('end module milca_vrmhd_cylinder_leaves')
    call w%close()
    print '(a)', 'screw coframe of cylinder fields: verified symbolically'
end program gen_vrmhd_cylinder
