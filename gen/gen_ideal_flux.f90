program gen_ideal_flux
    ! Pointwise flux-coordinate maps for global stability (docs/stability.md,
    ! P1e.3). Chart x(rho, theta, zeta) in Cartesian components with first and
    ! second derivatives; field B = grad psi x grad(theta + lambda)
    ! + iota grad zeta x grad psi, psi(rho) the toroidal flux per radian.
    ! Outputs: sqrt(g), B, g(i,j) = d_j B_i, grad p, and the linear map T from
    ! the contravariant densities D^u = sqrt(g) xi^u and their coordinate
    ! derivatives to (xi, A), A(i,j) = d_j xi_i. Also the coefficient matrix
    ! of the Eulerian delta-W form in (xi, A).
    use fortsym_expr, only: expr_t, sym, sin, cos, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: xu(3, 3), xuu(3, 3, 3), psi1, psi2, iota, iota1, lam(3, 3), pp
    type(expr_t) :: jac, jacu(3), sb(2), sbu(2, 3), b(3), bu(3, 3), dual(3, 3)
    type(expr_t) :: g(3, 3), gp(3), d(3), du(3, 3), xi(3), xiu(3, 3), a(3, 3)
    type(expr_t) :: zero, tmap(12, 12), outs(16 + 144), lu(3)
    character(8) :: inames(39), onames(16 + 144)
    integer :: i, j, k, u, v, at
    call writer%open('gen_ideal_flux', 'src/generated/milca_ideal_flux_leaves.f90')
    call inputs()
    zero = 0*psi1
    ! sqrt(g) and its coordinate derivatives.
    jac = triple(xu(:, 1), xu(:, 2), xu(:, 3))
    do u = 1, 3
        jacu(u) = triple(xuu(:, 1, u), xu(:, 2), xu(:, 3)) &
            + triple(xu(:, 1), xuu(:, 2, u), xu(:, 3)) &
            + triple(xu(:, 1), xu(:, 2), xuu(:, 3, u))
    end do
    ! Dual basis grad u.
    dual(:, 1) = cross(xu(:, 2), xu(:, 3))
    dual(:, 2) = cross(xu(:, 3), xu(:, 1))
    dual(:, 3) = cross(xu(:, 1), xu(:, 2))
    do u = 1, 3
        do i = 1, 3
            dual(i, u) = dual(i, u)/jac
        end do
    end do
    ! sqrt(g) B^theta = psi'(iota - lambda_zeta), sqrt(g) B^zeta = psi'(1 + lambda_theta).
    sb(1) = psi1*(iota - lu(3))
    sb(2) = psi1*(1 + lu(2))
    do u = 1, 3
        sbu(1, u) = -psi1*lam(3, u)
        sbu(2, u) = psi1*lam(2, u)
    end do
    sbu(1, 1) = sbu(1, 1) + psi2*(iota - lu(3)) + psi1*iota1
    sbu(2, 1) = sbu(2, 1) + psi2*(1 + lu(2))
    do i = 1, 3
        b(i) = (sb(1)*xu(i, 2) + sb(2)*xu(i, 3))/jac
        do u = 1, 3
            bu(i, u) = (sbu(1, u)*xu(i, 2) + sb(1)*xuu(i, 2, u) &
                + sbu(2, u)*xu(i, 3) + sb(2)*xuu(i, 3, u))/jac - b(i)*jacu(u)/jac
        end do
    end do
    do j = 1, 3
        do i = 1, 3
            g(i, j) = bu(i, 1)*dual(j, 1) + bu(i, 2)*dual(j, 2) + bu(i, 3)*dual(j, 3)
        end do
        gp(j) = pp*dual(j, 1)
    end do
    ! Displacement from densities: xi = sum_c D^c x_c / sqrt(g).
    do i = 1, 3
        xi(i) = (d(1)*xu(i, 1) + d(2)*xu(i, 2) + d(3)*xu(i, 3))/jac
        do u = 1, 3
            xiu(i, u) = zero
            do k = 1, 3
                xiu(i, u) = xiu(i, u) + (du(k, u)*xu(i, k) + d(k)*xuu(i, k, u))/jac
            end do
            xiu(i, u) = xiu(i, u) - xi(i)*jacu(u)/jac
        end do
    end do
    do j = 1, 3
        do i = 1, 3
            a(i, j) = xiu(i, 1)*dual(j, 1) + xiu(i, 2)*dual(j, 2) + xiu(i, 3)*dual(j, 3)
        end do
    end do
    ! div B = 0 and sqrt(g) div xi = d_u D^u hold for every chart; the general
    ! symbolic proof is too costly, so test_ideal_flux checks both at random
    ! jets.
    do j = 1, 12
        do i = 1, 12
            if (i <= 3) then
                tmap(i, j) = diff(xi(i), jet(j))
            else
                tmap(i, j) = diff(a(1 + mod(i - 4, 3), 1 + (i - 4)/3), jet(j))
            end if
        end do
    end do
    call writer%line('! Generated by gen/gen_ideal_flux.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module milca_ideal_flux_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    outs(1) = jac; onames(1) = 'jac'
    do i = 1, 3
        outs(1 + i) = b(i); write(onames(1 + i), '(a,i1)') 'b', i
        outs(13 + i) = gp(i); write(onames(13 + i), '(a,i1)') 'q', i
    end do
    do j = 1, 3
        do i = 1, 3
            outs(4 + i + 3*(j - 1)) = g(i, j)
            write(onames(4 + i + 3*(j - 1)), '(a,i1,i1)') 'g', i, j
        end do
    end do
    at = 16
    do j = 1, 12
        do i = 1, 12
            at = at + 1
            outs(at) = tmap(i, j)
            write(onames(at), '(a,i2.2,i2.2)') 't', i, j
        end do
    end do
    call writer%emit('flux_jets', inames, onames, outs)
    call emit_form_matrix()
    call emit_toroidal_chart()
    call emit_wrappers()
    call writer%line('end module milca_ideal_flux_leaves')
    call writer%close()
    print '(a)', 'PASS: flux-coordinate leaves emitted'
contains
    subroutine inputs()
        character(8) :: name
        at = 0
        do u = 1, 3
            do i = 1, 3
                write(name, '(a,i1,i1)') 'x', i, u
                at = at + 1; inames(at) = name; xu(i, u) = sym(trim(name))
            end do
        end do
        do v = 1, 3
            do u = 1, v
                do i = 1, 3
                    write(name, '(a,i1,i1,i1)') 'y', i, u, v
                    at = at + 1; inames(at) = name
                    xuu(i, u, v) = sym(trim(name)); xuu(i, v, u) = xuu(i, u, v)
                end do
            end do
        end do
        inames(at + 1:at + 5) = [character(8) :: 'psi1', 'psi2', 'iota', 'iota1', 'pp']
        psi1 = sym('psi1'); psi2 = sym('psi2'); iota = sym('iota')
        iota1 = sym('iota1'); pp = sym('pp')
        at = at + 5
        ! lambda_theta, lambda_zeta and their derivatives lam(c,u) = d_u lambda_c.
        inames(at + 1:at + 2) = [character(8) :: 'l2', 'l3']
        lu(1) = 0*psi1; lu(2) = sym('l2'); lu(3) = sym('l3')
        at = at + 2
        do v = 2, 3
            do u = 1, 3
                if (v == 3 .and. u == 2) then
                    lam(3, 2) = lam(2, 3); cycle
                end if
                write(name, '(a,i1,i1)') 'l', v, u
                at = at + 1; inames(at) = name; lam(v, u) = sym(trim(name))
            end do
        end do
        lam(1, :) = 0*psi1
        do k = 1, 3
            write(name, '(a,i1)') 'd', k
            d(k) = sym(trim(name))
            do u = 1, 3
                write(name, '(a,i1,i1)') 'e', k, u
                du(k, u) = sym(trim(name))
            end do
        end do
    end subroutine inputs

    type(expr_t) function jet(j)
        ! Density jet order: D(3), then D_rho(3), D_theta(3), D_zeta(3).
        integer, intent(in) :: j
        if (j <= 3) then
            jet = d(j)
        else
            jet = du(1 + mod(j - 4, 3), 1 + (j - 4)/3)
        end if
    end function jet

    subroutine emit_form_matrix()
        ! C(k,l) = d^2 form / d eta_k d xi_l in the order (xi(3), A(9)).
        type(expr_t) :: bb(3), gg(3, 3), p, q(3), gam, mu, x(3), aa(3, 3), y(3)
        type(expr_t) :: c(3, 3), form, cm(144), vx(12), vy(12)
        character(8) :: names(18), cn(144)
        integer :: kk, ll
        do i = 1, 3
            write(names(i), '(a,i1)') 'b', i; bb(i) = sym(trim(names(i)))
            write(names(12 + i), '(a,i1)') 'q', i; q(i) = sym(trim(names(12 + i)))
            do j = 1, 3
                write(names(3 + i + 3*(j - 1)), '(a,i1,i1)') 'g', i, j
                gg(i, j) = sym(trim(names(3 + i + 3*(j - 1))))
            end do
        end do
        names(16:18) = [character(8) :: 'p', 'gam', 'mu']
        p = sym('p'); gam = sym('gam'); mu = sym('mu')
        do i = 1, 3
            x(i) = sym('u'//achar(48 + i)); y(i) = sym('v'//achar(48 + i))
            do j = 1, 3
                aa(i, j) = sym('a'//achar(48 + i)//achar(48 + j))
                c(i, j) = sym('c'//achar(48 + i)//achar(48 + j))
            end do
        end do
        form = bernstein(bb, gg, p, q, gam, mu, x, aa, y, c)
        vx(1:3) = x; vy(1:3) = y
        do j = 1, 3
            do i = 1, 3
                vx(3 + i + 3*(j - 1)) = aa(i, j); vy(3 + i + 3*(j - 1)) = c(i, j)
            end do
        end do
        do ll = 1, 12
            do kk = 1, 12
                cm(kk + 12*(ll - 1)) = diff(diff(form, vy(kk)), vx(ll))
                write(cn(kk + 12*(ll - 1)), '(a,i2.2,i2.2)') 'c', kk, ll
            end do
        end do
        call writer%emit('flux_form_matrix', [character(8) :: names(1:15), &
            names(16), names(17), names(18)], cn, cm)
    end subroutine emit_form_matrix

    subroutine emit_toroidal_chart()
        ! x = R (cos phi, sin phi, 0) + Z e_z with R, Z, phi functions of
        ! (rho, theta, zeta); outputs in the argument order of flux_jets.
        type(expr_t) :: rr(0:3, 0:3), zz(0:3, 0:3), ff(0:3, 0:3), e(3), ep(3)
        type(expr_t) :: o(27), ez(3)
        character(8) :: an(29), on(27)
        integer :: uu, vv, c
        at = 0
        call jets('r', rr, .true., an, at)
        call jets('z', zz, .false., an, at)
        call jets('f', ff, .true., an, at)
        e = [cos(ff(0, 0)), sin(ff(0, 0)), 0*ff(0, 0)]
        ep = [-sin(ff(0, 0)), cos(ff(0, 0)), 0*ff(0, 0)]
        ez = [0*ff(0, 0), 0*ff(0, 0), 1 + 0*ff(0, 0)]
        c = 0
        do uu = 1, 3
            do i = 1, 3
                c = c + 1
                o(c) = rr(uu, 0)*e(i) + rr(0, 0)*ff(uu, 0)*ep(i) + zz(uu, 0)*ez(i)
                write(on(c), '(a,i1,i1)') 'x', i, uu
            end do
        end do
        do vv = 1, 3
            do uu = 1, vv
                do i = 1, 3
                    c = c + 1
                    o(c) = (rr(uu, vv) - rr(0, 0)*ff(uu, 0)*ff(vv, 0))*e(i) &
                        + (rr(uu, 0)*ff(vv, 0) + rr(vv, 0)*ff(uu, 0) &
                        + rr(0, 0)*ff(uu, vv))*ep(i) + zz(uu, vv)*ez(i)
                    write(on(c), '(a,i1,i1,i1)') 'y', i, uu, vv
                end do
            end do
        end do
        call writer%emit('flux_toroidal_chart', an(1:at), on, o)
    end subroutine emit_toroidal_chart

    subroutine jets(prefix, x, with_value, an, at)
        ! x(u,0) = d_u, x(u,v) = d_u d_v (symmetric), x(0,0) the value.
        character(*), intent(in) :: prefix
        type(expr_t), intent(out) :: x(0:3, 0:3)
        logical, intent(in) :: with_value
        character(8), intent(inout) :: an(:)
        integer, intent(inout) :: at
        character(8) :: name
        integer :: a1, a2
        x(0, 0) = 0*psi1
        if (with_value) then
            at = at + 1; an(at) = prefix; x(0, 0) = sym(prefix)
        end if
        do a1 = 1, 3
            write(name, '(a,i1)') prefix, a1
            at = at + 1; an(at) = name; x(a1, 0) = sym(trim(name))
            x(0, a1) = x(a1, 0)
        end do
        do a2 = 1, 3
            do a1 = 1, a2
                write(name, '(a,i1,i1)') prefix, a1, a2
                at = at + 1; an(at) = name
                x(a1, a2) = sym(trim(name)); x(a2, a1) = x(a1, a2)
            end do
        end do
    end subroutine jets

    subroutine emit_wrappers()
        ! Array interfaces over the scalar leaves, in their argument order.
        character(:), allocatable :: args
        character(12) :: item
        integer :: uu, vv
        args = ''
        do uu = 1, 3
            do i = 1, 3
                write(item, '(a,i1,a,i1,a)') 'xu(', i, ',', uu, ')'
                args = args//trim(item)//','
            end do
        end do
        do vv = 1, 3
            do uu = 1, vv
                do i = 1, 3
                    write(item, '(a,i1,a,i1,a,i1,a)') 'xuu(', i, ',', uu, ',', vv, ')'
                    args = args//trim(item)//','
                end do
            end do
        end do
        args = args//'psi1,psi2,iota,iota1,pp,'
        do i = 1, 7
            write(item, '(a,i1,a)') 'lam(', i, ')'
            args = args//trim(item)//','
        end do
        args = args//'jac,b(1),b(2),b(3),'
        do j = 1, 3
            do i = 1, 3
                write(item, '(a,i1,a,i1,a)') 'g(', i, ',', j, ')'
                args = args//trim(item)//','
            end do
        end do
        args = args//'q(1),q(2),q(3)'
        do j = 1, 12
            do i = 1, 12
                write(item, '(a,i0,a,i0,a)') ',t(', i, ',', j, ')'
                args = args//trim(item)
            end do
        end do
        call writer%line('pure subroutine flux_jets_array(xu, xuu, psi1, psi2, &')
        call writer%line('        iota, iota1, pp, lam, jac, b, g, q, t)')
        call writer%line('    use, intrinsic :: iso_fortran_env, only: dp => real64')
        call writer%line('    real(dp), intent(in) :: xu(3,3), xuu(3,3,3), psi1, psi2, &')
        call writer%line('        iota, iota1, pp, lam(7)')
        call writer%line('    real(dp), intent(out) :: jac, b(3), g(3,3), q(3), t(12,12)')
        call wrapped_call('flux_jets', args)
        call writer%line('end subroutine flux_jets_array')
        args = 'b(1),b(2),b(3),'
        do j = 1, 3
            do i = 1, 3
                write(item, '(a,i1,a,i1,a)') 'g(', i, ',', j, ')'
                args = args//trim(item)//','
            end do
        end do
        args = args//'q(1),q(2),q(3),p,gam,mu'
        do j = 1, 12
            do i = 1, 12
                write(item, '(a,i0,a,i0,a)') ',c(', i, ',', j, ')'
                args = args//trim(item)
            end do
        end do
        call writer%line('pure subroutine flux_form_matrix_array(b, g, q, p, gam, mu, c)')
        call writer%line('    use, intrinsic :: iso_fortran_env, only: dp => real64')
        call writer%line('    real(dp), intent(in) :: b(3), g(3,3), q(3), p, gam, mu')
        call writer%line('    real(dp), intent(out) :: c(12,12)')
        call wrapped_call('flux_form_matrix', args)
        call writer%line('end subroutine flux_form_matrix_array')
    end subroutine emit_wrappers

    subroutine wrapped_call(name, args)
        character(*), intent(in) :: name, args
        character(:), allocatable :: line
        integer :: start, cut
        line = '    call '//name//'('
        start = 1
        do while (start <= len(args))
            cut = min(len(args), start + 70 - len(line))
            if (cut < len(args)) cut = start - 1 + index(args(start:cut), ',', &
                back=.true.)
            line = line//args(start:cut)
            start = cut + 1
            if (start <= len(args)) then
                call writer%line(line//' &')
                line = '        '
            end if
        end do
        call writer%line(line//')')
    end subroutine wrapped_call

    function bernstein(bv, gv, p, qv, gam, mu, xv, av, yv, cv) result(form)
        ! Same Hermitian part of the Eulerian delta W as gen/gen_ideal_dw.f90.
        type(expr_t), intent(in) :: bv(3), gv(3, 3), p, qv(3), gam, mu, xv(3), &
            av(3, 3), yv(3), cv(3, 3)
        type(expr_t) :: form, qx(3), qy(3), cur(3), divx, divy, jqx(3), jqy(3)
        integer :: kk
        qx = qfield(bv, xv, av, gv); qy = qfield(bv, yv, cv, gv)
        cur(1) = (gv(3, 2) - gv(2, 3))/mu
        cur(2) = (gv(1, 3) - gv(3, 1))/mu
        cur(3) = (gv(2, 1) - gv(1, 2))/mu
        jqx = cross(cur, qx); jqy = cross(cur, qy)
        divx = av(1, 1) + av(2, 2) + av(3, 3)
        divy = cv(1, 1) + cv(2, 2) + cv(3, 3)
        form = gam*p*divx*divy
        do kk = 1, 3
            form = form + qx(kk)*qy(kk)/mu &
                + (xv(kk)*qv(kk)*divy + yv(kk)*qv(kk)*divx)/2 &
                - (yv(kk)*jqx(kk) + xv(kk)*jqy(kk))/2
        end do
    end function bernstein

    function qfield(bv, xv, av, gv) result(qv)
        type(expr_t), intent(in) :: bv(3), xv(3), av(3, 3), gv(3, 3)
        type(expr_t) :: qv(3), divx, divb
        integer :: kk, ll
        divx = av(1, 1) + av(2, 2) + av(3, 3)
        divb = gv(1, 1) + gv(2, 2) + gv(3, 3)
        do kk = 1, 3
            qv(kk) = xv(kk)*divb - bv(kk)*divx
            do ll = 1, 3
                qv(kk) = qv(kk) + bv(ll)*av(kk, ll) - xv(ll)*gv(kk, ll)
            end do
        end do
    end function qfield

    function cross(p, q) result(w)
        type(expr_t), intent(in) :: p(3), q(3)
        type(expr_t) :: w(3)
        w(1) = p(2)*q(3) - p(3)*q(2)
        w(2) = p(3)*q(1) - p(1)*q(3)
        w(3) = p(1)*q(2) - p(2)*q(1)
    end function cross

    function triple(p, q, r) result(t)
        type(expr_t), intent(in) :: p(3), q(3), r(3)
        type(expr_t) :: t, w(3)
        w = cross(q, r)
        t = p(1)*w(1) + p(2)*w(2) + p(3)*w(3)
    end function triple

end program gen_ideal_flux
