program gen_ideal_gll
    ! Axisymmetric specialization of the same frozen-in energy as ideal_map.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use kin6d_symbolic_ideal, only: frozen_energy
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: writer
    type(expr_t) :: z(7), b(3), d(3, 3), pressure, mu0, energy, jac, zero
    type(expr_t) :: gradient(7), hessian(28), u, v, delta
    character(8) :: names(7), gn(7), hn(28), args(12)
    integer :: i, j, k
    call arena%init()
    names = [character(8) :: 'r', 'ru', 'zu', 'ou', 'rv', 'zv', 'ov']
    do i = 1, 7
        z(i) = sym(arena, trim(names(i)))
        write(gn(i), '(a,i1)') 'g', i
    end do
    b = [sym(arena, 'b1'), sym(arena, 'b2'), sym(arena, 'b3')]
    pressure = sym(arena, 'pressure'); mu0 = sym(arena, 'mu0')
    zero = 0*z(1)
    ! Cartesian DX at phi+omega=0; rotation invariance removes omega's value.
    d(:, 1) = [z(2), z(1)*z(4), z(3)]
    d(:, 2) = [z(5), z(1)*z(7), z(6)]
    d(:, 3) = [zero, z(1), zero]
    energy = frozen_energy(d, b, pressure, mu0, zero - 1, jac)
    do i = 1, 7
        gradient(i) = diff(energy, z(i))
    end do
    k = 0
    do j = 1, 7
        do i = 1, j
            k = k + 1
            hessian(k) = diff(gradient(i), z(j))
            write(hn(k), '(a,i1,i1)') 'h', i, j
        end do
    end do
    args = [character(8) :: names, 'b1', 'b2', 'b3', 'pressure', 'mu0']
    call writer%open(arena, 'gen_ideal_gll', &
        'src/generated/kin6d_ideal_gll_leaves.f90')
    call writer%line('! Generated by gen/gen_ideal_gll.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module kin6d_ideal_gll_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('gll_energy', args, ['energy', 'jac   '], [energy, jac])
    call writer%emit('gll_gradient', args, gn, gradient)
    call writer%emit('gll_hessian', args, hn, hessian)
    ! Exact L boundary map from the disk in (u=(R^2-1)/2,Z).
    u = sym(arena, 'u'); v = sym(arena, 'v'); delta = sym(arena, 'delta')
    call writer%emit('gll_landreman_map', ['u    ', 'v    ', 'delta'], &
        ['r', 'z'], [sqrt(1 + 2*sqrt(delta)*u), sqrt(delta)*v])
    call writer%line('end module kin6d_ideal_gll_leaves')
    call writer%close()
end program
