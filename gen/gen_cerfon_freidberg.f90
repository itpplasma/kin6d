program gen_cerfon_freidberg
    ! Cerfon & Freidberg, Phys. Plasmas 17, 032502 (2010),
    ! doi:10.1063/1.3328818, eqs. (5), (6), (8). x=R/R0>0, y=Z/R0.
    ! This is the up-down symmetric family, including logarithmic terms.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, log, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(leaf_writer_t) :: w
    type(expr_t) :: x, y, a, c(7), basis(7), particular, psi, jet(6), residual
    character(2) :: name
    integer :: i
    call arena%init()
    engine = make_native_engine(arena)
    x = sym(arena, 'x'); y = sym(arena, 'y'); a = sym(arena, 'a')
    ! Eq. (8), in the published ordering, without a coefficient fit.
    basis(1) = 1 + 0*x
    basis(2) = x**2
    basis(3) = y**2 - x**2*log(x)
    basis(4) = x**4 - 4*x**2*y**2
    basis(5) = 2*y**4 - 9*y**2*x**2 + 3*x**4*log(x) - 12*x**2*y**2*log(x)
    basis(6) = x**6 - 12*x**4*y**2 + 8*x**2*y**4
    basis(7) = 8*y**6 - 140*y**4*x**2 + 75*y**2*x**4 - 15*x**6*log(x) &
        + 180*x**4*y**2*log(x) - 120*x**2*y**4*log(x)
    particular = x**4/8 + a*(x**2*log(x)/2 - x**4/8) ! Eq. (6).
    psi = particular
    do i = 1, 7
        write (name, '(a,i1)') 'c', i
        c(i) = sym(arena, name)
        psi = psi + c(i)*basis(i)
        residual = diff(diff(basis(i), x), x) - diff(basis(i), x)/x &
            + diff(diff(basis(i), y), y)
        identity = engine%zero_test(residual)
        if (identity%verdict /= VERDICT_TRUE) error stop 'homogeneous GS identity'
    end do
    jet = [psi, diff(psi, x), diff(psi, y), diff(diff(psi, x), x), &
        diff(diff(psi, x), y), diff(diff(psi, y), y)]
    identity = engine%zero_test(jet(4) - jet(2)/x + jet(6) - ((1 - a)*x**2 + a))
    if (identity%verdict /= VERDICT_TRUE) error stop 'full GS identity (5)'
    call w%open(arena, 'gen_cerfon_freidberg', &
        'src/generated/kin6d_cerfon_freidberg_leaves.f90')
    call w%line('! Generated by gen/gen_cerfon_freidberg.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Cerfon & Freidberg (2010), eqs. (5)-(8); x>0.')
    call w%line('module kin6d_cerfon_freidberg_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('cerfon_freidberg_jet', &
        [character(2) :: 'x', 'y', 'a', 'c1', 'c2', 'c3', 'c4', 'c5', 'c6', 'c7'], &
        [character(3) :: 'psi', 'px', 'py', 'pxx', 'pxy', 'pyy'], jet, ad=.true.)
    call w%line('end module kin6d_cerfon_freidberg_leaves')
    call w%close()
    print '(a)', 'Cerfon-Freidberg: eight exact GS identities PASS (no probes)'
end program
