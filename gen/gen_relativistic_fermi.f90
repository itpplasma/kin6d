program gen_relativistic_fermi
    ! Relativistic ideal Fermi gas leaves (campaign case Q8). The normalization
    ! of gen_fermi_gas is retained: r=p/pF, theta=kB*T/EF, mu=chemical/EF with
    ! the nonrelativistic EF=pF**2/(2*m). The relativity parameter is
    ! x=pF/(m*c). The kinetic energy E=m*c**2*(sqrt(1+x**2*r**2)-1) becomes
    ! eps=2*r**2/(s+1), s=sqrt(1+x**2*r**2), which equals r**2 exactly at x=0.
    ! The square root is carried as an auxiliary chart variable s with
    ! ds/dr=x**2*r/s; all identities below are proved after substitution.
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, exp, sqrt, abs, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_products, only: jvp
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(expr_t) :: r, s, x, theta, mu, occupation, root, eps, er, sr
    type(expr_t) :: fr, fm, ft, physical
    type(expr_t) :: moments(11), curvature(11), eof(6), gradient(6)
    type(expr_t) :: iv(11), dmu, directions(4), variables(4)
    type(expr_t) :: radius, factor, kappa, tails(3), bounds(11)
    integer :: j, m, k
    character(10), parameter :: names(11) = [character(10) :: &
        'i2', 'ip', 'iu', 'i2mu', 'i2theta', 'ipmu', 'iptheta', 'iumu', &
        'iutheta', 'i2mumu', 'i2mutheta']
    character(16), parameter :: outputs(6) = [character(16) :: 'chemical', &
        'pressure', 'energy', 'susceptibility', 'screening_ratio', 'bulk_modulus']

    call arena%init()
    engine = make_native_engine(arena)
    r = sym(arena, 'r'); s = sym(arena, 's'); x = sym(arena, 'relativity')
    theta = sym(arena, 'theta'); mu = sym(arena, 'mu')
    occupation = sym(arena, 'occupation'); radius = sym(arena, 'radius')
    root = sqrt(1 + x**2*r**2)
    eps = 2*r**2/(s + 1)
    er = 2*r/s
    sr = x**2*r/s
    ! Chart identities: ds/dr and d(eps)/dr=2*r/s=v/c*(m*c/pF)*2 (group velocity).
    call prove(subs(sr, s, root) - diff(root, r), 'chart root')
    ! Prove on the chart variety s**2=1+x**2*r**2 by eliminating x.
    call prove(subs(diff(eps, r) + diff(eps, s)*sr - er, x, sqrt(s**2 - 1)/r), &
               'chart energy')
    fr = -er/theta*occupation*(1 - occupation)
    fm = occupation*(1 - occupation)/theta
    ft = (eps - mu)/theta**2*occupation*(1 - occupation)
    ! Occupation identities in the chart (r,s): d/dr acts as d_r+sr*d_s.
    physical = 1/(1 + exp((eps - mu)/theta))
    call prove(subs(subs(fr, occupation, physical) - diff(physical, r) - &
                    diff(physical, s)*sr, x, sqrt(s**2 - 1)/r), 'occupation r')
    call prove(subs(fm, occupation, physical) - diff(physical, mu), 'occupation mu')
    call prove(subs(ft, occupation, physical) - diff(physical, theta), &
               'occupation theta')
    ! Density, pressure p*v/3 and kinetic-energy moments with their mu/theta
    ! derivatives. P/(n*EF)=ip, U/(n*EF)=3*iu, density 3*i2=1.
    moments(1) = r**2*occupation
    moments(2) = r**3*er*occupation
    moments(3) = r**2*eps*occupation
    moments(4) = d_mu(moments(1)); moments(5) = d_theta(moments(1))
    moments(6) = d_mu(moments(2)); moments(7) = d_theta(moments(2))
    moments(8) = d_mu(moments(3)); moments(9) = d_theta(moments(3))
    moments(10) = d_mu(moments(4)); moments(11) = d_theta(moments(4))
    do j = 1, 11
        curvature(j) = d_r(d_r(moments(j)))
        iv(j) = sym(arena, trim(names(j)))
    end do
    eof = [mu, iv(2), 3*iv(3), 3*iv(4), sqrt(2*iv(4)), 1/(3*iv(4))]
    dmu = -iv(5)/iv(4)
    variables = [mu, iv(2), iv(3), iv(4)]
    directions = [dmu, iv(7) + iv(6)*dmu, iv(9) + iv(8)*dmu, iv(11) + iv(10)*dmu]
    gradient = jvp(eof, variables, directions)

    call w%open(arena, 'gen_relativistic_fermi', 'src/generated/kin6d_relativistic_fermi_leaves.f90')
    w%runtime%log = str('log')
    w%runtime%sqrt = str('sqrt')
    write (w%unit, '(a)') '! Generated by gen/gen_relativistic_fermi.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, '(a)') '! Ideal homogeneous relativistic 3D spin-two Fermi gas.'
    write (w%unit, '(a)') '! r=p/pF; x=pF/(m*c); s=sqrt(1+x^2 r^2); eps=2r^2/(s+1)=E/EF_nr.'
    write (w%unit, '(a)') '! theta=kBT/EF_nr>0; mu=chemical_potential/EF_nr; 3*i2=1.'
    write (w%unit, '(a)') '! AD smooth theta>0; root products use implicit equations.'
    write (w%unit, '(a)') 'module kin6d_relativistic_fermi_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('fermi_rel_root', ['r         ', 'relativity'], ['s'], [root], &
              ad=.true., interval=.true.)
    call w%emit('fermi_rel_energy', ['r', 's'], ['eps'], [eps], ad=.true., &
              interval=.true.)
    call w%emit('fermi_rel_argument', ['r    ', 's    ', 'theta', 'mu   '], ['z'], &
              [(eps - mu)/theta], ad=.true., interval=.true.)
    call w%emit('fermi_rel_integrands', [character(10) :: 'r', 's', 'theta', 'mu', &
              'relativity', 'occupation'], names, moments, interval=.true.)
    call w%emit('fermi_rel_density_integrand', [character(10) :: 'r', 's', &
              'theta', 'mu', 'relativity', 'occupation'], ['i2  ', 'i2mu'], &
              [moments(1), moments(4)], interval=.true.)
    call w%emit('fermi_rel_density_curvature_interval', [character(10) :: 'r', &
              's', 'theta', 'mu', 'relativity', 'occupation'], ['curvature'], &
              [curvature(1)], rigorous=.true.)
    call w%emit('fermi_rel_curvature_interval', [character(10) :: 'r', 's', &
              'theta', 'mu', 'relativity', 'occupation'], names, curvature, &
              rigorous=.true.)
    call w%emit('fermi_rel_eos', ['mu  ', 'ip  ', 'iu  ', 'i2mu'], outputs, eof, &
              ad=.true., interval=.true.)
    call w%emit('fermi_rel_theta_derivative', names, outputs, gradient, &
              interval=.true.)
    ! Candidate bracket and integration radius. f>1/2 on r<=2 at mu=eps(2)
    ! gives density above four. The radius solves eps(R)=4*eps(1)+36*theta
    ! through the exact inverse r(eps)=sqrt(eps*(1+x**2*eps/4)).
    call w%emit('fermi_rel_root_bracket', ['theta     ', 'relativity'], &
              ['upper ', 'radius'], [8/(sqrt(1 + 4*x**2) + 1) + 4*theta, &
              sqrt((8/(sqrt(1 + x**2) + 1) + 36*theta)* &
                   (1 + x**2*(8/(sqrt(1 + x**2) + 1) + 36*theta)/4))])
    ! Graded mesh for degenerate states: a window of halfwidth 20*theta/eps'(1)
    ! around the cold Fermi surface r=1 resolves the occupation edge. The mesh
    ! only places quadrature cells; the certificate holds for any edges.
    call w%emit('fermi_rel_window', ['theta     ', 'relativity'], ['halfwidth'], &
              [20*theta*sqrt(1 + x**2)])
    call w%emit('fermi_rel_grid', ['index', 'cells', 'lower', 'upper'], &
              ['coordinate'], [sym(arena, 'lower') + (sym(arena, 'upper') - &
              sym(arena, 'lower'))*sym(arena, 'index')/sym(arena, 'cells')])
    ! Convexity tail: eps''=2/s**3>0, so eps(r)>=eps(R)+eps'(R)*(r-R) and
    ! f<=a*exp(-kappa*(r-R)), a=exp((mu-eps(R))/theta), kappa=eps'(R)/theta.
    ! Tm=a*sum_j m!/(m-j)!*R**(m-j)/kappa**(j+1) bounds integral_R^oo r^m f.
    ! With eps<=r**2, eps'<=2*r, f*(1-f)<=f and abs(1-2f)<=1 every moment
    ! integrand is bounded by the listed combinations.
    factor = exp((mu - subs(eps, r, radius))/theta)
    kappa = subs(er, r, radius)/theta
    do k = 1, 3
        m = 2*k
        tails(k) = radius**m/kappa
        do j = 1, m
            tails(k) = tails(k) + falling(m, j)*radius**(m - j)/kappa**(j + 1)
        end do
        tails(k) = factor*tails(k)
    end do
    bounds = [tails(1), 2*tails(2), tails(2), tails(1)/theta, &
              (tails(2) + abs(mu)*tails(1))/theta**2, 2*tails(2)/theta, &
              2*(tails(3) + abs(mu)*tails(2))/theta**2, tails(2)/theta, &
              (tails(3) + abs(mu)*tails(2))/theta**2, tails(1)/theta**2, &
              (tails(2) + abs(mu)*tails(1))/theta**3 + tails(1)/theta**2]
    call w%emit('fermi_rel_tail_interval', [character(10) :: 'theta', 'mu', &
              'radius', 's', 'relativity'], names, bounds, rigorous=.true.)
    ! Limiting normalized pressures P/(n*EF): cold nonrelativistic 2/5,
    ! cold ultrarelativistic (hbar*c/4)*(3*pi**2)**(1/3)*n**(4/3)/(n*EF)
    ! =1/(2*x), classical ideal gas n*kB*T/(n*EF)=theta for every x.
    call w%emit('fermi_rel_limits', ['theta     ', 'relativity'], &
              ['nonrelativistic  ', 'ultrarelativistic', 'classical        '], &
              [rat(arena, 2_int64, 5_int64), 1/(2*x), theta], ad=.true.)
    write (w%unit, '(a)') 'end module kin6d_relativistic_fermi_leaves'
    call w%close()

contains

    pure integer function falling(m, j) result(value)
        integer, intent(in) :: m, j
        integer :: i
        value = 1
        do i = 0, j - 1
            value = value*(m - i)
        end do
    end function falling

    subroutine prove(expression, label)
        type(expr_t), intent(in) :: expression
        character(*), intent(in) :: label
        identity = engine%zero_test(expression)
        if (identity%verdict /= VERDICT_TRUE) &
            error stop 'relativistic Fermi identity unproved: '//label
    end subroutine prove

    function d_r(expression) result(derivative)
        type(expr_t), intent(in) :: expression
        type(expr_t) :: derivative
        derivative = diff(expression, r) + diff(expression, s)*sr + &
                     diff(expression, occupation)*fr
    end function d_r

    function d_mu(expression) result(derivative)
        type(expr_t), intent(in) :: expression
        type(expr_t) :: derivative
        derivative = diff(expression, mu) + diff(expression, occupation)*fm
    end function d_mu

    function d_theta(expression) result(derivative)
        type(expr_t), intent(in) :: expression
        type(expr_t) :: derivative
        derivative = diff(expression, theta) + diff(expression, occupation)*ft
    end function d_theta

end program gen_relativistic_fermi
