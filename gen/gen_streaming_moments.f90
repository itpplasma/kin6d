program gen_streaming_moments
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: vl, vr, al, ar, acc, radius, density, current, velocity
    call arena%init()
    vl = sym(arena, 'vl'); vr = sym(arena, 'vr')
    al = sym(arena, 'al'); ar = sym(arena, 'ar'); acc = sym(arena, 'acc')
    radius = sym(arena, 'radius'); density = sym(arena, 'density')
    current = sym(arena, 'current'); velocity = sym(arena, 'velocity')
    call w%open(arena, 'gen_streaming_moments', 'src/generated/kin6d_streaming_moments_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_streaming_moments.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, '(a)') '! n=0.5 integral f dv, j=0.5 integral v*f dv, u=j/n.'
    write (w%unit, '(a)') '! Velocity domain [-1,1]; current P1 cell integral is exact.'
    write (w%unit, '(a)') &
        '! Bulk quotient requires a strictly positive density enclosure.'
    write (w%unit, '(a)') '! JVP/VJP: smooth leaves; Euclidean coefficient pairing.'
    write (w%unit, '(a)') 'module kin6d_streaming_moments_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('streaming_moments_current_cell', &
        ['vl ', 'vr ', 'al ', 'ar ', 'acc'], ['next'], &
        [acc + (vr - vl)*((2*vl + vr)*al + (vl + 2*vr)*ar)/12], &
        ad=.true., interval=.true.)
    ! |0.5 integral v*(f-fbar) dv| <= radius/2 on [-1,1].
    call w%emit('streaming_moments_current_radius', ['radius'], ['error'], &
        [radius/2], interval=.true.)
    call w%emit('streaming_moments_bulk', ['density', 'current'], ['bulk'], &
        [current/density], ad=.true., interval=.true.)
    call w%emit('streaming_moments_initial', ['velocity'], ['mean    ', 'harmonic'], &
        [1 + velocity/2, (1 + velocity/2)/2], ad=.true., interval=.true.)
    write (w%unit, '(a)') 'end module kin6d_streaming_moments_leaves'
    call w%close()
end program gen_streaming_moments
