program gen_fp
    use fortsym, only: arena_t, expr_t, sym, operator(+), operator(-), &
                       operator(*), operator(/), operator(**), exp
    use fortsym_diff, only: diff
    use fortsym_string, only: str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    type(arena_t), target :: arena
    type(expr_t) :: v, theta, h, a, b, mass, z, vm, lo, hi, index, count, radius
    type(expr_t) :: gaussian, flux, step, curvature
    integer :: unit
    call arena%init()
    v = sym(arena, 'v'); theta = sym(arena, 'theta'); h = sym(arena, 'h')
    a = sym(arena, 'a'); b = sym(arena, 'b'); mass = sym(arena, 'mass')
    z = sym(arena, 'z'); vm = sym(arena, 'vm')
    lo = sym(arena, 'lo'); hi = sym(arena, 'hi')
    index = sym(arena, 'index'); count = sym(arena, 'count')
    radius = sym(arena, 'radius')
    ! OU heat bath on [-2,2]: J=theta*f'+v*f, f_t=nu*J', J(+-2)=0.
    ! theta>0, nu>0, prescribed mass>0. nu changes relaxation, not this state.
    ! Exact stationary ODE and mass fix f=mass*exp(-v^2/(2 theta))/Z.
    ! Centered zero-flux recurrence is the candidate solver, not this formula.
    gaussian = exp(-v**2/(2*theta))
    flux = theta*(b - a)/h + v*(a + b)/2
    step = a*(2*theta - h*v)/(2*theta + h*v)
    ! |Gaussian''| <= (vm^2/theta^2 + 1/theta), since Gaussian <= 1.
    curvature = vm**2/theta**2 + 1/theta
    open (newunit=unit, file='src/generated/kin6d_fp_leaves.f90', status='replace')
    write (unit, '(a)') '! Generated by gen/gen_fp.f90; do not edit.'
    write (unit, '(a)') '! Independent oracle: zero flux gives log f(v)-log f(0)=-v^2/(2 theta).'
    write (unit, '(a)') '! Finite domain, prescribed mass, positive heat-bath theta; no whole-line claim.'
    write (unit, '(a)') 'module kin6d_fp_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('fp_coordinate', ['lo   ', 'hi   ', 'index', 'count'], &
              ['value'], [lo + (hi - lo)*index/count])
    call emit('fp_cell', ['lo', 'hi'], ['v', 'h'], [(lo + hi)/2, hi - lo])
    call emit('fp_interval_cell', ['lo', 'hi'], ['v', 'h'], &
              [(lo + hi)/2, hi - lo], rigorous=.true.)
    call emit('fp_step', ['v    ', 'theta', 'h    ', 'a    '], ['b'], [step], ad=.true.)
    call emit('fp_flux', ['v    ', 'theta', 'h    ', 'a    ', 'b    '], &
              ['value'], [flux], ad=.true.)
    call emit('fp_area', ['h', 'a', 'b'], ['value'], [h*(a + b)/2])
    call emit('fp_interval_area', ['h', 'a', 'b'], ['value'], &
              [h*(a + b)/2], rigorous=.true.)
    call emit('fp_add', ['a', 'b'], ['value'], [a + b])
    call emit('fp_scale', ['a   ', 'mass', 'z   '], ['value'], [a*mass/z], ad=.true.)
    call emit('fp_weight', ['lo', 'hi', 'v '], ['value'], [(v - lo)/(hi - lo)])
    call emit('fp_interpolate', ['a', 'b', 'v'], ['value'], [a*(1 - v) + b*v], ad=.true.)
    call emit('fp_normalizer_cell', ['v    ', 'theta', 'h    ', 'vm   '], &
              ['lower', 'upper'], &
              [h*gaussian - h**3*curvature/24, h*gaussian + h**3*curvature/24], &
              rigorous=.true.)
    call emit('fp_interval_add', ['a', 'b'], ['value'], [a + b], rigorous=.true.)
    call emit('fp_reference', ['v    ', 'theta', 'mass ', 'z    '], &
              ['value'], [mass*gaussian/z], rigorous=.true.)
    call emit('fp_difference', ['a', 'b'], ['value'], [a - b], rigorous=.true.)
    call emit('fp_interpolation_error', ['theta', 'mass ', 'z    ', 'h    ', 'vm   '], &
              ['value'], [mass*h**2*curvature/(8*z)], rigorous=.true.)
    call emit('fp_interval_interpolate', ['a', 'b', 'v'], ['value'], &
              [a*(1 - v) + b*v], rigorous=.true.)
    call emit('fp_interval_weight', ['lo', 'hi', 'v '], ['value'], &
              [(v - lo)/(hi - lo)], rigorous=.true.)
    call emit('fp_band', ['a', 'b'], ['lower', 'upper'], &
              [a - b, a + b], rigorous=.true.)
    call emit('fp_mass_error_band', ['lo    ', 'hi    ', 'radius'], &
              ['lower', 'upper'], [lo - 4*radius, hi + 4*radius], rigorous=.true.)
    write (unit, '(a)') 'end module kin6d_fp_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, roots, rigorous, ad)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: rigorous, ad
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        logical :: ok
        character(:), allocatable :: message
        integer :: k
        if (present(rigorous)) then
            rspec%name = str(name); rspec%generator = str('gen_fp')
            rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
            rspec%runtime%exp = str('exp')
            allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
            do k = 1, size(args)
                rspec%args(k) = str(trim(args(k)))
            end do
            do k = 1, size(outputs)
                rspec%outputs(k) = str(trim(outputs(k)))
            end do
            write (unit, '(a)') chars(emit_rigorous_kernel(roots, rspec, ok, message))
            if (.not. ok) error stop message
            return
        end if
        spec%name = str(name); spec%generator = str('gen_fp')
        spec%pure_procedure = .true.; spec%elemental_procedure = .true.
        spec%generator_revision = str('102c1cbe392e1ba70d169fd75aeda0f2ffe8ab88')
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do k = 1, size(args)
            spec%args(k) = str(trim(args(k)))
        end do
        do k = 1, size(outputs)
            spec%outputs(k) = str(trim(outputs(k)))
        end do
        write (unit, '(a)') chars(emit_kernel(roots, spec))
        if (present(ad)) call derivatives(name, args, outputs, roots)
    end subroutine
    subroutine derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: parameters(:), jroots(:), vroots(:)
        character(64), allocatable :: jargs(:), jouts(:), vargs(:), vouts(:)
        integer :: k, l, narg, nout
        narg = size(args); nout = size(outputs)
        allocate (parameters(narg), jroots(nout), vroots(narg))
        allocate (jargs(2*narg), jouts(nout), vargs(narg + nout), vouts(narg))
        do k = 1, narg
            parameters(k) = sym(arena, trim(args(k)))
            jargs(k) = trim(args(k)); jargs(narg + k) = 'd_'//trim(args(k))
            vargs(k) = trim(args(k)); vouts(k) = 'g_'//trim(args(k))
        end do
        do l = 1, nout
            jouts(l) = 'd_'//trim(outputs(l)); vargs(narg + l) = 'w_'//trim(outputs(l))
            jroots(l) = 0*roots(l)
            do k = 1, narg
                jroots(l) = jroots(l) + diff(roots(l), parameters(k))* &
                            sym(arena, trim(jargs(narg + k)))
            end do
        end do
        do k = 1, narg
            vroots(k) = 0*roots(1)
            do l = 1, nout
                vroots(k) = vroots(k) + diff(roots(l), parameters(k))* &
                            sym(arena, trim(vargs(narg + l)))
            end do
        end do
        call emit(name//'_jvp', jargs, jouts, jroots)
        call emit(name//'_vjp', vargs, vouts, vroots)
    end subroutine
end program
