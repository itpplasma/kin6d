program gen_fp
    use fortsym, only: expr_t, sym, operator(+), operator(-), &
                       operator(*), operator(/), operator(**), exp
    use milca_gen_support, only: leaf_writer_t
    use milca_symbolic_physics, only: p1_weight, p1_blend
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: v, theta, h, a, b, mass, z, vm, lo, hi, index, count, radius
    type(expr_t) :: gaussian, flux, step, curvature
    v = sym('v'); theta = sym('theta'); h = sym('h')
    a = sym('a'); b = sym('b'); mass = sym('mass')
    z = sym('z'); vm = sym('vm')
    lo = sym('lo'); hi = sym('hi')
    index = sym('index'); count = sym('count')
    radius = sym('radius')
    ! OU heat bath on [-2,2]: J=theta*f'+v*f, f_t=nu*J', J(+-2)=0.
    ! theta>0, nu>0, prescribed mass>0. nu changes relaxation, not this state.
    ! Exact stationary ODE and mass fix f=mass*exp(-v^2/(2 theta))/Z.
    ! Centered zero-flux recurrence is the candidate solver, not this formula.
    gaussian = exp(-v**2/(2*theta))
    flux = theta*(b - a)/h + v*(a + b)/2
    step = a*(2*theta - h*v)/(2*theta + h*v)
    ! |Gaussian''| <= (vm^2/theta^2 + 1/theta), since Gaussian <= 1.
    curvature = vm**2/theta**2 + 1/theta
    call w%open('gen_fp', 'src/generated/kin6d_fp_leaves.f90')
    call w%line('! Generated by gen/gen_fp.f90; do not edit.')
    call w%line('! Independent oracle: zero flux gives log f(v)-log f(0)=-v^2/(2 theta).')
    call w%line('! Finite domain, prescribed mass, positive heat-bath theta; no whole-line claim.')
    call w%line('module kin6d_fp_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('fp_coordinate', ['lo   ', 'hi   ', 'index', 'count'], &
              ['value'], [lo + (hi - lo)*index/count])
    call w%emit('fp_cell', ['lo', 'hi'], ['v', 'h'], [(lo + hi)/2, hi - lo])
    call w%emit('fp_interval_cell', ['lo', 'hi'], ['v', 'h'], &
              [(lo + hi)/2, hi - lo], rigorous=.true.)
    call w%emit('fp_step', ['v    ', 'theta', 'h    ', 'a    '], ['b'], [step], ad=.true.)
    call w%emit('fp_flux', ['v    ', 'theta', 'h    ', 'a    ', 'b    '], &
              ['value'], [flux], ad=.true.)
    call w%emit('fp_area', ['h', 'a', 'b'], ['value'], [h*(a + b)/2])
    call w%emit('fp_interval_area', ['h', 'a', 'b'], ['value'], &
              [h*(a + b)/2], rigorous=.true.)
    call w%emit('fp_add', ['a', 'b'], ['value'], [a + b])
    call w%emit('fp_scale', ['a   ', 'mass', 'z   '], ['value'], [a*mass/z], ad=.true.)
    call w%emit('fp_weight', ['lo', 'hi', 'v '], ['value'], [p1_weight(v, lo, hi)])
    call w%emit('fp_interpolate', ['a', 'b', 'v'], ['value'], [p1_blend(a, b, v)], ad=.true.)
    call w%emit('fp_normalizer_cell', ['v    ', 'theta', 'h    ', 'vm   '], &
              ['lower', 'upper'], &
              [h*gaussian - h**3*curvature/24, h*gaussian + h**3*curvature/24], &
              rigorous=.true.)
    call w%emit('fp_interval_add', ['a', 'b'], ['value'], [a + b], rigorous=.true.)
    call w%emit('fp_reference', ['v    ', 'theta', 'mass ', 'z    '], &
              ['value'], [mass*gaussian/z], rigorous=.true.)
    call w%emit('fp_difference', ['a', 'b'], ['value'], [a - b], rigorous=.true.)
    call w%emit('fp_interpolation_error', ['theta', 'mass ', 'z    ', 'h    ', 'vm   '], &
              ['value'], [mass*h**2*curvature/(8*z)], rigorous=.true.)
    call w%emit('fp_interval_interpolate', ['a', 'b', 'v'], ['value'], &
              [p1_blend(a, b, v)], rigorous=.true.)
    call w%emit('fp_interval_weight', ['lo', 'hi', 'v '], ['value'], &
              [p1_weight(v, lo, hi)], rigorous=.true.)
    call w%emit('fp_band', ['a', 'b'], ['lower', 'upper'], &
              [a - b, a + b], rigorous=.true.)
    call w%emit('fp_mass_error_band', ['lo    ', 'hi    ', 'radius'], &
              ['lower', 'upper'], [lo - 4*radius, hi + 4*radius], rigorous=.true.)
    call w%line('end module kin6d_fp_leaves')
    call w%close()
end program
