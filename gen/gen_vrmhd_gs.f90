program gen_vrmhd_gs
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_expr, only: expr_t, sym, rat, log, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: x, y, k, psi, px, py, eta, zero, one, c, a, alpha, radius2
    type(expr_t) :: exact, source, rho, av(3), bv(3), jv(3), grho(3), out(38)
    character(16) :: names(38), suffix, index_text
    integer :: kind, i
    zero = rat(0_int64, 1_int64); one = rat(1_int64, 1_int64)
    c = one/5; a = one/5
    x = sym('x'); y = sym('y'); k = sym('k')
    psi = sym('psi'); px = sym('px'); py = sym('py')
    eta = sym('eta')
    do i = 1, size(names)
        write (names(i), '(a,i0)') 'out', i
    end do
    call w%open('gen_vrmhd_gs', 'src/generated/milca_vrmhd_gs_leaves.f90')
    call w%line('! Generated by gen/gen_vrmhd_gs.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_vrmhd_gs_leaves')
    call w%line('implicit none')
    call w%line('contains')
    do kind = 1, 2
        if (kind == 1) then
            suffix = 'rotation'
            exact = c*x*x*(log(x) - one/2)/2
            source = -c/x
            rho = 3 - c*c*log(x)**2/4
            av = [zero, psi/x, zero]
            bv = [-py/x, zero, px/x]
            jv = [zero, -c/x, zero]
            grho = [diff(rho, x), zero, zero]
        else
            suffix = 'screw'
            radius2 = x*x + y*y
            alpha = (k - a)/2
            exact = alpha*radius2
            source = -4*alpha/(one + k*k*radius2)**2
            rho = 3 - a*a*radius2/2
            av = [-y/2, x/2, psi - k*radius2/2]
            bv = [py - k*y, -px + k*x, one]
            jv = [zero, zero, 2*a]
            grho = [diff(rho, x), diff(rho, y), zero]
        end if
        out = zero
        out(1) = rho; out(5:7) = av; out(8:10) = jv
        out(11:12) = one; out(13:15) = grho; out(25:27) = bv
        out(37) = exact; out(38) = source
        call w%emit('vrmhd_gs_'//trim(suffix), &
            [character(8) :: 'x', 'y', 'k', 'psi', 'px', 'py'], names, out)
        call w%line('subroutine gs_lift_'//trim(suffix)//'(x,y,k,psi,px,py,u)')
        call w%line('real(8), intent(in) :: x,y,k,psi,px,py')
        call w%line('real(8), intent(out) :: u(38)')
        call w%line('call vrmhd_gs_'//trim(suffix)//'(x,y,k,psi,px,py, &')
        do i = 1, 38
            write (index_text, '(i0)') i
            if (i < 38) then
                call w%line('u('//trim(index_text)//'), &')
            else
                call w%line('u('//trim(index_text)//'))')
            end if
        end do
        call w%line('end subroutine')
        call w%emit('vrmhd_gs_flux_'//trim(suffix), &
            [character(8) :: 'x', 'y', 'k'], &
            [character(8) :: 'psi', 'px', 'py', 'source'], &
            [exact, diff(exact, x), diff(exact, y), source])
        if (kind == 1) then
            call w%emit('vrmhd_gs_heat_'//trim(suffix), &
                [character(8) :: 'x', 'eta'], [character(8) :: 'qe'], &
                [-eta*(jv(1)**2 + jv(2)**2 + jv(3)**2)])
        else
            call w%emit('vrmhd_gs_heat_'//trim(suffix), &
                [character(8) :: 'eta'], [character(8) :: 'qe'], &
                [-eta*(jv(1)**2 + jv(2)**2 + jv(3)**2)])
        end if
    end do
    call w%line('end module milca_vrmhd_gs_leaves')
    call w%close()
end program
