program gen_ideal_field_angle
    ! Boundary field-line angle of the frozen reference field (docs/ideal-seed-3d.md).
    ! The reference disk (u,v) = rho (cos theta, sin theta), s = rho^2, carries
    ! b = (F/2pi) ds^d(theta) - chi'(s) ds^dphi. The relabelling
    ! theta -> theta + eta(u,v,phi) gives b' = (F/2pi) ds^d(theta + eta) - chi' ds^dphi,
    ! linear in eta, with the field lines straight in theta + eta at the same iota.
    ! eta = sum Re/Im of c (u+iv)^m exp(-i k phi): a regular harmonic extension.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/), operator(**), sin, cos
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs_many
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: proof
    type(expr_t) :: re, im, m, k, c, s, ca, cb, cosb, sinb, eta, eta_t, eta_p
    type(expr_t) :: r, t, p, polar, u, v, flux, pi, dcu, dcv, db3
    type(expr_t) :: eu, ev, iota, bu, bv, bp, rho2, eup, evp, div
    call arena%init()
    engine = make_native_engine(arena)
    call w%open(arena, 'gen_ideal_field_angle', &
        'src/generated/kin6d_ideal_field_angle_leaves.f90')
    call w%line('! Generated by gen/gen_ideal_field_angle.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module kin6d_ideal_field_angle_leaves')
    call w%line('use, intrinsic :: iso_fortran_env, only: dp => real64')
    call w%line('implicit none')
    call w%line('contains')
    ! One real mode pair: (re, im) = (u + i v)^m, (c, s) = (cos, sin)(k phi).
    re = sym(arena, 're'); im = sym(arena, 'im')
    m = sym(arena, 'm'); k = sym(arena, 'k')
    c = sym(arena, 'c'); s = sym(arena, 's')
    ca = sym(arena, 'ca'); cb = sym(arena, 'cb')
    cosb = re*c + im*s
    sinb = im*c - re*s
    eta = ca*cosb + cb*sinb
    eta_t = m*(cb*cosb - ca*sinb)
    eta_p = k*(ca*sinb - cb*cosb)
    call w%emit('field_angle_mode', [character(2) :: 're', 'im', 'm', 'k', 'c', 's', &
        'ca', 'cb'], [character(5) :: 'eta', 'eta_t', 'eta_p'], [eta, eta_t, eta_p], &
        ad=.true.)
    ! eta_t and eta_p are the exact theta and phi derivatives of eta in polar
    ! form re = r^m cos(m t), im = r^m sin(m t), c = cos(k p), s = sin(k p).
    r = sym(arena, 'r'); t = sym(arena, 't'); p = sym(arena, 'p')
    polar = subs_many(eta, [re, im, c, s], &
        [r**m*cos(m*t), r**m*sin(m*t), cos(k*p), sin(k*p)])
    proof = engine%zero_test(subs_many(eta_t, [re, im, c, s], &
        [r**m*cos(m*t), r**m*sin(m*t), cos(k*p), sin(k*p)]) - diff(polar, t))
    if (proof%verdict /= VERDICT_TRUE) error stop 'field-angle theta derivative unproved'
    proof = engine%zero_test(subs_many(eta_p, [re, im, c, s], &
        [r**m*cos(m*t), r**m*sin(m*t), cos(k*p), sin(k*p)]) - diff(polar, p))
    if (proof%verdict /= VERDICT_TRUE) error stop 'field-angle phi derivative unproved'
    ! Increment of the frozen form in the seed's (chi gradient, b3) channels:
    ! (F/2pi) ds^d eta = d(-F eta_p s/2pi)^dphi-part + (F/pi) eta_t du^dv, i.e.
    ! chi_u, chi_v += -(F/pi) eta_p (u, v) and b3 += (F/pi) eta_t.
    u = sym(arena, 'u'); v = sym(arena, 'v')
    flux = sym(arena, 'flux'); pi = sym(arena, 'pi')
    t = sym(arena, 'eta_t'); p = sym(arena, 'eta_p')
    dcu = 0 - flux*p*u/pi
    dcv = 0 - flux*p*v/pi
    db3 = flux*t/pi
    call w%emit('field_angle_form', [character(5) :: 'u', 'v', 'eta_t', 'eta_p', &
        'flux', 'pi'], [character(3) :: 'dcu', 'dcv', 'db3'], [dcu, dcv, db3], ad=.true.)
    ! Closedness of (-dcv, dcu, db3) in (u, v, phi) for any smooth eta, with
    ! eta_t = u eta_v - v eta_u and symmetric second derivatives as symbols.
    eu = sym(arena, 'eta_u'); ev = sym(arena, 'eta_v')
    eup = sym(arena, 'eta_up'); evp = sym(arena, 'eta_vp')
    ! d/du and d/dv of eta_p are eup and evp; eta_t enters db3 only.
    div = 0 - (diff(subs_many(dcv, [t], [u*ev - v*eu]), u) &
        + diff(subs_many(dcv, [t], [u*ev - v*eu]), p)*eup) &
        + (diff(subs_many(dcu, [t], [u*ev - v*eu]), v) &
        + diff(subs_many(dcu, [t], [u*ev - v*eu]), p)*evp) &
        + flux*(u*evp - v*eup)/pi
    proof = engine%zero_test(div)
    if (proof%verdict /= VERDICT_TRUE) error stop 'field-angle closed form unproved'
    ! Field lines of b' are straight in theta + eta with the unchanged iota:
    ! b' . grad(theta + eta) = iota b'^phi, seed chi gradient F iota (u, v)/pi.
    iota = sym(arena, 'iota')
    rho2 = u**2 + v**2
    bu = 0 - (flux*iota*v/pi + subs_many(dcv, [t], [u*ev - v*eu]))
    bv = flux*iota*u/pi + subs_many(dcu, [t], [u*ev - v*eu])
    bp = flux/pi + subs_many(db3, [t], [u*ev - v*eu])
    proof = engine%zero_test(bu*(0 - v/rho2 + eu) + bv*(u/rho2 + ev) + bp*p - iota*bp)
    if (proof%verdict /= VERDICT_TRUE) error stop 'field-angle straight lines unproved'
    call w%line('end module kin6d_ideal_field_angle_leaves')
    call w%close()
    print '(a)', '[V] FortSym field-angle derivatives, closed form and straight field lines proved'
end program
