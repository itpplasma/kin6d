program gen_slab_oscillation
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, abs, sin, cos, &
                        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
                                     emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(expr_t) :: tau, tl, tr, q, p, ql, qr, pl, pr, h, u, qc(4), d0, d1
    type(expr_t) :: polynomial, velocity, acceleration, qinitial, pinitial
    type(expr_t) :: bound, acc, value, radius, center, width, x0, y, i, n, duration
    integer :: unit

    call arena%init()
    engine = make_native_engine(arena)
    tau = sym(arena, 'tau'); tl = sym(arena, 'tl'); tr = sym(arena, 'tr')
    q = sym(arena, 'q'); p = sym(arena, 'momentum')
    ql = sym(arena, 'ql'); qr = sym(arena, 'qr')
    pl = sym(arena, 'pl'); pr = sym(arena, 'pr')
    qinitial = sym(arena, 'qinitial'); pinitial = sym(arena, 'pinitial')
    bound = sym(arena, 'bound'); acc = sym(arena, 'acc')
    value = sym(arena, 'value'); radius = sym(arena, 'radius')
    center = sym(arena, 'center'); width = sym(arena, 'width')
    x0 = sym(arena, 'x0'); y = sym(arena, 'y')
    i = sym(arena, 'i'); n = sym(arena, 'n'); duration = sym(arena, 'duration')
    h = tr - tl
    u = (tau - tl)/h
    ! C1 cubic Hermite q_h and p_h=q_h': no C2 assertion across time knots.
    qc = [ql, ql + h*pl/3, qr - h*pr/3, qr]
    polynomial = qc(1)*(1 - u)**3 + 3*qc(2)*u*(1 - u)**2 + &
                 3*qc(3)*u**2*(1 - u) + qc(4)*u**3
    velocity = 3*((qc(2) - qc(1))*(1 - u)**2 + &
                  2*(qc(3) - qc(2))*u*(1 - u) + (qc(4) - qc(3))*u**2)/h
    d0 = 6*(qc(3) - 2*qc(2) + qc(1))/h**2
    d1 = 6*(qc(4) - 2*qc(3) + qc(2))/h**2
    acceleration = d0*(1 - u) + d1*u
    identity = engine%zero_test(diff(polynomial, tau) - velocity)
    if (identity%verdict /= VERDICT_TRUE) &
        error stop 'Hermite velocity identity unproved'
    identity = engine%zero_test(diff(velocity, tau) - acceleration)
    if (identity%verdict /= VERDICT_TRUE) &
        error stop 'Hermite acceleration identity unproved'

    open (newunit=unit, file='src/generated/kin6d_slab_oscillation_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_slab_oscillation.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//revision
    write (unit, '(a)') &
        '! Cold planar electron slab against fixed infinite planar ions.'
    write (unit, '(a)') '! tau=omega_pe*t, q=xi/xi0, p=dq/dtau, qprime=p, pprime=-q.'
    write (unit, '(a)') '! No 3D periodic k0 restoring OCP or microscopic N-body claim.'
    write (unit, '(a)') '! Candidate integration: upstream FortNum Cash-Karp RK5(4).'
    write (unit, '(a)') '! Certificate: strict cubic residual Bernstein hull + Duhamel.'
    write (unit, '(a)') &
        '! Derivatives: smooth leaf Euclidean pairings; density edges events.'
    write (unit, '(a)') 'module kin6d_slab_oscillation_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('slab_oscillation_rhs', ['tau     ', 'q       ', 'momentum'], &
              ['qdot', 'pdot'], [p, -q], ad=.true.)
    call emit('slab_oscillation_time', ['i       ', 'n       ', 'duration'], &
              ['tau'], [duration*i/n], interval=.true.)
    call emit('slab_oscillation_span', ['tl', 'tr'], ['h'], [h])
    call emit('slab_oscillation_hermite', ['tau', 'tl ', 'tr ', 'ql ', 'qr ', &
                      'pl ', 'pr '], ['position    ', 'momentum    ', 'acceleration'], &
              [polynomial, velocity, acceleration], &
              ad=.true., interval=.true.)
    call emit('slab_oscillation_residual_interval', &
              ['tl', 'tr', 'ql', 'qr', 'pl', 'pr'], &
              ['r0', 'r1', 'r2', 'r3'], &
              [qc(1) + d0, qc(2) + (2*d0 + d1)/3, &
               qc(3) + (d0 + 2*d1)/3, qc(4) + d1], rigorous=.true.)
    call emit('slab_oscillation_initial_radius_interval', &
              ['q       ', 'momentum', 'qinitial', 'pinitial'], ['radius'], &
              [abs(q - qinitial) + abs(p - pinitial)], rigorous=.true.)
    call emit('slab_oscillation_radius_interval', &
              ['tl   ', 'tr   ', 'bound', 'acc  '], &
              ['next'], [acc + h*bound], rigorous=.true.)
    call emit('slab_oscillation_enlarge_interval', ['value ', 'radius'], &
              ['lower', 'upper'], [value - radius, value + radius], rigorous=.true.)
    call emit('slab_oscillation_difference_interval', ['value    ', 'reference'], &
              ['error'], [value - sym(arena, 'reference')], rigorous=.true.)
    call emit('slab_oscillation_difference', ['value    ', 'reference'], &
              ['error'], [value - sym(arena, 'reference')])
    call emit('slab_oscillation_margin_interval', ['radius ', 'padding'], &
              ['margin'], [radius + sym(arena, 'padding')], rigorous=.true.)
    ! Independent analytical comparator; not called by the production checker.
    call emit('slab_oscillation_reference', ['tau     ', 'qinitial', 'pinitial'], &
              ['q', 'p'], [qinitial*cos(tau) + pinitial*sin(tau), &
                           pinitial*cos(tau) - qinitial*sin(tau)], interval=.true.)
    call emit('slab_oscillation_period', ['periods'], ['duration'], &
              [2*pi_expr(arena)*sym(arena, 'periods')])
    call emit('slab_oscillation_marker', ['x0', 'q '], ['x'], [x0 + q], ad=.true.)
    call emit('slab_oscillation_display_displacement', ['q    ', 'ratio'], ['shift'], &
              [q*sym(arena, 'ratio')], ad=.true., interval=.true.)
    call emit('slab_oscillation_field_force', ['q'], ['field', 'force'], &
              [q, -q], ad=.true.)
    call emit('slab_oscillation_edges', ['center', 'width '], ['left ', 'right'], &
              [center - width, center + width], ad=.true., interval=.true.)
    call emit('slab_oscillation_marker_grid', ['i', 'n'], ['x0'], &
              [(-4*(n - 1) + 8*i)/(5*(n - 1))])
    call emit('slab_oscillation_error_curvature_interval', &
              ['bound   ', 'qinitial', 'pinitial'], ['next'], &
              [bound + abs(qinitial) + abs(pinitial)], rigorous=.true.)
    write (unit, '(a)') 'end module kin6d_slab_oscillation_leaves'
    close (unit)

contains
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = str('gen_slab_oscillation; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_slab_oscillation')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen_slab_oscillation from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_slab_oscillation
