program gen_slab_oscillation
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, abs, sin, cos, &
                        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(expr_t) :: tau, tl, tr, q, p, ql, qr, pl, pr, h, u, qc(4), d0, d1
    type(expr_t) :: polynomial, velocity, acceleration, qinitial, pinitial
    type(expr_t) :: bound, acc, value, radius, center, width, x0, y, i, n, duration
    call arena%init()
    engine = make_native_engine(arena)
    tau = sym(arena, 'tau'); tl = sym(arena, 'tl'); tr = sym(arena, 'tr')
    q = sym(arena, 'q'); p = sym(arena, 'momentum')
    ql = sym(arena, 'ql'); qr = sym(arena, 'qr')
    pl = sym(arena, 'pl'); pr = sym(arena, 'pr')
    qinitial = sym(arena, 'qinitial'); pinitial = sym(arena, 'pinitial')
    bound = sym(arena, 'bound'); acc = sym(arena, 'acc')
    value = sym(arena, 'value'); radius = sym(arena, 'radius')
    center = sym(arena, 'center'); width = sym(arena, 'width')
    x0 = sym(arena, 'x0'); y = sym(arena, 'y')
    i = sym(arena, 'i'); n = sym(arena, 'n'); duration = sym(arena, 'duration')
    h = tr - tl
    u = (tau - tl)/h
    ! C1 cubic Hermite q_h and p_h=q_h': no C2 assertion across time knots.
    qc = [ql, ql + h*pl/3, qr - h*pr/3, qr]
    polynomial = qc(1)*(1 - u)**3 + 3*qc(2)*u*(1 - u)**2 + &
                 3*qc(3)*u**2*(1 - u) + qc(4)*u**3
    velocity = 3*((qc(2) - qc(1))*(1 - u)**2 + &
                  2*(qc(3) - qc(2))*u*(1 - u) + (qc(4) - qc(3))*u**2)/h
    d0 = 6*(qc(3) - 2*qc(2) + qc(1))/h**2
    d1 = 6*(qc(4) - 2*qc(3) + qc(2))/h**2
    acceleration = d0*(1 - u) + d1*u
    identity = engine%zero_test(diff(polynomial, tau) - velocity)
    if (identity%verdict /= VERDICT_TRUE) &
        error stop 'Hermite velocity identity unproved'
    identity = engine%zero_test(diff(velocity, tau) - acceleration)
    if (identity%verdict /= VERDICT_TRUE) &
        error stop 'Hermite acceleration identity unproved'

    call w%open(arena, 'gen_slab_oscillation', 'src/generated/kin6d_slab_oscillation_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_slab_oscillation.f90; do not edit.'
    write (w%unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (w%unit, '(a)') &
        '! Cold planar electron slab against fixed infinite planar ions.'
    write (w%unit, '(a)') '! tau=omega_pe*t, q=xi/xi0, p=dq/dtau, qprime=p, pprime=-q.'
    write (w%unit, '(a)') '! No 3D periodic k0 restoring OCP or microscopic N-body claim.'
    write (w%unit, '(a)') '! Candidate integration: upstream FortNum Cash-Karp RK5(4).'
    write (w%unit, '(a)') '! Certificate: strict cubic residual Bernstein hull + Duhamel.'
    write (w%unit, '(a)') &
        '! Derivatives: smooth leaf Euclidean pairings; density edges events.'
    write (w%unit, '(a)') 'module kin6d_slab_oscillation_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('slab_oscillation_rhs', ['tau     ', 'q       ', 'momentum'], &
              ['qdot', 'pdot'], [p, -q], ad=.true.)
    call w%emit('slab_oscillation_time', ['i       ', 'n       ', 'duration'], &
              ['tau'], [duration*i/n], interval=.true.)
    call w%emit('slab_oscillation_span', ['tl', 'tr'], ['h'], [h])
    call w%emit('slab_oscillation_hermite', ['tau', 'tl ', 'tr ', 'ql ', 'qr ', &
                      'pl ', 'pr '], ['position    ', 'momentum    ', 'acceleration'], &
              [polynomial, velocity, acceleration], &
              ad=.true., interval=.true.)
    call w%emit('slab_oscillation_residual_interval', &
              ['tl', 'tr', 'ql', 'qr', 'pl', 'pr'], &
              ['r0', 'r1', 'r2', 'r3'], &
              [qc(1) + d0, qc(2) + (2*d0 + d1)/3, &
               qc(3) + (d0 + 2*d1)/3, qc(4) + d1], rigorous=.true.)
    call w%emit('slab_oscillation_initial_radius_interval', &
              ['q       ', 'momentum', 'qinitial', 'pinitial'], ['radius'], &
              [abs(q - qinitial) + abs(p - pinitial)], rigorous=.true.)
    call w%emit('slab_oscillation_radius_interval', &
              ['tl   ', 'tr   ', 'bound', 'acc  '], &
              ['next'], [acc + h*bound], rigorous=.true.)
    call w%emit('slab_oscillation_enlarge_interval', ['value ', 'radius'], &
              ['lower', 'upper'], [value - radius, value + radius], rigorous=.true.)
    call w%emit('slab_oscillation_difference_interval', ['value    ', 'reference'], &
              ['error'], [value - sym(arena, 'reference')], rigorous=.true.)
    call w%emit('slab_oscillation_difference', ['value    ', 'reference'], &
              ['error'], [value - sym(arena, 'reference')])
    call w%emit('slab_oscillation_margin_interval', ['radius ', 'padding'], &
              ['margin'], [radius + sym(arena, 'padding')], rigorous=.true.)
    ! Independent analytical comparator; not called by the production checker.
    call w%emit('slab_oscillation_reference', ['tau     ', 'qinitial', 'pinitial'], &
              ['q', 'p'], [qinitial*cos(tau) + pinitial*sin(tau), &
                           pinitial*cos(tau) - qinitial*sin(tau)], interval=.true.)
    call w%emit('slab_oscillation_period', ['periods'], ['duration'], &
              [2*pi_expr(arena)*sym(arena, 'periods')])
    call w%emit('slab_oscillation_marker', ['x0', 'q '], ['x'], [x0 + q], ad=.true.)
    call w%emit('slab_oscillation_display_displacement', ['q    ', 'ratio'], ['shift'], &
              [q*sym(arena, 'ratio')], ad=.true., interval=.true.)
    call w%emit('slab_oscillation_field_force', ['q'], ['field', 'force'], &
              [q, -q], ad=.true.)
    call w%emit('slab_oscillation_edges', ['center', 'width '], ['left ', 'right'], &
              [center - width, center + width], ad=.true., interval=.true.)
    call w%emit('slab_oscillation_marker_grid', ['i', 'n'], ['x0'], &
              [(-4*(n - 1) + 8*i)/(5*(n - 1))])
    call w%emit('slab_oscillation_error_curvature_interval', &
              ['bound   ', 'qinitial', 'pinitial'], ['next'], &
              [bound + abs(qinitial) + abs(pinitial)], rigorous=.true.)
    write (w%unit, '(a)') 'end module kin6d_slab_oscillation_leaves'
    call w%close()

end program gen_slab_oscillation
