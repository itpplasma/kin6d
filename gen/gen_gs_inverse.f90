program gen_gs_inverse
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, log, atan2, operator(+), operator(-), &
        operator(*), operator(/)
    use fortsym_diff, only: diff
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: writer
    type(expr_t) :: radius, r, radial_gradient, q, two_pi, coarea
    type(expr_t) :: flux_left, flux_right, square_left, square_right, square, branch
    type(expr_t) :: dlevel, dpsi_fixed
    type(expr_t) :: value, slope, curvature, offset, trace
    type(expr_t) :: va,vm,vb,length,bgr,bgz
    type(expr_t) :: edge_square, axis_flux, integral_tangent, edge_tangent, f_value
    type(expr_t) :: mean_target, partial_mean, last_weight, ff_left, ff_right
    type(expr_t) :: ratio, delta_axis, delta_psi, gr, gz, hrr, hrz, hzz, dgr, dgz, dr, dz
    call arena%init()
    radius = sym(arena, 'radius'); r = sym(arena, 'r')
    radial_gradient = sym(arena, 'radial_gradient')
    q = sym(arena, 'q'); two_pi = sym(arena, 'two_pi'); coarea = sym(arena, 'coarea')
    flux_left = sym(arena, 'flux_left'); flux_right = sym(arena, 'flux_right')
    square_left = sym(arena, 'square_left'); square_right = sym(arena, 'square_right')
    square = sym(arena, 'square'); branch = sym(arena, 'branch')
    dlevel = sym(arena, 'dlevel'); dpsi_fixed = sym(arena, 'dpsi_fixed')
    value = sym(arena, 'value'); slope = sym(arena, 'slope')
    curvature = sym(arena, 'curvature'); offset = sym(arena, 'offset')
    bgr=sym(arena,"bgrad_r");bgz=sym(arena,"bgrad_z")
    va=sym(arena,"va");vm=sym(arena,"vm");vb=sym(arena,"vb");length=sym(arena,"length")
    edge_square=sym(arena,"edge_square"); axis_flux=sym(arena,"axis_flux")
    integral_tangent=sym(arena,"integral_tangent"); edge_tangent=sym(arena,"edge_tangent")
    f_value=sym(arena,"f_value")
    ratio=sym(arena,"ratio"); delta_axis=sym(arena,"delta_axis")
    delta_psi=sym(arena,"delta_psi"); gr=sym(arena,"gr"); gz=sym(arena,"gz")
    hrr=sym(arena,"hrr"); hrz=sym(arena,"hrz"); hzz=sym(arena,"hzz")
    dgr=sym(arena,"tg_r"); dgz=sym(arena,"tg_z"); dr=sym(arena,"dr"); dz=sym(arena,"dz")
    mean_target=sym(arena,"mean_target"); partial_mean=sym(arena,"partial_mean")
    last_weight=sym(arena,"last_weight")
    ff_left=sym(arena,"ff_left"); ff_right=sym(arena,"ff_right")
    trace = value+slope*offset+curvature*offset*offset/2
    call writer%open(arena, 'gen_gs_inverse', &
        'src/generated/kin6d_gs_inverse_leaves.f90')
    call writer%line('! Generated by gen/gen_gs_inverse.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('! Positive-outward flux, R>0, monotone star-shaped contours.')
    call writer%line('module kin6d_gs_inverse_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('gs_f_from_coarea', ['q     ', 'two_pi', 'coarea'], &
        ['f'], [two_pi*q/coarea], ad=.true.)
    call writer%emit('gs_square_slope', &
        ['flux_left   ', 'flux_right  ', 'square_left ', 'square_right'], &
        ['ffprime'], [(square_right-square_left)/(2*(flux_right-flux_left))], ad=.true.)
    call writer%emit('gs_f_from_square', ['square', 'branch'], &
        ['f'], [branch*sqrt(square)], ad=.true.)
    ! Equation-level contour tangent: grad(psi).e_r * d(radius) = dlevel-dpsi_fixed.
    call writer%emit('gs_normalized_profile_response', &
        ['slope     ', 'delta_psi ', 'ratio     ', 'delta_axis'], &
        ['delta_ff'], [slope*(delta_psi-ratio*delta_axis)], ad=.true.)
    call writer%emit('gs_profile_square_response', &
        ['square          ','edge_square     ','axis_flux       ','delta_axis      ', &
        'integral_tangent','edge_tangent    '], &
        ['square_tangent'],[(square-edge_square)*delta_axis/axis_flux+2*integral_tangent+edge_tangent], &
        ad=.true.)
    call writer%emit('gs_q_profile', ['f_value','coarea ','two_pi '], &
        ['q_value'],[f_value*coarea/two_pi],ad=.true.)
    call writer%emit('gs_q_log_residual', ['f_value','coarea ','two_pi ','q      '], &
        ['residual'],[log(f_value*coarea/(two_pi*q))],ad=.true.)
    call writer%emit('gs_profile_mean_last', &
        ['mean_target ', 'partial_mean', 'last_weight '], &
        ['last_ff'], [(mean_target-partial_mean)/last_weight], ad=.true.)
    call writer%emit('gs_ff_zero', &
        ['flux_left ', 'flux_right', 'ff_left   ', 'ff_right  '], &
        ['flux_zero'], [(ff_right*flux_left-ff_left*flux_right)/(ff_right-ff_left)], ad=.true.)
    call writer%line('end module kin6d_gs_inverse_leaves')
    call writer%close()
end program gen_gs_inverse
