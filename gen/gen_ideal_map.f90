program gen_ideal_map
   ! Frozen-in ideal-MHD energy density of a map X from abstract coordinates
   ! (s1, s2, s3) into Cartesian space. Charts X = H(q) and their jets are
   ! core leaves (gen/gen_equilibrium_core.f90).
   ! The energy sees only DX = dX/ds (row a: Cartesian component, column i:
   ! abstract direction) and sigma*det(DX) > 0; charts supply H(q) and its
   ! q-derivatives. b^i is the frozen contravariant flux density (closed
   ! 2-form) in the abstract coordinates and p the frozen pressure (gamma=0):
   !   w = |DX b|^2/(2*mu0*J) - p*J,  J = sigma*det(DX).
   use fortsym_arena, only: arena_t
   use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
                           operator(*), operator(/), operator(**)
   use fortsym_diff, only: diff
   use fortsym_products, only: jvp
   use fortsym_kernel_ir, only: kernel_ir_t, lower_kernel_ir
   use fortsym_kernel_emit, only: kernel_emit_spec_t, emit_cuda_device_ir, &
      emit_fortran_kernel_ir, TARGET_CUDA, TARGET_FORTRAN_CPU, &
      PRECISION_REAL64, PRECISION_REAL32, PRECISION_MIXED
   use fortsym_string, only: str_t, str, chars
   use fortsym_engine, only: engine_result_t, VERDICT_TRUE
   use fortsym_engine_native, only: native_engine_t, make_native_engine
   use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
   implicit none
   type(arena_t), target :: arena
   type(leaf_writer_t) :: w
   type(native_engine_t) :: engine
   type(engine_result_t) :: identity
   type(expr_t) :: d(3, 3), b(3), p, mu0, sigma, jac, density, bx(3)
   type(expr_t) :: gradient(9), hessian(45)
   type(expr_t) :: r, psi_r, psi_z, f, cyl(3, 3), identity_density
   character(8) :: names9(9), names45(45)
   character(16) :: argument
   integer :: a, i, j, n
   call arena%init()
   engine = make_native_engine(arena)
   do i = 1, 3
      do a = 1, 3
         write (names9(a + 3*(i - 1)), '(a,i1,i1)') 'd', a, i
         d(a, i) = sym(arena, trim(names9(a + 3*(i - 1))))
      end do
   end do
   b(1) = sym(arena, 'b1'); b(2) = sym(arena, 'b2'); b(3) = sym(arena, 'b3')
   p = sym(arena, 'p'); mu0 = sym(arena, 'mu0'); sigma = sym(arena, 'sigma')
   jac = sigma*(d(1, 1)*(d(2, 2)*d(3, 3) - d(2, 3)*d(3, 2)) &
      - d(1, 2)*(d(2, 1)*d(3, 3) - d(2, 3)*d(3, 1)) &
      + d(1, 3)*(d(2, 1)*d(3, 2) - d(2, 2)*d(3, 1)))
   do a = 1, 3
      bx(a) = d(a, 1)*b(1) + d(a, 2)*b(2) + d(a, 3)*b(3)
   end do
   density = (bx(1)**2 + bx(2)**2 + bx(3)**2)/(2*mu0*jac) - p*jac
   ! Identity cylindrical map at phi=0, columns d/dR, d/dZ, d/dphi, and the
   ! axisymmetric flux density b=(-psi_Z, psi_R, F/R): w = R*B^2/(2 mu0) - p*R.
   r = sym(arena, 'r'); psi_r = sym(arena, 'psi_r'); psi_z = sym(arena, 'psi_z')
   f = sym(arena, 'f')
   cyl = 0*r
   cyl(1, 1) = 1 + 0*r; cyl(3, 2) = 1 + 0*r; cyl(2, 3) = r
   identity_density = substitute_identity()
   identity = engine%zero_test(identity_density &
      - (r*((psi_r**2 + psi_z**2)/r**2 + f**2/r**2)/(2*mu0) - p*r))
   if (identity%verdict /= VERDICT_TRUE) error stop 'ideal energy GS reduction unproved'
   do i = 1, 9
      gradient(i) = diff(density, d(1 + mod(i - 1, 3), 1 + (i - 1)/3))
   end do
   n = 0
   do j = 1, 9
      do i = 1, j
         n = n + 1
         write (names45(n), '(a,i1,i1)') 'h', i, j
         hessian(n) = diff(gradient(i), d(1 + mod(j - 1, 3), 1 + (j - 1)/3))
      end do
   end do
   call w%open(arena, 'gen_ideal_map', 'src/generated/kin6d_ideal_map_leaves.f90')
   call w%line('! Generated by gen/gen_ideal_map.f90; do not edit.')
   call w%line('! FortSym revision: '//fortsym_revision)
   call w%line('! w = |DX b|^2/(2 mu0 J) - p J, J = sigma det DX; d(a,i) = dX_a/ds_i.')
   call w%line('module kin6d_ideal_map_leaves')
   call w%line('implicit none')
   call w%line('contains')
   call w%emit('ideal_energy_density', [character(8) :: names9, 'b1', 'b2', 'b3', &
      'p', 'mu0', 'sigma'], ['w  ', 'jac'], [density, jac])
   call w%emit('ideal_energy_gradient', [character(8) :: names9, 'b1', 'b2', 'b3', &
      'p', 'mu0', 'sigma'], [character(8) :: ('g'//names9(i)(2:3), i=1, 9)], gradient)
   call w%emit('ideal_energy_hessian', [character(8) :: names9, 'b1', 'b2', 'b3', &
      'p', 'mu0', 'sigma'], names45, hessian)
   call w%line('end module kin6d_ideal_map_leaves')
   call w%close()
   if (command_argument_count() > 0) then
      call get_command_argument(1, argument)
      if (trim(argument) /= '--gpu') error stop 'expected --gpu'
      call gpu_prototype()
   end if
contains
   subroutine gpu_prototype()
      ! Same Hessian roots as the production consumer; schedules stay outside
      ! the leaves. HVP is the JVP of the retained energy gradient.
      type(expr_t) :: direction(9), action(9)
      type(kernel_ir_t) :: hir, vir
      character(8) :: vnames(9), ynames(9), args(15)
      character(:), allocatable :: message
      logical :: ok
      integer :: k, cu, fu
      args = [character(8) :: names9, 'b1', 'b2', 'b3', 'p', 'mu0', 'sigma']
      do k = 1, 9
         write (vnames(k), '(a,i1)') 'v', k
         write (ynames(k), '(a,i1)') 'y', k
         direction(k) = sym(arena, trim(vnames(k)))
      end do
      action = jvp(gradient, reshape(d, [9]), direction)
      call lower_kernel_ir(hessian, hir, ok, message)
      if (.not. ok) error stop message
      call lower_kernel_ir(action, vir, ok, message)
      if (.not. ok) error stop message
      open (newunit=cu, file='benchmarks/equilibrium-gpu/generated/ideal_map_gpu.cuh', &
         status='replace')
      open (newunit=fu, file='benchmarks/equilibrium-gpu/generated/ideal_map_gpu_cpu.f90', &
         status='replace')
      write (cu, '(a)') '// Generated by gen_ideal_map --gpu; FortSym '//fortsym_revision
      write (cu, '(a)') '#pragma once'
      write (fu, '(a)') '! Generated by gen_ideal_map --gpu; FortSym '//fortsym_revision
      write (fu, '(a)') 'module ideal_map_gpu_cpu'
      write (fu, '(a)') 'implicit none'
      write (fu, '(a)') 'contains'
      call variant(hir, args, names45, 'ideal_hessian_f64', PRECISION_REAL64, cu, fu)
      call variant(hir, args, names45, 'ideal_hessian_f32', PRECISION_REAL32, cu, fu)
      call variant(hir, args, names45, 'ideal_hessian_mixed', PRECISION_MIXED, cu, fu)
      call variant(vir, [args, vnames], ynames, 'ideal_hvp_f64', PRECISION_REAL64, cu, fu)
      call variant(vir, [args, vnames], ynames, 'ideal_hvp_f32', PRECISION_REAL32, cu, fu)
      call variant(vir, [args, vnames], ynames, 'ideal_hvp_mixed', PRECISION_MIXED, cu, fu)
      write (fu, '(a)') 'end module ideal_map_gpu_cpu'
      close (cu)
      close (fu)
   end subroutine

   subroutine variant(ir, args, outputs, name, precision, cu, fu)
      type(kernel_ir_t), intent(in) :: ir
      character(*), intent(in) :: args(:), outputs(:), name
      integer, intent(in) :: precision, cu, fu
      type(kernel_emit_spec_t) :: spec
      type(str_t) :: source
      character(:), allocatable :: message
      logical :: ok
      integer :: k
      spec%name = str(name)
      spec%args = [(str(trim(args(k))), k=1, size(args))]
      spec%outputs = [(str(trim(outputs(k))), k=1, size(outputs))]
      spec%precision = precision
      spec%generator = str('gen/gen_ideal_map.f90 --gpu')
      spec%generator_revision = str(fortsym_revision)
      spec%regenerate_command = str('build-dev-fast/gen_ideal_map --gpu')
      spec%target = TARGET_CUDA
      source = emit_cuda_device_ir(ir, spec, ok, message)
      if (.not. ok) error stop message
      write (cu, '(a)') chars(source)
      if (precision /= PRECISION_REAL64) return
      spec%target = TARGET_FORTRAN_CPU
      spec%pure_procedure = .true.
      source = emit_fortran_kernel_ir(ir, spec, ok, message)
      if (.not. ok) error stop message
      write (fu, '(a)') chars(source)
   end subroutine

   function substitute_identity() result(value)
      ! density with d -> cyl and b -> (-psi_z, psi_r, f/r), sigma = -1
      type(expr_t) :: value, bb(3), v(3), det
      integer :: c
      bb = [0 - psi_z, psi_r, f/r]
      det = -(cyl(1, 1)*(cyl(2, 2)*cyl(3, 3) - cyl(2, 3)*cyl(3, 2)) &
         - cyl(1, 2)*(cyl(2, 1)*cyl(3, 3) - cyl(2, 3)*cyl(3, 1)) &
         + cyl(1, 3)*(cyl(2, 1)*cyl(3, 2) - cyl(2, 2)*cyl(3, 1)))
      do c = 1, 3
         v(c) = cyl(c, 1)*bb(1) + cyl(c, 2)*bb(2) + cyl(c, 3)*bb(3)
      end do
      value = (v(1)**2 + v(2)**2 + v(3)**2)/(2*mu0*det) - p*det
   end function
end program gen_ideal_map
