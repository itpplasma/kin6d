program gen_correlation_hierarchy
    ! Leaves of the classical OCP correlation-hierarchy map (H1a,
    ! docs/correlation-hierarchy.md). Wigner-Seitz units: a = 1,
    ! e^2/(4 pi eps0) = 1, k_B T = 1/Gamma, n = 3/(4 pi); every energy below
    ! is in k_B T (beta v = Gamma/r). Physics formulas come from
    ! gen/kin6d_symbolic_physics.f90 (Coulomb, Ewald splitting, Yukawa,
    ! Debye length); this file only composes them.
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, rat, pi_expr, exp, sqrt, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    use kin6d_symbolic_physics, only: coulomb_potential, coulomb_force, &
        ewald_real_potential, ewald_reciprocal_weight, yukawa_potential, debye_length
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: r, gamma, kappa, alpha, k2, gs, cs, vl, n, s, mu, h, u, var
    type(expr_t) :: a1, a2, a3, b1, b2, b3, b4, x(3), f(3), one, density, c

    call arena%init()
    r = sym(arena, 'r'); gamma = sym(arena, 'gamma'); kappa = sym(arena, 'kappa')
    alpha = sym(arena, 'alpha'); k2 = sym(arena, 'k2'); gs = sym(arena, 'gs')
    cs = sym(arena, 'cs'); vl = sym(arena, 'vl'); n = sym(arena, 'n')
    s = sym(arena, 's'); mu = sym(arena, 'mu'); h = sym(arena, 'h')
    u = sym(arena, 'u'); var = sym(arena, 'var')
    a1 = sym(arena, 'a1'); a2 = sym(arena, 'a2'); b1 = sym(arena, 'b1')
    b2 = sym(arena, 'b2'); b3 = sym(arena, 'b3'); b4 = sym(arena, 'b4')
    one = rat(arena, 1_int64, 1_int64)
    density = 3/(4*pi_expr(arena))*one

    call w%open(arena, 'gen_correlation_hierarchy', &
                'src/generated/kin6d_correlation_hierarchy_leaves.f90')
    call w%line('! Generated by gen/gen_correlation_hierarchy.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Classical OCP correlation hierarchy (H1a): Debye-Hueckel pair')
    call w%line('! distribution, HNC kernels with the Ng long-range split, YBG force')
    call w%line('! moment, excess-energy density, fluctuation derivative and the')
    call w%line('! Potekhin-Chabrier (2000) fit form. Units: a = 1, beta v = Gamma/r.')
    call w%line('module kin6d_correlation_hierarchy_leaves')
    call w%line('implicit none')
    call w%line('contains')
    ! Debye wavenumber kappa a = a/lambda_D at T = 1/Gamma, n = 3/(4 pi): sqrt(3 Gamma).
    call w%emit('ch_debye_wavenumber', ['gamma'], ['kappa'], &
                [1/debye_length(1/gamma, density, one)], ad=.true.)
    ! Real-space Ewald pair potential per unit coupling (minimum-image Monte
    ! Carlo energy differences), the same definition as the force leaves.
    call w%emit('ch_ewald_real_potential', ['r    ', 'alpha'], ['u'], &
                [ewald_real_potential(one, alpha, r)])
    ! Debye-Hueckel pair distribution exp(-beta w_DH), w_DH the Yukawa
    ! potential of mean force, and its linearization 1 - beta w_DH.
    call w%emit('ch_debye_hueckel_g', ['r    ', 'gamma', 'kappa'], ['g'], &
                [exp(-yukawa_potential(gamma, 1/kappa, r))], ad=.true.)
    call w%emit('ch_debye_hueckel_linear_g', ['r    ', 'gamma', 'kappa'], ['g'], &
                [1 - yukawa_potential(gamma, 1/kappa, r)], ad=.true.)
    ! Debye-Hueckel excess energy -(3/2) Gamma^2 lambda_D = -(sqrt 3/2) Gamma^(3/2).
    call w%emit('ch_debye_hueckel_energy', ['gamma'], ['u'], &
                [-3*gamma**2*debye_length(1/gamma, density, one)/2], ad=.true.)
    ! HNC with the Ng split beta v = beta v_s + beta v_L (Ewald splitting
    ! with parameter alpha): short part, Fourier transform of the long part
    ! (the continuous Ewald reciprocal weight at unit volume).
    call w%emit('ch_hnc_short_potential', ['r    ', 'gamma', 'alpha'], ['v'], &
                [ewald_real_potential(gamma, alpha, r)], ad=.true.)
    call w%emit('ch_hnc_long_fourier', ['k2   ', 'gamma', 'alpha'], ['v'], &
                [ewald_reciprocal_weight(gamma, alpha, one, k2)], ad=.true.)
    ! Closure: g = exp(-beta v_s + gamma_s), gamma_s = h - c_s, c_s = c + beta v_L.
    call w%emit('ch_hnc_closure', ['r    ', 'gamma', 'alpha', 'gs   '], ['cs'], &
                [exp(gs - ewald_real_potential(gamma, alpha, r)) - 1 - gs], ad=.true.)
    ! Ornstein-Zernike in k: c = c_s - v_L, h = c/(1 - n c), gamma_s = h - c_s.
    c = cs - vl
    call w%emit('ch_oz_indirect', ['cs', 'vl', 'n '], ['gs'], &
                [c/(1 - n*c) - cs], ad=.true.)
    ! YBG force moment: s^2 times the R-hat component of beta F(r13), the
    ! Coulomb force on particle 1 from particle 3 at s = r1 - r3, mu = s.R-hat.
    x = [s*sqrt(1 - mu**2), 0*s, s*mu]
    f = coulomb_force(gamma, x)
    call w%emit('ch_ybg_force_moment', ['gamma', 's    ', 'mu   '], ['moment'], &
                [s**2*f(3)], ad=.true.)
    ! Excess energy per particle: beta u = integral_0^oo 2 pi n r^2 beta v h dr.
    call w%emit('ch_excess_energy_density', ['r    ', 'gamma', 'h    ', 'n    '], &
                ['density'], [2*pi_expr(arena)*n*r**2*coulomb_potential(gamma, r)*h], &
                ad=.true.)
    ! Canonical fluctuation formula at fixed density: beta = Gamma (a = 1),
    ! d u/d Gamma = (u - Var(beta U)/N)/Gamma with u = <beta U>/N.
    call w%emit('ch_energy_fluctuation_derivative', ['u    ', 'var  ', 'gamma'], &
                ['dudg'], [(u - var)/gamma], ad=.true.)
    ! Potekhin & Chabrier, Phys. Rev. E 62, 8554 (2000), Eq. (16) form:
    ! u = A1 G^(3/2)/sqrt(G + A2) + A3 G^(3/2)/(G + 1) + B1 G^2/(G + B2)
    !   + B3 G^2/(G^2 + B4), A3 = -sqrt(3)/2 - A1/sqrt(A2) (Debye limit).
    a3 = -sqrt(rat(arena, 3_int64, 1_int64))/2 - a1/sqrt(a2)
    call w%emit('ch_ocp_energy_fit', [character(5) :: 'gamma', 'a1', 'a2', 'b1', &
                'b2', 'b3', 'b4'], ['u'], &
                [a1*(gamma*sqrt(gamma))/sqrt(gamma + a2) + a3*(gamma*sqrt(gamma))/(gamma + 1) + &
                 b1*gamma**2/(gamma + b2) + b3*gamma**2/(gamma**2 + b4)], ad=.true.)
    call w%line('end module kin6d_correlation_hierarchy_leaves')
    call w%close()
end program gen_correlation_hierarchy
