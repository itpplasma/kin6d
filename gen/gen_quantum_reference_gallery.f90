program gen_quantum_reference_gallery
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, sin, cos, sqrt, abs, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use kin6d_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: ar, ai, br, bi, weight, x, mode, n2, radius, m1, m2
    type(expr_t) :: same, gap, curvature, error, normsum, n0, hbar, angle
    call arena%init()
    ar = sym(arena, 'ar'); ai = sym(arena, 'ai')
    br = sym(arena, 'br'); bi = sym(arena, 'bi')
    weight = sym(arena, 'weight'); x = sym(arena, 'x')
    mode = sym(arena, 'mode'); n2 = sym(arena, 'n2')
    radius = sym(arena, 'radius'); m1 = sym(arena, 'm1')
    m2 = sym(arena, 'm2'); same = sym(arena, 'same')
    gap = sym(arena, 'gap'); curvature = sym(arena, 'curvature')
    n0 = sym(arena, 'n0'); hbar = sym(arena, 'hbar')
    angle = 2*pi_expr(arena)*mode*x
    error = (2*sqrt(n2)*radius + radius**2)/n0
    normsum = (n2 + (sqrt(n2) + radius)**2)/n0
    call w%open(arena, 'gen_quantum_reference_gallery', 'src/generated/kin6d_quantum_reference_gallery_leaves.f90')
    write (w%unit, '(a)') '! Generated by gen/gen_quantum_reference_gallery.f90.'
    write (w%unit, '(a)') '! 3D plane-wave observables on y=z=0; x means x/L.'
    write (w%unit, '(a)') '! Dimensionless density V*n and pair density V**2*P.'
    write (w%unit, '(a)') '! Paired real/imag; Euclidean JVP/VJP pairing.'
    write (w%unit, '(a)') 'module kin6d_quantum_reference_gallery_leaves'
    write (w%unit, '(a)') 'implicit none'
    write (w%unit, '(a)') 'contains'
    call w%emit('qgallery_accumulate', ['ar    ', 'ai    ', 'br    ', 'bi    ', &
        'weight'], ['rr', 'ri'], [ar + weight*br, ai + weight*bi], &
        ad=.true., interval=.true.)
    call w%emit('qgallery_fourier', ['ar  ', 'ai  ', 'mode', 'x   '], ['value'], &
        [ar*cos(angle) - ai*sin(angle)], &
        ad=.true., interval=.true.)
    call w%emit('qgallery_phase', ['mode', 'x   '], ['br', 'bi'], &
        [cos(angle), sin(angle)], ad=.true., interval=.true.)
    call w%emit('qgallery_contract', ['ar', 'ai', 'br', 'bi'], ['value'], &
        [ar*br - ai*bi], ad=.true., interval=.true.)
    call w%emit('qgallery_voxel', ['mode', 'x   '], ['value'], &
        [sin(pi_expr(arena)*mode*x)/(pi_expr(arena)*mode*x)], &
        ad=.true., interval=.true.)
    call w%emit('qgallery_outer', ['ar', 'ai', 'br', 'bi'], ['rr', 'ri'], &
        [ar*br + ai*bi, ai*br - ar*bi], ad=.true., interval=.true.)
    call w%emit('qgallery_sector_error', ['n2    ', 'radius', 'm1    ', 'n0    '], &
        ['occupation', 'pair      ', 'exchange  '], &
        [error, m1*error, error*(1 + n2/n0)], ad=.true., interval=.true.)
    call w%emit('qgallery_norm_add', ['n2', 'ar', 'ai'], ['result'], &
        [n2 + ar**2 + ai**2], interval=.true.)
    call w%emit('qgallery_error', &
        ['n2    ', 'radius', 'm1    ', 'm2    ', 'same  ', 'n0    '], &
        ['occupation', 'pair      ', 'cumulant  '], &
        [error, m1*m2*error, m1*m2*error*(1 + (1 + same)*normsum)], &
        ad=.true., interval=.true.)
    call w%emit('qgallery_curvature', ['curvature', 'ar       ', 'ai       ', &
        'mode     '], ['result'], &
        [curvature + 4*pi_expr(arena)**2*mode**2*(abs(ar) + abs(ai))], &
        interval=.true.)
    call w%emit('qgallery_band', ['ar    ', 'radius'], ['lower', 'upper'], &
        [ar - radius, ar + radius], interval=.true.)
    call w%emit('qgallery_time', ['weight', 'x     '], ['value'], &
        [weight*x], interval=.true.)
    call w%emit('qgallery_gap', ['ar', 'br'], ['gap'], [br - ar], interval=.true.)
    call w%emit('qgallery_radius', ['ar', 'br'], ['radius'], &
        [(br - ar)/2], interval=.true.)
    call w%emit('qgallery_normalize', ['ar', 'ai', 'n0'], ['rr', 'ri'], &
        [ar/n0, ai/n0], ad=.true., interval=.true.)
    call w%emit('qgallery_hamiltonian_defect', &
        ['n0    ', 'radius', 'weight', 'x     ', 'hbar  '], ['result'], &
        [radius + sqrt(n0)*weight*x/hbar], interval=.true.)
    write (w%unit, '(a)') 'end module kin6d_quantum_reference_gallery_leaves'
    call w%close()
end program gen_quantum_reference_gallery
