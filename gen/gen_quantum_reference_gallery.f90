program gen_quantum_reference_gallery
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, pi_expr, sin, cos, sqrt, abs, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel
    use fortsym_rigorous_emit, only: rigorous_kernel_spec_t, interval_runtime, &
        emit_rigorous_kernel
    implicit none
    character(*), parameter :: revision = 'a6142712af998b727c245fb6cfbb3745b296ec24'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: ar, ai, br, bi, weight, x, mode, n2, radius, m1, m2
    type(expr_t) :: same, gap, curvature, error, normsum, n0, hbar, angle
    integer :: unit
    call arena%init()
    engine = make_native_engine(arena)
    ar = sym(arena, 'ar'); ai = sym(arena, 'ai')
    br = sym(arena, 'br'); bi = sym(arena, 'bi')
    weight = sym(arena, 'weight'); x = sym(arena, 'x')
    mode = sym(arena, 'mode'); n2 = sym(arena, 'n2')
    radius = sym(arena, 'radius'); m1 = sym(arena, 'm1')
    m2 = sym(arena, 'm2'); same = sym(arena, 'same')
    gap = sym(arena, 'gap'); curvature = sym(arena, 'curvature')
    n0 = sym(arena, 'n0'); hbar = sym(arena, 'hbar')
    angle = 2*pi_expr(arena)*mode*x
    error = (2*sqrt(n2)*radius + radius**2)/n0
    normsum = (n2 + (sqrt(n2) + radius)**2)/n0
    open (newunit=unit, &
        file='src/generated/kin6d_quantum_reference_gallery_leaves.f90', &
        status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_quantum_reference_gallery.f90.'
    write (unit, '(a)') '! 3D plane-wave observables on y=z=0; x means x/L.'
    write (unit, '(a)') '! Dimensionless density V*n and pair density V**2*P.'
    write (unit, '(a)') '! Paired real/imag; Euclidean JVP/VJP pairing.'
    write (unit, '(a)') 'module kin6d_quantum_reference_gallery_leaves'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'contains'
    call emit('qgallery_accumulate', ['ar    ', 'ai    ', 'br    ', 'bi    ', &
        'weight'], ['rr', 'ri'], [ar + weight*br, ai + weight*bi], &
        ad=.true., interval=.true.)
    call emit('qgallery_fourier', ['ar  ', 'ai  ', 'mode', 'x   '], ['value'], &
        [ar*cos(angle) - ai*sin(angle)], &
        ad=.true., interval=.true.)
    call emit('qgallery_phase', ['mode', 'x   '], ['br', 'bi'], &
        [cos(angle), sin(angle)], ad=.true., interval=.true.)
    call emit('qgallery_contract', ['ar', 'ai', 'br', 'bi'], ['value'], &
        [ar*br - ai*bi], ad=.true., interval=.true.)
    call emit('qgallery_voxel', ['mode', 'x   '], ['value'], &
        [sin(pi_expr(arena)*mode*x)/(pi_expr(arena)*mode*x)], &
        ad=.true., interval=.true.)
    call emit('qgallery_outer', ['ar', 'ai', 'br', 'bi'], ['rr', 'ri'], &
        [ar*br + ai*bi, ai*br - ar*bi], ad=.true., interval=.true.)
    call emit('qgallery_sector_error', ['n2    ', 'radius', 'm1    ', 'n0    '], &
        ['occupation', 'pair      ', 'exchange  '], &
        [error, m1*error, error*(1 + n2/n0)], ad=.true., interval=.true.)
    call emit('qgallery_norm_add', ['n2', 'ar', 'ai'], ['result'], &
        [n2 + ar**2 + ai**2], interval=.true.)
    call emit('qgallery_error', &
        ['n2    ', 'radius', 'm1    ', 'm2    ', 'same  ', 'n0    '], &
        ['occupation', 'pair      ', 'cumulant  '], &
        [error, m1*m2*error, m1*m2*error*(1 + (1 + same)*normsum)], &
        ad=.true., interval=.true.)
    call emit('qgallery_curvature', ['curvature', 'ar       ', 'ai       ', &
        'mode     '], ['result'], &
        [curvature + 4*pi_expr(arena)**2*mode**2*(abs(ar) + abs(ai))], &
        interval=.true.)
    call emit('qgallery_band', ['ar    ', 'radius'], ['lower', 'upper'], &
        [ar - radius, ar + radius], interval=.true.)
    call emit('qgallery_time', ['weight', 'x     '], ['value'], &
        [weight*x], interval=.true.)
    call emit('qgallery_gap', ['ar', 'br'], ['gap'], [br - ar], interval=.true.)
    call emit('qgallery_radius', ['ar', 'br'], ['radius'], &
        [(br - ar)/2], interval=.true.)
    call emit('qgallery_normalize', ['ar', 'ai', 'n0'], ['rr', 'ri'], &
        [ar/n0, ai/n0], ad=.true., interval=.true.)
    call emit('qgallery_hamiltonian_defect', &
        ['n0    ', 'radius', 'weight', 'x     ', 'hbar  '], ['result'], &
        [radius + sqrt(n0)*weight*x/hbar], interval=.true.)
    write (unit, '(a)') 'end module kin6d_quantum_reference_gallery_leaves'
    close (unit)
contains
    recursive subroutine emit(name, args, outputs, roots, ad, interval, rigorous)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in), optional :: ad, interval, rigorous
        type(kernel_spec_t) :: spec
        type(rigorous_kernel_spec_t) :: rspec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        integer :: j

        if (present(rigorous)) then
            if (rigorous) then
                rspec%name = str(name)
                rspec%generator = &
                    str('gen_quantum_reference_gallery; FortSym '//revision)
                rspec%runtime = interval_runtime('fortnum_interval', 'interval_t')
                rspec%runtime%sin = str('sin')
                rspec%runtime%cos = str('cos')
                rspec%runtime%abs = str('abs')
                rspec%runtime%sincos = str('sincos')
                rspec%elemental_procedure = .true.
                allocate (rspec%args(size(args)), rspec%outputs(size(outputs)))
                do j = 1, size(args)
                    rspec%args(j) = str(trim(args(j)))
                end do
                do j = 1, size(outputs)
                    rspec%outputs(j) = str(trim(outputs(j)))
                end do
                source = emit_rigorous_kernel(roots, rspec, ok, message)
                if (.not. ok) error stop message
                write (unit, '(a)') chars(source)
                return
            end if
        end if
        spec%name = str(name)
        spec%generator = str('gen_quantum_reference_gallery')
        spec%generator_revision = str(revision)
        spec%regenerate_command = &
            str('gen_quantum_reference_gallery from pinned FortSym build')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%openmp_declare_target = .false.
        spec%openacc_routine_seq = .false.
        allocate (spec%args(size(args)), spec%outputs(size(outputs)))
        do j = 1, size(args)
            spec%args(j) = str(trim(args(j)))
        end do
        do j = 1, size(outputs)
            spec%outputs(j) = str(trim(outputs(j)))
        end do
        source = emit_kernel(roots, spec, ok, message=message)
        if (.not. ok) error stop message
        write (unit, '(a)') chars(source)
        if (present(ad)) then
            if (ad) call emit_derivatives(name, args, outputs, roots)
        end if
        if (present(interval)) then
            if (interval) then
                call emit(name//'_interval', args, outputs, roots, rigorous=.true.)
            end if
        end if
    end subroutine emit

    subroutine emit_derivatives(name, args, outputs, roots)
        character(*), intent(in) :: name, args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(expr_t), allocatable :: variables(:), directions(:), weights(:)
        type(expr_t), allocatable :: derivative_roots(:)
        type(engine_result_t) :: simplified
        character(32), allocatable :: tangent_args(:), tangent_outputs(:)
        character(32), allocatable :: adjoint_args(:), adjoint_outputs(:)
        integer :: j, n, m

        n = size(args)
        m = size(outputs)
        allocate (variables(n), directions(n), weights(m))
        allocate (tangent_args(2*n), tangent_outputs(m))
        allocate (adjoint_args(n + m), adjoint_outputs(n))
        do j = 1, n
            variables(j) = sym(arena, trim(args(j)))
            directions(j) = sym(arena, 'd'//trim(args(j)))
            tangent_args(j) = args(j)
            tangent_args(n + j) = 'd'//trim(args(j))
            adjoint_args(j) = args(j)
            adjoint_outputs(j) = 'g'//trim(args(j))
        end do
        do j = 1, m
            weights(j) = sym(arena, 'b'//trim(outputs(j)))
            tangent_outputs(j) = 'd'//trim(outputs(j))
            adjoint_args(n + j) = 'b'//trim(outputs(j))
        end do
        derivative_roots = jvp(roots, variables, directions)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_jvp', tangent_args, tangent_outputs, derivative_roots)
        derivative_roots = vjp(roots, variables, weights)
        do j = 1, size(derivative_roots)
            simplified = engine%simplify(derivative_roots(j))
            if (.not. simplified%ok) error stop chars(simplified%message)
            derivative_roots(j) = simplified%value
        end do
        call emit(name//'_vjp', adjoint_args, adjoint_outputs, derivative_roots)
    end subroutine emit_derivatives
end program gen_quantum_reference_gallery
