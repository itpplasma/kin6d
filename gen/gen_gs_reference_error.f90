program gen_gs_reference_error
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use kin6d_gen_support, only: leaf_writer_t
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: writer
    type(native_engine_t) :: engine
    type(engine_result_t) :: identity
    type(expr_t) :: r, z, r0, c, edge, f, mu0, pp, ph, gr, gz
    type(expr_t) :: psi, exact_b(3), native_b(3), field_error, energy_error
    type(expr_t) :: difference(3), average(3)
    type(expr_t) :: stress_error, trace, delta, pressure_error
    integer :: i, j
    call arena%init()
    engine=make_native_engine(arena)
    r = sym(arena, 'r'); z = sym(arena, 'z'); r0 = sym(arena, 'r0')
    c = sym(arena, 'c'); edge = sym(arena, 'edge'); f = sym(arena, 'f')
    mu0 = sym(arena, 'mu0'); pp = sym(arena, 'pp')
    ph = sym(arena, 'ph'); gr = sym(arena, 'gr'); gz = sym(arena, 'gz')
    psi = c*((r**2-r0**2)**2 + 4*r**2*z**2)-edge
    identity=engine%zero_test(diff(diff(psi,r),r)-diff(psi,r)/r &
        +diff(diff(psi,z),z)-16*c*r**2)
    if(identity%verdict/=VERDICT_TRUE) error stop 'exact GS reference unproved'
    exact_b = [-diff(psi,z)/r, diff(psi,r)/r, f/r]
    native_b = [-gz/r, gr/r, f/r]
    difference = [native_b(1)-exact_b(1), native_b(2)-exact_b(2), 0*psi]
    do i=1,3
        average(i) = (native_b(i)+exact_b(i))/2
    end do
    field_error = (native_b(1)-exact_b(1))**2 &
        + (native_b(2)-exact_b(2))**2
    energy_error = r*field_error
    pressure_error = pp*ph + 16*c*psi/mu0
    trace = difference(1)*average(1)+difference(2)*average(2)
    stress_error = 0*psi
    do j = 1, 3
        do i = 1, 3
            delta = (difference(i)*average(j)+average(i)*difference(j))/mu0
            identity=engine%zero_test(delta &
                -(native_b(i)*native_b(j)-exact_b(i)*exact_b(j))/mu0)
            if(identity%verdict/=VERDICT_TRUE) error stop 'stress factor unproved'
            if (i == j) delta = delta-trace/mu0-pressure_error
            stress_error = stress_error + delta**2
        end do
    end do
    call writer%open(arena, 'gen_gs_reference_error', &
        'src/generated/kin6d_gs_reference_error_leaves.f90')
    call writer%line('! Generated by gen/gen_gs_reference_error.f90; do not edit.')
    call writer%line('module kin6d_gs_reference_error_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    call writer%emit('gs_reference_error_density', &
        ['r   ', 'z   ', 'r0  ', 'c   ', 'edge', 'f   ', 'mu0 ', &
         'pp  ', 'ph  ', 'gr  ', 'gz  '], &
        ['field_error ', 'energy_error', 'stress_error'], &
        [field_error, energy_error, r*stress_error], interval=.true.)
    call writer%line('end module kin6d_gs_reference_error_leaves')
    call writer%close()
    print '(a)', 'PASS: 10 exact GS/stress identities; zero numerical probes'
end program gen_gs_reference_error
